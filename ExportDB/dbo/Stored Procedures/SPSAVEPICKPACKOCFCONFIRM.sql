
CREATE PROCEDURE [dbo].[SPSAVEPICKPACKOCFCONFIRM]

AS
BEGIN
DECLARE @VPACKREQHEADERID INT,@VGLOBALID INT,@VPACKREQNUMBER VARCHAR(50),@VPACKREQDATE VARCHAR(50),@VCUSTOMERID INT,@VTERMSCONDITION VARCHAR(500),@VDESCRIPTIONS VARCHAR(500),
@DOCUMENTCREATEDDATE VARCHAR(50),@VDOCUMENTCREATEDBY INT,@VDOCUMENTSTATUSID INT,@VISACTIVE BIT,@VUNITID INT,@VPISCNUMBER INT,@VFLAG INT, @VSHIPMENTPERIOD VARCHAR(50),
@VDOCSTATUSID INT,@VAUTOID INT,@VPICKPACKNUMBER VARCHAR(50),@piid int,@formattedDate VARCHAR(8)
SELECT @piid=isnull(MAX(ID),0) FROM TBLPICKINGPACKINGHEADER;
	  set @piid=@piid+1;

	  SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  	SET @VPICKPACKNUMBER='PP' + '-' + @formattedDate + '-' + cast(@piid as varchar(10));

DECLARE @POno NVARCHAR(50),@doid int,@doitemid int,@sqid int,@docheckid int,@enrollcreate int;
select @doid=max(intId) from  ERP_SAD.dbo.tblSalesOrder ;
select @doitemid=intOcfItemID from ERP_SAD.dbo.tblSalesOrderDetails where intSOId=@doid
select @sqid=intQuatationId from erp_sad.dbo.tblSalesQuatationDetails where intOCFItemID=@doitemid
SELECT @POno =  strOCFNO
FROM erp_sad.dbo.tblSalesQuatation
WHERE intId=@sqid and strPOno LIKE 'OCFPR-[0-9]%-[0-9]%'

IF @POno IS NOT NULL 
begin

SET @VPACKREQHEADERID=(select ID from TBLPACKINGREQUESTHEADER where OCF=@POno)
SET @VGLOBALID=(select GLOBALID from TBLPACKINGREQUESTHEADER where OCF=@POno)
set @enrollcreate=(select DOCUMENTCREATEDBY from TBLPACKINGREQUESTHEADER where OCF=@POno)
SELECT @VPACKREQHEADERID=@VPACKREQHEADERID,
@VGLOBALID=@VGLOBALID,
@VPACKREQDATE=dteDate,@VCUSTOMERID=intCustomerId,@VTERMSCONDITION=(select TERMSCONDITION from TBLPACKINGREQUESTHEADER where OCF=@POno),
@VDESCRIPTIONS=(select DESCRIPTIONS from TBLPACKINGREQUESTHEADER where OCF=@POno),@DOCUMENTCREATEDDATE=dteDate,@VDOCUMENTCREATEDBY=intInsertBy,
@VDOCUMENTSTATUSID=7,@VISACTIVE=1,@VUNITID=intUnitId,@VPISCNUMBER=(select PISCNUMBER from TBLPACKINGREQUESTHEADER where OCF=@POno),
@VFLAG=1,@VSHIPMENTPERIOD=(select SHIPMENTPERIOD from TBLPACKINGREQUESTHEADER where OCF=@POno) 
FROM erp_sad.dbo.tblSalesQuatation WHERE strOCFNO=@POno
declare @SERIALNO int






SET @VDOCSTATUSID=7
INSERT INTO TBLPICKINGPACKINGHEADER
(
PICKPACKNUMBER,
GLOBALID,
PACKINGREQUESTHEADERID,
--PICKPACKNUMBER,
PICKPACKDATE,
CUSTOMERID,
TERMSCONDITION,
DESCRIPTIONS,
DOCUMENTCREATEDDATE,
DOCUMENTCREATEDBY,
DOCUMENTSTATUSID,
ISACTIVE,
UNITID,
FLAG
)
VALUES
(
@VPICKPACKNUMBER,
@VGLOBALID,
@VPACKREQHEADERID,
GETDATE(),
@VCUSTOMERID,
@VTERMSCONDITION,
@VDESCRIPTIONS,
@DOCUMENTCREATEDDATE,
@enrollcreate,
@VDOCSTATUSID,
1,
@VUNITID,
1
--@VFLAG
)
declare @packingpicid int,@tol int,@datesq datetime
 select @packingpicid=MAX(ID) from TBLPICKINGPACKINGHEADER

 select @tol=decTorranceRate from ERP_SAD.dbo.tblOCF where strOCFNo=@POno
 select @datesq=dteDate from ERP_SAD.dbo.tblSalesQuatation where strOCFNo=@POno
DECLARE @LINEID INT,@LINEPACKINGREQUESTHEADERID INT,@LINEBATCHID VARCHAR(50),@LINESERIALNO INT,@LINEITEMID INT,@LINEQUANTITY DECIMAL(18,2),@LINEPACKINGREQQUANTITY DECIMAL(18,2),
@LINETOLERANCEID INT,@LINEEXPPRODUCTIONORDERDATE VARCHAR(50),@LINEISACTIVE BIT,@LINEREMARKS VARCHAR(500),@LINEDESCRIPTIONS VARCHAR(500)

DECLARE SQLCURSOR CURSOR FOR  
SELECT intId,@packingpicid,'',1,intProductId,numQuantity,
numApprQuantity,
@tol,@datesq,1,'','' 
FROM ERP_SAD.dbo.tblSalesOrderDetails WHERE intSOId=@doid

OPEN SQLCURSOR
FETCH NEXT FROM SQLCURSOR INTO @LINEID,@LINEPACKINGREQUESTHEADERID,@LINEBATCHID,@LINESERIALNO,@LINEITEMID,@LINEQUANTITY,@LINEPACKINGREQQUANTITY,@LINETOLERANCEID,@LINEEXPPRODUCTIONORDERDATE,@LINEISACTIVE,@LINEREMARKS,@LINEDESCRIPTIONS;  


  WHILE @@FETCH_STATUS = 0  
  BEGIN
    set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPICKINGPACKINGLINE where PICKINGPACKINGHEADERID=(SELECT MAX(ID) FROM TBLPACKINGREQUESTHEADER))
  INSERT INTO TBLPICKINGPACKINGLINE
  (
  PICKINGPACKINGHEADERID,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PACKINGREQQUANTITY,
  PICKINGPACKINGQUANTITY,
  TOLERANCEID,
  ISACTIVE,
  REMARKS,
  DESCRIPTIONS
  )
  VALUES
  (
 @LINEPACKINGREQUESTHEADERID,
  @LINEBATCHID,
  @LINESERIALNO,
  @LINEITEMID,
  @LINEQUANTITY,
  @LINEPACKINGREQQUANTITY,
  0,
  @LINETOLERANCEID,
  1,
  @LINEREMARKS,
  @LINEDESCRIPTIONS
  )
  FETCH NEXT FROM sqlcursor INTO @LINEID,@LINEPACKINGREQUESTHEADERID,@LINEBATCHID,@LINESERIALNO,@LINEITEMID,@LINEQUANTITY,@LINEPACKINGREQQUANTITY,@LINETOLERANCEID,@LINEEXPPRODUCTIONORDERDATE,@LINEISACTIVE,@LINEREMARKS,@LINEDESCRIPTIONS; 
  END;
  CLOSE SQLCURSOR
DEALLOCATE SQLCURSOR
end



END;