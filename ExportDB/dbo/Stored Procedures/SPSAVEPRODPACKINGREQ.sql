
--DROP PROCEDURE SPSAVEPRODPACKINGREQ
CREATE PROCEDURE [dbo].[SPSAVEPRODPACKINGREQ]
(
@TYPEPACKINGREQINSERTLINE	TYPEPACKINGREQINSERTLINE READONLY,
@PACKREQDATE				VARCHAR(50),
@CUSTOMERID					INT,
@PISCNUMBER					INT,
@SHIPMENTPERIOD				VARCHAR(50),
@TERMSCONDITION				VARCHAR(500),
@DESCRIPTIONS				VARCHAR(500),

@INVOICENUMBER VARCHAR(500),
@INVOICEDATE  VARCHAR(500),
@INVOICETO VARCHAR(500),
@SHIPPEDPER VARCHAR(500),
@CONTRACTNO VARCHAR(500),
@CONTRACTDATE date,

@SHIPPEDFROM VARCHAR(500),
@SHIPPEDTO VARCHAR(500),

@PURCHASEORDERNO VARCHAR(500), 
@PURCHASEORDERDATED date, 

@ModuleCode					VARCHAR(50),
@UNITID						INT,
@Enroll						INT,
@DocStatus					VARCHAR(50),
@ProcessName				VARCHAR(500),
@MsgStatus					VARCHAR(500),
@NOTIFICATION				VARCHAR(100),
@LOG						VARCHAR(MAX),
@PACKINGMODE INT,
@CUSTOMERCATEGORY INT,
@SHIPPOINT INT,
@BIAXPROTYPE VARCHAR(50),
@Msg						VARCHAR(100) OUTPUT
)
AS
BEGIN

DECLARE @VITEMID INT,@VQUANTITY DECIMAL(18,2),@VPACKINGREQQUANTITY DECIMAL(18,2),@VEXPPRODUCTIONORDERDATE VARCHAR(50),@VTRUSSNO INT,
@VCOUNTNO VARCHAR(500),@VTOTALPALLET INT,@VTOTALCARTOON INT,@VADDWEIGHT DECIMAL(18,2),@VGROSSWEIGHT DECIMAL(18,2),@VMEASUREMENT NVARCHAR(200),@VSINO VARCHAR(50),@VTOTALSPOOL INT,@VMARKINK VARCHAR(500),@VSPOOLORPALAT VARCHAR(500),@VREMARKS VARCHAR(500),@VDESCRIPTIONS VARCHAR(500),@VMILLID INT,@VPACKREQNUMBER VARCHAR(50),@VCUSTOMERID INT,@VPISCNUMBER INT,@VDOCSTATUS INT,
@ID	INT,@BATCHID VARCHAR(100),@VGLOBALID INT,@SERIALNO INT,@PROCESSCODE varchar(100),@CHECKHEADER INT,@HEADER INT,@TEMPLOGLINE VARCHAR(MAX),
@piid int,@formattedDate VARCHAR(8),@NUMBER varchar(50),@OCF VARCHAR(50),@PISCLINEID INT
	SELECT @piid=isnull(MAX(ID),0)  FROM TBLPACKINGREQUESTHEADER;
	
	  set @piid=@piid+1;

	  SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  	SET @NUMBER='MD' + '-' + @formattedDate + '-' + cast(@piid as varchar(10))

DECLARE SQL_CURSOR CURSOR FOR  
 SELECT ID,ITEMID,QUANTITY,PACKINGREQQUANTITY,EXPPRODUCTIONORDERDATE, TRUSSNO, CountNo,TotalPallet,TotalCartoon,AddWeight,GrossWeight,MEASUREMENT,SINo,TotalSpool,MarkInk,SpoolOrPalat,REMARKS,DESCRIPTIONS,MILLID
 FROM @TYPEPACKINGREQINSERTLINE
 OPEN SQL_CURSOR
 FETCH NEXT FROM SQL_CURSOR INTO @PISCLINEID,@VITEMID,@VQUANTITY,@VPACKINGREQQUANTITY,@VEXPPRODUCTIONORDERDATE,@VTRUSSNO,@VCOUNTNO,@VTOTALPALLET,@VTOTALCARTOON,@VADDWEIGHT,@VGROSSWEIGHT,@VMEASUREMENT,@VSINO,@VTOTALSPOOL,@VMARKINK,@VSPOOLORPALAT,@VREMARKS,@VDESCRIPTIONS,@VMILLID;  

 SET @VCUSTOMERID=(SELECT CUSTOMERID FROM TBLPISCHEADER WHERE ID=@PISCNUMBER)
 SET @VDOCSTATUS=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='PEND')
 SET @CHECKHEADER=(SELECT COUNT(ID) FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER=@PISCNUMBER)
 if @UNITID=91
 begin
 declare @checkpi int,@checkpc int
 select @checkpc=ID from TBLPRICECONFIRMHEADER where PROFORMAINVOICEHEADERID=@PISCNUMBER
 if @checkpc is not null
 begin
 INSERT INTO TBLPACKINGREQUESTHEADER
(
PACKREQNUMBER,
PACKREQDATE,
SHIPMENTPERIOD,
CUSTOMERID,
TERMSCONDITION,
DESCRIPTIONS,

INVOICENUMBER,INVOICEDATE,INVOICETO,SHIPPEDPER,CONTRACTNO,CONTRACTDATE,

SHIPPEDFROM ,
SHIPPEDTO ,
PURCHASEORDERNO , 
PURCHASEORDERDATED,

DOCUMENTCREATEDDATE,
DOCUMENTCREATEDBY,
DOCUMENTSTATUSID,
ISACTIVE,
UNITID,
PISCNUMBER,
FLAG,
PACKINGMODE,
CUSTOMERCATEGORY,
SHIPPOINT,
BIAXPRODUCTTYPE
)
VALUES
(
@NUMBER,
@PACKREQDATE,
@SHIPMENTPERIOD,
@CUSTOMERID,
@TERMSCONDITION,
@DESCRIPTIONS,

@INVOICENUMBER,@INVOICEDATE,@INVOICETO,@SHIPPEDPER,@CONTRACTNO,@CONTRACTDATE,

@SHIPPEDFROM ,
@SHIPPEDTO ,

@PURCHASEORDERNO ,
@PURCHASEORDERDATED ,

GETDATE(),
@Enroll,
@VDOCSTATUS,
1,
@UNITID,
@PISCNUMBER,
0,
@PACKINGMODE ,
@CUSTOMERCATEGORY,
@SHIPPOINT,
@BIAXPROTYPE 
);



SET @id=SCOPE_IDENTITY()
SET @BATCHID=(SELECT 'BATCH'+CAST(@id AS VARCHAR(100)))

UPDATE TBLPACKINGREQUESTHEADER
SET GLOBALID=@id where ID=@id;

  WHILE @@FETCH_STATUS = 0  
  BEGIN
  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPACKINGREQUESTLINE where PACKINGREQUESTHEADERID=@id)

  INSERT INTO TBLPACKINGREQUESTLINE
  (
  PISCLINEID,
  PACKINGREQUESTHEADERID,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PACKINGREQQUANTITY,
  EXPPRODUCTIONORDERDATE,
  TRUSSNO,
  ISACTIVE,
  COUNTNO,
  TOTALPALLET,
  TOTALCARTOON,
  ADDITIONALWEIGHT,
  GROSSWEIGHT,
  MEASUREMENT,
  SINO,
  TOTALSPOOL,
  MARKINK,
  SPOOLORPALAT,
  REMARKS,
  DESCRIPTIONS,
  MILLID
  )
  VALUES
  (
  @PISCLINEID,
  @id,
  @BATCHID,
  @SERIALNO,
  @VITEMID,
  @VQUANTITY,
  @VPACKINGREQQUANTITY,
  @VEXPPRODUCTIONORDERDATE,
  @VTRUSSNO,
  1,
  @VCOUNTNO,
  @VTOTALPALLET,
  @VTOTALCARTOON,
  @VADDWEIGHT,
  @VGROSSWEIGHT,
  @VMEASUREMENT,
  @VSINO,
  @VTOTALSPOOL,
  @VMARKINK,
  @VSPOOLORPALAT,
  @VREMARKS,
  @VDESCRIPTIONS,
  @VMILLID
  )
  FETCH NEXT FROM sql_cursor INTO @PISCLINEID,@VITEMID,@VQUANTITY,@VPACKINGREQQUANTITY,@VEXPPRODUCTIONORDERDATE,@VTRUSSNO,@VCOUNTNO,@VTOTALPALLET,@VTOTALCARTOON,@VADDWEIGHT,@VGROSSWEIGHT,@VMEASUREMENT,@VSINO,@VTOTALSPOOL,@VMARKINK,@VSPOOLORPALAT,@VREMARKS,@VDESCRIPTIONS,@VMILLID;
  END;
  --set @Msg=@id
   SET @TEMPLOGLINE=@LOG;
   SET @LOG='INSERT INTO TBLPACKINGREQUESTHEADER (ID,PACKREQDATE,SHIPMENTPERIOD,CUSTOMERID,TERMSCONDITION,DESCRIPTIONS,DOCUMENTCREATEDDATE,DOCUMENTCREATEDBY,PISCNUMBER) VALUES ('+
   CAST(@id AS VARCHAR(50))+CAST(@PACKREQDATE AS VARCHAR(50))+CAST(@SHIPMENTPERIOD AS VARCHAR(50))+CAST(@CUSTOMERID AS VARCHAR(50))+CAST(@DESCRIPTIONS AS VARCHAR(50))+CAST(@Enroll AS VARCHAR(50))+CAST(@PISCNUMBER AS VARCHAR(50))
 
  SET @PROCESSCODE=@NUMBER
  --SET @PROCESSCODE=@PROCESSNAME+CAST(@id AS VARCHAR(50))
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@id,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@PROCESSCODE,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
 if @UNITID=91
 begin
 exec sprExportocfcreate @Enroll

 select @OCF=strOCFNo from ERP_SAD.dbo.tblOCF WHERE intInsertBy=@Enroll
 update TBLPACKINGREQUESTHEADER set OCF=@OCF Where ID=(select max(ID) FROM TBLPACKINGREQUESTHEADER WHERE DOCUMENTCREATEDBY=@Enroll)
 end
 end
 else
 begin
 set @Msg='Please At First Done Price Confirmation'
 end
 end
 else
 begin
 INSERT INTO TBLPACKINGREQUESTHEADER
(
PACKREQNUMBER,
PACKREQDATE,
SHIPMENTPERIOD,
CUSTOMERID,
TERMSCONDITION,
DESCRIPTIONS,

INVOICENUMBER,INVOICEDATE,INVOICETO,SHIPPEDPER,CONTRACTNO,CONTRACTDATE,

SHIPPEDFROM,
SHIPPEDTO,

PURCHASEORDERNO ,
PURCHASEORDERDATED ,

DOCUMENTCREATEDDATE,
DOCUMENTCREATEDBY,
DOCUMENTSTATUSID,
ISACTIVE,
UNITID,
PISCNUMBER,
FLAG,
PACKINGMODE,
CUSTOMERCATEGORY,
SHIPPOINT,
BIAXPRODUCTTYPE
)
VALUES
(
@NUMBER,
@PACKREQDATE,
@SHIPMENTPERIOD,
@CUSTOMERID,
@TERMSCONDITION,
@DESCRIPTIONS,

@INVOICENUMBER,@INVOICEDATE,@INVOICETO,@SHIPPEDPER,@CONTRACTNO,@CONTRACTDATE,

@SHIPPEDFROM,
@SHIPPEDTO,

 @PURCHASEORDERNO , 
 @PURCHASEORDERDATED ,

GETDATE(),
@Enroll,
@VDOCSTATUS,
1,
@UNITID,
@PISCNUMBER,
0,
@PACKINGMODE ,
@CUSTOMERCATEGORY,
@SHIPPOINT,
@BIAXPROTYPE 
);



SET @id=SCOPE_IDENTITY()
SET @BATCHID=(SELECT 'BATCH'+CAST(@id AS VARCHAR(100)))

UPDATE TBLPACKINGREQUESTHEADER
SET GLOBALID=@id where ID=@id;

  WHILE @@FETCH_STATUS = 0  
  BEGIN
  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPACKINGREQUESTLINE where PACKINGREQUESTHEADERID=@id)

  INSERT INTO TBLPACKINGREQUESTLINE
  (
  PISCLINEID,
  PACKINGREQUESTHEADERID,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PACKINGREQQUANTITY,
  EXPPRODUCTIONORDERDATE,
  TRUSSNO,
  ISACTIVE,
  COUNTNO,
  TOTALPALLET,
  TOTALCARTOON,
  ADDITIONALWEIGHT,
  GROSSWEIGHT,
  MEASUREMENT,
  SINO,
  TOTALSPOOL,
  MARKINK,
  SPOOLORPALAT,
  REMARKS,
  DESCRIPTIONS,
  MILLID
  )
  VALUES
  (
  @PISCLINEID,
  @id,
  @BATCHID,
  @SERIALNO,
  @VITEMID,
  @VQUANTITY,
  @VPACKINGREQQUANTITY,
  @VEXPPRODUCTIONORDERDATE,
  @VTRUSSNO,
  1,
  @VCOUNTNO,
  @VTOTALPALLET,
  @VTOTALCARTOON,
  @VADDWEIGHT,
  @VGROSSWEIGHT,
  @VMEASUREMENT,
  @VSINO,
  @VTOTALSPOOL,
  @VMARKINK,
  @VSPOOLORPALAT,
  @VREMARKS,
  @VDESCRIPTIONS,
  @VMILLID
  )
  FETCH NEXT FROM sql_cursor INTO @PISCLINEID,@VITEMID,@VQUANTITY,@VPACKINGREQQUANTITY,@VEXPPRODUCTIONORDERDATE,@VTRUSSNO, @VCOUNTNO,@VTOTALPALLET,@VTOTALCARTOON,@VADDWEIGHT,@VGROSSWEIGHT,@VMEASUREMENT,@VSINO,@VTOTALSPOOL,@VMARKINK,@VSPOOLORPALAT,@VREMARKS,@VDESCRIPTIONS,@VMILLID ;
  END;
  --set @Msg=@id
   SET @TEMPLOGLINE=@LOG;
   SET @LOG='INSERT INTO TBLPACKINGREQUESTHEADER (ID,PACKREQDATE,SHIPMENTPERIOD,CUSTOMERID,TERMSCONDITION,DESCRIPTIONS,DOCUMENTCREATEDDATE,DOCUMENTCREATEDBY,PISCNUMBER) VALUES ('+
   CAST(@id AS VARCHAR(50))+CAST(@PACKREQDATE AS VARCHAR(50))+CAST(@SHIPMENTPERIOD AS VARCHAR(50))+CAST(@CUSTOMERID AS VARCHAR(50))+CAST(@DESCRIPTIONS AS VARCHAR(50))+CAST(@Enroll AS VARCHAR(50))+CAST(@PISCNUMBER AS VARCHAR(50))
 
  SET @PROCESSCODE=@NUMBER
  --SET @PROCESSCODE=@PROCESSNAME+CAST(@id AS VARCHAR(50))
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@id,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@PROCESSCODE,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
 if @UNITID=91
 begin
 exec sprExportocfcreate @Enroll

 select @OCF=strOCFNo from ERP_SAD.dbo.tblOCF WHERE intInsertBy=@Enroll
 update TBLPACKINGREQUESTHEADER set OCF=@OCF Where ID=(select max(ID) FROM TBLPACKINGREQUESTHEADER WHERE DOCUMENTCREATEDBY=@Enroll)
 end
 end


  
END;
