CREATE PROCEDURE [dbo].[SPGETPICKINGPACKINGFORAPPROVAL]
		(
		@Type			INT,
		@ENROLL			INT,
		@ID				VARCHAR(50),
		@UnitID			INT
		)
		AS
		BEGIN

		DECLARE @STATUSID INT
		SET @STATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@ID)
		IF @Type=7
		BEGIN
		SELECT APPHISTORY.ID AS ID,PICKPACK.PICKPACKNUMBER,PICKPACK.PACKINGREQUESTHEADERID,CAST(CAST(PICKPACK.PICKPACKDATE AS DATE) AS VARCHAR(50)) PICKPACKDATE,
		PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PICKPACK.FLAG
		FROM     TBLPACKINGREQUESTHEADER PACKH						INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					LEFT JOIN TBLPICKINGPACKINGHEADER		PICKPACK
		ON       PACKH.ID=PICKPACK.PACKINGREQUESTHEADERID			INNER JOIN TBLAPPROVERMATRIXHISTORY		APPHISTORY
		ON		 PICKPACK.ID=APPHISTORY.PROCESSID					INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=APPHISTORY.DOCUMENTSTATUSID
		WHERE    APPHISTORY.ACTIONTAKERID=@ENROLL AND APPHISTORY.DOCUMENTSTATUSID=@STATUSID AND PICKPACK.ISACTIVE=1
		order by PICKPACK.ID desc
		
		END;
		ELSE IF  @Type=1
		BEGIN
		SELECT APPHISTORY.ID AS ID,PICKPACK.PICKPACKNUMBER,PICKPACK.PACKINGREQUESTHEADERID,CAST(CAST(PICKPACK.PICKPACKDATE AS DATE) AS VARCHAR(50)) PICKPACKDATE,
		PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PICKPACK.FLAG
		FROM     TBLPACKINGREQUESTHEADER PACKH						INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID			    LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					INNER JOIN TBLPICKINGPACKINGHEADER		PICKPACK
		ON       PACKH.ID=PICKPACK.PACKINGREQUESTHEADERID			INNER JOIN TBLAPPROVERMATRIXHISTORY		APPHISTORY
		ON		 PICKPACK.ID=APPHISTORY.PROCESSID					INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=APPHISTORY.DOCUMENTSTATUSID
		WHERE    APPHISTORY.ID=@ID  /*AND APPHISTORY.DOCUMENTSTATUSID=@STATUSID*/ AND PICKPACK.ISACTIVE=1
		--WHERE    PICKPACK.ID=(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID)  /*AND APPHISTORY.DOCUMENTSTATUSID=@STATUSID*/ AND PICKPACK.ISACTIVE=1
		END;
	END;