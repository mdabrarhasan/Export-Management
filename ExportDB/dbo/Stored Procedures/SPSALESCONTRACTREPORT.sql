CREATE PROCEDURE [dbo].[SPSALESCONTRACTREPORT]
    @HEADERID INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @PRODUCT_QUANTITY NVARCHAR(500)
    DECLARE @DESCRIPTION_SPECIFICATION NVARCHAR(1000)
    DECLARE @DESTINATIONPORT NVARCHAR(50)
    DECLARE @SHIPMENTPERIOD NVARCHAR(50)
    DECLARE @CONTRACTNUMBER NVARCHAR(50)
    DECLARE @ITEM_BLOCK NVARCHAR(MAX) = ''

    -- Get header fields
    SELECT 
        @PRODUCT_QUANTITY = ISNULL(PRODUCT_QUANTITY, ''),
        @DESCRIPTION_SPECIFICATION = ISNULL(DESCRIPTION_SPECIFICATION, ''),
        @DESTINATIONPORT = ISNULL(DESTINATIONPORT, '')
    FROM TBLSALESQUOTATIONHEADER
    WHERE ID = @HEADERID AND ISACTIVE = 1

    -- Get shipment period from packing request header
    SELECT TOP 1
        @SHIPMENTPERIOD = ISNULL(UPPER(FORMAT(SHIPMENTDATE, 'MMMM yyyy')), '')
    FROM TBLPISCHEADER
    WHERE SALESQUOTATIONHEADERID = @HEADERID
        AND ISACTIVE = 1

    -- Get contract number from PISC header
    SELECT TOP 1
        @CONTRACTNUMBER = ISNULL([NUMBER], '')
    FROM TBLPISCHEADER
    WHERE SALESQUOTATIONHEADERID = @HEADERID
        AND ISACTIVE = 1

    -- Build the item block using a cursor for guaranteed order
    DECLARE @ITEMTITLE NVARCHAR(MAX)
    DECLARE @ITEMNAME NVARCHAR(200)
    DECLARE @QUANTITY DECIMAL(18,2)
    DECLARE @UOM NVARCHAR(500)
    DECLARE @QUALITY NVARCHAR(MAX)
    DECLARE @SIZE NVARCHAR(MAX)
    DECLARE @CONSTRUCTION NVARCHAR(MAX)
    DECLARE @WEIGHT NVARCHAR(MAX)
    DECLARE @SLIT NVARCHAR(MAX)
    DECLARE @SCRIM NVARCHAR(MAX)
    DECLARE @PACKINGDETAILS NVARCHAR(MAX)
    DECLARE @REMARKS NVARCHAR(1000)
    DECLARE @ITEM_NUMBER INT
    DECLARE @SUB_POINT_NUMBER INT
    DECLARE @PREV_ITEM_NUMBER INT = 0

    DECLARE item_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT
            ITEM_NUMBER,
            SUB_POINT_NUMBER,
            ITEMTITLE,
            ITEMNAME,
            QUANTITY,
            UOM,
            QUALITY,
            SIZE,
            CONSTRUCTION,
            WEIGHT,
            SLIT,
            SCRIM,
            PACKINGDETAILS,
            REMARKS
        FROM (
            SELECT
                L.ITEMTITLE,
                I.strProductName AS ITEMNAME,
                L.QUANTITY,
                U.strUOM AS UOM,
                L.QUALITY,
                L.SIZE,
                L.CONSTRUCTION,
                L.WEIGHT,
                L.SLIT,
                L.SCRIM,
                L.PACKINGDETAILS,
                L.REMARKS,
                L.SERIALNO,
                DENSE_RANK() OVER (ORDER BY L.ITEMTITLE) AS ITEM_NUMBER,
                ROW_NUMBER() OVER (PARTITION BY L.ITEMTITLE ORDER BY L.SERIALNO) AS SUB_POINT_NUMBER
            FROM TBLSALESQUOTATIONLINE L
            INNER JOIN ERP_SAD.dbo.tblItem I
                ON L.ITEMID = I.intID
            LEFT JOIN ERP_SAD.dbo.tblUOM U
                ON L.UOMID = U.intID
            WHERE L.SALESQUOTATIONHEADERID = @HEADERID
                AND L.ISACTIVE = 1
        ) AS T
        ORDER BY ITEM_NUMBER, SUB_POINT_NUMBER

    OPEN item_cursor
    FETCH NEXT FROM item_cursor INTO 
        @ITEM_NUMBER, @SUB_POINT_NUMBER, @ITEMTITLE, @ITEMNAME,
        @QUANTITY, @UOM, @QUALITY, @SIZE, @CONSTRUCTION, @WEIGHT,
        @SLIT, @SCRIM, @PACKINGDETAILS, @REMARKS

    WHILE @@FETCH_STATUS = 0
    BEGIN
        IF @ITEM_NUMBER != @PREV_ITEM_NUMBER
        BEGIN
            IF @ITEM_BLOCK != ''
                SET @ITEM_BLOCK = @ITEM_BLOCK + CHAR(13) + CHAR(10)

            SET @ITEM_BLOCK = @ITEM_BLOCK 
                + CAST(@ITEM_NUMBER AS VARCHAR(10)) + '/. ' 
                + ISNULL(@ITEMTITLE, '') + CHAR(13) + CHAR(10)

            SET @PREV_ITEM_NUMBER = @ITEM_NUMBER
        END

        -- Add sub-point line
        SET @ITEM_BLOCK = @ITEM_BLOCK 
            + CHAR(64 + @SUB_POINT_NUMBER) + ') '
            + CASE 
                WHEN @QUANTITY = CAST(CAST(@QUANTITY AS INT) AS DECIMAL(18,2)) 
                    THEN CAST(CAST(@QUANTITY AS INT) AS VARCHAR(20))
                ELSE FORMAT(@QUANTITY, '0.##')
              END
            + CASE WHEN @UOM IS NOT NULL AND @UOM != '' THEN @UOM ELSE '' END
            + CASE WHEN @ITEMNAME IS NOT NULL AND @ITEMNAME != '' THEN ', ' + @ITEMNAME ELSE '' END
            + CASE WHEN @QUALITY IS NOT NULL AND @QUALITY != '' THEN ', ' + @QUALITY ELSE '' END
            + CASE WHEN @SIZE IS NOT NULL AND @SIZE != '' THEN ', ' + @SIZE ELSE '' END
            + CASE WHEN @CONSTRUCTION IS NOT NULL AND @CONSTRUCTION != '' THEN ', ' + @CONSTRUCTION ELSE '' END
            + CASE WHEN @WEIGHT IS NOT NULL AND @WEIGHT != '' THEN ', ' + @WEIGHT ELSE '' END
            + CASE WHEN @SLIT IS NOT NULL AND @SLIT != '' THEN ', ' + @SLIT ELSE '' END
            + CASE WHEN @SCRIM IS NOT NULL AND @SCRIM != '' THEN ', ' + @SCRIM ELSE '' END
            + CASE WHEN @PACKINGDETAILS IS NOT NULL AND @PACKINGDETAILS != '' THEN ', ' + @PACKINGDETAILS ELSE '' END
            + CASE WHEN @REMARKS IS NOT NULL AND @REMARKS != '' THEN ', ' + @REMARKS ELSE '' END
            + CHAR(13) + CHAR(10)

        FETCH NEXT FROM item_cursor INTO 
            @ITEM_NUMBER, @SUB_POINT_NUMBER, @ITEMTITLE, @ITEMNAME,
            @QUANTITY, @UOM, @QUALITY, @SIZE, @CONSTRUCTION, @WEIGHT,
            @SLIT, @SCRIM, @PACKINGDETAILS, @REMARKS
    END

    CLOSE item_cursor
    DEALLOCATE item_cursor

    -- Return all values
    SELECT 
        @PRODUCT_QUANTITY AS PRODUCT_QUANTITY,
        @DESCRIPTION_SPECIFICATION AS DESCRIPTION_SPECIFICATION,
        @ITEM_BLOCK AS ITEM_BLOCK,
        @SHIPMENTPERIOD AS SHIPMENTPERIOD,
        @DESTINATIONPORT AS DESTINATIONPORT,
        @CONTRACTNUMBER AS CONTRACTNUMBER
END