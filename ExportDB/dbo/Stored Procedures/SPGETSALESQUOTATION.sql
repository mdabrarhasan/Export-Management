CREATE PROCEDURE [dbo].[SPGETSALESQUOTATION]
@type int,
@Enroll int
AS
BEGIN
/*SELECT ID,SQNUMBER AS NAME FROM TBLSALESQUOTATIONHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP') AND ID NOT IN(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER)*/
if(@type=0)
begin
SELECT ID,SQNUMBER AS NAME FROM TBLSALESQUOTATIONHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP') AND ID NOT IN(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER) --and DOCUMENTCREATEDBY=@Enroll
union
SELECT ID,NUMBER AS NAME FROM TBLPISCHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP') AND SALESQUOTATIONHEADERID NOT IN (SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE='PITOSC')) and DOCUMENTCREATEDBY=@Enroll
end
if(@type=1)
begin
SELECT ID,SQNUMBER AS NAME FROM TBLSALESQUOTATIONHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP')  AND ID NOT IN(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER) --and DOCUMENTCREATEDBY=@Enroll
end
if(@type=2)
begin
SELECT ID,SQNUMBER AS NAME FROM TBLSALESQUOTATIONHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP')  AND ID NOT IN(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER)
/*SELECT ID,NUMBER AS NAME FROM TBLPISCHEADER 
WHERE DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP') AND AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE='PI') 
AND SALESQUOTATIONHEADERID NOT IN (SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE='PITOSC')) --and DOCUMENTCREATEDBY=@Enroll*/
end
END;