
CREATE PROCEDURE SPGETLOANINFO
(
@ID				INT,
@LOANAMOUNT		DECIMAL(18,2)	OUTPUT,
@CONRATE		DECIMAL(18,2)	OUTPUT,
@MATURITYDATE	VARCHAR(50)		OUTPUT,
@CURRENCYID		INT				OUTPUT
)
AS
BEGIN
SELECT @LOANAMOUNT=LOANAMOUNT,@CONRATE=CONRATE,@MATURITYDATE=CAST(CAST(MATURITYDATE AS DATE) AS VARCHAR(50)),@CURRENCYID=CURRENCYID FROM TBLBANKLOAN WHERE ID=@ID
END;