

CREATE PROCEDURE [dbo].[SPGetSalesQuatationApprovalByID]
(
@UNITID			INT,
@CODE		VARCHAR(100),
@ENROLL			INT,
@ID				VARCHAR(50)
)
AS
BEGIN

DECLARE @DOCSTATUSID INT,@CHECKSTATUSID INT;
SET @DOCSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@ID)
SET @CHECKSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@ID)

SELECT  SQH.SQTYPEID,SQTYPE.strTypeName AS SQTYPENAME,CAST(CAST(SQH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,APVMH.ID AS HISTRYID, SQH.UNITID AS UNITID,STRUNIT AS UNITNAME,STRDESCRIPTION AS  UNITDESCRIPTION,UNIT.STRACCEMAILADDRESS AS SELLEREMAIL,UNIT.STRPHONE AS SELLERPHONE,UNIT.STRTIN AS SELLERTIN,
SQH.CUSTOMERID AS CUSID,CUS.STRNAME AS CUSTOMERNAME,CUS.STRPHONE AS CUSPHONE,CUS.STREMAILADDRESS AS CUSEMAIL,
CUS.STRADDRESS AS CUSADDRESS,CAST(SQH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,SQH.ISPROCESSEDWITHAPPROVAL,
DS.NAME AS DOCSTATUS,SQH.ID,SQNUMBER,APVMH.DESCRIPTIONS,SQH.TERMSCONDITION,DS.CODE,CASE WHEN ISNULL(SQH.FLAG,0)=0 THEN 0 ELSE SQH.FLAG END AS FLAG,GLOBALID,


 SQH.DESCRIPTION_SPECIFICATION AS DESCRIPTIONSPECIFICATION,
            SQH.PRODUCT_QUANTITY AS QUANTITYSUMMARY,

            SQH.DOCUMENTCREATEDBY,
            SQH.DOCUMENTSTATUSID,

            SQH.SHIPMENTMODE,
            ISNULL(SQH.FROMSHIPMENT, 0) AS FROMSHIPMENT,
            SQH.TOSHIPMENT,
            SQH.TEXTFROMSHIPMENT,
            SQH.DESTINATIONPORT,

            SQH.CURRENCY,
            SQH.LOADINGPORT,
            SQH.LOADINGPLACE,
            SQH.INCOTERM,
            SQH.TRANSPORTATIONMODE,

            SQH.PAYMENTTERMS_ID AS PAYMENTTERMSID,
            SQH.PAYMENTTERMS_OTHERS AS PAYMENTTERMSOTHERS,
			SQH.PAYMENTTERMS,
            SQH.SHIPPINGPERIOD


FROM TBLSALESQUOTATIONHEADER SQH,
TBLAPPROVERMATRIXHISTORY APVMH,
ERP_HR.DBO.TBLUNIT UNIT,
ERP_SAD.DBO.TBLCUSTOMER CUS,
TBLDOCUMENTSTATUS DS,
ERP_SAD.DBO.tblCustomerType SQTYPE
WHERE SQH.ID=APVMH.PROCESSID AND 
SQH.UNITID=UNIT.INTUNITID AND 
SQH.CUSTOMERID=CUS.INTCUSID AND
APVMH.ACTIONTAKERID=@ENROLL AND
APVMH.DOCUMENTSTATUSID=DS.ID
AND SQH.SQTYPEID=SQTYPE.intTypeID AND
APVMH.DOCUMENTSTATUSID=@CHECKSTATUSID AND APVMH.DOCUMENTSTATUSID !=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT') AND
--APVMH.UNITID=@UNITID AND
SQH.ISACTIVE=1 AND
SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=TRIM(@CODE))
ORDER BY SQH.ID DESC;
END;