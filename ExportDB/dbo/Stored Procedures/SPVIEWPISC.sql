
CREATE PROCEDURE [dbo].[SPVIEWPISC]
(
@ID				INT,
@HEADERID		INT
)
AS 
BEGIN
	IF @ID=0
	BEGIN
		
SELECT 0 AS HISTRYID, PH.ID AS AGREEMENTID,SH.TEXTFROMSHIPMENT, '' AS TEXTPAYMENT,SH.DESTINATIONPORT ,PH.TEXTDESTINATIONPORT AS TEXTDESTINATIONPORT ,PH.UNITID,PH.NUMBER AS PINUMBER,CAST(PH.DATE AS VARCHAR) AS PIDATE,CAST(PH.EXPIREDATE AS VARCHAR) AS PIEXPIREDATE,
		CAST(PH.AGREEMENTTYPEID AS VARCHAR(50)) AS AGREEMENTTYPEID,'' AS AGREEMENTTYPE, PH.BUYERREGNO,PH.CURRENCYID,CUR.NAME AS CURRENCY,PH.DESCRIPTIONS,
		PH.TERMSCONDITION,PH.DELIVERYTERMID,PH.HSCODE,PH.SALESQUOTATIONHEADERID,PH.SHIPMENTMODEID,
		CAST(PH.SHIPMENTDATE AS VARCHAR) AS SHIPMENTDATE,CAST(PH.DOCUMENTCREATEDDATE AS VARCHAR) AS DOCUMENTCREATEDDATE,CUS.STRNAME AS CUSTOMERNAME,'' AS SQNUMBER,
		ISNULL(SM.ID,0) AS SHIPMENTID,SM.NAME AS SHIPMENT,ISNULL(PT.ID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,
		ISNULL(TSC.ID,0)  AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,FSC.ID AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
		ISNULL(LP.ID,0) AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,ISNULL(DP.ID,0) AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,
		PH.TARRIFCODE,INCO.ID AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,DS.ID AS DOCSTATUSID,DS.NAME AS DOSSTATUS,
		'' AS DELIVERYTERM,0 AS FLAG,--CASE WHEN ISNULL(SQH.FLAG,0)=0 THEN 0 ELSE SQH.FLAG END AS FLAG,
		PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
		PH.NOTIFYPARTY,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL
		FROM TBLPISCHEADER PH				 INNER JOIN ERP_SAD.DBO.TBLCUSTOMER			   CUS
		ON PH.CUSTOMERID=CUS.INTCUSID	     LEFT JOIN TBLSHIPMENTMODE					   SM
		ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
		ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
		ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
		ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
		ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
		ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
		ON PH.INCOTERM=INCO.ID				 LEFT JOIN TBLDOCUMENTSTATUS				   DS
		ON PH.DOCUMENTSTATUSID=DS.ID		 INNER JOIN TBLCURRENCY						   CUR
		ON PH.CURRENCYID=CUR.ID              INNER JOIN TBLSALESQUOTATIONHEADER            SH
        ON PH.SALESQUOTATIONHEADERID = SH.ID
	    WHERE PH.ID=@HEADERID
	END;
	ELSE IF @ID=1
	BEGIN
	DECLARE @UNITID INT
	
	SELECT @UNITID=UNITID FROM TBLPISCHEADER WHERE ID=@HEADERID

	SELECT ID,PISCHEADER,B.STRPRODUCTNAME+' '+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
	A.ITEMID,
	A.ITEMTYPEID,A.ITEMTITLE,PACKINGDETAILS,
	SIZE,SLIT,SCRIM,CONSTRUCTION,QUALITY,WEIGHT,
	UOMID,UOM.strUOM AS UOM,BATCHID,SERIALNO,ITEMID AS PRODUCTCODE,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,
	ISNULL(TOTALAMOUNT,0.0) AS TOTALAMOUNT,DESCRIPTIONS,REMARKS,CASE WHEN A.DISCOUNTID=0 THEN '' ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID=A.DISCOUNTID) END AS DISNAME
	FROM TBLPISCLINE A,
	ERP_SAD.DBO.TBLITEM B,
	ERP_SAD.dbo.tblUOM UOM 
	WHERE A.ITEMID=B.INTID AND A.ISACTIVE=1 
	AND PISCHEADER=@HEADERID AND A.UOMID=UOM.INTID  ORDER BY A.ITEMID DESC
	END;
	ELSE IF @ID=2
	BEGIN

	
	SELECT @UNITID=UNITID FROM TBLPISCHEADER WHERE ID=@HEADERID

	SELECT ID,PISCHEADER,B.STRPRODUCTNAME+' '+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
	A.ITEMID,
	A.ITEMTYPEID,A.ITEMTITLE,PACKINGDETAILS,
	SIZE,SLIT,SCRIM,CONSTRUCTION,QUALITY,WEIGHT,
	UOMID,UOM.strUOM,BATCHID,SERIALNO,ITEMID AS PRODUCTCODE,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,
	ISNULL(TOTALAMOUNT,0.0) TOTALAMOUNT,DESCRIPTIONS,REMARKS,CASE WHEN A.DISCOUNTID=0 THEN '' ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID=A.DISCOUNTID) END AS DISNAME
	FROM TBLPISCLINE A,
	ERP_SAD.DBO.TBLITEM B,
	ERP_SAD.dbo.tblUOM UOM 
	WHERE A.ITEMID=B.INTID AND A.ISACTIVE=1 
	AND PISCHEADER=@HEADERID AND A.UOMID=UOM.INTID  ORDER BY A.ITEMID DESC
	END;
	ELSE 
	BEGIN
	
	SELECT @UNITID=UNITID FROM TBLPISCHEADER WHERE ID=@HEADERID

	SELECT ID,PISCHEADER,B.STRPRODUCTNAME AS ITEMNAME,
	A.ITEMTYPEID,A.ITEMTITLE,PACKINGDETAILS,
	SIZE,SLIT,SCRIM,CONSTRUCTION,QUALITY,WEIGHT,
	UOMID,UOM.strUOM AS UOM,BATCHID,SERIALNO,ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,
	ISNULL(TOTALAMOUNT,0.0) TOTALAMOUNT,DESCRIPTIONS,REMARKS,CASE WHEN A.DISCOUNTID=0 THEN '' ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID=A.DISCOUNTID) END AS DISNAME
	FROM TBLPISCLINE A,
	ERP_SAD.DBO.TBLITEM B,
	ERP_SAD.dbo.tblUOM UOM 
	WHERE A.ITEMID=B.INTID AND A.ISACTIVE=1 
	AND PISCHEADER=@HEADERID AND A.UOMID=UOM.INTID ORDER BY A.ITEMID DESC
	END;
END;