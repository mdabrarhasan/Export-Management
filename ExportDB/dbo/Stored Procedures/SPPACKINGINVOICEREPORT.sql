--EXEC SPPACKINGINVOICEREPORT 1137
CREATE PROCEDURE [dbo].[SPPACKINGINVOICEREPORT]
    @HEADERID INT
AS
BEGIN
    SET NOCOUNT ON;

    -- Header fields
    DECLARE @INVOICENUMBER VARCHAR(50)
    DECLARE @INVOICEDATE DATE
    DECLARE @INVOICETO VARCHAR(50)
    DECLARE @CUSTOMERADDRESS NVARCHAR(MAX)
    DECLARE @SHIPPEDPER VARCHAR(50)
    DECLARE @SHIPPEDFROM VARCHAR(50)
    DECLARE @SHIPPEDTO VARCHAR(50)
    DECLARE @CONTRACTNO VARCHAR(50)
    DECLARE @CONTRACTDATE DATE
    DECLARE @PURCHASEORDERNO VARCHAR(50)
    DECLARE @PURCHASEORDERDATED DATE
    DECLARE @BINNO VARCHAR(50)
    DECLARE @TIN VARCHAR(50)
    DECLARE @GROSSWEIGHT DECIMAL(18,2)
	DECLARE @NETWEIGHT DECIMAL(18,2)

	DECLARE @INCOTERM NVARCHAR(100)
	DECLARE @CURRENCYNAME NVARCHAR(100)
	DECLARE @DESTINATIONPORT NVARCHAR(200)
	DECLARE @TOTALAMOUNT DECIMAL(20,2)
	DECLARE @TERMS NVARCHAR(MAX)
	DECLARE @TOTALPRICE NVARCHAR(200)

	--Marks
	DECLARE @MARKS NVARCHAR(MAX) = ''

	--Truss
	DECLARE @TRUSSES NVARCHAR(MAX) = ''

	--Carton
	DECLARE @CARTONS NVARCHAR(MAX) = ''

	--Bundle
	DECLARE @BUNDLES NVARCHAR(MAX) = ''

    -- Description of Goods fields (from sales contract)
    DECLARE @PRODUCT_QUANTITY NVARCHAR(500)
    DECLARE @DESCRIPTION_SPECIFICATION NVARCHAR(1000)
    DECLARE @ITEM_BLOCK NVARCHAR(MAX) = ''
	DECLARE @TOTALAMOUNTINWORDS NVARCHAR(MAX)
	DECLARE @UNITNAME NVARCHAR(200)

    -- Linking variable
    DECLARE @SALESCONTRACTHEADERID INT

    -- Get header fields
    SELECT 
        @INVOICENUMBER = ISNULL(H.INVOICENUMBER, ''),
        @INVOICEDATE = TRY_CONVERT(DATE, H.INVOICEDATE),
        @INVOICETO = ISNULL(H.INVOICETO, ''),
        @SHIPPEDPER = ISNULL(H.SHIPPEDPER, ''),
        @SHIPPEDFROM = ISNULL(H.SHIPPEDFROM, ''),
        @SHIPPEDTO = ISNULL(H.SHIPPEDTO, ''),
        @CONTRACTNO = ISNULL(H.CONTRACTNO, ''),
        @CONTRACTDATE = H.CONTRACTDATE,
        @PURCHASEORDERNO = ISNULL(H.PURCHASEORDERNO, ''),
        @PURCHASEORDERDATED = H.PURCHASEORDERDATED,
        @SALESCONTRACTHEADERID = H.SALESCONTRACTHEADERID,
        @BINNO = ISNULL(U.strBINNo, ''),
        @TIN = ISNULL(U.strTIN, '')
		--@UNITNAME = ISNULL(U.strDescription, '')
    FROM TBLPACKINGREQUESTHEADER H
    INNER JOIN ERP_HR.dbo.tblUnit U
        ON U.intUnitID = H.UNITID
    WHERE H.ID = @HEADERID AND H.ISACTIVE = 1

	-- Get SALESCONTRACTHEADERID via PISC header if not directly available
	IF @SALESCONTRACTHEADERID IS NULL
	BEGIN
		SELECT @SALESCONTRACTHEADERID = PIS.SALESQUOTATIONHEADERID
		FROM TBLPISCHEADER PIS
		WHERE PIS.ID = (
			SELECT PISCNUMBER FROM TBLPACKINGREQUESTHEADER WHERE ID = @HEADERID
		)
	END

	-- Get unit name from sales quotation header
   SELECT @UNITNAME = ISNULL(U.strDescription, '')
   FROM TBLSALESQUOTATIONHEADER SQ
   INNER JOIN ERP_HR.dbo.tblUnit U
       ON U.intUnitID = SQ.UNITID
   WHERE SQ.ID = @SALESCONTRACTHEADERID AND SQ.ISACTIVE = 1

    -- Get customer address via PISC header
    SELECT @CUSTOMERADDRESS = ISNULL(C.strAddress, '')
    FROM TBLPISCHEADER PIS
    INNER JOIN ERP_SAD.dbo.tblCustomer C
        ON C.intCusID = PIS.CUSTOMERID
    WHERE PIS.ID = (
        SELECT PISCNUMBER FROM TBLPACKINGREQUESTHEADER WHERE ID = @HEADERID
    )

    -- Get gross weight (sum across all lines)
    SELECT @GROSSWEIGHT = ISNULL(SUM(GROSSWEIGHT), 0)
    FROM TBLPACKINGREQUESTLINE
    WHERE PACKINGREQUESTHEADERID = @HEADERID AND ISACTIVE = 1

	-- Get net weight (sum across all lines)
	SELECT @NETWEIGHT = ISNULL(SUM(ADDITIONALWEIGHT), 0)
	FROM TBLPACKINGREQUESTLINE
	WHERE PACKINGREQUESTHEADERID = @HEADERID AND ISACTIVE = 1

    -- Get description of goods fields from sales quotation header
    SELECT 
        @PRODUCT_QUANTITY = ISNULL(PRODUCT_QUANTITY, ''),
        @DESCRIPTION_SPECIFICATION = ISNULL(DESCRIPTION_SPECIFICATION, '')
    FROM TBLSALESQUOTATIONHEADER
    WHERE ID = @SALESCONTRACTHEADERID AND ISACTIVE = 1

	-- Get incoterm, currency, destination port from sales quotation header
	SELECT 
		@DESTINATIONPORT = ISNULL(SQ.DESTINATIONPORT, ''),
		@INCOTERM = ISNULL(IC.NAME, ''),
		@CURRENCYNAME = ISNULL(CR.NAME, '')
	FROM TBLSALESQUOTATIONHEADER SQ
	LEFT JOIN TBLINCOTERM IC
		ON IC.ID = SQ.INCOTERM
	LEFT JOIN TBLCURRENCY CR
		ON CR.ID = SQ.CURRENCY
	WHERE SQ.ID = @SALESCONTRACTHEADERID AND SQ.ISACTIVE = 1

	-- Get total amount (sum from sales quotation lines)
	SELECT @TOTALAMOUNT = ISNULL(SUM(TOTALAMOUNT), 0)
	FROM TBLSALESQUOTATIONLINE
	WHERE SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID AND ISACTIVE = 1

	-- Build TERMS: Incoterm + Destination Port
	SET @TERMS = @INCOTERM 
		+ CASE WHEN @DESTINATIONPORT != '' THEN CHAR(13) + CHAR(10) + @DESTINATIONPORT ELSE '' END

	-- Build TOTALPRICE: Incoterm + Currency + Total Amount
	SET @TOTALPRICE = @INCOTERM 
		+ CASE WHEN @CURRENCYNAME != '' THEN ' ' + @CURRENCYNAME ELSE '' END
		+ ' ' + LTRIM(RTRIM(FORMAT(@TOTALAMOUNT, '#,##0.00')))

	--SET @TOTALAMOUNTINWORDS = UPPER(@CURRENCYNAME) + UPPER(dbo.MoneyToWords(@TOTALAMOUNT, 'en'))
	SET @TOTALAMOUNTINWORDS = UPPER(RTRIM(@CURRENCYNAME)) + ' ' + UPPER(dbo.MoneyToWords(@TOTALAMOUNT, 'en'))

    -- Build the item block using cursor (same logic as SPSALESCONTRACTREPORT)
    DECLARE @ITEMTITLE NVARCHAR(MAX)
    DECLARE @ITEMNAME NVARCHAR(200)
    DECLARE @QUANTITY DECIMAL(18,2)
    DECLARE @UOM NVARCHAR(500)
    DECLARE @QUALITY NVARCHAR(MAX)
    DECLARE @SIZE NVARCHAR(MAX)
    DECLARE @CONSTRUCTION NVARCHAR(MAX)
    DECLARE @WEIGHT NVARCHAR(MAX)
    DECLARE @SLIT NVARCHAR(MAX)
    DECLARE @SCRIM NVARCHAR(MAX)
    DECLARE @PACKINGDETAILS NVARCHAR(MAX)
    DECLARE @REMARKS NVARCHAR(1000)
    DECLARE @ITEM_NUMBER INT
    DECLARE @SUB_POINT_NUMBER INT
    DECLARE @PREV_ITEM_NUMBER INT = 0

    DECLARE item_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT
            ITEM_NUMBER,
            SUB_POINT_NUMBER,
            ITEMTITLE,
            ITEMNAME,
            QUANTITY,
            UOM,
            QUALITY,
            SIZE,
            CONSTRUCTION,
            WEIGHT,
            SLIT,
            SCRIM,
            PACKINGDETAILS,
            REMARKS
        FROM (
            SELECT
                L.ITEMTITLE,
                I.strProductName AS ITEMNAME,
                L.QUANTITY,
                U.strUOM AS UOM,
                L.QUALITY,
                L.SIZE,
                L.CONSTRUCTION,
                L.WEIGHT,
                L.SLIT,
                L.SCRIM,
                L.PACKINGDETAILS,
                L.REMARKS,
                L.SERIALNO,
                DENSE_RANK() OVER (ORDER BY L.ITEMTITLE) AS ITEM_NUMBER,
                ROW_NUMBER() OVER (PARTITION BY L.ITEMTITLE ORDER BY L.SERIALNO) AS SUB_POINT_NUMBER
            FROM TBLSALESQUOTATIONLINE L
            INNER JOIN ERP_SAD.dbo.tblItem I
                ON L.ITEMID = I.intID
            LEFT JOIN ERP_SAD.dbo.tblUOM U
                ON L.UOMID = U.intID
            WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
                AND L.ISACTIVE = 1
        ) AS T
        ORDER BY ITEM_NUMBER, SUB_POINT_NUMBER

    OPEN item_cursor
    FETCH NEXT FROM item_cursor INTO 
        @ITEM_NUMBER, @SUB_POINT_NUMBER, @ITEMTITLE, @ITEMNAME,
        @QUANTITY, @UOM, @QUALITY, @SIZE, @CONSTRUCTION, @WEIGHT,
        @SLIT, @SCRIM, @PACKINGDETAILS, @REMARKS

    WHILE @@FETCH_STATUS = 0
    BEGIN
        IF @ITEM_NUMBER != @PREV_ITEM_NUMBER
        BEGIN
            IF @ITEM_BLOCK != ''
                SET @ITEM_BLOCK = @ITEM_BLOCK + CHAR(13) + CHAR(10)

            SET @ITEM_BLOCK = @ITEM_BLOCK 
                + CAST(@ITEM_NUMBER AS VARCHAR(10)) + '/. '
                + ISNULL(@ITEMTITLE, '') + CHAR(13) + CHAR(10)

            SET @PREV_ITEM_NUMBER = @ITEM_NUMBER
        END

        -- Add sub-point line
        SET @ITEM_BLOCK = @ITEM_BLOCK 
            + CHAR(64 + @SUB_POINT_NUMBER) + ') '
            + CASE 
                WHEN @QUANTITY = CAST(CAST(@QUANTITY AS INT) AS DECIMAL(18,2)) 
                    THEN CAST(CAST(@QUANTITY AS INT) AS VARCHAR(20))
                ELSE FORMAT(@QUANTITY, '0.##')
              END
            + CASE WHEN @UOM IS NOT NULL AND @UOM != '' THEN @UOM ELSE '' END
            + CASE WHEN @ITEMNAME IS NOT NULL AND @ITEMNAME != '' THEN ', ' + @ITEMNAME ELSE '' END
            + CASE WHEN @QUALITY IS NOT NULL AND @QUALITY != '' THEN ', ' + @QUALITY ELSE '' END
            + CASE WHEN @SIZE IS NOT NULL AND @SIZE != '' THEN ', ' + @SIZE ELSE '' END
            + CASE WHEN @CONSTRUCTION IS NOT NULL AND @CONSTRUCTION != '' THEN ', ' + @CONSTRUCTION ELSE '' END
            + CASE WHEN @WEIGHT IS NOT NULL AND @WEIGHT != '' THEN ', ' + @WEIGHT ELSE '' END
            + CASE WHEN @SLIT IS NOT NULL AND @SLIT != '' THEN ', ' + @SLIT ELSE '' END
            + CASE WHEN @SCRIM IS NOT NULL AND @SCRIM != '' THEN ', ' + @SCRIM ELSE '' END
            + CASE WHEN @PACKINGDETAILS IS NOT NULL AND @PACKINGDETAILS != '' THEN ', ' + @PACKINGDETAILS ELSE '' END
            + CASE WHEN @REMARKS IS NOT NULL AND @REMARKS != '' THEN ', ' + @REMARKS ELSE '' END
            + CHAR(13) + CHAR(10)

        FETCH NEXT FROM item_cursor INTO 
            @ITEM_NUMBER, @SUB_POINT_NUMBER, @ITEMTITLE, @ITEMNAME,
            @QUANTITY, @UOM, @QUALITY, @SIZE, @CONSTRUCTION, @WEIGHT,
            @SLIT, @SCRIM, @PACKINGDETAILS, @REMARKS
    END

    CLOSE item_cursor
    DEALLOCATE item_cursor

	-- Build MARKS: grouped by ITEMNAME, with distinct QUALITY values
	SELECT @MARKS = @MARKS 
		+ CASE WHEN @MARKS != '' THEN ', ' ELSE '' END
		+ ISNULL(ITEMNAME, '')
		+ CASE WHEN SIZE IS NOT NULL AND SIZE != '' THEN ' ' + SIZE ELSE '' END
		+ CASE WHEN QUALITIES != '' THEN ', ' + QUALITIES ELSE '' END
	FROM (
		SELECT 
			ITEMNAME,
			MAX(SIZE) AS SIZE,
			STRING_AGG(QUALITY, ', ') AS QUALITIES
		FROM (
			SELECT DISTINCT
				I.strProductName AS ITEMNAME,
				L.SIZE,
				L.QUALITY
			FROM TBLSALESQUOTATIONLINE L
			INNER JOIN ERP_SAD.dbo.tblItem I
				ON L.ITEMID = I.intID
			WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
				AND L.ISACTIVE = 1
				AND L.QUALITY IS NOT NULL AND L.QUALITY != ''
		) AS DistinctRows
		GROUP BY ITEMNAME
	) AS Grouped

	-- Build TRUSSES from PACKINGDETAILS
	DECLARE @PD NVARCHAR(MAX)
	DECLARE @TRUSS_POS INT
	DECLARE @NUM_START INT
	DECLARE @NUM_STR VARCHAR(20)
	DECLARE @TSN INT

	DECLARE truss_cursor CURSOR LOCAL FAST_FORWARD FOR
		SELECT L.PACKINGDETAILS, L.SERIALNO
		FROM TBLSALESQUOTATIONLINE L
		WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
			AND L.ISACTIVE = 1
			AND L.PACKINGDETAILS LIKE '%TRUS%'
		ORDER BY L.SERIALNO

	OPEN truss_cursor
	FETCH NEXT FROM truss_cursor INTO @PD, @TSN

	WHILE @@FETCH_STATUS = 0
	BEGIN
		-- Find position of 'TRUSSES'
		SET @TRUSS_POS = PATINDEX('%TRUS%', @PD)
    
		-- Extract the number portion before 'TRUSSES'
		SET @NUM_STR = ''
		SET @NUM_START = @TRUSS_POS - 1
    
		-- Skip spaces before TRUSSES
		WHILE @NUM_START > 0 AND SUBSTRING(@PD, @NUM_START, 1) = ' '
			SET @NUM_START = @NUM_START - 1
    
		-- Read digits backwards
		WHILE @NUM_START > 0 AND SUBSTRING(@PD, @NUM_START, 1) LIKE '[0-9]'
		BEGIN
			SET @NUM_STR = SUBSTRING(@PD, @NUM_START, 1) + @NUM_STR
			SET @NUM_START = @NUM_START - 1
		END
    
		IF @NUM_STR != ''
		BEGIN
			IF @TRUSSES != ''
				SET @TRUSSES = @TRUSSES + ' '
			SET @TRUSSES = @TRUSSES + '1-' + @NUM_STR
		END
    
		FETCH NEXT FROM truss_cursor INTO @PD, @TSN
	END

	CLOSE truss_cursor
	DEALLOCATE truss_cursor

	-- Build CARTONS from PACKINGDETAILS
	DECLARE @CPD NVARCHAR(MAX)
	DECLARE @CARTON_POS INT
	DECLARE @CNUM_START INT
	DECLARE @CNUM_STR VARCHAR(20)
	DECLARE @CSN INT

	DECLARE carton_cursor CURSOR LOCAL FAST_FORWARD FOR
		SELECT L.PACKINGDETAILS, L.SERIALNO
		FROM TBLSALESQUOTATIONLINE L
		WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
			AND L.ISACTIVE = 1
			AND L.PACKINGDETAILS LIKE '%CARTON%'
		ORDER BY L.SERIALNO

	OPEN carton_cursor
	FETCH NEXT FROM carton_cursor INTO @CPD, @CSN

	WHILE @@FETCH_STATUS = 0
	BEGIN
		SET @CARTON_POS = PATINDEX('%CARTON%', @CPD)
		SET @CNUM_STR = ''
		SET @CNUM_START = @CARTON_POS - 1

		WHILE @CNUM_START > 0 AND SUBSTRING(@CPD, @CNUM_START, 1) = ' '
			SET @CNUM_START = @CNUM_START - 1

		WHILE @CNUM_START > 0 AND SUBSTRING(@CPD, @CNUM_START, 1) LIKE '[0-9]'
		BEGIN
			SET @CNUM_STR = SUBSTRING(@CPD, @CNUM_START, 1) + @CNUM_STR
			SET @CNUM_START = @CNUM_START - 1
		END

		IF @CNUM_STR != ''
		BEGIN
			IF @CARTONS != ''
				SET @CARTONS = @CARTONS + ' '
			SET @CARTONS = @CARTONS + '1-' + @CNUM_STR
		END

		FETCH NEXT FROM carton_cursor INTO @CPD, @CSN
	END

	CLOSE carton_cursor
	DEALLOCATE carton_cursor

	-- Build BUNDLES from PACKINGDETAILS
	DECLARE @BPD NVARCHAR(MAX)
	DECLARE @BUNDLE_POS INT
	DECLARE @BNUM_START INT
	DECLARE @BNUM_STR VARCHAR(20)
	DECLARE @BSN INT

	DECLARE bundle_cursor CURSOR LOCAL FAST_FORWARD FOR
		SELECT L.PACKINGDETAILS, L.SERIALNO
		FROM TBLSALESQUOTATIONLINE L
		WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
			AND L.ISACTIVE = 1
			AND L.PACKINGDETAILS LIKE '%BUNDLE%'
		ORDER BY L.SERIALNO

	OPEN bundle_cursor
	FETCH NEXT FROM bundle_cursor INTO @BPD, @BSN

	WHILE @@FETCH_STATUS = 0
	BEGIN
		SET @BUNDLE_POS = PATINDEX('%BUNDLE%', @BPD)
		SET @BNUM_STR = ''
		SET @BNUM_START = @BUNDLE_POS - 1

		WHILE @BNUM_START > 0 AND SUBSTRING(@BPD, @BNUM_START, 1) = ' '
			SET @BNUM_START = @BNUM_START - 1

		WHILE @BNUM_START > 0 AND SUBSTRING(@BPD, @BNUM_START, 1) LIKE '[0-9]'
		BEGIN
			SET @BNUM_STR = SUBSTRING(@BPD, @BNUM_START, 1) + @BNUM_STR
			SET @BNUM_START = @BNUM_START - 1
		END

		IF @BNUM_STR != ''
		BEGIN
			IF @BUNDLES != ''
				SET @BUNDLES = @BUNDLES + ' '
			SET @BUNDLES = @BUNDLES + '1-' + @BNUM_STR
		END

		FETCH NEXT FROM bundle_cursor INTO @BPD, @BSN
	END

	CLOSE bundle_cursor
	DEALLOCATE bundle_cursor

    -- Return all values as single row
    SELECT 
        @INVOICENUMBER AS INVOICENUMBER,
		FORMAT(@INVOICEDATE, 'dd-MM-yyyy') AS INVOICEDATE,
        UPPER(@INVOICETO) AS INVOICETO,
        @CUSTOMERADDRESS AS CUSTOMERADDRESS,
        @SHIPPEDPER AS SHIPPEDPER,
        @SHIPPEDFROM AS SHIPPEDFROM,
        @SHIPPEDTO AS SHIPPEDTO,
        @CONTRACTNO AS CONTRACTNO,
		FORMAT(@CONTRACTDATE, 'dd-MM-yyyy') AS CONTRACTDATE,
        @PURCHASEORDERNO AS PURCHASEORDERNO,
		FORMAT(@PURCHASEORDERDATED, 'dd-MM-yyyy') AS PURCHASEORDERDATED,
        @BINNO AS BINNO,
        @TIN AS TIN,
		@UNITNAME AS UNITNAME,
        @GROSSWEIGHT AS GROSSWEIGHT,
		@NETWEIGHT AS NETWEIGHT,
        @PRODUCT_QUANTITY AS PRODUCT_QUANTITY,
        @DESCRIPTION_SPECIFICATION AS DESCRIPTION_SPECIFICATION,
        @ITEM_BLOCK AS ITEM_BLOCK,
		@TERMS AS TERMS,
		@TOTALPRICE AS TOTALPRICE,
		@TOTALAMOUNTINWORDS AS TOTALAMOUNTINWORDS,
		@DESTINATIONPORT AS DESTINATIONPORT,
		UPPER(@MARKS) AS MARKS,
		CASE WHEN @TRUSSES != '' THEN 'TRUSS NO. ' + @TRUSSES ELSE '' END AS TRUSSNO,
		CASE WHEN @CARTONS != '' THEN 'CARTON NO. ' + @CARTONS ELSE '' END AS CARTONNO,
		CASE WHEN @BUNDLES != '' THEN 'BUNDLE NO. ' + @BUNDLES ELSE '' END AS BUNDLENO
END