CREATE PROCEDURE [dbo].[SPUPDATEPISC]
(
@ID									INT,
@SALESQUOTATIONHEADERID				INT,
@AGREEMENTTYPEID					VARCHAR(50),
@DATE								VARCHAR(100),
@EXPIREDATE							VARCHAR(100),
@SHIPMENTDATE						VARCHAR(100),
@SHIPMENTMODEID						INT,
@PAYMENTTERMID						INT,
@DELIVERYTERMID						INT,
@TERMSCONDITION						VARCHAR(MAX),
@TOSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTPORTID					INT,
@TODISCHARGEPORT					INT,
@TARRIFCODE							VARCHAR(100),
@HSCODE								VARCHAR(100),
@BUYERREGNO							VARCHAR(100),
@INCOTERM							INT,
@CURRENCYID							INT,
@DESCRIPTIONS						VARCHAR(MAX),

@BUYERBANKDETAILS					VARCHAR(500),
@SELLERBANKID						INT,
@BUYERCOUNTRYHSCODE					VARCHAR(100),
@TRANSHIPMENT						INT,
@PARTIALSHIPMENT					INT,
@ORIGINOFCOUNTRY					VARCHAR(50),
@BUYERORDERCONFIRMDATE				VARCHAR(50),
@NOTIFYPARTY						VARCHAR(500),
@OTHERSPAYTERM						VARCHAR(500),

@MODULECODE							VARCHAR(100),
@ENROLL								INT,
@UNITID								INT,
@PROCESSNAME						VARCHAR(100),
@MessageName						VARCHAR(100),
@Notification						VARCHAR(100),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN TRY
DECLARE @LOG VARCHAR(MAX),@AGTYPEID INT,@ProcessCode VARCHAR(50),@check int
SET @AGTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@AGREEMENTTYPEID)

UPDATE TBLPISCHEADER
SET AGREEMENTTYPEID=@AGTYPEID,DATE=@DATE,EXPIREDATE=@EXPIREDATE,SHIPMENTDATE=@SHIPMENTDATE,SHIPMENTMODEID=@SHIPMENTMODEID,PAYMENTTERMID=@PAYMENTTERMID,
TERMSCONDITION=@TERMSCONDITION,TOSHIPMENTCOUNTRYID=@TOSHIPMENTCOUNTRYID,FROMSHIPMENTCOUNTRYID=@FROMSHIPMENTCOUNTRYID,FROMSHIPMENTPORTID=@FROMSHIPMENTPORTID,
TODISCHARGEPORT=@TODISCHARGEPORT,TARRIFCODE=@TARRIFCODE,HSCODE=@HSCODE,INCOTERM=@INCOTERM,DESCRIPTIONS=@DESCRIPTIONS,BUYERREGNO=@BUYERREGNO,CURRENCYID=@CURRENCYID,
DELIVERYTERMID=@DELIVERYTERMID,BUYERBANKDETAILS=@BUYERBANKDETAILS,SELLERBANKID=@SELLERBANKID,BUYERCOUNTRYHSCODE=@BUYERCOUNTRYHSCODE,TRANSHIPMENT=@TRANSHIPMENT,
PARTIALSHIPMENT=@PARTIALSHIPMENT,ORIGINOFCOUNTRY=@ORIGINOFCOUNTRY,BUYERORDERCONFIRMDATE=@BUYERORDERCONFIRMDATE,NOTIFYPARTY=@NOTIFYPARTY,OTHERSPAYTERM=@OTHERSPAYTERM

WHERE ID=@ID
SELECT @check=COUNT(QTYCHECK)
    FROM TBLPISCLINE where PISCHEADER=@ID
IF @check>0
begin
declare @piid int,@NUMBER VARCHAR(50),@formattedDate VARCHAR(50)
	SELECT @piid=isnull(MAX(ID),0) FROM TBLPISCHEADER;
	set @piid=@piid+1;
	

	  SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  	SET @NUMBER=(CASE WHEN @AGREEMENTTYPEID='PI' THEN 'PI' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='SC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='PITOSC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) END)
insert into TBLPISCHEADER(
   LOADINGPLACE,
	LOADINGBYID,
	NUMBER,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	ISACTIVE,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	PITOSC,
	ISPROCESSEDWITHAPPROVAL

)
select  LOADINGPLACE,
	LOADINGBYID,
	@NUMBER,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	ISACTIVE,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	PITOSC,
	ISPROCESSEDWITHAPPROVAL from TBLPISCHEADER where ID=@ID
	SELECT @piid=isnull(MAX(ID),0) FROM TBLPISCHEADER where DOCUMENTCREATEDBY=@ENROLL	
update TBLPISCLINE set PISCHEADER=@piid where QTYCHECK=1 AND PISCHEADER=@ID
EXEC SPAPPROVEMATRIXHISTORY 'PEND',@piid,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
end

set @LOG='UPDATE TBLPISCHEADER SET AGREEMENTTYPEID='+CAST(@AGREEMENTTYPEID as varchar(100))+ 'UNITID='+CAST(@UNITID as varchar(100))+'EXPIREDATE='+CAST(@EXPIREDATE as varchar(100))+'SHIPMENTDATE='+CAST(@SHIPMENTDATE as varchar(100))+
'PAYMENTTERMID='+CAST(@PAYMENTTERMID as varchar(100))+'TOSHIPMENTCOUNTRYID='+CAST(@TOSHIPMENTCOUNTRYID as varchar(100))+'BUYERBANKDETAILS='+@BUYERBANKDETAILS+'SELLERBANKID='+CAST(@SELLERBANKID AS VARCHAR(50))
--set @Msg=@ID
SET @ProcessCode=@PROCESSNAME+CAST(@ID AS VARCHAR(100))
set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MessageName)
EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
exec SPActivityLog @Log,'',@ID,@ModuleCode,@PROCESSNAME,@UNITID,@ENROLL

END TRY
BEGIN CATCH
SET @Msg=ERROR_MESSAGE()
END CATCH