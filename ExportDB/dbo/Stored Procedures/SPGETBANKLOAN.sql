
CREATE PROCEDURE [dbo].[SPGETBANKLOAN]
(
@LENDERBANK			INT,
@SDATE				DATE,
@EDATE				DATE
)
AS
BEGIN
SELECT BT.BANKNAME AS LENDERBANK,
UT.NAME AS BORROWERUNIT,LOANTYPE.LOANTYPE,PS.REFLOANNUMBER,
CURR.NAME AS CURRENCY,PS.AMOUNT,ISNULL(PS.CRATE,0.0) AS CONRATE,
ISNULL(PS.AMOUNT,0.0)*ISNULL(PS.CRATE,0.0) AS TOTALBDT,
CAST(CAST(PS.PAYMENTDATE AS DATE) AS VARCHAR(100)) AS PAYMENTDATE
FROM TBLPAYMENTRESCHEDULE PS,TBLBANKFORTREASURY BT,TBLUNITFORTREASURY UT,TBLPAYMENTRESCHEDULETYPE TYPE,
TBLBANKLOAN BL,TBLCURRENCY CURR,TBLLOANTYPE LOANTYPE
WHERE PS.BANKID=BT.BANKID AND
PS.BORROWERUNITID=UT.ID   AND
PS.TYPEID=TYPE.ID		  AND
PS.REFID=BL.ID			  AND
LOANTYPE.ID=BL.LOANTYPEID AND
CURR.ID=BL.CURRENCYID	  AND
PS.ISACTIVE=1			  AND
(@LENDERBANK=0 OR BL.LENDERBANKID=@LENDERBANK)
END;