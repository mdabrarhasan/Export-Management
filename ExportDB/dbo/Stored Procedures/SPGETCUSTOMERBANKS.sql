CREATE PROCEDURE [dbo].[SPGETCUSTOMERBANKS]
AS
BEGIN
    SELECT
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE,
        CREATEDBY,
        CREATEDDATE,
        UPDATEDBY,
        UPDATEDDATE
    FROM TBLCUSTOMERBANK
    WHERE ISACTIVE != 0
    ORDER BY ID DESC
END;