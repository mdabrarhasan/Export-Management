
--drop PROCEDURE [dbo].[SPUPDATEQUOTATIONLINE]
create PROCEDURE [dbo].[SPUPDATEQUOTATIONLINE]
(
@TYPEQUOTATIONINSERTLINE			TYPEQUOTATIONINSERTLINE READONLY,
@QUOTATIONLINEID					INT,
@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN

	DECLARE @NUMBER VARCHAR(100),@AGREEMENTTYPE INT,@formattedDate VARCHAR(8),
	@ITEMID INT,@QUANTITY DECIMAL(18,2),@PRICE DECIMAL(18,2),@DISCOUNTID INT,@DISCOUNT DECIMAL(18,2),@VATID INT,@VATAMOUNT DECIMAL(18,2),
	@COMMISSION DECIMAL(18,2),@TOTALAMOUNT DECIMAL(18,2),@REMARKS VARCHAR(MAX),@HSCODELINE VARCHAR(100),
	@TOLARANCEID DECIMAL(18,2),@FROMSHIPMENTSCHEDULEDATE VARCHAR(50),@TOSHIPMENTSCHEDULEDATE VARCHAR(50),@BATCHID VARCHAR(100),@SERIALNO INT,
	@hid int,@lineid int,@nextactiontacker int,@checkapproid int,
	@submenuid int,@scopdeid int,@BATCHIDAPPHISTORY VARCHAR(50),@ProcessID int,@ProcessCode varchar(100),@DocStatusID int,@sqllog nvarchar(max),@initiateid int,
	@approvecheck int,@checkcom int,@PITOSCID INT,@CHECKPITOSCCHECK INT,@ITEMSPEBATCH VARCHAR(1000),@Toleranceid int,
	@UOMID INT,@THIKNESS DECIMAL(18,2),@WIDTH DECIMAL(18,2),@LENGTH DECIMAL(18,2),@TREATMENTLEVEL VARCHAR(500),@TREATMENTDIRECTIONID INT,@COREID INT,@REALOD VARCHAR(500),
	@DISEREDDATEOFDELIVERY VARCHAR(500),@TENTATIVEDATEOFDELIVERY VARCHAR(500),@DESCRIPTIONS VARCHAR(MAX)

	 DECLARE SQL_CURSOR CURSOR FOR  
	 SELECT ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,VATID,VATAMOUNT,TOLERANCEID,TOTALAMOUNT,REMARKS,DESCRIPTIONS,FROMSHIPMENTSCHEDULEDATE,TOSHIPMENTSCHEDULEDATE,HSCODE,
	 UOMID,THIKNESS,WIDTH,LENGTH,TREATMENTLEVEL,TREATMENTDIRECTIONID,COREID,REALOD,DISEREDDATEOFDELIVERY,TENTATIVEDATEOFDELIVERY
	 FROM @TYPEQUOTATIONINSERTLINE
	 OPEN SQL_CURSOR
	 FETCH NEXT FROM SQL_CURSOR INTO @ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONS,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
	 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
	 
	  WHILE @@FETCH_STATUS = 0  
	  BEGIN
	  UPDATE TBLQUOTATIONLINE
	  SET ITEMID=@ITEMID,QUANTITY=@QUANTITY,PRICE=@PRICE,DISCOUNTID=@DISCOUNTID,DISCOUNT=@DISCOUNT,TOTALAMOUNT=@TOTALAMOUNT,
	  UOMID=@UOMID,THIKNESS=@THIKNESS,WIDTH=@WIDTH,LENGTH=@LENGTH,TREATMENTLEVEL=@TREATMENTLEVEL,TREATMENTDIRECTIONID=@TREATMENTDIRECTIONID,
	  COREID=@COREID,REALOD=@REALOD,DISEREDDATEOFDELIVERY=@DISEREDDATEOFDELIVERY,TENTATIVEDATEOFDELIVERY=@TENTATIVEDATEOFDELIVERY,
	  REMARKS=@REMARKS,DESCRIPTIONS=@DESCRIPTIONS,TOLERANCEID=@Toleranceid WHERE ID=@QUOTATIONLINEID
	  
	  FETCH NEXT FROM sql_cursor INTO @ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONS,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
		 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
	  END;
	  --set @Msg=@id
	  SET @ProcessCode=(SELECT QUOTATIONNUMBER FROM TBLQUOTATIONHEADER WHERE ID=(SELECT QUOTATIONHEADERID FROM TBLQUOTATIONLINE WHERE ID=@QUOTATIONLINEID))

	  SET @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@MODULECODE) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
	 
	  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
END;