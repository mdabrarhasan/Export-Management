CREATE PROCEDURE [dbo].[SPGETOCFPILISTPENDING]
(
@ID			INT
)
AS
BEGIN
SELECT LINE.ID AS ID,QH.ID AS HEADERID,LIST.intID AS ITEMID,LIST.strProductCode AS PRODUCTCODE,LIST.strProductName AS ITEMNAME,'' AS BUYERNAME,0 AS BUYERID,
LINE.QUANTITY,LINE.PRICE,ISNULL(LINE.DISCOUNTID,0) AS DISCOUNTID,CAST(LINE.DISCOUNT AS VARCHAR(50)) AS DISCOUNT,LINE.TOTALAMOUNT,LINE.UOMID,UOM.strUOM AS UOM,
LINE.THIKNESS,LINE.WIDTH,LINE.LENGTH,ISNULL(LINE.TREATMENTLEVEL,0) AS TREATMENTLEVEL,ISNULL(LINE.TREATMENTDIRECTIONID,0) AS TREATMENTDIRECTIONID,DIR.strTreatmentDirection AS TREATMENTDIRECTION,
ISNULL(LINE.COREID,0) AS COREID,COREID.strBiaxFlimCoreID AS CORENAME,
CAST(CAST(LINE.DISEREDDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS DISEREDDATEOFDELIVERY,
CAST(CAST(LINE.TENTATIVEDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS TENTATIVEDATEOFDELIVERY,LINE.REMARKS,
LINE.DESCRIPTIONS,LINE.REALOD,LINE.TOLERANCEID,'' AS TOLERANCE
FROM 
TBLQUOTATIONHEADER QH										INNER JOIN TBLQUOTATIONLINE						LINE
ON QH.ID=LINE.QUOTATIONHEADERID								INNER JOIN ERP_SAD.DBO.tblItem					LIST
ON LINE.ITEMID=LIST.intID									LEFT JOIN TBLDISCOUNT							DIS
ON LINE.DISCOUNTID=DIS.ID									INNER JOIN ERP_SAD.DBO.tblUOM					UOM
ON LINE.UOMID=UOM.intID										LEFT JOIN  ERP_SAD.DBO.tblTreatmentDirection		DIR			
ON LINE.TREATMENTDIRECTIONID=DIR.intTreatmentDirection		LEFT JOIN  ERP_SAD.DBO.tblBiaxFlimCoreID			COREID
ON LINE.COREID=COREID.intBiaxFlimCoreID						
WHERE QH.ID=@ID AND LINE.ISACTIVE=1 
AND LINE.ID NOT IN (SELECT QUOTATIONLINEID FROM TBLPRICECONFIRMLINE WHERE PRICECONFIRMHEADERID IN (SELECT ID FROM TBLPRICECONFIRMHEADER WHERE PROFORMAINVOICEHEADERID=@ID))
END;