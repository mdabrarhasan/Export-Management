
CREATE PROCEDURE [dbo].[SPGETDATAFORINTERESTAPPROVAL]
(
@unitid			INT,
@Code			VARCHAR(100),
@Enroll			INT,		
@ID				VARCHAR(100)
)
AS
BEGIN
	DECLARE @CHECKINT INT
	SET @CHECKINT=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT')
	SELECT IC.ID AS ID,IC.LENDERUNITID,LENDERUNIT.strUnit AS LENDERUNIT,IC.BORROWERUNITID,BORROWERUNIT.strUnit AS BORROWERUNIT,
	IC.AMOUNT AS AMOUNT,FORMAT(IC.AMOUNT,'N2') AS VAMOUNT,
	CAST(CAST(IC.STARTDATE AS DATE) AS VARCHAR(100)) STARTDATE,
	CAST(CAST(IC.STARTDATE AS DATE) AS VARCHAR(100)) ENDDATE,
	IC.NOOFDAYS,IC.INTERESTRATE,
	IC.INTERESTAMT,FORMAT(IC.INTERESTAMT,'N2') AS VINTERESTAMT,
	IC.DETAILS,
	CAST(CAST(IC.CREATEDDATE AS DATE) AS VARCHAR(100)) CREATEDDATE,
	CAST(CAST(IC.UPDATEDDATE AS DATE) AS VARCHAR(100)) UPDATEDDATE,
	IC.CREATEDBY,IC.UPDATEDBY,DOC.CODE AS DOCSTATUSCODE,DOC.NAME AS STATUS,APPHIS.ID HID
	FROM TBLINTERESTCALCULATION IC					INNER JOIN ERP_HR.DBO.TBLUNIT LENDERUNIT
	ON IC.LENDERUNITID=LENDERUNIT.intUnitID			INNER JOIN ERP_HR.DBO.TBLUNIT		BORROWERUNIT
	ON IC.BORROWERUNITID=BORROWERUNIT.intUnitID		INNER JOIN TBLAPPROVERMATRIXHISTORY APPHIS
	ON IC.ID=APPHIS.PROCESSID						INNER JOIN TBLDOCUMENTSTATUS		DOC
	ON APPHIS.DOCUMENTSTATUSID=DOC.ID
	WHERE APPHIS.DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@ID)
	AND IC.ISACTIVE <> 0 AND 
	APPHIS.SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=TRIM(@Code)) AND APPHIS.ACTIONTAKERID=@Enroll 
	AND APPHIS.DOCUMENTSTATUSID <> @CHECKINT
    ORDER BY CREATEDDATE DESC
END;