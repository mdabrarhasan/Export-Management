
/* ============================================================
   Master Type Stored Procedures
   Tables: TBLSIZE, TBLWEIGHT, TBLCONSTRUCTION, TBLSLIT, TBLSCRIM, TBLQUALITY
   ============================================================ */

/* 1) GET ALL BY TYPE */
CREATE   PROCEDURE [dbo].[SPMASTERTYPEGETALL]
    @MASTERTYPE VARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON;

    SET @MASTERTYPE = UPPER(ISNULL(LTRIM(RTRIM(@MASTERTYPE)), ''));

    IF @MASTERTYPE = 'SIZE'
    BEGIN
        SELECT [ID], 'SIZE' AS [MASTERTYPE], [SIZE] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLSIZE]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    IF @MASTERTYPE = 'WEIGHT'
    BEGIN
        SELECT [ID], 'WEIGHT' AS [MASTERTYPE], [WEIGHT] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLWEIGHT]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    IF @MASTERTYPE = 'CONSTRUCTION'
    BEGIN
        SELECT [ID], 'CONSTRUCTION' AS [MASTERTYPE], [CONSTRUCTION] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLCONSTRUCTION]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    IF @MASTERTYPE = 'SLIT'
    BEGIN
        SELECT [ID], 'SLIT' AS [MASTERTYPE], [SLIT] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLSLIT]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    IF @MASTERTYPE = 'SCRIM'
    BEGIN
        SELECT [ID], 'SCRIM' AS [MASTERTYPE], [SCRIM] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLSCRIM]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    IF @MASTERTYPE = 'QUALITY'
    BEGIN
        SELECT [ID], 'QUALITY' AS [MASTERTYPE], [QUALITY] AS [VALUE], [ISACTIVE], [CREATEDBY], [CREATEDDATE], [UPDATEDBY], [UPDATEDDATE]
        FROM [dbo].[TBLQUALITY]
        WHERE ISNULL([ISACTIVE], 1) = 1
        ORDER BY [ID] DESC;
        RETURN;
    END

    SELECT TOP 0
        CAST(NULL AS INT) AS [ID],
        CAST(NULL AS VARCHAR(50)) AS [MASTERTYPE],
        CAST(NULL AS VARCHAR(MAX)) AS [VALUE],
        CAST(NULL AS BIT) AS [ISACTIVE],
        CAST(NULL AS INT) AS [CREATEDBY],
        CAST(NULL AS DATE) AS [CREATEDDATE],
        CAST(NULL AS INT) AS [UPDATEDBY],
        CAST(NULL AS DATE) AS [UPDATEDDATE];
END