
/* 1) GET ALL */
CREATE   PROCEDURE [dbo].[SPSPCUSTOMERBANKGETALL]
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        [ID],
        [CUSTOMERNAME],
        [CUSTOMERBANKBRANCHNAME],
        [CUSTOMERBANKNAME],
        [CUSTOMERBANKADDRESSLINEONE],
        [CUSTOMERBANKADDRESSLINETWO],
        [CUSTOMERBANKADDRESSLINETHREE],
        [CUSTOMERBANKBINNO],
        [ISACTIVE],
        [CREATEDBY],
        [CREATEDDATE],
        [UPDATEDBY],
        [UPDATEDDATE]
    FROM [dbo].[TBLCUSTOMERBANK]
    WHERE ISNULL([ISACTIVE], 1) = 1
    ORDER BY [ID] DESC;
END