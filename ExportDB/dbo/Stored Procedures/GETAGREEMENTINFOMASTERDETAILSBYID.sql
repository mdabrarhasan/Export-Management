
CREATE Procedure [dbo].[GETAGREEMENTINFOMASTERDETAILSBYID]
(
@id				int,
@headerid		int
)

-- Exec GETAGREEMENTINFOMASTERDETAILSBYID 6,1068

AS
BEGIN
declare @unitid int
IF @id=0 
BEGIN
SELECT PH.ID AS HISTRYID,PH.ID AS AGREEMENTID,PH.UNITID,PH.NUMBER AS PINUMBER,PH.SALESQUOTATIONHEADERID,AGT.CODE AS AGREEMENTTYPEID,AGT.NAME AS AGREEMENTTYPE,CAST(CAST(PH.DATE AS DATE) AS VARCHAR(50)) AS PIDATE,CAST(CAST(PH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS PIEXPIREDATE,
PH.SHIPMENTMODEID,CAST(CAST(PH.SHIPMENTDATE AS DATE) AS VARCHAR(50))  AS SHIPMENTDATE,CAST(CAST(PH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,SQH.SQNUMBER,
SM.ID AS SHIPMENTID,SM.NAME AS SHIPMENT,PT.ID AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PH.HSCODE,PH.BUYERREGNO,PH.CURRENCYID,PH.DELIVERYTERMID,PH.DESCRIPTIONS,PH.TERMSCONDITION,
TSC.ID AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,FSC.ID AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
LP.ID AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,DP.ID AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL,
PH.TARRIFCODE,INCO.ID AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,DS.ID AS DOCSTATUSID,DS.NAME AS DOSSTATUS,'' AS CURRENCY,'' AS DELIVERYTERM,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
PH.NOTIFYPARTY,
SQH.TEXTFROMSHIPMENT,
'' AS DESTINATIONPORT

from TBLPISCHEADER PH				 INNER JOIN ERP_SAD.DBO.tblCustomer			   CUS
ON ph.CUSTOMERID=cus.intCusID		 LEFT JOIN TBLSALESQUOTATIONHEADER			   SQH		
ON PH.SALESQUOTATIONHEADERID=SQH.ID  LEFT JOIN TBLSHIPMENTMODE					   SM
ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
ON PH.INCOTERM=INCO.ID				 INNER JOIN TBLDOCUMENTSTATUS				   DS
ON PH.DOCUMENTSTATUSID=DS.ID		 INNER JOIN TBLAGREEMENTTYPE				   AGT
ON PH.AGREEMENTTYPEID=AGT.ID
WHERE PH.ID=@headerid AND PH.ISACTIVE=1
END; 
ELSE IF @id=1 
BEGIN
select @unitid=UNITID from TBLPISCHEADER where ID=@headerid
SELECT LINE.ID,
PISCHEADER,
@unitid as UNITID ,
BATCHID,
SERIALNO,
ITEMID,
LINE.HSCODE,
IITEM.strProductName AS ITEMNAME,
--case when IITEM.intUnitID=91 then 'KG' when IITEM.intUnitID=178 then 'pecs' when IITEM.intUnitID=182 then 'Pecs' end AS UOM,
--case when IITEM.intUnitID=91 then 'KG' when IITEM.intUnitID=178 then 'KG' when IITEM.intUnitID=182 then 'KG' end AS UOM,
'KG' as UOM,
QUANTITY,
PRICE,
DISCOUNTID,
DISCOUNT,
DIS.NAME AS disname,
LINE.TOLERANCEID,
REMARKS,
LINE.DESCRIPTIONS,
CAST(CAST(FROMSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) FROMSHIPMENTSCHEDULEDATE,
CAST(CAST(TOSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) TOSHIPMENTSCHEDULEDATE,
SALEH.SHIPMENTMODE,
SALEH.FROMSHIPMENT,
SALEH.TOSHIPMENT,
SALEH.TEXTFROMSHIPMENT,
SALEH.CURRENCY,
SALEH.LOADINGPORT,
SALEH.LOADINGPLACE,
SALEH.INCOTERM,
SALEH.PAYMENTTERMS,
SALEH.SHIPPINGPERIOD,
SALEH.TRANSPORTATIONMODE ,
'' AS SHIPMENTMARK,
SALEH.DESTINATIONPORT AS DESTINATIONPORT

FROM TBLPISCLINE LINE			INNER JOIN ERP_SAD.dbo.tblItem IITEM							
ON LINE.ITEMID=IITEM.intID  LEFT JOIN TBLTOLERANCE					 TOL
ON LINE.TOLERANCEID=TOL.ID      LEFT JOIN TBLDISCOUNT DIS ON LINE.DISCOUNTID=DIS.ID
INNER JOIN TBLPISCHEADER SH
ON LINE.PISCHEADER=SH.ID         INNER JOIN  TBLSALESQUOTATIONHEADER SALEH
ON SALEH.ID=SH.SALESQUOTATIONHEADERID
WHERE PISCHEADER=@headerid AND LINE.ISACTIVE=1

/*SELECT LINE.ID,PISCHEADER,BATCHID,SERIALNO,ITEMID,HSCODE,IITEM.strItemName AS ITEMNAME,IITEM.strUoM AS UOM,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,DIS.NAME AS disname,VATID,'' AS vatname,VATAMOUNT,TOTALAMOUNT,
0 AS TOLERANCEID,REMARKS,DESCRIPTIONS,CAST(CAST(FROMSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) FROMSHIPMENTSCHEDULEDATE,CAST(CAST(TOSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) TOSHIPMENTSCHEDULEDATE
FROM TBLPISCLINE LINE			INNER JOIN ERP_Inventory.DBO.tblItemList IITEM
ON LINE.ITEMID=IITEM.intItemID  
LEFT JOIN TBLDISCOUNT DIS ON LINE.DISCOUNTID=DIS.ID
WHERE PISCHEADER=@headerid AND LINE.ISACTIVE=1*/
--WHERE PISCHEADER=(SELECT ID FROM TBLPISCHEADER WHERE SALESQUOTATIONHEADERID=@headerid)
END;
ELSE IF @id=2
BEGIN
SELECT ID,SALESQUOTATIONHEADERID,B.STRPRODUCTNAME+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
	A.ITEMTYPEID,A.ITEMTITLE,
	'' AS SIZE,'' AS SLIT,'' AS SCRIM,'' AS CONSTRUCTION,'' AS QUALITY,'' AS WEIGHT,
	UOMID,UOM.strUOM AS UOM,BATCHID,SERIALNO,ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,
	TOTALAMOUNT,DESCRIPTIONS,REMARKS,CASE WHEN A.DISCOUNTID=0 THEN '' ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID=A.DISCOUNTID) END AS DISNAME
	FROM TBLSALESQUOTATIONLINE A,
	ERP_SAD.DBO.TBLITEM B,
	ERP_SAD.dbo.tblUOM UOM 
	WHERE A.ITEMID=B.INTID AND A.ISACTIVE=1 
	AND SALESQUOTATIONHEADERID=@HEADERID AND A.UOMID=UOM.intID ORDER BY A.ITEMID DESC
END
ELSE IF @id=3
BEGIN
select @unitid=UNITID from TBLPISCHEADER where ID=@headerid
SELECT LINE.ID,0 AS PISCHEADER,@unitid as UNITID,BATCHID,SERIALNO,ITEMID,LINE.HSCODE HSCODE,IITEM.strProductName AS ITEMNAME,case when IITEM.intUnitID=91 then 'KG' when IITEM.intUnitID=178 then 'pecs' when IITEM.intUnitID=182 then 'Pecs' end AS UOM,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,'' AS disname,TOTALAMOUNT,
0 AS TOLERANCEID,REMARKS,LINE.DESCRIPTIONS,FROMSHIPMENTSCHEDULEDATE AS FROMSHIPMENTSCHEDULEDATE,TOSHIPMENTSCHEDULEDATE AS TOSHIPMENTSCHEDULEDATE,
SALEH.SHIPMENTMODE,SALEH.FROMSHIPMENT,SALEH.TOSHIPMENT,SALEH.CURRENCY,SALEH.LOADINGPORT,SALEH.DESTINATIONPORT,SALEH.LOADINGPLACE,SALEH.INCOTERM,SALEH.PAYMENTTERMS,SALEH.SHIPPINGPERIOD,SALEH.TRANSPORTATIONMODE,LINE.SHIPMENTMARK AS SHIPMENTMARK
FROM TBLPISCLINE LINE			INNER JOIN ERP_SAD.dbo.tblItem IITEM
ON LINE.ITEMID=IITEM.intID		INNER JOIN TBLPISCHEADER SH
ON LINE.PISCHEADER=SH.ID        INNER JOIN  TBLSALESQUOTATIONHEADER SALEH
ON SALEH.ID=SH.SALESQUOTATIONHEADERID
WHERE PISCHEADER=@headerid AND LINE.ISACTIVE=1
END
ELSE IF @id=4
BEGIN
SELECT ID,UNITID,CURRENCY,SHIPMENTMODE,FROMSHIPMENT,TOSHIPMENT,LOADINGPORT,DESTINATIONPORT,LOADINGPLACE,TRANSPORTATIONMODE,PAYMENTTERMS 
FROM TBLSALESQUOTATIONHEADER WHERE ID=@headerid
END;
ELSE IF @id=5
BEGIN
SELECT ID,SALESQUOTATIONHEADERID,B.STRPRODUCTNAME AS ITEMNAME,
	A.ITEMTYPEID,A.ITEMTITLE,PACKINGDETAILS,
	SIZE,SLIT,SCRIM,CONSTRUCTION,QUALITY,WEIGHT,
	UOMID,UOM.strUOM AS UOM,BATCHID,SERIALNO,ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,
	TOTALAMOUNT,DESCRIPTIONS,REMARKS,CASE WHEN A.DISCOUNTID=0 THEN '' ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID=A.DISCOUNTID) END AS DISNAME
	FROM TBLSALESQUOTATIONLINE A,
	ERP_SAD.DBO.TBLITEM B,
	ERP_SAD.dbo.tblUOM UOM 
	WHERE A.ITEMID=B.INTID AND A.ISACTIVE=1 
	AND SALESQUOTATIONHEADERID=@HEADERID AND A.UOMID=UOM.intID ORDER BY A.ITEMID DESC
END

IF @id=6
BEGIN
SELECT PH.ID AS HISTRYID,ISNULL(PH.ID,0) AS AGREEMENTID,PH.UNITID,PH.NUMBER AS PINUMBER,PH.SALESQUOTATIONHEADERID,AGT.CODE AS AGREEMENTTYPEID,AGT.NAME AS AGREEMENTTYPE,CAST(CAST(PH.DATE AS DATE) AS VARCHAR(50)) AS PIDATE,CAST(CAST(PH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS PIEXPIREDATE,
ISNULL(PH.SHIPMENTMODEID,0) AS SHIPMENTMODEID,CAST(CAST(PH.SHIPMENTDATE AS DATE) AS VARCHAR(50))  AS SHIPMENTDATE,CAST(CAST(PH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,SQH.SQNUMBER,
ISNULL(SM.ID,0) AS SHIPMENTID,SM.NAME AS SHIPMENT,ISNULL(PT.ID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PH.HSCODE,PH.BUYERREGNO,PH.CURRENCYID,PH.DELIVERYTERMID,PH.DESCRIPTIONS,PH.TERMSCONDITION,
ISNULL(TSC.ID,0) AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,ISNULL(FSC.ID,0) AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
ISNULL(LP.ID,0) AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,DP.ID AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL,
PH.TARRIFCODE,INCO.ID AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,DS.ID AS DOCSTATUSID,DS.NAME AS DOSSTATUS,'' AS CURRENCY,'' AS DELIVERYTERM,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
PH.NOTIFYPARTY,
SQH.TEXTFROMSHIPMENT,
'' AS DESTINATIONPORT,'' AS TEXTPAYMENT

from TBLPISCHEADER PH				 INNER JOIN ERP_SAD.DBO.tblCustomer			   CUS
ON ph.CUSTOMERID=cus.intCusID		 LEFT JOIN TBLSALESQUOTATIONHEADER			   SQH		
ON PH.SALESQUOTATIONHEADERID=SQH.ID  LEFT JOIN TBLSHIPMENTMODE					   SM
ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
ON PH.INCOTERM=INCO.ID				 INNER JOIN TBLDOCUMENTSTATUS				   DS
ON PH.DOCUMENTSTATUSID=DS.ID		 INNER JOIN TBLAGREEMENTTYPE				   AGT
ON PH.AGREEMENTTYPEID=AGT.ID
WHERE PH.ID=@HEADERID AND PH.ISACTIVE=1
END;
END;