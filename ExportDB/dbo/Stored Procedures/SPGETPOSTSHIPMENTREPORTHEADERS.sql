CREATE PROCEDURE SPGETPOSTSHIPMENTREPORTHEADERS
    @NEEDNAME VARCHAR(200)
AS
BEGIN


DECLARE @TotalAmount BIGINT;
DECLARE @hh decimal(20,2);



    -- Calculate the total amount (sum of PRICE * QUANTITY)
    SELECT @TotalAmount = (
	
	select sum(QUANTITY * PRICE - DISCOUNT) from ABGAPIS.dbo.TBLPISCLINE as ln
INNER JOIN ABGAPIS.dbo.TBLPISCHEADER as hd
ON hd.ID = ln.PISCHEADER
INNER JOIN ABGAPIS.dbo.TBLPACKINGREQUESTHEADER as PH
ON PH.PISCNUMBER = hd.ID
INNER JOIN ABGAPIS.dbo.TBLPICKINGPACKINGHEADER as PT
ON PT.PACKINGREQUESTHEADERID = ph.ID
where PT.PICKPACKNUMBER = @NEEDNAME	
	)

	SELECT @hh = (
	
	select sum(QUANTITY * PRICE - DISCOUNT) from ABGAPIS.dbo.TBLPISCLINE as ln
INNER JOIN ABGAPIS.dbo.TBLPISCHEADER as hd
ON hd.ID = ln.PISCHEADER
INNER JOIN ABGAPIS.dbo.TBLPACKINGREQUESTHEADER as PH
ON PH.PISCNUMBER = hd.ID
INNER JOIN ABGAPIS.dbo.TBLPICKINGPACKINGHEADER as PT
ON PT.PACKINGREQUESTHEADERID = ph.ID
where PT.PICKPACKNUMBER = @NEEDNAME	
	)

    SELECT 
        Head.INVOICENUMBER,
        Head.INVOICEDATE,
        Head.INVOICETO,
        Head.SHIPPEDPER,
        Head.SHIPPEDFROM,
        Head.SHIPPEDTO,
        PPHead.CONTRACTNO,
        PPHead.CONTRACTDATED,
        PPHead.BUYERSCONTNO,
        PPHead.BUYRERSCONTDATED,
		dbo.MoneyToWords(@hh,'en') as TotalInWords,
		@TotalAmount as Totalamount
    FROM 
        ABGAPIS.dbo.TBLPICKINGPACKINGHEADER AS PPHead
    INNER JOIN 
        ABGAPIS.dbo.TBLPACKINGREQUESTHEADER AS Head
        ON Head.ID = PPHead.PACKINGREQUESTHEADERID
    WHERE 
        PPHEAD.PICKPACKNUMBER= @NEEDNAME;
END;