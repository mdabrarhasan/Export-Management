
CREATE Procedure [dbo].[GETPRICECONFIRMFORAPPROVAL]
(
@Enroll		INT,
@UnitID		INT,
@Code		varchar(100),
@ID			varchar(100),
@TYPE   	INT
)
AS
BEGIN
declare @docstatusid int,@checkstatusid int,@AGGTYPEID INT,@CHECKINIT INT
set @docstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
set @checkstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
SET @CHECKINIT=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT')
IF @TYPE=0
	BEGIN
		SELECT PCH.ID,PCH.SALESQUOTATIONHEADERID,SQH.CUSTOMERID,SQH.UNITID,PCH.PCNUMBER,APVMH.ID AS HISTRYID,SQH.SQNUMBER,PCH.PROFORMAINVOICEHEADERID,PIH.NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,APVMH.DESCRIPTIONS,CAST(CAST(PCH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		CUS.strName AS CUSNAME,UNIT.strUnit AS SELLERNAME,CUR.NAME AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLSALESQUOTATIONHEADER			SQH
		ON	PCH.SALESQUOTATIONHEADERID=SQH.ID		INNER JOIN  TBLPISCHEADER					PIH
		ON	PCH.PROFORMAINVOICEHEADERID=PIH.ID		INNER JOIN  TBLAPPROVERMATRIXHISTORY        APVMH
		ON  PCH.ID=APVMH.PROCESSID					INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  APVMH.DOCUMENTSTATUSID=DS.ID			INNER JOIN  TBLAGREEMENTTYPE				AGT
		ON  PIH.AGREEMENTTYPEID=AGT.ID				INNER JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  PIH.CUSTOMERID=CUS.intCusID				INNER JOIN  TBLCURRENCY						CUR
		ON	PIH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON  UNIT.intUnitID=PCH.SELLERID
		WHERE APVMH.ACTIONTAKERID=@Enroll AND 
		(APVMH.DOCUMENTSTATUSID=@checkstatusid and APVMH.DOCUMENTSTATUSID != @CHECKINIT) AND
		PCH.ISACTIVE=1 and
		SUBMENUID=(select ID from TBLSUBMENU where CODE=trim(@Code))	
	END;
ELSE IF @TYPE=1
	BEGIN
	SELECT  0 AS HISTRYID,PCH.ID,SQH.CUSTOMERID,SQH.UNITID,PCH.SALESQUOTATIONHEADERID,PCH.PCNUMBER,SQH.SQNUMBER,PCH.PROFORMAINVOICEHEADERID,PIH.NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,PCH.DESCRIPTIONS,CAST(CAST(PCH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		CUS.strName AS CUSNAME,UNIT.strUnit AS SELLERNAME,CUR.NAME AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLSALESQUOTATIONHEADER			SQH
		ON	PCH.SALESQUOTATIONHEADERID=SQH.ID		INNER JOIN  TBLPISCHEADER					PIH
		ON	PCH.PROFORMAINVOICEHEADERID=PIH.ID		INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  PCH.DOCUMENTSTATUSID=DS.ID				INNER JOIN  TBLAGREEMENTTYPE				AGT
		ON  PIH.AGREEMENTTYPEID=AGT.ID				INNER JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  PIH.CUSTOMERID=CUS.intCusID				INNER JOIN  TBLCURRENCY						CUR
		ON  PIH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON	PCH.SELLERID=UNIT.intUnitID			    
		WHERE PCH.ID=@ID
	END;
	ELSE IF @TYPE=2
	BEGIN
	--SELECT [ID],[PRICECONFIRMHEADERID],[ITEMID] AS PRODUCTCODE,LIST.strProductName AS ITEMNAME,case when LIST.intUnitID=91 then 'KG' when LIST.intUnitID=178 then 'pecs' when LIST.intUnitID=182 then 'Pecs' end AS  strUoM,[QUANTITY],[PRICE],[OFFERPRICE],[CONFIRMPRICE] 
	--FROM TBLPRICECONFIRMLINE LINE INNER JOIN ERP_SAD.dbo.tblItem LIST
	--ON LINE.ITEMID=LIST.intID WHERE PRICECONFIRMHEADERID=@ID AND LINE.ISACTIVE=1

	
		SELECT LINE.[ID],[PRICECONFIRMHEADERID],LINE.[ITEMID],LIST.strProductName+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
		uom.strUOM AS  strUoM,LINE.[QUANTITY],LINE.[PRICE],[OFFERPRICE],[CONFIRMPRICE] 
		FROM TBLPRICECONFIRMLINE LINE			INNER JOIN ERP_SAD.dbo.tblItem LIST
		ON LINE.ITEMID=LIST.intID				INNER JOIN TBLPRICECONFIRMHEADER PCH
		ON PCH.ID=LINE.PRICECONFIRMHEADERID		INNER JOIN TBLPISCHEADER   PISCH
		ON PISCH.ID=PCH.PROFORMAINVOICEHEADERID INNER JOIN TBLPISCLINE     PISCL
		ON PISCH.ID=PISCL.PISCHEADER			AND PISCL.ITEMID=LIST.intID AND PISCL.ID=LINE.QUOTATIONLINEID
		INNER JOIN ERP_SAD.dbo.tblUOM UOM
		ON PISCL.UOMID=UOM.intID
		WHERE PRICECONFIRMHEADERID=@ID		    AND LINE.ISACTIVE=1
		ORDER BY ITEMTYPEID 

	END;
	ELSE IF @TYPE=3
	BEGIN
	SELECT  0 AS HISTRYID,PCH.ID,SQH.CUSTOMERID,SQH.UNITID,PCH.SALESQUOTATIONHEADERID,PCH.PCNUMBER,SQH.SQNUMBER,PCH.PROFORMAINVOICEHEADERID,PIH.NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,PCH.DESCRIPTIONS,CAST(CAST(PCH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		CUS.strName AS CUSNAME,UNIT.strUnit AS SELLERNAME,CUR.NAME AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLSALESQUOTATIONHEADER			SQH
		ON	PCH.SALESQUOTATIONHEADERID=SQH.ID		INNER JOIN  TBLPISCHEADER					PIH
		ON	PCH.PROFORMAINVOICEHEADERID=PIH.ID		INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  PCH.DOCUMENTSTATUSID=DS.ID				INNER JOIN  TBLAGREEMENTTYPE				AGT
		ON  PIH.AGREEMENTTYPEID=AGT.ID				INNER JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  PIH.CUSTOMERID=CUS.intCusID				INNER JOIN  TBLCURRENCY						CUR
		ON  PIH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON	PCH.SELLERID=UNIT.intUnitID		
		WHERE  PCH.ISACTIVE=1
		--WHERE PCH.DOCUMENTCREATEDBY=@Enroll AND PCH.ISACTIVE=1
	END;
	ELSE IF @TYPE=4
	BEGIN
	SELECT [ID] AS ID,[PRICECONFIRMHEADERID],[ITEMID],LIST.strProductName AS ITEMNAME,case when LIST.intUnitID=91 then 'KG' when LIST.intUnitID=178 then 'pecs' when LIST.intUnitID=182 then 'Pecs' end AS  strUoM, [QUANTITY],[PRICE],[OFFERPRICE],[CONFIRMPRICE] 
	FROM TBLPRICECONFIRMLINE LINE INNER JOIN ERP_SAD.dbo.tblItem LIST
	ON LINE.ITEMID=LIST.intID WHERE PRICECONFIRMHEADERID=@ID AND LINE.ISACTIVE=1
	END;
END;