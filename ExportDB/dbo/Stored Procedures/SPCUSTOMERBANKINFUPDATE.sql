CREATE PROCEDURE SPCUSTOMERBANKINFUPDATE
    @ID INT,
    @CUSTOMERNAME NVARCHAR(MAX),
    @CUSTOMERBANKBRANCHNAME NVARCHAR(MAX),
    @CUSTOMERBANKNAME NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINEONE NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINETWO NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINETHREE NVARCHAR(MAX),
    @CUSTOMERBANKBINNO NVARCHAR(MAX),
    @UPDATEDBY INT,
    @Msg CHAR(100) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        UPDATE [ABGAPIS].[dbo].[TBLCUSTOMERBANK]
        SET CUSTOMERNAME = @CUSTOMERNAME,
            CUSTOMERBANKBRANCHNAME = @CUSTOMERBANKBRANCHNAME,
            CUSTOMERBANKNAME = @CUSTOMERBANKNAME,
            CUSTOMERBANKADDRESSLINEONE = @CUSTOMERBANKADDRESSLINEONE,
            CUSTOMERBANKADDRESSLINETWO = @CUSTOMERBANKADDRESSLINETWO,
            CUSTOMERBANKADDRESSLINETHREE = @CUSTOMERBANKADDRESSLINETHREE,
            CUSTOMERBANKBINNO = @CUSTOMERBANKBINNO,
            UPDATEDBY = @UPDATEDBY,
            UPDATEDDATE = GETDATE()
        WHERE ID = @ID
        
        SET @Msg = 'Record updated successfully'
    END TRY
    BEGIN CATCH
        SET @Msg = ERROR_MESSAGE()
    END CATCH
END