
CREATE PROCEDURE SPGETQUOTATIONLINE
(
@ID			INT
)
AS
BEGIN
SELECT LINE.ID AS ID,QH.ID AS HEADERID,QUOTATIONTYPEID		
FROM TBLQUOTATIONHEADER				QH INNER JOIN TBLQUOTATIONLINE				LINE
ON QH.ID=LINE.QUOTATIONHEADERID		   INNER JOIN TBLQUOTATIONTYPE				QT
ON QH.QUOTATIONTYPEID=QT.ID			   INNER JOIN ERP_SAD.DBO.tblCustomer		CUS
ON QH.CUSTOMERID=CUS.intCusID		   
WHERE QH.ID=9
END;