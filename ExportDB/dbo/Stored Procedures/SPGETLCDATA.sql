
CREATE PROCEDURE [dbo].[SPGETLCDATA]
@TYPE			INT,
@ENROLL		INT
AS
BEGIN
IF @TYPE=0
	BEGIN
		SELECT LCD.ID,0 AS HISTRYID,LCD.PISCHEADERID,LCD.LCNUMBER,CAST(CAST(LCD.LCISSUEDATE AS DATE) AS VARCHAR(50)) AS LCISSUEDATE,CAST(CAST(LCD.LCEXPIREDATE AS DATE) AS VARCHAR(50)) AS LCEXPIREDATE,
		'' AS LCCREATEDPLACE,LCD.TOELRANCECRAMTPERCENTAGE,CAST(CAST(LCD.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,
		PISCH.CUSTOMERID,CUS.strName AS CUSNAME,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.HSCODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,LCD.DOCUMENTSTATUSID,DS.CODE AS CODE,DS.NAME AS DOCSTATUS,
		PISCH.AGREEMENTTYPEID,AT.NAME AS AGREEMENTTYPE,LD.NAME AS TODISCHARGEPORT,LD.NAME AS LOADINGPORTNAME,CAST(CAST(LCD.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
		CAST(LCD.PRESENTATIONINDATE  AS VARCHAR(50)) AS PRESENTATIONINDATE,TCON.NAME AS TRANSSHIPMENT,LCD.NOTIFIEDPARTYDETAILS,PCON.NAME AS PARTIALSHIPMENT,
		LCD.BUYERADDITIONALCONDITION,LCD.BUYERDOCUMENTREQUIRED,LCD.BUYERBANK,(select NUMBER from TBLPISCHEADER where ID=PISCH.ID) AS PISC,
		CASE WHEN ISNULL(LCD.FLAG,0)=0 THEN 0 ELSE LCD.FLAG END AS FLAG,LCD.LCEXPIREDPLACE,LCD.LCTENORPERIOD,CAST(CAST(LCD.SHIPMENTLATESTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTLATESTDATE
		,BUYERBANKID,(select strCode from ERP_DURBIN.dbo.tblCusBilling where intBillID=BILLNOID) as BILLNO,INVOICENO,TYPE,DOCUMENTREQUIRE,0 AS CURRENCYID,'' AS CURRENCY,0 AS PARTIALSHIPMENTID,0 AS TRANSHIPMENTID
		FROM TBLLCDETAILS LCD						INNER JOIN		TBLPISCHEADER				PISCH
		ON   LCD.PISCHEADERID=PISCH.ID				INNER JOIN		ERP_SAD.DBO.tblCustomer		CUS
		ON	 PISCH.CUSTOMERID=CUS.intCusID			INNER JOIN		TBLSHIPMENTMODE				SM
		ON   PISCH.SHIPMENTMODEID=sm.ID				LEFT JOIN		TBLPAYMENTTERMS				PT
		ON	 PISCH.PAYMENTTERMID=PT.ID				INNER JOIN      TBLFROMLOADINGPORT			LD
		ON	 PISCH.TODISCHARGEPORT=LD.ID			INNER JOIN		TBLDOCUMENTSTATUS			DS
		ON	 LCD.DOCUMENTSTATUSID=DS.ID				INNER JOIN		TBLFROMLOADINGPORT			DP
		ON	 PISCH.TODISCHARGEPORT=DP.ID			INNER JOIN		TBLAGREEMENTTYPE			AT
		ON	 PISCH.AGREEMENTTYPEID=AT.ID			INNER JOIN		TBLCONFIRM					TCON
		ON	 LCD.TRANSSHIPMENT=TCON.ID				INNER JOIN      TBLCONFIRM					PCON
		ON   LCD.PARTIALSHIPMENT=PCON.ID
		WHERE LCD.DOCUMENTCREATEDBY=@Enroll AND LCD.ISACTIVE=1 
		
	END;

	IF @TYPE=1
	BEGIN
		SELECT LCD.ID,0 AS HISTRYID,LCD.PISCHEADERID,LCD.LCNUMBER,CAST(CAST(LCD.LCISSUEDATE AS DATE) AS VARCHAR(50)) AS LCISSUEDATE,CAST(CAST(LCD.LCEXPIREDATE AS DATE) AS VARCHAR(50)) AS LCEXPIREDATE,
		'' AS LCCREATEDPLACE,LCD.TOELRANCECRAMTPERCENTAGE,CAST(CAST(LCD.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,
		PISCH.CUSTOMERID,CUS.strName AS CUSNAME,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.HSCODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,LCD.DOCUMENTSTATUSID,DS.CODE AS CODE,DS.NAME AS DOCSTATUS,
		PISCH.AGREEMENTTYPEID,AT.NAME AS AGREEMENTTYPE,LD.NAME AS TODISCHARGEPORT,LD.NAME AS LOADINGPORTNAME,CAST(CAST(LCD.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
		CAST(+LCD.PRESENTATIONINDATE  AS VARCHAR(50)) AS PRESENTATIONINDATE,CAST(TCON.ID AS VARCHAR(50)) AS TRANSSHIPMENT,LCD.NOTIFIEDPARTYDETAILS,CAST(PCON.ID AS VARCHAR(50)) AS PARTIALSHIPMENT,
		LCD.BUYERADDITIONALCONDITION,LCD.BUYERDOCUMENTREQUIRED,LCD.BUYERBANK,(select NUMBER from TBLPISCHEADER where ID=PISCH.ID) AS PISC,
		CASE WHEN ISNULL(LCD.FLAG,0)=0 THEN 0 ELSE LCD.FLAG END AS FLAG,LCD.LCEXPIREDPLACE,LCD.LCTENORPERIOD,CAST(CAST(LCD.SHIPMENTLATESTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTLATESTDATE
		,BUYERBANKID,(select strCode from ERP_DURBIN.dbo.tblCusBilling where intBillID=BILLNOID) as BILLNO,INVOICENO,TYPE,DOCUMENTREQUIRE,0 AS CURRENCYID,'' AS CURRENCY,0 AS PARTIALSHIPMENTID,0 AS TRANSHIPMENTID
		FROM TBLLCDETAILS LCD						INNER JOIN		TBLPISCHEADER				PISCH
		ON   LCD.PISCHEADERID=PISCH.ID				INNER JOIN		ERP_SAD.DBO.tblCustomer		CUS
		ON	 PISCH.CUSTOMERID=CUS.intCusID			INNER JOIN		TBLSHIPMENTMODE				SM
		ON   PISCH.SHIPMENTMODEID=sm.ID				INNER JOIN		TBLPAYMENTTERMS				PT
		ON	 PISCH.PAYMENTTERMID=PT.ID				INNER JOIN      TBLFROMLOADINGPORT			LD
		ON	 PISCH.TODISCHARGEPORT=LD.ID			INNER JOIN		TBLDOCUMENTSTATUS			DS
		ON	 LCD.DOCUMENTSTATUSID=DS.ID				INNER JOIN		TBLFROMLOADINGPORT			DP
		ON	 PISCH.TODISCHARGEPORT=DP.ID			INNER JOIN		TBLAGREEMENTTYPE			AT
		ON	 PISCH.AGREEMENTTYPEID=AT.ID			INNER JOIN		TBLCONFIRM					TCON
		ON	 LCD.TRANSSHIPMENT=TCON.ID				INNER JOIN      TBLCONFIRM					PCON
		ON   LCD.PARTIALSHIPMENT=PCON.ID
		WHERE LCD.ID=@ENROLL AND LCD.ISACTIVE=1 ORDER BY LCD.ID DESC
	END;
END;