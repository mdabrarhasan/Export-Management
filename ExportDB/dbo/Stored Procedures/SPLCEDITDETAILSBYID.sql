


CREATE PROCEDURE SPLCEDITDETAILSBYID
(
@id						INT,
@headerid				INT
)
AS
BEGIN
IF @id=0
BEGIN
SELECT ID,PISCHEADER,BATCHID,SERIALNO,ITEMID,HSCODE,IITEM.strItemName AS ITEMNAME,IITEM.strUoM AS UOM,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,'' AS disname,VATID,'' AS vatname,VATAMOUNT,TOTALAMOUNT,
0 AS TOLERANCEID,REMARKS,DESCRIPTIONS,CAST(CAST(FROMSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) FROMSHIPMENTSCHEDULEDATE,CAST(CAST(TOSHIPMENTSCHEDULEDATE AS DATE) AS VARCHAR(50)) TOSHIPMENTSCHEDULEDATE
FROM TBLPISCLINE LINE			INNER JOIN ERP_Inventory.DBO.tblItemList IITEM
ON LINE.ITEMID=IITEM.intItemID  
WHERE PISCHEADER IN(SELECT PISCHEADERID FROM TBLLCDETAILS WHERE PISCHEADERID=(SELECT PISCHEADERID FROM TBLLCDETAILS WHERE ID=@headerid)) AND LINE.ISACTIVE=1
END
END;