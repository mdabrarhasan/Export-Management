CREATE Procedure [dbo].[GetAgreementInfo]
(
@Enroll		INT,
@Code		varchar(100),
@UnitID		INT
)
AS
BEGIN
SELECT 0 AS HISTRYID,PH.ID AS AGREEMENTID,PH.UNITID,PH.NUMBER AS PINUMBER,PH.SALESQUOTATIONHEADERID,AGT.CODE AGREEMENTTYPEID,AGT.NAME AS AGREEMENTTYPE,cast(PH.DATE AS VARCHAR) AS PIDATE,CAST(PH.EXPIREDATE AS VARCHAR) AS PIEXPIREDATE,
CAST(PH.SHIPMENTDATE AS VARCHAR) AS SHIPMENTDATE,PH.SHIPMENTMODEID,CAST(PH.DOCUMENTCREATEDDATE AS VARCHAR) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,SQH.SQNUMBER,SQH.TEXTFROMSHIPMENT,'' AS TEXTPAYMENT,SQH.DESTINATIONPORT,
ISNULL(SM.ID,0) AS SHIPMENTID,SM.NAME AS SHIPMENT,ISNULL(PT.ID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PH.HSCODE,PH.BUYERREGNO,PH.CURRENCYID,PH.DELIVERYTERMID,PH.DESCRIPTIONS,PH.TERMSCONDITION,
ISNULL(TSC.ID,0) AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,ISNULL(FSC.ID,0) AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
ISNULL(LP.ID,0) AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,ISNULL(DP.ID,0) AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,'' AS CURRENCY,'' AS DELIVERYTERM,
PH.TARRIFCODE,ISNULL(INCO.ID,0) AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,ISNULL(DS.ID,0) AS DOCSTATUSID,DS.NAME AS DOSSTATUS,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,ISNULL(PH.SELLERBANKID,0) AS SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
PH.NOTIFYPARTY,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL
from TBLPISCHEADER PH	 INNER JOIN ERP_SAD.DBO.tblCustomer			   CUS
ON ph.CUSTOMERID=cus.intCusID		 INNER JOIN TBLSALESQUOTATIONHEADER			   SQH		
ON PH.SALESQUOTATIONHEADERID=SQH.ID  LEFT JOIN TBLSHIPMENTMODE					   SM
ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
ON PH.INCOTERM=INCO.ID				 INNER JOIN TBLDOCUMENTSTATUS				   DS
ON PH.DOCUMENTSTATUSID=DS.ID		 INNER JOIN TBLAGREEMENTTYPE				   AGT
ON PH.AGREEMENTTYPEID=AGT.ID		
WHERE PH.DOCUMENTCREATEDBY=@Enroll AND PH.AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@Code) AND PH.ISACTIVE=1
Order BY PH.ID Desc
END;