
CREATE PROCEDURE [dbo].[SPIUPDATEINTERESTCALCULATION]
(
@ID									INT,
@LENDERUNITID						INT,
@BORROWERUNITID						INT,
@AMOUNT								DECIMAL(18,2),
@STARTDATE							DATE,
@ENDDATE							DATE,
@NOOFDAYS							INT,
@INTERESTRATE						DECIMAL(18,2),
@INTERESTAMT						DECIMAL(18,2),
@DETAILS							VARCHAR(MAX),

@MODULECODE							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@DOCSTATUS							VARCHAR(100),
@MESSAGENAME						VARCHAR(100),
@NOTIFICATION						VARCHAR(100),			
@DOCUMENTCREATEDBY					INT,
@MSG								VARCHAR(100)		OUT,
@STATUSMSG							VARCHAR(100)		OUT
)
AS
BEGIN
	UPDATE TBLINTERESTCALCULATION
	SET 
	LENDERUNITID=@LENDERUNITID,
	BORROWERUNITID=@BORROWERUNITID,
	AMOUNT=@AMOUNT,
	STARTDATE=@STARTDATE,
	ENDDATE=@ENDDATE,
	NOOFDAYS=@NOOFDAYS,
	INTERESTRATE=@INTERESTRATE,
	INTERESTAMT=@INTERESTAMT,
	DETAILS=@DETAILS,
	UPDATEDBY=@DOCUMENTCREATEDBY,
	UPDATEDDATE=GETDATE() WHERE ID=@ID
	

	SET @MSG='DATA UPDATE SUCCESSFULLY.'
	SET @STATUSMSG='success';
END;