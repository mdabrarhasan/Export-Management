CREATE   PROCEDURE [dbo].[SPGETCUSTOMERINFOSafwan]
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE
    FROM dbo.TBLCUSTOMERBANK
	
	WHERE ISACTIVE > 0 
    ORDER BY ID DESC;
END