
CREATE PROCEDURE [DBO].[SPUpdatePIDetailsByID]
(
@ID						INT,
@ITEMTYPEID				INT,
@ITEMID					INT,
@QUALITY				VARCHAR(100),
@QUANTITY				DECIMAL(18,2),
@PRICE					DECIMAL(18,2),


@SIZE					VARCHAR(MAX),
@CONSTRUCTION			VARCHAR(MAX),
@WEIGHT					VARCHAR(MAX),
@SLIT					VARCHAR(MAX),
@SCRIM					VARCHAR(MAX),
@ITEMTITLE				VARCHAR(MAX),
@PACKINGDETAILS			VARCHAR(MAX),


@DISCOUNTID				INT,
@DISCOUNTAMT			DECIMAL(18,2),

@UOMID					INT,
--@TOLERANCEID			INT,
@TOTALAMT				DECIMAL(18,2),
@DESCRIPTIONS			VARCHAR(500),
@REMARKS				VARCHAR(500),
--@FROMSHIPMENTSCHEDULEDATE VARCHAR(100),
--@TOSHIPMENTSCHEDULEDATE  VARCHAR(100),
@UNITID					INT,
@MODULECODE				VARCHAR(50),
@ENROLL					INT,
@PROCESSCODE			VARCHAR(50),
@MESSAGENAME			VARCHAR(50),
@MSG					VARCHAR(100)    OUT
)
AS
DECLARE @LOG VARCHAR(MAX)
BEGIN TRY
UPDATE TBLPISCLINE
SET [ITEMID]=@ITEMID,
ITEMTYPEID=@ITEMTYPEID,
QUALITY=@QUALITY,
[QUANTITY]=@QUANTITY,
[PRICE]=@PRICE,
SIZE=@SIZE,
CONSTRUCTION=@CONSTRUCTION,
WEIGHT=@WEIGHT,
SLIT=@SLIT,
SCRIM=@SCRIM,
ITEMTITLE=@ITEMTITLE,
PACKINGDETAILS=@PACKINGDETAILS,
[DISCOUNTID]=@DISCOUNTID,
[DISCOUNT]=@DISCOUNTAMT,
UOMID=@UOMID,
--TOLERANCEID=@TOLERANCEID,
[TOTALAMOUNT]=@TOTALAMT,
[DESCRIPTIONS]=@DESCRIPTIONS,
[REMARKS]=@REMARKS
--[FROMSHIPMENTSCHEDULEDATE]=@FROMSHIPMENTSCHEDULEDATE,
--[TOSHIPMENTSCHEDULEDATE]=@TOSHIPMENTSCHEDULEDATE
WHERE ID=@ID;
SET @MSG=(SELECT NAME FROM TBLMESSAGE WHERE SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=@MODULECODE) AND CODE=@MESSAGENAME)
	SET @LOG='UPDATE TBLPISCLINE SET ITEMID='+CAST(@ITEMID AS VARCHAR(50))+' QUANTITY='+CAST(@QUANTITY AS VARCHAR(50))+''
	+' PRICE='+CAST(@PRICE AS VARCHAR(50))+''
	+' DISCOUNTID='+CAST(@DISCOUNTID AS VARCHAR(50))+' DISCOUNT='+CAST(@DISCOUNTAMT AS VARCHAR(50))

	EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSCODE,@UNITID,@ENROLL
END TRY
BEGIN CATCH
SET @MSG=ERROR_MESSAGE()
END CATCH