		CREATE PROCEDURE [dbo].[SPGETPACKINGREQLANDING]
		(
		@Type			INT,
		@ENROLL			INT,
		@ID				INT,
		@UnitID			INT
		)
		AS
		BEGIN
		
		IF @Type=0
		BEGIN
		SELECT PACKH.ID,PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,'' AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,'' AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PACKH.FLAG,PACKH.PISCNUMBER as PIHEADERID
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							LEFT JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    LEFT JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							INNER JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							INNER JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				
		--INNER JOIN TBLCONFIRM					TRANSHIP
		--ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						
		--INNER JOIN TBLCONFIRM					PARTIAL
		--ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID
		WHERE    PACKH.DOCUMENTCREATEDBY=@ENROLL  AND PACKH.ISACTIVE=1
		Order By PACKH.ID desc
		END;

		ELSE IF @Type=1
		BEGIN
		SELECT PACKH.ID,PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PACKH.FLAG,PACKH.PISCNUMBER as PIHEADERID
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLSHIPMENTMODE				TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID
		WHERE    PACKH.DOCUMENTCREATEDBY=@ENROLL AND PACKH.ID=@ID AND PACKH.ISACTIVE=1
		Order By PACKH.ID desc
		END;

		ELSE IF @Type=2
		BEGIN
		/*SELECT ID,SERIALNO,ITEMID,ITEM.strItemName AS ITEMNAME,ITEM.strUoM AS UOM,QUANTITY,PACKINGREQQUANTITY,0.0 AS REMAININGQTY,TOLERANCEID,
		CAST(CAST(EXPPRODUCTIONORDERDATE AS DATE) AS VARCHAR(50)) AS EXPPRODUCTIONORDERDATE,REMARKS,DESCRIPTIONS,
		PRL.PACKINGREQUESTHEADERID
		from TBLPACKINGREQUESTLINE PRL			INNER JOIN	ERP_Inventory.dbo.tblItemList ITEM
		ON PRL.ITEMID=ITEM.intItemID
		WHERE PACKINGREQUESTHEADERID=@ID AND ISACTIVE=1 ORDER BY EXPPRODUCTIONORDERDATE*/
		DECLARE @VPINUMBER INT;
		
		SELECT @VPINUMBER=PISCNUMBER FROM TBLPACKINGREQUESTHEADER WHERE ID=@ID
		SELECT PRL.ID,SERIALNO,ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM,QUANTITY,PACKINGREQQUANTITY,TOLERANCEID,
		COUNTNO as CountNo,TOTALPALLET as TotalPallet,TOTALCARTOON as TotalCartoon,ADDITIONALWEIGHT AS AddWeight,
		GROSSWEIGHT as GrossWeight,PRL.MEASUREMENT as Measurement,SINO as SINo,TOTALSPOOL as TotalSpool,MARKINK as MarkInk,
		SPOOLORPALAT as SpoolOrPalat,
				EXPPRODUCTIONORDERDATE,PRL.TRUSSNO as TrussNo,REMARKS,DESCRIPTIONS,PRL.MILLID,M.MillName AS MILLNAME,
		PRL.PACKINGREQUESTHEADERID,
		(
		SELECT  MAX(LINE.QUANTITY)-SUM(LINE.PACKINGREQQUANTITY) FROM TBLPACKINGREQUESTHEADER HEADER			
		INNER JOIN										TBLPACKINGREQUESTLINE	LINE
		ON HEADER.ID=LINE.PACKINGREQUESTHEADERID WHERE HEADER.PISCNUMBER=@VPINUMBER AND line.ITEMID=PRL.ITEMID GROUP BY line.ITEMID
		) AS REMAININGQTY
		from TBLPACKINGREQUESTLINE PRL			INNER JOIN	ERP_SAD.dbo.tblItem ITEM
		ON PRL.ITEMID=ITEM.intID
		INNER JOIN TBLMILL M ON M.ID = PRL.MILLID
		WHERE PACKINGREQUESTHEADERID=@ID AND PRL.ISACTIVE=1 ORDER BY EXPPRODUCTIONORDERDATE

		END;

		ELSE IF @Type=3
		BEGIN
		/*SELECT MAX(PRL.ID) AS ID,ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM, MAX(QUANTITY) AS QUANTITY,SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,MAX(QUANTITY)-SUM(PACKINGREQQUANTITY) AS REMAININGQTY,
		PRL.PACKINGREQUESTHEADERID,

		PRL.COUNTNO as CountNo,PRL.TOTALPALLET as TotalPallet,PRL.TOTALCARTOON as TotalCartoon,PRL.ADDITIONALWEIGHT AS AddWeight,
		PRL.GROSSWEIGHT as GrossWeight,PRL.SINO as SINo,PRL.TOTALSPOOL as TotalSpool,PRL.MARKINK as MarkInk,
		PRL.SPOOLORPALAT as SpoolOrPalat,PRL.REMARKS,
		PRL.DESCRIPTIONS,PRL.EXPPRODUCTIONORDERDATE,PRL.SERIALNO

		from TBLPACKINGREQUESTLINE PRL			INNER JOIN	ERP_SAD.dbo.tblItem ITEM
		ON PRL.ITEMID=ITEM.intID
		WHERE PACKINGREQUESTHEADERID=@ID AND ISACTIVE=1 GROUP BY 
		ITEMID,ITEM.strProductName,PRL.PACKINGREQUESTHEADERID,

		PRL.COUNTNO,PRL.TOTALPALLET,PRL.TOTALCARTOON,
		PRL.ADDITIONALWEIGHT,PRL.GROSSWEIGHT,
		PRL.SINO,PRL.TOTALSPOOL,PRL.MARKINK,PRL.SPOOLORPALAT,
		PRL.REMARKS,PRL.DESCRIPTIONS,PRL.EXPPRODUCTIONORDERDATE,PRL.SERIALNO,

		case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end;*/

		SELECT MAX(PRL.ID) AS ID,PRL.ITEMID,ITEM.strProductName+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
		UOM.STRUOM AS UOM,
		MAX(PRL.QUANTITY) AS QUANTITY,SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,MAX(PRL.QUANTITY)-SUM(PRL.PACKINGREQQUANTITY) AS REMAININGQTY,
		PRL.PACKINGREQUESTHEADERID,

		PRL.COUNTNO as CountNo,PRL.TOTALPALLET as TotalPallet,PRL.TOTALCARTOON as TotalCartoon,PRL.ADDITIONALWEIGHT AS AddWeight,
		PRL.GROSSWEIGHT as GrossWeight,PRL.SINO as SINo,PRL.TOTALSPOOL as TotalSpool,PRL.MARKINK as MarkInk,
		PRL.SPOOLORPALAT as SpoolOrPalat,PRL.REMARKS,
				PRL.DESCRIPTIONS,CAST(CAST(PRL.EXPPRODUCTIONORDERDATE AS DATE) AS VARCHAR(100)) AS EXPPRODUCTIONORDERDATE,PRL.TRUSSNO as TrussNo,PRL.SERIALNO,MAX(PRL.MILLID) AS MILLID,MAX(M.MillName) AS MILLNAME

		from TBLPACKINGREQUESTLINE PRL			INNER JOIN	ERP_SAD.dbo.tblItem ITEM
		ON PRL.ITEMID=ITEM.intID				INNER JOIN  TBLPACKINGREQUESTHEADER  PRH
		ON PRL.PACKINGREQUESTHEADERID=PRH.ID	INNER JOIN  TBLPISCHEADER PISC
		ON PRH.PISCNUMBER=PISC.ID				INNER JOIN  TBLPISCLINE  PISCL
		ON PISC.ID=PISCL.PISCHEADER				AND PRL.ITEMID=PISCL.ITEMID  INNER JOIN ERP_SAD.DBO.tblUOM UOM
		ON UOM.intID=PISCL.UOMID
		INNER JOIN TBLMILL M ON M.ID = PRL.MILLID

		WHERE PACKINGREQUESTHEADERID=@ID AND PRL.ISACTIVE=1 
		GROUP BY 
		PRL.ITEMID,ITEM.strProductName,PRL.PACKINGREQUESTHEADERID,

		PRL.COUNTNO,PRL.TOTALPALLET,PRL.TOTALCARTOON,
		PRL.ADDITIONALWEIGHT,PRL.GROSSWEIGHT,
		PRL.SINO,PRL.TOTALSPOOL,PRL.MARKINK,PRL.SPOOLORPALAT,
		PRL.REMARKS,PRL.DESCRIPTIONS,PRL.EXPPRODUCTIONORDERDATE,PRL.TRUSSNO,PRL.SERIALNO,UOM.STRUOM,ITEMTYPEID,QUALITY,SIZE,CONSTRUCTION,SLIT,SCRIM,CONSTRUCTION,WEIGHT
		END;

		ELSE IF @Type=4 
		BEGIN
		DECLARE @CHECKPHL INT , @NO INT = NULL
		SELECT @CHECKPHL=ID FROM TBLPACKINGREQUESTLINE WHERE PACKINGREQUESTHEADERID=@ID
		--SELECT MAX(LINE.ID) AS ID,LINE.ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM,MAX(LINE.QUANTITY) AS QUANTITY,SUM(LINE.PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,
		--MAX(LINE.QUANTITY)-SUM(LINE.PACKINGREQQUANTITY) AS REMAININGQTY,0 AS PACKINGREQUESTHEADERID
		--FROM
		--TBLPACKINGREQUESTHEADER PACKREQH				INNER JOIN		TBLPACKINGREQUESTLINE				LINE
		--ON PACKREQH.ID=LINE.PACKINGREQUESTHEADERID		INNER JOIN		ERP_SAD.dbo.tblItem		ITEM
		--ON LINE.ITEMID=ITEM.intID WHERE PACKREQH.PISCNUMBER=@ID GROUP BY LINE.ITEMID,ITEM.strProductName,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end HAVING MAX(LINE.QUANTITY)-SUM(LINE.PACKINGREQQUANTITY)>0
		--UNION
		--SELECT PISCLINE.ID AS ID,PISCLINE.ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM ,
		--PISCLINE.QUANTITY,0 AS PACKINGREQQUANTITY,
		--PISCLINE.QUANTITY AS REMAININGQTY,0 AS PACKINGREQUESTHEADERID
		--FROM TBLPISCLINE PISCLINE	INNER JOIN ERP_SAD.dbo.tblItem ITEM 
		--ON ITEM.intID=PISCLINE.ITEMID WHERE PISCLINE.PISCHEADER=@ID AND ITEMID NOT IN
		--(SELECT DISTINCT ITEMID FROM TBLPACKINGREQUESTLINE WHERE PACKINGREQUESTHEADERID IN(select ID FROM TBLPACKINGREQUESTHEADER where PISCNUMBER=@ID))
		--AND PISCLINE.ISACTIVE=1
		IF @CHECKPHL IS NOT NULL
		BEGIN
		SELECT 
    MAX(LINE.ID) AS ID,
    LINE.ITEMID,
    ITEM.strProductName AS ITEMNAME,
    CASE 
        WHEN ITEM.intUnitID = 91 THEN 'KG' 
        WHEN ITEM.intUnitID = 178 THEN 'pecs' 
        WHEN ITEM.intUnitID = 182 THEN 'Pecs' 
    END AS UOM,

    MAX(LINE.QUANTITY) AS QUANTITY,
    SUM(LINE.PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,
    MAX(LINE.QUANTITY) - SUM(LINE.PACKINGREQQUANTITY) AS REMAININGQTY,
    0 AS PACKINGREQUESTHEADERID
FROM
    TBLPACKINGREQUESTHEADER PACKREQH
INNER JOIN
    TBLPACKINGREQUESTLINE LINE ON PACKREQH.ID = LINE.PACKINGREQUESTHEADERID
INNER JOIN
    ERP_SAD.dbo.tblItem ITEM ON LINE.ITEMID = ITEM.intID

WHERE 
    PACKREQH.PISCNUMBER = @ID 
GROUP BY 
    LINE.ITEMID,
    ITEM.strProductName,
    CASE 
        WHEN ITEM.intUnitID = 91 THEN 'KG' 
        WHEN ITEM.intUnitID = 178 THEN 'pecs' 
        WHEN ITEM.intUnitID = 182 THEN 'Pecs' 
    END 
--HAVING 
--    MAX(LINE.QUANTITY) - SUM(LINE.PACKINGREQQUANTITY) < 0

UNION

SELECT 
    PISCLINE.ID AS ID,
    PISCLINE.ITEMID,
    ITEM.strProductName AS ITEMNAME,
    CASE 
        WHEN ITEM.intUnitID = 91 THEN 'KG' 
        WHEN ITEM.intUnitID = 178 THEN 'pecs' 
        WHEN ITEM.intUnitID = 182 THEN 'Pecs' 
    END AS UOM,
    PISCLINE.QUANTITY,
    0 AS PACKINGREQQUANTITY,
    PISCLINE.QUANTITY AS REMAININGQTY,
    0 AS PACKINGREQUESTHEADERID
FROM 
    TBLPISCLINE PISCLINE
INNER JOIN 
    ERP_SAD.dbo.tblItem ITEM ON ITEM.intID = PISCLINE.ITEMID
	
WHERE 
    PISCLINE.PISCHEADER = @ID 
    AND (SELECT PL.PACKINGREQQUANTITY FROM TBLPACKINGREQUESTHEADER PH
INNER JOIN TBLPACKINGREQUESTLINE PL ON PH.ID = PL.PACKINGREQUESTHEADERID WHERE PL.PACKINGREQUESTHEADERID = @ID) <> PISCLINE.QUANTITY
    AND PISCLINE.ITEMID NOT IN (
        SELECT DISTINCT ITEMID 
        FROM TBLPACKINGREQUESTLINE 
        WHERE PACKINGREQUESTHEADERID IN (SELECT ID FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER = @ID)
    )
    AND PISCLINE.ISACTIVE = 1
		END
		ELSE
		BEGIN
		SELECT 
    MAX(LINE.ID) AS ID,
    LINE.ITEMID,
    ITEM.strProductName AS ITEMNAME,
    CASE 
        WHEN ITEM.intUnitID = 91 THEN 'KG' 
        WHEN ITEM.intUnitID = 178 THEN 'pecs' 
        WHEN ITEM.intUnitID = 182 THEN 'Pecs' 
    END AS UOM,
    MAX(LINE.QUANTITY) AS QUANTITY,
    SUM(LINE.PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,
    MAX(LINE.QUANTITY) - SUM(LINE.PACKINGREQQUANTITY) AS REMAININGQTY,
    0 AS PACKINGREQUESTHEADERID
FROM
    TBLPACKINGREQUESTHEADER PACKREQH
INNER JOIN
    TBLPACKINGREQUESTLINE LINE ON PACKREQH.ID = LINE.PACKINGREQUESTHEADERID
INNER JOIN
    ERP_SAD.dbo.tblItem ITEM ON LINE.ITEMID = ITEM.intID

WHERE 
    PACKREQH.PISCNUMBER = @ID 
GROUP BY 
    LINE.ITEMID,
    ITEM.strProductName,
    CASE 
        WHEN ITEM.intUnitID = 91 THEN 'KG' 
        WHEN ITEM.intUnitID = 178 THEN 'pecs' 
        WHEN ITEM.intUnitID = 182 THEN 'Pecs' 
    END 
--HAVING 
--    MAX(LINE.QUANTITY) - SUM(LINE.PACKINGREQQUANTITY) < 0

UNION

SELECT 
    PISCLINE.ID AS ID,
    PISCLINE.ITEMID,
    ITEM.strProductName AS ITEMNAME,
    UOM.strUOM AS UOM,
    PISCLINE.QUANTITY,
    0 AS PACKINGREQQUANTITY,
    PISCLINE.QUANTITY AS REMAININGQTY,
    0 AS PACKINGREQUESTHEADERID
FROM 
    TBLPISCLINE PISCLINE
INNER JOIN 
    ERP_SAD.dbo.tblItem ITEM ON ITEM.intID = PISCLINE.ITEMID
INNER JOIN ERP_SAD.DBO.tblUOM UOM 
ON PISCLINE.UOMID=UOM.intID

WHERE 
    PISCLINE.PISCHEADER = @ID 
    
    AND PISCLINE.ITEMID NOT IN (
        SELECT DISTINCT ITEMID 
        FROM TBLPACKINGREQUESTLINE 
        WHERE PACKINGREQUESTHEADERID IN (SELECT ID FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER = @ID)
    )
    AND PISCLINE.ISACTIVE = 1
		END
		

		END;

		ELSE IF @Type=5
		BEGIN
		SELECT HEADER.ID,HEADER.PACKREQNUMBER AS PACKREQNUMBER,
		CAST(CAST(PACKREQDATE AS DATE) AS VARCHAR(50)) AS PACKREQDATE,CAST(CAST(SHIPMENTPERIOD AS DATE) AS VARCHAR(50)) AS SHIPMENTPERIOD,HEADER.CUSTOMERID,
		CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,HEADER.DOCUMENTCREATEDBY,HEADER.UNITID,
		HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS,PISC.NUMBER as PISCNUMBER
		FROM TBLPACKINGREQUESTHEADER HEADER			INNER JOIN	TBLPISCHEADER  PISC
		ON HEADER.PISCNUMBER=PISC.ID WHERE HEADER.ID=(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID)
		END;

		ELSE IF @Type=6    --FOR APPROVAL
		BEGIN
		DECLARE @STATUS INT
		SET @STATUS=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='PEND')
		SELECT PACKH.ID,PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PACKH.PISCNUMBER as PIHEADERID
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							INNER JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						INNER JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						INNER JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							INNER JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							INNER JOIN TBLSHIPMENTMODE				TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				INNER JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						INNER JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID
		WHERE    PACKH.DOCUMENTCREATEDBY=@ENROLL AND PACKH.DOCUMENTSTATUSID=@STATUS AND PACKH.ISACTIVE=1
		END;

		ELSE IF @Type=7   
		BEGIN
		SELECT PACKH.ID,PACKH.PACKREQNUMBER,PACKH.FLAG,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TODISCHARGEPORT AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PACKH.PISCNUMBER as PIHEADERID
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID
		WHERE    PACKH.ID =(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID)  AND PACKH.ISACTIVE=1
		Order By PACKH.ID desc
		END;
		
		ELSE IF @Type=8
		BEGIN
		SELECT MAX(PRL.ID) AS ID,ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM, MAX(QUANTITY) AS QUANTITY,SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,MAX(QUANTITY)-SUM(PACKINGREQQUANTITY) AS REMAININGQTY,
		PRL.PACKINGREQUESTHEADERID
		from TBLPACKINGREQUESTLINE PRL			INNER JOIN	ERP_SAD.dbo.tblItem ITEM
		ON PRL.ITEMID=ITEM.intID
		WHERE PACKINGREQUESTHEADERID=(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID) AND PRL.ISACTIVE=1 GROUP BY ITEMID,ITEM.strProductName,PRL.PACKINGREQUESTHEADERID,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end;
		END;

		ELSE IF @Type=9  
		BEGIN
		SELECT PACKH.BIAXPRODUCTTYPE AS BIAXPROTYPE,
		PACKH.SHIPPOINT,
		PACKH.PACKINGMODE,
		PACKH.CUSTOMERCATEGORY ,
		PACKH.ID,PACKH.PACKREQNUMBER,
		CAST(CAST(PACKH.PACKREQDATE AS DATE) AS VARCHAR(100)) AS PACKREQDATE,
		PACKH.TERMSCONDITION,
		PACKH.DESCRIPTIONS,
		CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,
		CUR.NAME AS CURRENCY,
		PISCH.NUMBER AS PISCNUMBER,
		DS.CODE,
		DS.NAME DOCSTATUS,
		0 AS CUSTOMERID,
		PACKH.DOCUMENTCREATEDBY,
		PACKH.UNITID,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,
		AGR.NAME AS AGREEMENTTYPE,
		PISCH.SHIPMENTMODEID,
		SM.NAME AS SHIPMENTMODE,
		PISCH.PAYMENTTERMID,
		PT.NAME AS PAYMENTTERM,
		PISCH.TOSHIPMENTCOUNTRYID,
		TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,
		TODISCHARGEPORT AS DISCHARGEPORT,
		PISCH.TRANSHIPMENT,
		TRANSHIP.NAME AS TRANSHIPMENTNAME,
		PISCH.PARTIALSHIPMENT,
		PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,
		PACKH.INVOICENUMBER,
		PACKH.INVOICEDATE,
		PACKH.INVOICETO,
		PACKH.CONTRACTNO,
		PACKH.SHIPPEDPER,
		PACKH.SHIPPEDFROM,
		PACKH.SHIPPEDTO,
		PACKH.PURCHASEORDERNO,
		PACKH.PURCHASEORDERDATED,
		CAST(CAST(PACKH.SHIPMENTPERIOD AS DATE) AS VARCHAR(100)) AS SHIPMENTPERIOD,
		PACKH.FLAG,
		PACKH.PISCNUMBER as PIHEADERID
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							INNER JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						INNER JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						INNER JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							INNER JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							INNER JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				INNER JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						INNER JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID
		WHERE    PACKH.ID=@ID AND PACKH.ISACTIVE=1
		END;
