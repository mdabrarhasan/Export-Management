CREATE PROCEDURE [dbo].[SPGETLCDATABIAX]
(
@TYPE			INT,
@ID				INT,
@ENROLL			INT
)
AS
BEGIN
	IF @TYPE=1
	BEGIN
	SELECT LCD.ID,0 AS HISTRYID,LCD.PROFORMAINVOICEHEADERID AS PISCHEADERID,LCD.LCNUMBER,CAST(CAST(LCD.LCISSUEDATE AS DATE) AS VARCHAR(50)) AS LCISSUEDATE,CAST(CAST(LCD.LCEXPIREDATE AS DATE) AS VARCHAR(50)) AS LCEXPIREDATE,
	'' AS LCCREATEDPLACE,LCD.TOELRANCECRAMTPERCENTAGE,CAST(CAST(LCD.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,
	QH.CUSTOMERID,CUS.strName AS CUSNAME,QH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,(SELECT STRING_AGG(HSCODE, ', ') 
FROM TBLQUOTATIONHSCODE WHERE QTID=QH.ID)  AS HSCODE,QH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,LCD.DOCUMENTSTATUSID,DS.CODE AS CODE,DS.NAME AS DOCSTATUS,
	QH.QUOTATIONTYPEID AS AGREEMENTTYPEID,AT.NAME AS AGREEMENTTYPE,LD.NAME AS TODISCHARGEPORT,LD.NAME AS LOADINGPORTNAME,CAST(CAST(LCD.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	CAST(LCD.PRESENTATIONINDATE  AS VARCHAR(50)) AS PRESENTATIONINDATE,TCON.ID AS TRANSHIPMENTID,TCON.NAME AS TRANSSHIPMENT,LCD.NOTIFIEDPARTYDETAILS,PCON.ID AS PARTIALSHIPMENTID,PCON.NAME AS PARTIALSHIPMENT,
	LCD.BUYERADDITIONALCONDITION,LCD.BUYERDOCUMENTREQUIRED,LCD.BUYERBANK,(select QUOTATIONNUMBER from TBLQUOTATIONHEADER where ID=QH.ID) AS PISC,
	CASE WHEN ISNULL(LCD.FLAG,0)=0 THEN 0 ELSE LCD.FLAG END AS FLAG,LCD.LCEXPIREDPLACE,LCD.LCTENORPERIOD,CAST(CAST(LCD.SHIPMENTLATESTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTLATESTDATE,
	CURRID.ID AS CURRENCYID,CURRID.NAME AS CURRENCY,LCD.BUYERBANKID,(select strCode from ERP_DURBIN.dbo.tblCusBilling where intBillID=BILLNOID) as BILLNO,INVOICENO,TYPE,DOCUMENTREQUIRE
	FROM TBLLCDETAILS LCD						LEFT JOIN		TBLQUOTATIONHEADER			QH
	ON   LCD.PROFORMAINVOICEHEADERID=QH.ID		LEFT JOIN		ERP_SAD.DBO.tblCustomer		CUS
	ON	 QH.CUSTOMERID=CUS.intCusID				LEFT JOIN		TBLSHIPMENTMODE				SM
	ON   QH.SHIPMENTMODEID=SM.ID				LEFT JOIN		TBLPAYMENTTERMS				PT
	ON	 QH.PAYMENTTERMID=PT.ID					LEFT JOIN      TBLFROMLOADINGPORT			LD
	ON	 QH.TODISCHARGEPORT=LD.ID				LEFT JOIN		TBLDOCUMENTSTATUS			DS
	ON	 LCD.DOCUMENTSTATUSID=DS.ID				LEFT JOIN		TBLFROMLOADINGPORT			DP
	ON	 QH.TODISCHARGEPORT=DP.ID				LEFT JOIN		TBLQUOTATIONTYPE			AT
	ON	 QH.QUOTATIONTYPEID=AT.ID				LEFT JOIN		TBLCONFIRM					TCON
	ON	 LCD.TRANSSHIPMENT=TCON.ID				LEFT JOIN      TBLCONFIRM					PCON
	ON   LCD.PARTIALSHIPMENT=PCON.ID			LEFT JOIN		TBLCURRENCY					CURRID
	ON   QH.CURRENCYID=CURRID.ID
	WHERE LCD.ISACTIVE=1 ORDER BY LCD.ID DESC
	END;
	ELSE IF @TYPE=2
	BEGIN
	SELECT LCD.ID,0 AS HISTRYID,LCD.PROFORMAINVOICEHEADERID AS PISCHEADERID,LCD.LCNUMBER,CAST(CAST(LCD.LCISSUEDATE AS DATE) AS VARCHAR(50)) AS LCISSUEDATE,CAST(CAST(LCD.LCEXPIREDATE AS DATE) AS VARCHAR(50)) AS LCEXPIREDATE,
	'' AS LCCREATEDPLACE,LCD.TOELRANCECRAMTPERCENTAGE,CAST(CAST(LCD.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,
	QH.CUSTOMERID,CUS.strName AS CUSNAME,QH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,(SELECT STRING_AGG(HSCODE, ', ') 
FROM TBLQUOTATIONHSCODE WHERE QTID=QH.ID)  AS HSCODE,QH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,LCD.DOCUMENTSTATUSID,DS.CODE AS CODE,DS.NAME AS DOCSTATUS,
	QH.QUOTATIONTYPEID AS AGREEMENTTYPEID,AT.NAME AS AGREEMENTTYPE,LD.NAME AS TODISCHARGEPORT,LD.NAME AS LOADINGPORTNAME,CAST(CAST(LCD.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	CAST(LCD.PRESENTATIONINDATE  AS VARCHAR(50)) AS PRESENTATIONINDATE,TCON.ID AS TRANSHIPMENTID,TCON.NAME AS TRANSSHIPMENT,LCD.NOTIFIEDPARTYDETAILS,PCON.ID AS PARTIALSHIPMENTID,PCON.NAME AS PARTIALSHIPMENT,
	LCD.BUYERADDITIONALCONDITION,LCD.BUYERDOCUMENTREQUIRED,LCD.BUYERBANK,(select QUOTATIONNUMBER from TBLQUOTATIONHEADER where ID=QH.ID) AS PISC,
	CASE WHEN ISNULL(LCD.FLAG,0)=0 THEN 0 ELSE LCD.FLAG END AS FLAG,LCD.LCEXPIREDPLACE,LCD.LCTENORPERIOD,CAST(CAST(LCD.SHIPMENTLATESTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTLATESTDATE,
	CURRID.ID AS CURRENCYID,CURRID.NAME AS CURRENCY,LCD.BUYERBANKID,(select strCode from ERP_DURBIN.dbo.tblCusBilling where intBillID=BILLNOID) as BILLNO,INVOICENO,TYPE,DOCUMENTREQUIRE
	FROM TBLLCDETAILS LCD						LEFT JOIN		TBLQUOTATIONHEADER			QH
	ON   LCD.PROFORMAINVOICEHEADERID=QH.ID		LEFT JOIN		ERP_SAD.DBO.tblCustomer		CUS
	ON	 QH.CUSTOMERID=CUS.intCusID				LEFT JOIN		TBLSHIPMENTMODE				SM
	ON   QH.SHIPMENTMODEID=SM.ID				LEFT JOIN		TBLPAYMENTTERMS				PT
	ON	 QH.PAYMENTTERMID=PT.ID					LEFT JOIN      TBLFROMLOADINGPORT			LD
	ON	 QH.TODISCHARGEPORT=LD.ID				LEFT JOIN		TBLDOCUMENTSTATUS			DS
	ON	 LCD.DOCUMENTSTATUSID=DS.ID				LEFT JOIN		TBLFROMLOADINGPORT			DP
	ON	 QH.TODISCHARGEPORT=DP.ID				LEFT JOIN		TBLQUOTATIONTYPE			AT
	ON	 QH.QUOTATIONTYPEID=AT.ID				LEFT JOIN		TBLCONFIRM					TCON
	ON	 LCD.TRANSSHIPMENT=TCON.ID				LEFT JOIN      TBLCONFIRM					PCON
	ON   LCD.PARTIALSHIPMENT=PCON.ID			LEFT JOIN		TBLCURRENCY					CURRID
	ON   QH.CURRENCYID=CURRID.ID
	WHERE LCD.ISACTIVE=1 AND LCD.ID=@ID ORDER BY LCD.ID DESC
    END
	ELSE IF @TYPE=3
	BEGIN
	SELECT LCD.ID,0 AS HISTRYID,LCD.PROFORMAINVOICEHEADERID AS PISCHEADERID,LCD.LCNUMBER,CAST(CAST(LCD.LCISSUEDATE AS DATE) AS VARCHAR(50)) AS LCISSUEDATE,CAST(CAST(LCD.LCEXPIREDATE AS DATE) AS VARCHAR(50)) AS LCEXPIREDATE,
	'' AS LCCREATEDPLACE,LCD.TOELRANCECRAMTPERCENTAGE,CAST(CAST(LCD.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,
	ISNULL(QH.CUSTOMERID,0) AS CUSTOMERID,CUS.strName AS CUSNAME,ISNULL(QH.SHIPMENTMODEID,0) AS SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,(SELECT STRING_AGG(HSCODE, ', ') 
FROM TBLQUOTATIONHSCODE WHERE QTID=QH.ID)  AS HSCODE,ISNULL(QH.PAYMENTTERMID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,LCD.DOCUMENTSTATUSID,DS.CODE AS CODE,DS.NAME AS DOCSTATUS,
	ISNULL(QH.QUOTATIONTYPEID,0) AS AGREEMENTTYPEID,AT.NAME AS AGREEMENTTYPE,LD.NAME AS TODISCHARGEPORT,LD.NAME AS LOADINGPORTNAME,CAST(CAST(LCD.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	CAST(LCD.PRESENTATIONINDATE  AS VARCHAR(50)) AS PRESENTATIONINDATE,TCON.ID AS TRANSHIPMENTID,TCON.NAME AS TRANSSHIPMENT,LCD.NOTIFIEDPARTYDETAILS,ISNULL(PCON.ID,0) AS PARTIALSHIPMENTID,PCON.NAME AS PARTIALSHIPMENT,
	LCD.BUYERADDITIONALCONDITION,LCD.BUYERDOCUMENTREQUIRED AS BUYERDOCUMENTREQUIRED,LCD.BUYERBANK,(select QUOTATIONNUMBER from TBLQUOTATIONHEADER where ID=QH.ID) AS PISC,
	CASE WHEN ISNULL(LCD.FLAG,0)=0 THEN 0 ELSE LCD.FLAG END AS FLAG,LCD.LCEXPIREDPLACE,LCD.LCTENORPERIOD,CAST(CAST(LCD.SHIPMENTLATESTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTLATESTDATE,
	ISNULL(CURRID.ID,0) AS CURRENCYID,CURRID.NAME AS CURRENCY,LCD.BUYERBANKID,(select strCode from ERP_DURBIN.dbo.tblCusBilling where intBillID=BILLNOID) as BILLNO,INVOICENO,TYPE,DOCUMENTREQUIRE
	FROM TBLLCDETAILS LCD						LEFT JOIN		TBLQUOTATIONHEADER			QH
	ON   LCD.PROFORMAINVOICEHEADERID=QH.ID		LEFT JOIN		ERP_SAD.DBO.tblCustomer		CUS
	ON	 QH.CUSTOMERID=CUS.intCusID				LEFT JOIN		TBLSHIPMENTMODE				SM
	ON   QH.SHIPMENTMODEID=SM.ID				LEFT JOIN		TBLPAYMENTTERMS				PT
	ON	 QH.PAYMENTTERMID=PT.ID					LEFT JOIN      TBLFROMLOADINGPORT			LD
	ON	 QH.TODISCHARGEPORT=LD.ID				LEFT JOIN		TBLDOCUMENTSTATUS			DS
	ON	 LCD.DOCUMENTSTATUSID=DS.ID				LEFT JOIN		TBLFROMLOADINGPORT			DP
	ON	 QH.TODISCHARGEPORT=DP.ID				LEFT JOIN		TBLQUOTATIONTYPE			AT
	ON	 QH.QUOTATIONTYPEID=AT.ID				LEFT JOIN		TBLCONFIRM					TCON
	ON	 LCD.TRANSSHIPMENT=TCON.ID				LEFT JOIN      TBLCONFIRM					PCON
	ON   LCD.PARTIALSHIPMENT=PCON.ID			LEFT JOIN		TBLCURRENCY					CURRID
	ON   QH.CURRENCYID=CURRID.ID
	WHERE LCD.ISACTIVE=1 AND LCD.PROFORMAINVOICEHEADERID=(SELECT PROFORMAINVOICEHEADERID FROM TBLLCDETAILS WHERE ID=268) ORDER BY LCD.ID DESC



	END;
END;