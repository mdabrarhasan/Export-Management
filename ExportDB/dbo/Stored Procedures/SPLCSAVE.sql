
CREATE PROCEDURE [dbo].[SPLCSAVE]
(
@BUSINESSUNIT									INT,
@DOCUMENTREQUIRE                                VARCHAR(500),
@BUYERBANKID                                    int,
@BILLNOID                                       int,
@INVOICENO                                      VARCHAR(500), 
@TYPE                                            int,
@LCNUMBER										VARCHAR(100),
@LCISSUEDATE 									VARCHAR(100),
@LCEXPIREDATE 									VARCHAR(100),
@LCCREATEDPLACE 								VARCHAR(200),
@TOELRANCECRAMTPERCENTAGE						DECIMAL(18,2),
@PRESENTATIONINDATE 							VARCHAR(100),						
@PARTIALSHIPMENT								INT,
@BUYERDOCUMENTREQUIRED							VARCHAR(500),
@BUYERADDITIONALCONDITION						VARCHAR(500),
@TRANSSHIPMENT									INT,
@NOTIFIEDPARTYDETAILS							VARCHAR(100),
@PISCHEADERID									INT,
@BUYERBANK										VARCHAR(100),

@SHIPMENTLATESTDATE								VARCHAR(100),
@LCTENORPERIOD									VARCHAR(100),
@LCEXPIREDPLACE									VARCHAR(100),

@MODULECODE										VARCHAR(100),
@UNITID											INT,
@ENROLL											INT,
@DOCSTATUS										VARCHAR(100),
@PROCESSNAME									VARCHAR(100),
@MsgStatus										VARCHAR(100),
@NOTIFICATION									VARCHAR(100),
@LOG											VARCHAR(MAX),
@MSG											VARCHAR(100) OUTPUT								
)
AS
BEGIN
DECLARE @SALESQUOTATIONHEADERID	INT,@VPISCHEADERID INT,@CUSTOMERID INT,@ID INT,@PROCESSCODE VARCHAR(100),@GLOBALID VARCHAR(100)

IF @BUSINESSUNIT=91
BEGIN
SELECT @SALESQUOTATIONHEADERID=ID,@CUSTOMERID=CUSTOMERID FROM TBLQUOTATIONHEADER WHERE ID=@PISCHEADERID
END;
ELSE
BEGIN
SELECT @SALESQUOTATIONHEADERID=SALESQUOTATIONHEADERID,@CUSTOMERID=CUSTOMERID FROM TBLPISCHEADER WHERE ID=@PISCHEADERID
END;

INSERT INTO TBLLCDETAILS
(
PROFORMAINVOICEHEADERID,
LCNUMBER,
LCISSUEDATE,
LCEXPIREDATE,
--LCCREATEDPLACE,
CUSTOMERID,
TOELRANCECRAMTPERCENTAGE,
PRESENTATIONINDATE,
PARTIALSHIPMENT,
BUYERDOCUMENTREQUIRED,
BUYERADDITIONALCONDITION,
TRANSSHIPMENT,
NOTIFIEDPARTYDETAILS,
DOCUMENTCREATEDDATE,
DOCUMENTCREATEDBY,
ISACTIVE,
UNITID,
PISCHEADERID,
DOCUMENTSTATUSID,
BUYERBANK,

LCEXPIREDPLACE,
LCTENORPERIOD,
SHIPMENTLATESTDATE,
BUYERBANKID,
   BILLNOID,
   INVOICENO,
   TYPE,
  DOCUMENTREQUIRE
)
VALUES
(
@SALESQUOTATIONHEADERID,
@LCNUMBER,									
@LCISSUEDATE, 									
@LCEXPIREDATE, 									
--@LCCREATEDPLACE, 									
@CUSTOMERID,									
@TOELRANCECRAMTPERCENTAGE,						
@PRESENTATIONINDATE, 										
@PARTIALSHIPMENT,									
@BUYERDOCUMENTREQUIRED,							
@BUYERADDITIONALCONDITION,						
@TRANSSHIPMENT,									
@NOTIFIEDPARTYDETAILS,							
GETDATE(),
@ENROLL,								
1,
@UNITID,											
@PISCHEADERID,
7,
@BUYERBANK,

@LCEXPIREDPLACE,
@LCTENORPERIOD,
@SHIPMENTLATESTDATE,
 @BUYERBANKID,
   @BILLNOID,
   @INVOICENO,
   @TYPE,
   @DOCUMENTREQUIRE
)
SET @ID=SCOPE_IDENTITY()

UPDATE TBLLCDETAILS
SET GLOBALID='GLOB'+CAST(@ID AS VARCHAR(100)) WHERE ID=@ID

SET @PROCESSCODE=@PROCESSNAME+CAST(@ID AS VARCHAR(100))
--set @MSG=@ID
SET @LOG='INSERT INTO TBLLCDETAILS (ID'+CAST(@ID AS VARCHAR(100))+ 'SALESQUOTATIONHEADERID'+CAST(@SALESQUOTATIONHEADERID AS VARCHAR(50))+'LCNUMBER='+CAST(@LCNUMBER AS VARCHAR(50))+'LCISSUEDATE='+CAST(@LCISSUEDATE AS VARCHAR(50))+'LCEXPIREDATE='+CAST(@LCEXPIREDATE AS VARCHAR(50))+'LCCREATEDPLACE='+CAST(@LCCREATEDPLACE AS VARCHAR(50))
set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)+' LC NO:'+CAST(@LCNUMBER AS VARCHAR(100))
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@ProcessName,@Notification
  EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSNAME,@UNITID,@ENROLL

END;