CREATE PROCEDURE [dbo].[SPSAVEPISC]
(
@TYPEPISCINSERTLINE					TYPEPISCINSERTLINE readonly,
@SALESQUOTATIONHEADERID				INT,
@AGREEMENTTYPEID					VARCHAR(50),
@DATE								VARCHAR(100),
@EXPIREDATE							VARCHAR(100),
@SHIPMENTDATE						VARCHAR(100),
@SHIPMENTMODEID						INT,
@PAYMENTTERMID						INT,
@DELIVERYTERMID						INT,
@TERMSCONDITION						VARCHAR(MAX),
@LOADINGPLACE                      Varchar(100),
@DELIVERYBY                         INT,
@TOSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTPORTID					INT,
@TODISCHARGEPORT					INT,
@TARRIFCODE							VARCHAR(100),
@HSCODE								VARCHAR(100),
@BUYERREGNO							VARCHAR(100),
@INCOTERM							INT,
@CURRENCYID							INT,
@DESCRIPTIONS						VARCHAR(MAX),

@BUYERBANKDETAILS					VARCHAR(500),
@SELLERBANKID						INT,
@BUYERCOUNTRYHSCODE					VARCHAR(100),
@TRANSHIPMENT						INT,
@PARTIALSHIPMENT					INT,
@ORIGINOFCOUNTRY					VARCHAR(50),
@BUYERORDERCONFIRMDATE				VARCHAR(50),
@NOTIFYPARTY						VARCHAR(500),
@OTHERSPAYTERM						VARCHAR(500),

@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT,
@TEXTDESTINATIONPORT                VARCHAR(50)
)
AS
BEGIN
DECLARE @CUSTOMERID INT,@NUMBER VARCHAR(100),@id INT,@AGREEMENTTYPE INT,@piid int,@formattedDate VARCHAR(8),
@ITEMID INT,@QUANTITY DECIMAL(18,2),@PRICE DECIMAL(18,2),@DISCOUNTID INT,@DISCOUNT DECIMAL(18,2),@VATID INT,@VATAMOUNT DECIMAL(18,2),
@COMMISSION DECIMAL(18,2),@TOTALAMOUNT DECIMAL(18,2),@REMARKS VARCHAR(MAX),@HSCODELINE VARCHAR(100),
@TOLARANCEID DECIMAL(18,2),@FROMSHIPMENTSCHEDULEDATE VARCHAR(50),@TOSHIPMENTSCHEDULEDATE VARCHAR(50),@BATCHID VARCHAR(100),@SERIALNO INT,
@hid int,@lineid int,@nextactiontacker int,@checkapproid int,
@submenuid int,@scopdeid int,@BATCHIDAPPHISTORY VARCHAR(50),@ProcessID int,@ProcessCode varchar(100),@DocStatusID int,@sqllog nvarchar(max),@initiateid int,
@approvecheck int,@checkcom int,@PITOSCID INT,@CHECKPITOSCCHECK INT,@ITEMSPEBATCH VARCHAR(1000),@Toleranceid int,@ITEMTYPEID INT,@UOMID INT,
@SIZE NVARCHAR(MAX),@CONSTRUCTION NVARCHAR(MAX),@WEIGHT NVARCHAR(MAX),@SLIT NVARCHAR(MAX),@SCRIM NVARCHAR(MAX),@QUALITY NVARCHAR(MAX),@ITEMTITLE NVARCHAR(MAX),@PACKINGDETAILS NVARCHAR(MAX)
	SELECT @piid=isnull(MAX(ID),0) FROM TBLPISCHEADER;
	set @piid=@piid+1;
	

SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
SET @NUMBER=(CASE WHEN @AGREEMENTTYPEID='PI' THEN 'PI' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='SC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='PITOSC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) END)
DECLARE SQL_CURSOR CURSOR FOR  
 SELECT ITEMTYPEID,ITEMID,UOMID,SIZE,CONSTRUCTION,WEIGHT,SLIT,SCRIM,QUALITY,ITEMTITLE,PACKINGDETAILS,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,TOTALAMOUNT,DESCRIPTIONS,REMARKS FROM @TYPEPISCINSERTLINE
 OPEN SQL_CURSOR
 FETCH NEXT FROM SQL_CURSOR INTO  @ITEMTYPEID,@ITEMID,@UOMID,@SIZE,@CONSTRUCTION,@WEIGHT,@SLIT,@SCRIM,@QUALITY,@ITEMTITLE,@PACKINGDETAILS,@QUANTITY, @PRICE, @DISCOUNTID,@DISCOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS  


SET @AGREEMENTTYPE=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@AGREEMENTTYPEID)
--SET @CHECKPITOSCCHECK=(SELECT COUNT(ID) FROM TBLPISCHEADER WHERE ID=@SALESQUOTATIONHEADERID AND AGREEMENTTYPEID=@AGREEMENTTYPE)
SET @CHECKPITOSCCHECK=(SELECT COUNT(ID) FROM TBLPISCHEADER WHERE ID=SALESQUOTATIONHEADERID AND PITOSC IS NOT NULL)

IF @CHECKPITOSCCHECK>0 
	BEGIN
	SET @Msg='PI ALREADY CONVERTED TO SC';
	END;
ELSE
	BEGIN
	IF @AGREEMENTTYPEID='PITOSC'
	BEGIN
	SET @CUSTOMERID=(SELECT CUSTOMERID FROM TBLSALESQUOTATIONHEADER WHERE ID=@SALESQUOTATIONHEADERID)    --@SALESQUOTATIONHEADERID AS PISCID
	SET @PITOSCID=(SELECT ID FROM TBLPISCHEADER WHERE ID=@SALESQUOTATIONHEADERID)
	SET @CHECKPITOSCCHECK=(SELECT COUNT(ID) FROM TBLPISCHEADER WHERE ID=@SALESQUOTATIONHEADERID)
	SET @SALESQUOTATIONHEADERID=(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE ID=@SALESQUOTATIONHEADERID)


	INSERT INTO TBLPISCHEADER
	(
	LOADINGPLACE,
	LOADINGBYID,
	NUMBER,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	ISACTIVE,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	PITOSC,
	ISPROCESSEDWITHAPPROVAL,
	TEXTDESTINATIONPORT
	)
	VALUES
	(
	@LOADINGPLACE,
	@DELIVERYBY  ,
	@NUMBER,
	@SALESQUOTATIONHEADERID,
	@AGREEMENTTYPE,
	@CUSTOMERID,
	@DATE,
	@EXPIREDATE,
	@SHIPMENTDATE,
	@SHIPMENTMODEID,
	@PAYMENTTERMID,
	@DELIVERYTERMID,
	@TERMSCONDITION,
	@TOSHIPMENTCOUNTRYID,
	@FROMSHIPMENTCOUNTRYID,
	@FROMSHIPMENTPORTID,
	@TODISCHARGEPORT,
	@TARRIFCODE,
	@HSCODE,
	@BUYERREGNO,
	@INCOTERM,
	@CURRENCYID,
	@DESCRIPTIONS,
	GETDATE(),
	@ENROLL,
	1,
	1,
	@UNITID,

	@BUYERBANKDETAILS,					
	@SELLERBANKID,						
	@BUYERCOUNTRYHSCODE,				
	@TRANSHIPMENT,					
	@PARTIALSHIPMENT,					
	@ORIGINOFCOUNTRY,					
	@BUYERORDERCONFIRMDATE,				
	@NOTIFYPARTY,
	@OTHERSPAYTERM,
	@PITOSCID,
	1,
	@TEXTDESTINATIONPORT
	);
	END;

	ELSE
	BEGIN
	SET @CUSTOMERID=(SELECT CUSTOMERID FROM TBLSALESQUOTATIONHEADER WHERE ID=@SALESQUOTATIONHEADERID)
	
	INSERT INTO TBLPISCHEADER
	(
	LOADINGPLACE,
	LOADINGBYID,
	NUMBER,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	ISACTIVE,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	ISPROCESSEDWITHAPPROVAL,
	TEXTDESTINATIONPORT
	)
	VALUES
	(
	@LOADINGPLACE,
	@DELIVERYBY  ,
	@NUMBER,
	@SALESQUOTATIONHEADERID,
	@AGREEMENTTYPE,
	@CUSTOMERID,
	@DATE,
	@EXPIREDATE,
	@SHIPMENTDATE,
	@SHIPMENTMODEID,
	@PAYMENTTERMID,
	@DELIVERYTERMID,
	@TERMSCONDITION,
	@TOSHIPMENTCOUNTRYID,
	@FROMSHIPMENTCOUNTRYID,
	@FROMSHIPMENTPORTID,
	@TODISCHARGEPORT,
	@TARRIFCODE,
	@HSCODE,
	@BUYERREGNO,
	@INCOTERM,
	@CURRENCYID,
	@DESCRIPTIONS,
	GETDATE(),
	@ENROLL,
	1,
	1,
	@UNITID,

	@BUYERBANKDETAILS,					
	@SELLERBANKID,						
	@BUYERCOUNTRYHSCODE,				
	@TRANSHIPMENT,					
	@PARTIALSHIPMENT,					
	@ORIGINOFCOUNTRY,					
	@BUYERORDERCONFIRMDATE,				
	@NOTIFYPARTY,
	@OTHERSPAYTERM,
	1,
	@TEXTDESTINATIONPORT
	);
END
      
	  --set @piidnum='SQ' + '-' + @formattedDate + '-' + cast(@piid as varchar(10))
	SET @id=SCOPE_IDENTITY()
	--SET @NUMBER=(CASE WHEN @AGREEMENTTYPEID='PI' THEN 'PI' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='SC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @AGREEMENTTYPEID='PITOSC' THEN 'SC' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) END)
	SET @BATCHID=(SELECT 'BATCH'+CAST(@id AS VARCHAR(100)))

	UPDATE TBLPISCHEADER
	SET GLOBALID=@id WHERE ID=@id;

  WHILE @@FETCH_STATUS = 0  
  BEGIN
  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPISCLINE where PISCHEADER=@id)
 
  INSERT INTO TBLPISCLINE
  (
  PISCHEADER,
  BATCHID,
  SERIALNO,
  ITEMTYPEID,
  ITEMID,
  UOMID,
  SIZE,
  CONSTRUCTION,
  WEIGHT,
  SLIT,
  SCRIM,
  QUALITY,
  ITEMTITLE,
  PACKINGDETAILS,
  QUANTITY, 
  PRICE, 
  DISCOUNTID,
  DISCOUNT,
  TOTALAMOUNT,
  DESCRIPTIONS,
  REMARKS,
  ISACTIVE
  )
  VALUES
  (
  @id,
  @BATCHID,
  @SERIALNO,
  @ITEMTYPEID, 
  @ITEMID,
  @UOMID,
  @SIZE,
  @CONSTRUCTION,
  @WEIGHT,
  @SLIT,
  @SCRIM,
  @QUALITY,
  @ITEMTITLE,
  @PACKINGDETAILS,
  @QUANTITY, 
  @PRICE, 
  @DISCOUNTID,
  @DISCOUNT, 
  @TOTALAMOUNT, 
  @DESCRIPTIONS, 
  @REMARKS, 
  1
  )
  FETCH NEXT FROM sql_cursor INTO @ITEMTYPEID,@ITEMID,@UOMID,@SIZE,@CONSTRUCTION,@WEIGHT,@SLIT,@SCRIM,@QUALITY,@ITEMTITLE,@PACKINGDETAILS,@QUANTITY, @PRICE, @DISCOUNTID,@DISCOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS
  END;
  --set @Msg=@id
  SET @ProcessCode=@NUMBER
  --SET @ProcessCode=@PROCESSNAME+CAST(@id AS VARCHAR(50))
  SET @ITEMSPEBATCH=(SELECT CASE WHEN (SELECT DISTINCT COUNT(BATCHID) FROM TBLITEMORDERSPEC WHERE PROCESSCODE=
  (SELECT DISTINCT SQNUMBER FROM TBLSALESQUOTATIONHEADER WHERE ID=(SELECT DISTINCT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE NUMBER=@ProcessCode)))=0 THEN
  'BATCH'+CAST((SELECT convert(numeric(12,0),rand() * 899999999999) + 100000000000) AS VARCHAR(500))
  ELSE (SELECT DISTINCT BATCHID FROM TBLITEMORDERSPEC WHERE PROCESSCODE=(SELECT DISTINCT SQNUMBER FROM TBLSALESQUOTATIONHEADER WHERE ID=(SELECT DISTINCT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE NUMBER=@ProcessCode))) END AS BATCHID)

  --'BATCH'+(SELECT convert(numeric(12,0),rand() * 899999999999) + 100000000000)

  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@submenuid,@Notification
  EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
  SELECT @piid=isnull(MAX(ID),0) FROM TBLPISCHEADER;
			select @checkapproid=ID from TBLAPPROVERMATRIXHISTORY where PROCESSID=@piid AND PROCESSNAME='PI'
			if(@checkapproid is null)
			begin
			update TBLPISCHEADER set ISPROCESSEDWITHAPPROVAL=0 where ID=@piid;
			end
END
END