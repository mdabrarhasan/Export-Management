CREATE PROCEDURE [dbo].[SPGETPREVIOUSPRICEHISTORY]
(
@PCID		INT
)
AS
BEGIN
DECLARE @PRODUCTID INT,	@PRODUCTCODE VARCHAR(100),@PRODUCTNAME VARCHAR(MAX),@THIKNESS DECIMAL(18,2),@CUSTOMERID INT,
	@RATEHEAD VARCHAR(100),
	@WIDTH DECIMAL(18,2),@LENGTH DECIMAL(18,2),@SELLINGRATE DECIMAL(18,2),@LEVEL INT,@LISTLEVEL VARCHAR(MAX),@sql_query NVARCHAR(MAX)
	SET @CUSTOMERID=(SELECT CUSTOMERID FROM ABGAPIS.DBO.TBLPRICECONFIRMHEADER WHERE ID=@PCID)
	IF CURSOR_STATUS('global', 'SQL_CURSOR') >= -1
	BEGIN
	CLOSE SQL_CURSOR;
	DEALLOCATE SQL_CURSOR;
	END

	DECLARE SQL_CURSOR CURSOR FOR  
	
	SELECT * FROM
	(
	SELECT max(OCFITEM.intProductID) AS PRODUCTID,
	max(OCFITEM.strProductCode) PRODUCTCODE,
	MAX(OCFITEM.strProductName) AS PRODUCTNAME,
	max(OCFITEM.decThickness) THKINESS,
	Max(ISNULL(OCFITEM.decSellingRate_per_kg,0)) AS PRICE,
	row_number() over(partition by OCFITEM.intProductID order by OCF.intOCFID desc) as LEVEL
	FROM ERP_SAD.DBO.tblOCF OCF,
	ERP_SAD.DBO.tblOCFItems OCFITEM,
	TBLPRICECONFIRMLINE PLINE,
	TBLPRICECONFIRMHEADER PHEADER
	WHERE OCF.intOCFID=OCFITEM.intOCFID AND
	OCFITEM.intProductID=PLINE.ITEMID  AND
	OCFITEM.decThickness=PLINE.THIKNESS  AND
	PHEADER.ID=PLINE.PRICECONFIRMHEADERID AND
	PHEADER.CUSTOMERID=@CUSTOMERID AND
	PHEADER.ID=@PCID
	group by OCF.intOCFID,OCFITEM.intProductID
	) AS T
	WHERE T.LEVEL <=10

	OPEN SQL_CURSOR
	FETCH NEXT FROM SQL_CURSOR INTO @PRODUCTID,@PRODUCTCODE,@PRODUCTNAME,@THIKNESS,@SELLINGRATE,@LEVEL
	WHILE @@FETCH_STATUS = 0  
	BEGIN
	SET @RATEHEAD='Rate '+CAST(@LEVEL AS VARCHAR(100))
	INSERT INTO TBLPIVOT
	(
	PRODUCTID,
	PRODUCTCODE,
	PRODUCTNAME,
	THIKNESS,
	SELLINGRATE,
	LEVEL,
	RATEHEADER
	)
	VALUES
	(
	@PRODUCTID,
	TRIM(@PRODUCTCODE),
	TRIM(@PRODUCTNAME),
	@THIKNESS,
	@SELLINGRATE,
	@LEVEL,
	@RATEHEAD
	)
	FETCH NEXT FROM SQL_CURSOR INTO @PRODUCTID,@PRODUCTCODE,@PRODUCTNAME,@THIKNESS,@SELLINGRATE,@LEVEL
	END;
	CLOSE SQL_CURSOR
	DEALLOCATE SQL_CURSOR

	CREATE TABLE #TEMP
	(
	LEVEL      INT,
	RATEHEADER VARCHAR(100)
	)
	INSERT INTO #TEMP
	SELECT LEVEL,RATEHEADER FROM TBLPIVOT GROUP BY LEVEL,RATEHEADER ORDER BY LEVEL ASC
	
	SET  @LISTLEVEL=(SELECT STRING_AGG(+'['+cast(RATEHEADER as varchar(100))+']',',') AS List_Output
	FROM #TEMP)
	
	SET @sql_query='SELECT PRODUCTCODE,PRODUCTNAME,THIKNESS,'+@LISTLEVEL+' FROM
	(SELECT PRODUCTCODE,PRODUCTNAME,THIKNESS,ISNULL(SELLINGRATE,0) AS PRICE,RATEHEADER
	FROM TBLPIVOT) AS PIVOTTABLE
	PIVOT
	(
	MAX(PRICE) FOR RATEHEADER IN ('+@LISTLEVEL+') 
	) AS PTABLE'

	EXEC sp_executesql @sql_query;

	DELETE FROM #TEMP
	DELETE FROM TBLPIVOT
END