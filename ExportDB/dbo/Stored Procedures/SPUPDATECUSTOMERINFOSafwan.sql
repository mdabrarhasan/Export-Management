CREATE   PROCEDURE dbo.SPUPDATECUSTOMERINFOSafwan
    @ID INT,
    @CUSTOMERNAME VARCHAR(500),
    @CUSTOMERBANKBRANCHNAME VARCHAR(500),
    @CUSTOMERBANKNAME VARCHAR(500),
    @CUSTOMERBANKADDRESSLINEONE VARCHAR(500),
    @CUSTOMERBANKADDRESSLINETWO VARCHAR(500),
    @CUSTOMERBANKADDRESSLINETHREE VARCHAR(500),
    @CUSTOMERBANKBINNO VARCHAR(500),
    @ISACTIVE INT,
    @UPDATEDBY INT,
    @Msg CHAR(100) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE dbo.TBLCUSTOMERBANK
    SET
        CUSTOMERNAME = @CUSTOMERNAME,
        CUSTOMERBANKBRANCHNAME = @CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKNAME = @CUSTOMERBANKNAME,
        CUSTOMERBANKADDRESSLINEONE = @CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO = @CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE = @CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO = @CUSTOMERBANKBINNO,
        ISACTIVE = @ISACTIVE,
        UPDATEDBY = @UPDATEDBY,
        UPDATEDDATE = GETDATE()
    WHERE ID = @ID;

    SET @Msg = 'Updated Successfully';
END