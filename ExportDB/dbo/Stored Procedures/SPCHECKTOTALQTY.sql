CREATE PROCEDURE SPCHECKTOTALQTY
(
@TYPE				INT,
@PINUMBER			INT,
@ITEMID				INT
)
AS
BEGIN
IF @TYPE=1
	BEGIN
	SELECT SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY  FROM TBLPACKINGREQUESTLINE WHERE PACKINGREQUESTHEADERID IN(SELECT ID FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER=@PINUMBER) AND ITEMID=@ITEMID
	GROUP BY ITEMID
	END;
END;