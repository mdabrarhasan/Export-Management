
CREATE PROCEDURE SPLCVSBILLDELETE
(
@ID				INT,
@MODULECODE		VARCHAR(100),
@MsgStatus		VARCHAR(100),
@Msg			VARCHAR(100)  OUTPUT
)
AS
BEGIN 
UPDATE TBLLCVSBILL
SET ISACTIVE=0 WHERE ID=@ID

set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE='LCVSBILL00001') and CODE='LCVSBILLDEL')
END;