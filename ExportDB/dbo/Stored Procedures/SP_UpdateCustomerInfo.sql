
-- Update customer
CREATE PROCEDURE SP_UpdateCustomerInfo
    @ID INT,
    @CUSTOMERNAME NVARCHAR(200),
    @CUSTOMERBANKBRANCHNAME NVARCHAR(200),
    @CUSTOMERBANKNAME NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINEONE NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINETWO NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINETHREE NVARCHAR(200),
    @CUSTOMERBANKBINNO NVARCHAR(50),
    @ISACTIVE BIT,
    @UPDATEDBY NVARCHAR(50)
AS
BEGIN
    UPDATE CustomerInfoX
    SET CUSTOMERNAME = @CUSTOMERNAME,
        CUSTOMERBANKBRANCHNAME = @CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKNAME = @CUSTOMERBANKNAME,
        CUSTOMERBANKADDRESSLINEONE = @CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO = @CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE = @CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO = @CUSTOMERBANKBINNO,
        ISACTIVE = @ISACTIVE,
        UPDATEDBY = @UPDATEDBY,
        UPDATEDDATE = GETDATE()
    WHERE ID = @ID
END