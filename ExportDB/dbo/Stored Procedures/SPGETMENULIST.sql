
CREATE PROCEDURE [dbo].[SPGETMENULIST]
(
@ENROLL			INT
)
AS
BEGIN
SELECT SUBMENU.ID MENUID,SUBMENU.NAME AS SUBMENU,SUBMENU.ICON,
SUBSUBMENU.ID AS SUBMENUID,SUBSUBMENU.NAME AS SUBMENUNAME,
SUBSUBMENU.CONTROLLERNAME,SUBSUBMENU.VIEWNAME,
PERLIST.ID AS ID,PERLIST.CANINSERT,PERLIST.CANUPDATE,PERLIST.CANDELETE,PERLIST.CANVIEW,PERLIST.CANPRINT,
PERLIST.UNITID
FROM TBLSUBMENU SUBMENU						INNER JOIN		TBLSUBSUBMENU				SUBSUBMENU
ON		SUBMENU.ID=SUBSUBMENU.SUBMENUID		INNER JOIN		TBLUSERPERMISSIONLIST		PERLIST
ON		SUBSUBMENU.ID=PERLIST.SUBMENUID		INNER JOIN		ERP_HR.DBO.TBLEMPLOYEE      EMP
ON		PERLIST.ENROLL=EMP.intEmployeeID

WHERE   SUBSUBMENU.ID IN (
SELECT SUBMENUID FROM TBLUSERPERMISSIONLIST WHERE ENROLL=@ENROLL AND PERLIST.UNITID IN (SELECT DISTINCT UNITID FROM TBLUSERPERMISSIONLIST WHERE ENROLL=@ENROLL) AND  CANVIEW !=0
)
AND SUBMENU.ISACTIVE=1 AND SUBSUBMENU.ISACTIVE=1 AND PERLIST.ISACTIVE=1  AND PERLIST.ENROLL=@ENROLL
ORDER BY SUBMENU.SEQUENCE,SUBSUBMENU.SEQUENCE
END;