CREATE PROCEDURE SPGETCUSTOMERINFO
AS
BEGIN
    SELECT 
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE,
        CREATEDBY,
        CREATEDDATE,
        UPDATEDBY,
        UPDATEDDATE
    FROM CustomerInfo
    WHERE ISACTIVE = 1
    ORDER BY ID
END