(
@TYPEPICKPACKINGINSERTLINE TYPEPICKPACKINGINSERTLINE readonly,
@ID								INT,
@PICKPACKDATE					VARCHAR(50),
@TERMSCONDITION					VARCHAR(500),
@DESCRIPTIONS					VARCHAR(500),

@VEHICALNO  VARCHAR(500),
@DRIVERNAME  VARCHAR(500),
@DRIVERPHONE VARCHAR(500),
@CUSTOMERDETAILS VARCHAR(500),
@GATENO VARCHAR(500),
@GATEPERSON VARCHAR(500),

@MODULECODE						VARCHAR(100),
@UNITID							INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN

DECLARE @ProcessCode VARCHAR(50),@CHECK INT
DECLARE @CUSTOMERID INT
--UPDATE TBLPICKINGPACKINGHEADER
--SET PICKPACKDATE=@PICKPACKDATE,@ProcessCode=PICKPACKNUMBER,TERMSCONDITION=@TERMSCONDITION,DESCRIPTIONS=@DESCRIPTIONS WHERE ID=@ID
--SELECT @CHECK=COUNT(QTYCHECK) FROM TBLPICKINGPACKINGLINE WHERE PICKINGPACKINGHEADERID=@ID
--IF @CHECK >0
BEGIN

SET @CUSTOMERID = (
select head.CUSTOMERID from ABGAPIS.dbo.TBLPACKINGREQUESTHEADER as head
where head.id = @ID
);

DECLARE @VPICKPACKNUMBER VARCHAR(50),@piid int,@formattedDate VARCHAR(8)
SELECT @piid=isnull(MAX(ID),0) FROM TBLPICKINGPACKINGHEADER;
	  set @piid=@piid+1;

	  SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  	SET @VPICKPACKNUMBER='PP' + '-' + @formattedDate + '-' + cast(@piid as varchar(10));

INSERT INTO TBLPICKINGPACKINGHEADER
(
PICKPACKNUMBER,
GLOBALID,
CUSTOMERID,
PACKINGREQUESTHEADERID,
PICKPACKDATE,
TERMSCONDITION,
DESCRIPTIONS,
ISACTIVE,
UNITID,
FLAG,
VEHICALNO ,
DRIVERNAME,  
DRIVERPHONE ,
CUSTOMERDETAILS ,
GATENO ,
GATEPERSON ,
DOCUMENTCREATEDBY,
DOCUMENTCREATEDDATE,
DOCUMENTSTATUSID
)
values
(
@VPICKPACKNUMBER,
@ID,
@CUSTOMERID,
@ID,
@PICKPACKDATE,
@TERMSCONDITION,
@DESCRIPTIONS,
1,
@UNITID,
0,
@VEHICALNO ,
@DRIVERNAME,  
@DRIVERPHONE ,
@CUSTOMERDETAILS ,
@GATENO ,
@GATEPERSON ,
@ENROLL,
@PICKPACKDATE,
1
);



--SELECT 
