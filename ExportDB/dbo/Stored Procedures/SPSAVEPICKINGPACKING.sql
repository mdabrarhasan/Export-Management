--FROM TBLPICKINGPACKINGHEADER WHERE ID=@ID
--SELECT @piid=isnull(MAX(ID),0) FROM TBLPICKINGPACKINGHEADER WHERE DOCUMENTCREATEDBY=@ENROLL	;
--UPDATE TBLPICKINGPACKINGLINE SET PICKINGPACKINGHEADERID=@piid,QUANTITY=PACKINGREQQUANTITY-PACKINGREQQUANTITY 
--where PICKINGPACKINGHEADERID=@ID



declare  @VITEMID INT,@VQUANTITY DECIMAL(18,2),@VPACKINGREQQUANTITY DECIMAL(18,2),
@VGROSSMEASURE VARCHAR(50),@VTRUCKNO VARCHAR(50),@VCONTAINERSIZE int,
@VCONTAINERNO VARCHAR(50),@VREMARKS VARCHAR(50),@VDESCRIPTION VARCHAR(50),@BATCHID VARCHAR(50),@SERIALNO VARCHAR(50)

DECLARE SQL_CURSOR CURSOR FOR  
    SELECT ITEMID, QUANTITY, PACKINGREQQUANTITY, GROSSMEASURE, TRUCKNO, CONTAINERSIZE, CONTAINERNO, REMARKS, DESCRIPTION 
    FROM @TYPEPICKPACKINGINSERTLINE;

OPEN SQL_CURSOR;

FETCH NEXT FROM SQL_CURSOR INTO 
    @VITEMID, @VQUANTITY, @VPACKINGREQQUANTITY, 
    @VGROSSMEASURE, @VTRUCKNO, @VCONTAINERSIZE, 
    @VCONTAINERNO, @VREMARKS, @VDESCRIPTION;


SET @id=SCOPE_IDENTITY()
SET @BATCHID=(SELECT 'BATCH'+CAST(@id AS VARCHAR(100)))


 WHILE @@FETCH_STATUS = 0  
  BEGIN
  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPACKINGREQUESTLINE where PACKINGREQUESTHEADERID=@id)

  INSERT INTO TBLPICKINGPACKINGLINE
  (
  PICKINGPACKINGHEADERID,
  BATCHID,
  SERIALNO,
  ITEMID ,
  QUANTITY ,
  PACKINGREQQUANTITY ,
  PICKINGPACKINGQUANTITY,
  GROSSMEASURE ,
  TRUCKNO ,
  CONTAINERSIZE ,
  CONTAINERNO ,
  REMARKS ,
  DESCRIPTIONS,
  ISACTIVE
  )
  VALUES
  (
  @id,
  @BATCHID,
  @SERIALNO,
  @VITEMID ,
  @VQUANTITY ,
  @VPACKINGREQQUANTITY ,
  0,
  @VGROSSMEASURE ,
  @VTRUCKNO ,
  @VCONTAINERSIZE ,
  @VCONTAINERNO ,
  @VREMARKS ,
  @VDESCRIPTION,
  1
  )
   FETCH NEXT FROM SQL_CURSOR INTO 
        @VITEMID, @VQUANTITY, @VPACKINGREQQUANTITY, 
        @VGROSSMEASURE, @VTRUCKNO, @VCONTAINERSIZE, 
        @VCONTAINERNO, @VREMARKS, @VDESCRIPTION;
		
		END;


  SET @LOG='UPDATE TBLPICKINGPACKINGHEADER SET PICKPACKDATE='+CAST(@PICKPACKDATE AS VARCHAR(50))+'TERMSCONDITION='+@TERMSCONDITION+'DESCRIPTIONS='+@DESCRIPTIONS+'WHERE ID='+CAST(@ID AS VARCHAR(50))
  SET @ProcessCode=@PROCESSNAME+CAST(@id AS VARCHAR(50))


  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  
  --set @Msg = 'ok'
  
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@submenuid,@Notification
--  EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll

END
END;