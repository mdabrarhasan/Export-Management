CREATE PROCEDURE [dbo].[SPENROLLENTRY]
(
@TYPE                                   INT,
@PERMISSIONENROLL						INT,
@USERENROLL                            INT

)
AS
BEGIN


IF(@TYPE=1)
BEGIN
DELETE FROM TBLUSERPERMISSIONLIST WHERE ENROLL=@PERMISSIONENROLL
INSERT INTO TBLUSERPERMISSIONLIST(
SUBMENUID,
CANINSERT,
CANUPDATE,
CANDELETE,
CANVIEW,
CANPRINT,
ENROLL,
CREATEDBY,
CREATEDDATE,
UPDATEDBY,
UPDATEDDATE,
ISACTIVE

)
SELECT USERLIST.SUBMENUID,
USERLIST.CANINSERT,
USERLIST.CANUPDATE,
USERLIST.CANDELETE,
USERLIST.CANVIEW,
USERLIST.CANPRINT,
@PERMISSIONENROLL,
USERLIST.CREATEDBY,
USERLIST.CREATEDDATE,
USERLIST.UPDATEDBY,
USERLIST.UPDATEDDATE,
USERLIST.ISACTIVE 
FROM TBLUSERPERMISSIONLIST USERLIST
INNER JOIN TBLSUBSUBMENU SUBSUBMENU ON SUBSUBMENU.ID=USERLIST.SUBMENUID
WHERE USERLIST.ENROLL=@USERENROLL AND SUBSUBMENU.ISACTIVE=1
END


IF @TYPE=2
BEGIN
DELETE FROM TBLAPPROVERMATRIXLINE WHERE VALUE=@PERMISSIONENROLL
INSERT INTO TBLAPPROVERMATRIXLINE
(
APPROVERMATRIXHEADERID,
BATCHID,
VALUE,
APPROVERROLETYPE,
SEQUENCE,
ISACTIVE
)
SELECT 
APPROVERMATRIXHEADERID,
BATCHID,
@PERMISSIONENROLL,
APPROVERROLETYPE,
SEQUENCE,
1

 FROM TBLAPPROVERMATRIXLINE WHERE VALUE=@USERENROLL
END

END;
