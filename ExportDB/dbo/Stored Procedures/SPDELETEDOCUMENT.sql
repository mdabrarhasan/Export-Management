

CREATE PROCEDURE SPDELETEDOCUMENT
(
@DOCHEADER				INT,
@PICKPACKID				INT,
@ROOTDOCLISTID			INT,
@ModuleCode				VARCHAR(50),
@UnitID					INT,
@Enroll					INT,
@ProcessName			VARCHAR(50),
@MessageName			VARCHAR(50),
@Notification			VARCHAR(50),
@Log					VARCHAR(100),
@Msg					varchar(100) OUTPUT 
)
AS
BEGIN
DECLARE @VMODULECODE VARCHAR(100),@ProcessCode VARCHAR(100)

SET @VMODULECODE=(SELECT CODE FROM TBLSUBMENU WHERE ID=(SELECT SUBMENUID FROM TBLDOCUMENTSETUPHEADER WHERE ID=@ROOTDOCLISTID))

IF @VMODULECODE='PRE00001'
  BEGIN
  SET @PROCESSNAME='PRE'
  SET @MessageName='PREDEL'
  SET @ProcessCode=@PROCESSNAME+CAST(@DOCHEADER AS VARCHAR(100))

  END;
  ELSE IF @VMODULECODE='POST00001'
  BEGIN
  SET @PROCESSNAME='POST'
  SET @MessageName='POSTDEL'
  SET @ProcessCode=@PROCESSNAME+CAST(@DOCHEADER AS VARCHAR(100))

  END;

UPDATE TBLDOCHEADER
SET ISACTIVE=0 WHERE ID=@DOCHEADER

set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@VMODULECODE) and CODE=@MessageName)
SET @Log='UPDATE TBLDOCHEADER SET ISACTIVE=0 WHERE ID='+CAST(@DOCHEADER AS VARCHAR(50))

exec SPActivityLog @Log,'',@ProcessCode,@VMODULECODE,@PROCESSNAME,@UNITID,@Enroll

END;