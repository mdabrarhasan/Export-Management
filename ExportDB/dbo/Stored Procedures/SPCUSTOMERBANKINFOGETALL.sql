CREATE   PROCEDURE [dbo].[SPCUSTOMERBANKINFOGETALL]
AS
BEGIN
    SELECT 
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE,
        CREATEDDATE   -- ✅ ADD THIS
    FROM TBLCUSTOMERBANK
END