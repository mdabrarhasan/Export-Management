CREATE PROCEDURE [dbo].[SPGETLOANFACILITYBYID]
(
@ID				INT
)
AS
BEGIN
SELECT LF.ID,UNITID,SANCTIONNO,SANCTIONREF,SODLIMIT,CAST(CAST(EXPIREDATE AS DATE) AS VARCHAR(100)) AS EXPIREDATE,
CASE WHEN INNERUNITID=0 THEN UNIT.NAME ELSE UNIT.NAME+'[inner '+(SELECT CODE FROM TBLUNITFORTREASURY WHERE ID=LF.INNERUNITID)+']' END AS UNIT,ISNULL(INNERUNITID,0) AS INNERUNITID,
'' AS INNERUNIT,BANKID,'' AS BANKNAME,ISNULL(RAWMATERIALLIMIT,0) AS RAWMATERIALLIMIT,ISNULL(LOANLIMIT,0) AS LOANLIMIT,
ISNULL(MACHINERYLIMIT,0) AS MACHINERYLIMIT,ISNULL(SHORTTERMLOAN,0) AS SHORTTERMLOAN,
ISNULL(OVERDRAFTFACILITY,0) AS OVERDRAFTFACILITY,ISNULL(BANKGUARANTEELIMIT,0) AS BANKGUARANTEELIMIT,
ISNULL(TIMELOANLIMIT,0) AS TIMELOANLIMIT,ISNULL(TERMLOANLIMIT,0) AS TERMLOANLIMIT,ISNULL(LCSPARESMACHINERYLIMIT,0) AS LCSPARESMACHINERYLIMIT,ISNULL(TOTAL,0) AS TOTAL
FROM TBLLIMITFACILITY LF INNER JOIN TBLUNITFORTREASURY UNIT
ON LF.UNITID=UNIT.ID
WHERE LF.ID=@ID
END;