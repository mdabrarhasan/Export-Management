CREATE PROCEDURE [dbo].[sprSQNEWINSERTAFTERREOPEN] 
	@sq int,@unitid int,
	@ModuleCode varchar(50),@Enroll int,@mgs varchar(100) output

AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;
	DECLARE @SALESQUOTATIONHEADERID INT,
        @BATCHID NVARCHAR(50),
        @SERIALNO INT,
        @ITEMID INT,
        @QUANTITY DECIMAL(18, 2),
        @PRICE DECIMAL(18, 2),
        @DISCOUNTID INT,
        @DISCOUNT DECIMAL(18, 2),
        @VATID INT,
        @VATAMOUNT DECIMAL(18, 2),
        @TOTALAMOUNT DECIMAL(18, 2),
        @DESCRIPTIONS NVARCHAR(1000),
        @REMARKS NVARCHAR(1000),
        @ISACTIVE BIT;
	DECLARE @Sqid int,@piid int,@PRID INT,@pc int,@pr int ,@pinum int,@formattedDate varchar(50),@pinumber varchar(50),@idsqnumcheck int,
	@ppid int,@type int,@lcid int,@procode varchar(50),@enrollcreate varchar(50)
	select @SQid=ID ,@procode=SQNUMBER,@enrollcreate=DOCUMENTCREATEDBY from TBLSALESQUOTATIONHEADER WHERE ID=@sq AND DOCUMENTSTATUSID=7 ;
	select @piid=ID from TBLPISCHEADER where SALESQUOTATIONHEADERID=@SQid AND DOCUMENTSTATUSID=7;
	select @lcid=ID from TBLLCDETAILS where PISCHEADERID=@piid AND DOCUMENTSTATUSID=7;
	SELECT @pc=ID FROM TBLPRICECONFIRMHEADER WHERE PROFORMAINVOICEHEADERID=@piid AND DOCUMENTSTATUSID=7;
	SELECT @pr=ID FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER=@piid AND DOCUMENTSTATUSID=7
	select @ppid=ID from TBLPICKINGPACKINGHEADER where PACKINGREQUESTHEADERID=@pr AND DOCUMENTSTATUSID=7;
	
	 SELECT @pinum=isnull(MAX(ID),0) FROM TBLSALESQUOTATIONHEADER;
	  
	  set @pinum=@pinum+1;

	   

	   SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  set @pinumber='SQ' + '-' + @formattedDate + '-' + cast(@pinum as varchar(10))
if (@piid IS NOT NULL)
begin
 set @mgs='Please At First Cancle The Profoma Invoice Request' 
end
 else
 begin
 update TBLSALESQUOTATIONHEADER set ISACTIVE=0 WHERE ID=@sq AND DOCUMENTSTATUSID=7
 insert into TBLSALESQUOTATIONHEADER
	   (
	   SQTYPEID,
	   EXPIREDATE,
	   GLOBALID,
	   SQNUMBER,
	   --SQDATE,
	   CUSTOMERID,
	   UNITID,
	   DESCRIPTIONS,
	   DOCUMENTCREATEDDATE,
	   DOCUMENTCREATEDBY,
	   DOCUMENTSTATUSID,
	   ISACTIVE,
	   TERMSCONDITION,
	   REOPENID,
	   REOPNSQNUMBER,
	   ISPROCESSEDWITHAPPROVAL
	   )
	   select 
	   SQTYPEID,
	   EXPIREDATE,
	   GLOBALID,
	   @pinumber,
	   --SQDATE,
	   CUSTOMERID,
	   UNITID,
	   DESCRIPTIONS,
	   DOCUMENTCREATEDDATE,
	   DOCUMENTCREATEDBY,
	   1,
	   1,
	   TERMSCONDITION,
	   @SQid,
	   @procode,
	   1
	   from TBLSALESQUOTATIONHEADER where ID=@sq;
	   select @idsqnumcheck=ID FROM TBLSALESQUOTATIONHEADER
	 CREATE TABLE Temp (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    SALESQUOTATIONHEADERID INT,
    BATCHID NVARCHAR(50),
    SERIALNO INT,
    ITEMID INT,
    QUANTITY DECIMAL(18, 2),
    PRICE DECIMAL(18, 2),
    DISCOUNT DECIMAL(18, 2),
    VATID INT,
    VATAMOUNT DECIMAL(18, 2),
    TOTALAMOUNT DECIMAL(18, 2),
    TOLERANCEID INT,
    REMARKS NVARCHAR(1000),
    DESCRIPTIONS NVARCHAR(1000),
    DISCOUNTID INT,
    ISACTIVE BIT,
 );
 INSERT INTO Temp (SALESQUOTATIONHEADERID,
	   BATCHID,
	   SERIALNO,
	   ITEMID,
	   QUANTITY,
	   PRICE,
	   DISCOUNTID,
	   DISCOUNT,
	   VATID,
	   VATAMOUNT,
	   TOTALAMOUNT,
	   DESCRIPTIONS,
	   REMARKS,
	   ISACTIVE)
SELECT @idsqnumcheck,
	   BATCHID,
	   SERIALNO,
	   ITEMID,
	   QUANTITY,
	   PRICE,
	   DISCOUNTID,
	   DISCOUNT,
	   VATID,
	   VATAMOUNT,
	   TOTALAMOUNT,
	   DESCRIPTIONS,
	   REMARKS,
	   ISACTIVE
FROM TBLSALESQUOTATIONLINE
WHERE SALESQUOTATIONHEADERID IN (SELECT ID FROM TBLSALESQUOTATIONHEADER where ID=@sq);
DECLARE cursor_name CURSOR FOR
SELECT SALESQUOTATIONHEADERID,
       BATCHID,
       SERIALNO,
       ITEMID,
       QUANTITY,
       PRICE,
       DISCOUNTID,
       DISCOUNT,
       VATID,
       VATAMOUNT,
       TOTALAMOUNT,
       DESCRIPTIONS,
       REMARKS,
       ISACTIVE
FROM Temp;

OPEN cursor_name;

FETCH NEXT FROM cursor_name INTO @SALESQUOTATIONHEADERID, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE;

WHILE @@FETCH_STATUS = 0
BEGIN
    INSERT INTO TBLSALESQUOTATIONLINE (SALESQUOTATIONHEADERID, BATCHID, SERIALNO, ITEMID, QUANTITY, PRICE, DISCOUNTID, DISCOUNT, VATID, VATAMOUNT, TOTALAMOUNT, DESCRIPTIONS, REMARKS, ISACTIVE)
    VALUES (@SALESQUOTATIONHEADERID, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE);

    FETCH NEXT FROM cursor_name INTO @SALESQUOTATIONHEADERID, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE;
END;

CLOSE cursor_name;
DEALLOCATE cursor_name;

SELECT @pinum=isnull(MAX(ID),0) FROM TBLSALESQUOTATIONHEADER;
exec SPActivityLog 'Reopen SQ','',@ModuleCode,'SQ',@procode,@unitid,@Enroll
 EXEC SPAPPROVEMATRIXHISTORY 'PEND',@pinum,@MODULECODE,@pinumber,'SQ',@enrollcreate,@unitid
drop table Temp	
end
END