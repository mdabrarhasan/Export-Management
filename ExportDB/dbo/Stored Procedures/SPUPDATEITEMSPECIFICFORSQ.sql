
CREATE PROCEDURE SPUPDATEITEMSPECIFICFORSQ
(
@ID							INT,
@ITEMID						INT,
@LENGTH						VARCHAR(100),
@WIDTH						VARCHAR(100),
@HEIGHT						VARCHAR(100),
@THICKNESS					VARCHAR(100),
@WEIGHT 					VARCHAR(100),
@COLOR						VARCHAR(100),
@SIZE						VARCHAR(100),
@DESIGN						VARCHAR(100),
@PACKAGING					VARCHAR(100),
@MATERIAL					VARCHAR(100),
@CONSTRUCTION				VARCHAR(100),
@PLY						VARCHAR(100),
@CORE						VARCHAR(100),
@TREATMENTDIRECTION			VARCHAR(100),
@OTHERS						VARCHAR(100),
@REMARK						VARCHAR(100),
@PROCESSID					INT,
@PROCESS					VARCHAR(100),
@PROCESSCODE				VARCHAR(100),
@SESSIONID					VARCHAR(100),
@DOCUMENTCREATEDBY			INT,
@MSG						VARCHAR(100)   OUTPUT
)
AS
BEGIN
DECLARE @CHECKITEM INT,@ITEMSPEBATCH VARCHAR(1000)
SET @CHECKITEM=(SELECT COUNT(ITEMID) FROM TBLITEMORDERSPEC WHERE ITEMID=@ITEMID AND PROCESSCODE=@PROCESSCODE)
IF @CHECKITEM=0 
BEGIN

INSERT INTO TBLITEMORDERSPECSTAGING
	(
	ITEMID,LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,SESSIONID,DOCUMENTCREATEDBY,DOCUMENTCREATEDDATE
	)
	VALUES
	(
	@ITEMID,@LENGTH,@WIDTH,@HEIGHT,@THICKNESS,@WEIGHT,@COLOR,@SIZE,@DESIGN,@PACKAGING,@MATERIAL,@CONSTRUCTION,@PLY,@CORE,@TREATMENTDIRECTION,@OTHERS,@REMARK,@SESSIONID,@DOCUMENTCREATEDBY,GETDATE()
	)

	SET @ITEMSPEBATCH=(SELECT CASE WHEN (SELECT DISTINCT COUNT(BATCHID) FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@ProcessCode)=0 THEN
			'BATCH'+CAST((SELECT convert(numeric(12,0),rand() * 899999999999) + 100000000000) AS VARCHAR(500))
			ELSE (SELECT DISTINCT BATCHID FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@ProcessCode) END AS BATCHID)

INSERT INTO TBLITEMORDERSPECSTAGINGHISTORY
SELECT ID,DOCUMENTCREATEDBY,ITEMID,LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,SESSIONID,DOCUMENTCREATEDDATE FROM TBLITEMORDERSPECSTAGING
	

INSERT INTO TBLITEMORDERSPEC    --@ID AS PROCESSID
SELECT @ITEMSPEBATCH,@PROCESSID,@PROCESS,@PROCESSCODE,0,'',ID,ITEMID,LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,SESSIONID,DOCUMENTCREATEDBY,DOCUMENTCREATEDDATE FROM TBLITEMORDERSPECSTAGING

DELETE FROM TBLITEMORDERSPECSTAGING

SET @MSG='Item Specification added for this Item.'
END;

ELSE
BEGIN
UPDATE TBLITEMORDERSPEC
SET LENGTH=@LENGTH,WIDTH=@WIDTH,HEIGHT=@HEIGHT,THICKNESS=@THICKNESS,WEIGHT=@WEIGHT,COLOR=@COLOR,SIZE=@SIZE,DESIGN=@DESIGN,PACKAGING=@PACKAGING,MATERIAL=@MATERIAL
,CONSTRUCTION=@CONSTRUCTION,PLY=@PLY,CORE=@CORE,TREATMENTDIRECTION=@TREATMENTDIRECTION,OTHERS=@OTHERS,REMARK=@REMARK,DOCUMENTCREATEDBY=@DOCUMENTCREATEDBY,DOCUMENTCREATEDDATE=GETDATE() WHERE ID=@ID
END;

SET @MSG='ITEM SPECIFICATION UPDATED FOR THIS ITEM.'


END;