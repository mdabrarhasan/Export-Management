CREATE PROCEDURE [dbo].[SPSAVEPRICECONFIRMBIAX]
(
@TYPEPRICECONFIRMINSERTLINE			TYPEPRICECONFIRMINSERTLINE readonly,
@PRICEEXDATE                         VARCHAR(100),
@TERMSCONDITION						VARCHAR(max),
@DESCRIPTIONS						VARCHAR(max),
@PROFORMAINVOICEHEADERID			INT,
@SELLERID							INT,
@CUSTOMERID							INT,
@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(100),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN
DECLARE @ITEMID INT,@QUANTITY DECIMAL(18,2),@PRICE DECIMAL(18,2),@DISCOUNTID INT,@DISCOUNT DECIMAL(18,2),@VATID INT,@VATAMOUNT DECIMAL(18,2),
@COMMISSION DECIMAL(18,2),@TOTALAMOUNT DECIMAL(18,2),@REMARKS VARCHAR(MAX),@HSCODELINE VARCHAR(100),
@TOLARANCEID DECIMAL(18,2),@FROMSHIPMENTSCHEDULEDATE VARCHAR(50),@TOSHIPMENTSCHEDULEDATE VARCHAR(50),@BATCHID VARCHAR(100),@SERIALNO INT,
@hid int,@lineid int,@nextactiontacker int,@checkapproid int,
@submenuid int,@scopdeid int,@BATCHIDAPPHISTORY VARCHAR(50),@ProcessID int,@ProcessCode varchar(100),@DocStatusID int,@sqllog nvarchar(max),@initiateid int,
@approvecheck int,@checkcom int,@PITOSCID INT,@CHECKPITOSCCHECK INT,@ITEMSPEBATCH VARCHAR(1000),@Toleranceid int,
@UOMID INT,@THIKNESS DECIMAL(18,2),@WIDTH DECIMAL(18,2),@LENGTH DECIMAL(18,2),@TREATMENTLEVEL VARCHAR(500),@TREATMENTDIRECTIONID INT,@COREID INT,@REALOD VARCHAR(500),
@DISEREDDATEOFDELIVERY VARCHAR(500),@TENTATIVEDATEOFDELIVERY VARCHAR(500),@NUMBER VARCHAR(100),@id INT,@SALESQUOTATIONHEADERID INT,@PROFORMAINVID INT,@GLOBALID VARCHAR(50),
@OFFERPRICE DECIMAL(18,2),@CONFIRMPRICE DECIMAL(18,2),@piid int,@COUNT  INT,
@MAXID VARCHAR(100),@QUOTATIONTYPEID INT,@PROINVID INT,@SEELERUNITID INT,@BUYERCUSTOMERID INT

	 DECLARE SQL_CURSOR CURSOR FOR  
	 SELECT ID,ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,VATID,VATAMOUNT,TOLERANCEID,TOTALAMOUNT,REMARKS,DESCRIPTIONS,FROMSHIPMENTSCHEDULEDATE,TOSHIPMENTSCHEDULEDATE,HSCODE,
	 UOMID,THIKNESS,WIDTH,LENGTH,TREATMENTLEVEL,TREATMENTDIRECTIONID,COREID,REALOD,DISEREDDATEOFDELIVERY,TENTATIVEDATEOFDELIVERY
	 FROM @TYPEPRICECONFIRMINSERTLINE
	 OPEN SQL_CURSOR
	 FETCH NEXT FROM SQL_CURSOR INTO @LINEID,@ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONS,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
	 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
	 

	SELECT @PROFORMAINVID=ID,@QUOTATIONTYPEID=QUOTATIONTYPEID,@SEELERUNITID=@UNITID,@BUYERCUSTOMERID=CUSTOMERID,
	@GLOBALID='GLOB'+CAST(@PROFORMAINVID AS VARCHAR(50)) FROM TBLQUOTATIONHEADER WHERE ID=@PROFORMAINVOICEHEADERID

	SET @COUNT=(SELECT COUNT(*) FROM TBLPRICECONFIRMHEADER WHERE PROFORMAINVOICEHEADERID=@PROFORMAINVOICEHEADERID)
	SET @DocStatusID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='PEND');
	SET @MAXID=(SELECT ISNULL(MAX(ID),0)+1 FROM TBLPRICECONFIRMHEADER);
	--SET @NUMBER=(SELECT 'PA'+CAST(RIGHT(YEAR(GETDATE()),2) AS VARCHAR(100))+'BO'+CAST(@MAXID AS VARCHAR(100)))
	SELECT @piid=isnull(MAX(ID),0) FROM TBLPRICECONFIRMHEADER;
	set @piid=@piid+1;

	 SET @NUMBER=(SELECT 'PA-'+Right(Year(getDate()),2)+UPPER(LEFT(Datename(month, GetDate()),3))+
	 CASE WHEN @piid BETWEEN 0 AND 9 THEN '0' + CAST(@piid AS VARCHAR(2)) WHEN @piid BETWEEN 10 AND 99 THEN '0' + CAST(@piid AS VARCHAR(2)) 
	 ELSE CAST(@piid AS VARCHAR(10)) END)
	 --##
	    -- DECLARE @piid INT;
			DECLARE @prefix VARCHAR(20);
			DECLARE @newIncrement INT;
			DECLARE @newQTNumber VARCHAR(30);
			SET @prefix = 'PA-' + RIGHT(YEAR(GETDATE()), 2) + UPPER(LEFT(DATENAME(month, GETDATE()), 3));

			SELECT @newIncrement = 
				ISNULL(MAX(CAST(RIGHT(PCNUMBER, 3) AS INT)), 0) + 1
			FROM TBLPRICECONFIRMHEADER
			WHERE 
				LEFT(PCNUMBER, LEN(@prefix)) = @prefix;

			SET @newQTNumber = @prefix + RIGHT('000' + CAST(@newIncrement AS VARCHAR(3)), 3);

			SET @NUMBER=@newQTNumber



	 --##


IF @COUNT=0
	BEGIN
	INSERT INTO TBLPRICECONFIRMHEADER
	(
	GLOBALID,
	QUOTATIONTYPEID,
	PROFORMAINVOICEHEADERID,
	PCNUMBER,
	SELLERID,
	CUSTOMERID,
	TERMSCONDITION,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	UNITID,
	ISACTIVE,
	PRICEEXDATE
	)
	VALUES
	(
	@GLOBALID,
	@QUOTATIONTYPEID,
	@PROFORMAINVID,
	@NUMBER,
	@SEELERUNITID,
	@BUYERCUSTOMERID,
	@TERMSCONDITION,
	@DESCRIPTIONS,
	GETDATE(),
	@ENROLL,
	@DocStatusID,
	@UNITID,
	1,
	@PRICEEXDATE
	);

	SET @ID=SCOPE_IDENTITY()
	--SET @NUMBER=@PROCESSNAME+CAST(@ID AS VARCHAR(50))
	SET @GLOBALID=(SELECT 'GLOB'+CAST(@ID AS VARCHAR(100)))
	SET @BATCHID=(SELECT 'BATCH'+CAST(@ID AS VARCHAR(100)))

	UPDATE TBLPRICECONFIRMHEADER
	SET GLOBALID=@GLOBALID,PCNUMBER=@NUMBER WHERE ID=@ID
	END
	ELSE
	BEGIN
	SELECT @ID=ID FROM TBLPRICECONFIRMHEADER WHERE PROFORMAINVOICEHEADERID=@PROFORMAINVOICEHEADERID
	SET @BATCHID=(SELECT 'BATCH'+CAST(@ID AS VARCHAR(100)))
	END;
	

  WHILE @@FETCH_STATUS = 0  
  BEGIN
  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLPRICECONFIRMLINE where PRICECONFIRMHEADERID=@ID)
  INSERT INTO TBLPRICECONFIRMLINE
  (
  PRICECONFIRMHEADERID,
  QUOTATIONLINEID,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PRICE,
  OFFERPRICE,
  CONFIRMPRICE,
  THIKNESS,
  WIDTH,
  LENGTH
  )
  VALUES
  (
  @ID,
  @LINEID,
  @BATCHID,
  @SERIALNO,
  @ITEMID,
  @QUANTITY,
  @PRICE,
  @PRICE,
  @PRICE,
  @THIKNESS,
  @WIDTH,
  @LENGTH
  )
  FETCH NEXT FROM SQL_CURSOR INTO @LINEID,@ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONS,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
  @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY

  END;
  --set @Msg=@id
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)
  SET @ProcessCode=@PROCESSNAME+CAST(@ID AS VARCHAR(50))
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@ProcessName,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
END