
/* 2) GET BY ID */
CREATE   PROCEDURE [dbo].[SPSPCUSTOMERBANKGETBYID]
    @ID INT
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        [ID],
        [CUSTOMERNAME],
        [CUSTOMERBANKBRANCHNAME],
        [CUSTOMERBANKNAME],
        [CUSTOMERBANKADDRESSLINEONE],
        [CUSTOMERBANKADDRESSLINETWO],
        [CUSTOMERBANKADDRESSLINETHREE],
        [CUSTOMERBANKBINNO],
        [ISACTIVE],
        [CREATEDBY],
        [CREATEDDATE],
        [UPDATEDBY],
        [UPDATEDDATE]
    FROM [dbo].[TBLCUSTOMERBANK]
    WHERE [ID] = @ID
      AND ISNULL([ISACTIVE], 1) = 1;
END