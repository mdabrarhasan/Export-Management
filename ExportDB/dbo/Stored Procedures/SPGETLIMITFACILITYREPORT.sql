CREATE PROCEDURE SPGETLIMITFACILITYREPORT
AS
BEGIN
SELECT CASE WHEN INNERUNITID=0 THEN BI.BANKNAME ELSE BI.BANKNAME+'[Inner-'+(SELECT NAME FROM TBLUNITFORTREASURY WHERE ID=6)+']' END AS INNERBANKUNIT,
UT.NAME,LF.RAWMATERIALLIMIT,LF.LOANLIMIT,LF.MACHINERYLIMIT,
LF.SHORTTERMLOAN,LF.OVERDRAFTFACILITY,LF.BANKGUARANTEELIMIT,LF.TIMELOANLIMIT,LF.TERMLOANLIMIT,LF.LCSPARESMACHINERYLIMIT
FROM TBLLIMITFACILITY LF,TBLBANKFORTREASURY BI,TBLUNITFORTREASURY UT
WHERE LF.BANKID=BI.BANKID AND
LF.UNITID=UT.ID
END;