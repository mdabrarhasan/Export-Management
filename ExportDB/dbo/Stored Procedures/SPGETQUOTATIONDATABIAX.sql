CREATE PROCEDURE [dbo].[SPGETQUOTATIONDATABIAX]
(
@TYPEID			INT,
@ENROLL			INT
)
AS
BEGIN
	IF @TYPEID=1
	BEGIN
	SELECT 0 AS HISTRYID,ISNULL(PH.ID,0) AS AGREEMENTID,PH.UNITID,PH.QUOTATIONNUMBER AS PINUMBER,0 AS SALESQUOTATIONHEADERID,ISNULL(PH.QUOTATIONTYPEID,0) AS AGREEMENTTYPEID,AGT.NAME AS AGREEMENTTYPE,
	CAST(CAST(PH.DATE AS DATE) AS VARCHAR(50)) AS PIDATE,(SELECT strTypeName FROM  ERP_SAD.DBO.tblCustomerType WHERE intTypeID=PH.SQTYPEID) AS PITYPE,
	CAST(CAST(PH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS PIEXPIREDATE,
	CAST(CAST(PH.SHIPMENTDATE AS DATE) AS VARCHAR(50)) AS SHIPMENTDATE,ISNULL(PH.SHIPMENTMODEID,0) AS SHIPMENTMODEID,
	CAST(CAST(PH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,'' AS SQNUMBER,
	ISNULL(SM.ID,0) AS SHIPMENTID,SM.NAME AS SHIPMENT,ISNULL(PT.ID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,(SELECT STRING_AGG(HSCODE, ', ') 
FROM TBLQUOTATIONHSCODE WHERE QTID=PH.ID) AS   HSCODE,PH.BUYERREGNO,PH.CURRENCYID,ISNULL(PH.DELIVERYTERMID,0) AS DELIVERYTERMID,PH.DESCRIPTIONS,PH.TERMSCONDITION,
	ISNULL(TSC.ID,0) AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,ISNULL(FSC.ID,0) AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
	ISNULL(LP.ID,0) AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,ISNULL(DP.ID,0) AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,CURR.NAME AS CURRENCY,'' AS DELIVERYTERM,
	PH.TARRIFCODE,ISNULL(INCO.ID,0) AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,ISNULL(DS.ID,0) AS DOCSTATUSID,DS.NAME AS DOSSTATUS,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
	PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERBANKID as BUYERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,
	CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
	PH.NOTIFYPARTY,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL,ISNULL(PH.QUOTATIONTYPEID,0) AS QUOTATIONTYPEID,
	ISNULL(LB.ID,0) AS LOADINGBYID,LB.NAME AS LOADINGBY,PH.LOADINGPLACE,
	ISNULL(PH.SALESTYPEID,0) AS SALESTYPEID,
	ST.NAME AS SALESTYPE,
	ISNULL(PH.CREDITTYPEID,0) AS CREDITTYPEID,
	CT.NAME AS CREDITTYPE,

	ISNULL(PH.FREEINCOTERM,0) as 'FREEINCOTERM' ,
	ISNULL(PH.FREEPAYMENTTERM,0) as 'FREEPAYMENTTERM',
	ISNULL(PH.TOLARENCEID,0) as 'TOLARENCEID',
	ISNULL(qdp.intDisPointId,0) as 'DELPOINTID',
	qdp.strContactPerson as 'DELPOINTCONTRACTPERSON',
	qdp.strContactNo as 'DELPOINTCONTRACTNO',
	qdp.strAddress as 'DELPOINTADDRESS',
	qdp.strDisPointName as 'DELPOINTNAME',

	PH.CREDITDAYS,ISNULL(PH.OCFID,0) AS OCFID,PH.OCFNO,0 AS PITYPEID
	from TBLQUOTATIONHEADER PH			 LEFT JOIN ERP_SAD.DBO.tblCustomer			   CUS
	ON PH.CUSTOMERID=cus.intCusID		 LEFT JOIN TBLSHIPMENTMODE					   SM
	ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
	ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
	ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
	ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
	ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
	ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
	ON PH.INCOTERM=INCO.ID				 LEFT JOIN TBLDOCUMENTSTATUS				   DS
	ON PH.DOCUMENTSTATUSID=DS.ID		 LEFT JOIN TBLQUOTATIONTYPE				   AGT
	ON PH.QUOTATIONTYPEID=AGT.ID		 LEFT JOIN TBLCURRENCY						   CURR
	ON CURR.ID=PH.CURRENCYID		   	 LEFT JOIN TBLOADINGBY						   LB
	ON PH.LOADINGBYID=LB.ID				 LEFT JOIN TBLSALESTYPE						   ST
	ON PH.SALESTYPEID=ST.ID				 LEFT JOIN TBLCREDITTYPE					   CT
	ON PH.CREDITTYPEID=CT.ID             LEFT JOIN ERP_SAD.dbo.qryDisPoint             qdp
	ON qdp.intDisPointId = PH.DELPOINTID
	WHERE PH.ISACTIVE=1 AND QUOTATIONTYPEID=1
	order by PH.ID desc;
	END;

	IF @TYPEID=2
	BEGIN
	SELECT 0 AS HISTRYID,QH.ID,QH.CUSTOMERID,CUS.strName AS CUSNAME,QH.QUOTATIONNUMBER,QH.QUOTATIONTYPEID,
	CAST(CAST(QH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,QH.SQTYPEID AS SQTYPEID,
	(SELECT strTypeName FROM  ERP_SAD.DBO.tblCustomerType WHERE intTypeID=QH.SQTYPEID) AS SQTYPE,DOCSTATUS.CODE AS CODE,DOCSTATUS.NAME AS DOCSTATUS,
	EMP.strEmployeeName+' ['+CAST(EMP.intEmployeeID AS VARCHAR(100))+' ]' AS EMPNAME,
	ISNULL(QH.SALESTYPEID,0) AS SALESTYPEID,
	ST.NAME AS SALESTYPE,
	ISNULL(QH.CREDITTYPEID,0) AS CREDITTYPEID,
	CT.NAME AS CREDITTYPE,
	QH.CREDITDAYS,ISNULL(QH.OCFID,0) AS OCFID,QH.OCFNO,QH.TERMSCONDITION
	FROM TBLQUOTATIONHEADER	QH					INNER JOIN		ERP_SAD.DBO.tblCustomer			CUS
	ON QH.CUSTOMERID=CUS.intCusID				LEFT JOIN      ERP_SAD.DBO.tblCustomerType						QTYPE
	ON QH.SQTYPEID=QTYPE.intTypeID			INNER JOIN      TBLDOCUMENTSTATUS				DOCSTATUS
	ON QH.DOCUMENTSTATUSID=DOCSTATUS.ID			INNER JOIN		ERP_HR.DBO.tblEmployee			EMP
	ON QH.DOCUMENTCREATEDBY=EMP.intEmployeeID	LEFT JOIN TBLSALESTYPE						    ST
	ON QH.SALESTYPEID=ST.ID						LEFT JOIN TBLCREDITTYPE							CT
	ON QH.CREDITTYPEID=CT.ID	
	WHERE QH.ISACTIVE=1 AND QUOTATIONTYPEID=2
	END;
	IF @TYPEID=3
	BEGIN
	SELECT 0 AS HISTRYID,QH.ID,QH.CUSTOMERID,CUS.strName AS CUSNAME,QH.QUOTATIONNUMBER,
	CAST(CAST(QH.SPOTDATE AS DATE) AS VARCHAR(50)) AS SPOTDATE,
	CAST(CAST(QH.LASTDATEOFDO AS DATE) AS VARCHAR(50)) AS LASTDATEOFDO,
	DOCSTATUS.CODE AS CODE,DOCSTATUS.NAME AS DOCSTATUS,QH.QUOTATIONTYPEID,
	EMP.strEmployeeName+' ['+CAST(EMP.intEmployeeID AS VARCHAR(100))+' ]' AS EMPNAME,
	ISNULL(QH.SALESTYPEID,0) AS SALESTYPEID,
	ST.NAME AS SALESTYPE,
	ISNULL(QH.CREDITTYPEID,0) AS CREDITTYPEID,
	CT.NAME AS CREDITTYPE,
	QH.CREDITDAYS,ISNULL(QH.OCFID,0) AS OCFID,QH.OCFNO,QH.TERMSCONDITION
	FROM TBLQUOTATIONHEADER	QH					INNER JOIN		ERP_SAD.DBO.tblCustomer			CUS
	ON QH.CUSTOMERID=CUS.intCusID				INNER JOIN      TBLDOCUMENTSTATUS				DOCSTATUS
	ON QH.DOCUMENTSTATUSID=DOCSTATUS.ID			INNER JOIN		ERP_HR.DBO.tblEmployee			EMP
	ON QH.DOCUMENTCREATEDBY=EMP.intEmployeeID	AND QUOTATIONTYPEID=3 AND QH.ISACTIVE=1
												LEFT JOIN TBLSALESTYPE						    ST
	ON QH.SALESTYPEID=ST.ID						LEFT JOIN TBLCREDITTYPE							CT
	ON QH.CREDITTYPEID=CT.ID					
	END;
	IF @TYPEID=4
	BEGIN
	SELECT 0 AS HISTRYID,ISNULL(QH.ID,0) AS ID,QH.QUOTATIONNUMBER,QH.QUOTATIONTYPEID,ISNULL(QH.WHID,0) AS WHID,
	(select TOP 1 strName FROM ERP_SAD.[dbo].[qryShipPointByOperator] WHERE intShipPointId=QH.WHID) AS WHNAME,CAST(CAST(QH.CONAPPSTATRDATE AS DATE) AS VARCHAR(50)) AS CONAPPSTATRDATE,
	CAST(CAST(QH.CONAPPENDDATE AS DATE) AS VARCHAR(50)) AS CONAPPENDDATE,
	QH.TERMSCONDITION,QH.DESCRIPTIONS,DOCSTATUS.CODE AS CODE,DOCSTATUS.NAME AS DOCSTATUS,
	EMP.strEmployeeName+' ['+CAST(EMP.intEmployeeID AS VARCHAR(100))+' ]' AS EMPNAME,
	ISNULL(QH.SALESTYPEID,0) AS SALESTYPEID,
	ST.NAME AS SALESTYPE,
	ISNULL(QH.CREDITTYPEID,0) AS CREDITTYPEID,
	CT.NAME AS CREDITTYPE,
	QH.CREDITDAYS,ISNULL(QH.OCFID,0) AS OCFID,QH.OCFNO
	--,QH.TERMSCONDITION
	FROM TBLQUOTATIONHEADER	QH					LEFT JOIN		ERP_Inventory.dbo.tblWearHouse	WH
	ON QH.WHID=WH.intWHID						INNER JOIN      TBLQUOTATIONTYPE				QTYPE
	ON QH.QUOTATIONTYPEID=QTYPE.ID				INNER JOIN      TBLDOCUMENTSTATUS				DOCSTATUS
	ON QH.DOCUMENTSTATUSID=DOCSTATUS.ID			INNER JOIN		ERP_HR.DBO.tblEmployee			EMP
	ON QH.DOCUMENTCREATEDBY=EMP.intEmployeeID	LEFT JOIN TBLSALESTYPE						    ST
	ON QH.SALESTYPEID=ST.ID						LEFT JOIN TBLCREDITTYPE							CT
	ON QH.CREDITTYPEID=CT.ID	
	WHERE QH.ISACTIVE=1 AND QUOTATIONTYPEID=4
	END;
	IF @TYPEID=5
	BEGIN
	SELECT 0 AS HISTRYID,QH.ID,QH.CUSTOMERID,CUS.strName AS CUSNAME,QH.QUOTATIONNUMBER,
	CAST(CAST(QH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,QH.SQTYPEID AS SQTYPEID,
	(SELECT strTypeName FROM  ERP_SAD.DBO.tblCustomerType WHERE intTypeID=QH.SQTYPEID) AS SQTYPE,DOCSTATUS.CODE AS CODE,DOCSTATUS.NAME AS DOCSTATUS,
	EMP.strEmployeeName+' ['+CAST(EMP.intEmployeeID AS VARCHAR(100))+' ]' AS EMPNAME,
	ISNULL(QH.SALESTYPEID,0) AS SALESTYPEID,
	ST.NAME AS SALESTYPE,
	ISNULL(QH.CREDITTYPEID,0) AS CREDITTYPEID,
	CT.NAME AS CREDITTYPE,
	QH.CREDITDAYS,ISNULL(QH.OCFID,0) AS OCFID,QH.OCFNO
	FROM TBLQUOTATIONHEADER	QH					INNER JOIN		ERP_SAD.DBO.tblCustomer			CUS
	ON QH.CUSTOMERID=CUS.intCusID				INNER JOIN      ERP_SAD.DBO.tblCustomerType						QTYPE
	ON QH.QUOTATIONTYPEID=QTYPE.intTypeID			INNER JOIN      TBLDOCUMENTSTATUS				DOCSTATUS
	ON QH.DOCUMENTSTATUSID=DOCSTATUS.ID			INNER JOIN		ERP_HR.DBO.tblEmployee			EMP
	ON QH.DOCUMENTCREATEDBY=EMP.intEmployeeID	LEFT JOIN TBLSALESTYPE						    ST
	ON QH.SALESTYPEID=ST.ID						LEFT JOIN TBLCREDITTYPE							CT
	ON QH.CREDITTYPEID=CT.ID	
	WHERE QH.ID=@ENROLL --AND QUOTATIONTYPEID=2
	
	END;
END;