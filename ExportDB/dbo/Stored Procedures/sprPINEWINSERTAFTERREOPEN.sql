CREATE PROCEDURE [dbo].[sprPINEWINSERTAFTERREOPEN] 
	@pi INT,@unitid int,
	@ModuleCode varchar(50),@Enroll int,@mgs varchar(100) output
AS
BEGIN
	-- SET NOCOUNT ON added to prevent extra result sets from
	-- interfering with SELECT statements.
	SET NOCOUNT ON;
	DECLARE @PISCHEADER INT,
        @BATCHID NVARCHAR(50),
        @SERIALNO INT,
        @ITEMID INT,
        @QUANTITY DECIMAL(18, 2),
        @PRICE DECIMAL(18, 2),
        @DISCOUNTID INT,
        @DISCOUNT DECIMAL(18, 2),
        @VATID INT,
        @VATAMOUNT DECIMAL(18, 2),
        @TOTALAMOUNT DECIMAL(18, 2),
        @DESCRIPTIONS NVARCHAR(1000),
        @REMARKS NVARCHAR(1000),
        @ISACTIVE BIT,
        @FROMSHIPMENTSCHEDULEDATE DATETIME,
        @TOSHIPMENTSCHEDULEDATE DATETIME,
        @HSCODE NVARCHAR(100);
DECLARE @Sqid int,@piid int,@PRID INT,@pc int,@pr int ,@ppid int,@formattedDate VARCHAR(50),@enrollcreate varchar(50),@idsqnumcheck INT,
@type int,@lcid int,@procode varchar(50),@pinum int,@pinumber varchar(50)
	--select @SQid=ID from TBLSALESQUOTATIONHEADER WHERE ID=@pi AND DOCUMENTSTATUSID=7 ;
	select @piid=ID,@procode=NUMBER,@enrollcreate=DOCUMENTCREATEDBY from TBLPISCHEADER where ID=@pi AND DOCUMENTSTATUSID=7;
	select @lcid=ID from TBLLCDETAILS where PISCHEADERID=@piid AND DOCUMENTSTATUSID=7;
	SELECT @pc=ID FROM TBLPRICECONFIRMHEADER WHERE PROFORMAINVOICEHEADERID=@piid AND DOCUMENTSTATUSID=7;
	SELECT @pr=ID FROM TBLPACKINGREQUESTHEADER WHERE PISCNUMBER=@piid AND DOCUMENTSTATUSID=7
	select @ppid=ID from TBLPICKINGPACKINGHEADER where PACKINGREQUESTHEADERID=@pr AND DOCUMENTSTATUSID=7;
	
	 SELECT @pinum=isnull(MAX(ID),0) FROM TBLPISCHEADER;
	   
	  set @pinum=@pinum+1;

	   

	   SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  set @pinumber='PI' + '-' + @formattedDate + '-' + cast(@pinum as varchar(10))
	if(@pr is not null)
	begin
	set @mgs='Please At First Cancle The Packing Request'
	end
	else if(@lcid is not null)
	begin
	set @mgs='Please At First Cancle The LC Request'
	end
	else if(@pc is not null)
	begin
	set @mgs='Please At First Cancle The Price Confirmation Request'
	end
	else
	begin
	update TBLPISCHEADER set ISACTIVE=0  WHERE ID=@pi AND DOCUMENTSTATUSID=7
	INSERT INTO TBLPISCHEADER
	(
	LOADINGPLACE,
	LOADINGBYID,
	NUMBER,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	DOCUMENTSTATUSID,
	ISACTIVE,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	PITOSC,
	ISPROCESSEDWITHAPPROVAL,
	REOPENID,
REOPNPINUMBER
	)
	select 
	LOADINGPLACE,
	LOADINGBYID,
	@pinumber,
	SALESQUOTATIONHEADERID,
	AGREEMENTTYPEID,
	CUSTOMERID,
	DATE,
	EXPIREDATE,
	SHIPMENTDATE,
	SHIPMENTMODEID,
	PAYMENTTERMID,
	DELIVERYTERMID,
	TERMSCONDITION,
	TOSHIPMENTCOUNTRYID,
	FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID,
	TODISCHARGEPORT,
	TARRIFCODE,
	HSCODE,
	BUYERREGNO,
	INCOTERM,
	CURRENCYID,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY,
	1,
	1,
	UNITID,

	BUYERBANKDETAILS,
	SELLERBANKID,
	BUYERCOUNTRYHSCODE,
	TRANSHIPMENT,
	PARTIALSHIPMENT,
	ORIGINOFCOUNTRY,
	BUYERORDERCONFIRMDATE,
	NOTIFYPARTY,
	OTHERSPAYTERM,
	PITOSC,
	1,
	@piid,
	@procode
	from TBLPISCHEADER where ID=@pi;
	 select @idsqnumcheck=ID FROM TBLPISCHEADER
	CREATE TABLE temp (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    PISCHEADER INT,
    BATCHID NVARCHAR(50),
    SERIALNO INT,
    ITEMID INT,
    QUANTITY DECIMAL(18, 2),
    PRICE DECIMAL(18, 2),
    DISCOUNTID INT,
    DISCOUNT DECIMAL(18, 2),
    VATID INT,
    VATAMOUNT DECIMAL(18, 2),
    TOTALAMOUNT DECIMAL(18, 2),
    TOLERANCEID INT,
    REMARKS NVARCHAR(1000),
    DESCRIPTIONS NVARCHAR(1000),
    ISACTIVE BIT,
    FROMSHIPMENTSCHEDULEDATE DATETIME,
    TOSHIPMENTSCHEDULEDATE DATETIME,
    HSCODE NVARCHAR(100)
);
INSERT INTO temp(
  PISCHEADER,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PRICE,
  DISCOUNTID,
  DISCOUNT,
  VATID,
  VATAMOUNT,
  TOTALAMOUNT,
  TOLERANCEID,
  REMARKS,
  DESCRIPTIONS,
  ISACTIVE,
  FROMSHIPMENTSCHEDULEDATE,
  TOSHIPMENTSCHEDULEDATE,
  HSCODE
  )
  select @idsqnumcheck,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PRICE,
  DISCOUNTID,
  DISCOUNT,
  VATID,
  VATAMOUNT,
  TOTALAMOUNT,
  TOLERANCEID,
  REMARKS,
  DESCRIPTIONS,
  ISACTIVE,
  FROMSHIPMENTSCHEDULEDATE,
  TOSHIPMENTSCHEDULEDATE,
  HSCODE from TBLPISCLINE where PISCHEADER in (SELECT ID FROM TBLPISCHEADER where ID=@pi);
  DECLARE cursor_name CURSOR FOR
SELECT PISCHEADER,
       BATCHID,
       SERIALNO,
       ITEMID,
       QUANTITY,
       PRICE,
       DISCOUNTID,
       DISCOUNT,
       VATID,
       VATAMOUNT,
       TOTALAMOUNT,
       DESCRIPTIONS,
       REMARKS,
       ISACTIVE,
       FROMSHIPMENTSCHEDULEDATE,
       TOSHIPMENTSCHEDULEDATE,
       HSCODE
FROM Temp;

OPEN cursor_name;

FETCH NEXT FROM cursor_name INTO @PISCHEADER, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE, @FROMSHIPMENTSCHEDULEDATE, @TOSHIPMENTSCHEDULEDATE, @HSCODE;

WHILE @@FETCH_STATUS = 0
BEGIN
    INSERT INTO TBLPISCLINE (PISCHEADER, BATCHID, SERIALNO, ITEMID, QUANTITY, PRICE, DISCOUNTID, DISCOUNT, VATID, VATAMOUNT, TOTALAMOUNT, DESCRIPTIONS, REMARKS, ISACTIVE, FROMSHIPMENTSCHEDULEDATE, TOSHIPMENTSCHEDULEDATE, HSCODE)
    VALUES (@PISCHEADER, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE, @FROMSHIPMENTSCHEDULEDATE, @TOSHIPMENTSCHEDULEDATE, @HSCODE);

    FETCH NEXT FROM cursor_name INTO @PISCHEADER, @BATCHID, @SERIALNO, @ITEMID, @QUANTITY, @PRICE, @DISCOUNTID, @DISCOUNT, @VATID, @VATAMOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, @ISACTIVE, @FROMSHIPMENTSCHEDULEDATE, @TOSHIPMENTSCHEDULEDATE, @HSCODE;
END;

CLOSE cursor_name;
DEALLOCATE cursor_name;
SELECT @pinum=isnull(MAX(ID),0) FROM TBLPISCHEADER;
exec SPActivityLog 'Reopen PI','',@ModuleCode,'PI',@procode,@unitid,@Enroll
  EXEC SPAPPROVEMATRIXHISTORY 'PEND',@pinum,@MODULECODE,@pinumber,'PI',@enrollcreate,@unitid
drop table temp;
end
END