
CREATE PROCEDURE SPCUSTOMERBANKINFGETALL
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE,
        CREATEDDATE
    FROM [ABGAPIS].[dbo].[TBLCUSTOMERBANK]
    WHERE ISACTIVE > 0
    ORDER BY CREATEDDATE DESC
END