CREATE PROCEDURE [dbo].[SPGetCombineSQitem]
    @TYPESQIDLINE TYPESQIDLINE READONLY
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        MAX(SQL_LINE.ID) AS ID,
        MAX(SQH.ID) AS PISCHEADER,
        MAX(SQH.UNITID) AS UNITID,
        CAST(ROW_NUMBER() OVER (ORDER BY SQL_LINE.ITEMID) AS INT) AS SERIALNO,
        SQL_LINE.ITEMID,
        ISNULL(MAX(IT.NAME), '') AS ITEMTYPENAME,
        ITEM.strProductName AS ITEMNAME,
        ISNULL(MAX(SQL_LINE.SIZE), '') AS SIZE,
        ISNULL(MAX(SQL_LINE.CONSTRUCTION), '') AS CONSTRUCTION,
        ISNULL(MAX(SQL_LINE.WEIGHT), '') AS WEIGHT,
        ISNULL(MAX(SQL_LINE.SLIT), '') AS SLIT,
        ISNULL(MAX(SQL_LINE.SCRIM), '') AS SCRIM,
        ISNULL(MAX(SQL_LINE.QUALITY), '') AS QUALITY,
        ISNULL(MAX(SQL_LINE.ITEMTITLE), '') AS ITEMTITLE,
        ISNULL(MAX(SQL_LINE.PACKINGDETAILS), '') AS PACKINGDETAILS,
        UOM.strUOM AS UOM,
        CAST(SUM(SQL_LINE.QUANTITY) AS DECIMAL(18,2)) AS QUANTITY,
        CAST(AVG(SQL_LINE.PRICE) AS DECIMAL(18,2)) AS PRICE,
        0 AS DISCOUNTID,
        '' AS vatname,
        CAST(0 AS DECIMAL(18,2)) AS DISCOUNT,
        0 AS VATID,
        '' AS disname,
        CAST(0 AS DECIMAL(18,2)) AS VATAMOUNT,
        CAST(0 AS DECIMAL(18,2)) AS TOTALAMOUNT,
        ISNULL(MAX(SQL_LINE.REMARKS), '') AS REMARKS,
        '' AS DESCRIPTIONS,
        MAX(SQH.SHIPMENTMODE) AS SHIPMENTMODE,
        MAX(SQH.FROMSHIPMENT) AS FROMSHIPMENT,
        MAX(SQH.TOSHIPMENT) AS TOSHIPMENT,
        MAX(SQH.CURRENCY) AS CURRENCY,
        MAX(SQH.LOADINGPORT) AS LOADINGPORT,
        MAX(ISNULL(SQH.LOADINGPLACE, '')) AS LOADINGPLACE,
        CAST(MAX(ISNULL(SQH.INCOTERM, 0)) AS VARCHAR(50)) AS INCOTERM,
        MAX(ISNULL(SQH.PAYMENTTERMS_ID, 0)) AS PAYMENTTERMS,
        MAX(ISNULL(SQH.SHIPPINGPERIOD, '')) AS SHIPPINGPERIOD,
        MAX(ISNULL(SQH.TRANSPORTATIONMODE, 0)) AS TRANSPORTATIONMODE,
        MAX(ISNULL(SQH.PAYMENTTERMS, '')) AS TEXTPAYMENT,
        MAX(ISNULL(SQH.TEXTFROMSHIPMENT, '')) AS TEXTFROMSHIPMENT,
        MAX(ISNULL(SQH.DESTINATIONPORT, '')) AS DESTINATIONPORT
    FROM TBLSALESQUOTATIONLINE SQL_LINE
    INNER JOIN TBLSALESQUOTATIONHEADER SQH 
        ON SQL_LINE.SALESQUOTATIONHEADERID = SQH.ID
    INNER JOIN ERP_SAD.DBO.tblItem ITEM 
        ON SQL_LINE.ITEMID = ITEM.intID
    INNER JOIN ERP_SAD.DBO.tblUOM UOM 
        ON SQL_LINE.UOMID = UOM.intID
    LEFT JOIN TBLITEMTYPE IT
        ON SQL_LINE.ITEMTYPEID = IT.ID
    LEFT JOIN (
        SELECT 
            PISCH.SALESQUOTATIONHEADERID,
            PRL.ITEMID,
            SUM(PRL.PACKINGREQQUANTITY) AS TAKEN_QTY
        FROM TBLPACKINGREQUESTHEADER PRH
        INNER JOIN TBLPACKINGREQUESTLINE PRL 
            ON PRH.ID = PRL.PACKINGREQUESTHEADERID
        INNER JOIN TBLPISCHEADER PISCH 
            ON PRH.PISCNUMBER = PISCH.ID
        WHERE PRL.ISACTIVE = 1
          AND PISCH.SALESQUOTATIONHEADERID IN (SELECT ID FROM @TYPESQIDLINE)
        GROUP BY PISCH.SALESQUOTATIONHEADERID, PRL.ITEMID
    ) PRL_AGG 
        ON PRL_AGG.SALESQUOTATIONHEADERID = SQL_LINE.SALESQUOTATIONHEADERID
       AND PRL_AGG.ITEMID = SQL_LINE.ITEMID
    WHERE SQL_LINE.SALESQUOTATIONHEADERID IN (SELECT ID FROM @TYPESQIDLINE)
      AND SQL_LINE.ISACTIVE = 1
    GROUP BY 
        SQL_LINE.ITEMID,
        ITEM.strProductName,
        UOM.strUOM
    HAVING SUM(SQL_LINE.QUANTITY) - ISNULL(SUM(PRL_AGG.TAKEN_QTY), 0) > 0
    ORDER BY SQL_LINE.ITEMID;
END