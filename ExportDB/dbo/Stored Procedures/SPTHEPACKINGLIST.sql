CREATE PROCEDURE [dbo].[SPTHEPACKINGLIST]
    @HEADERID INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @INVOICENUMBER VARCHAR(50), @INVOICEDATE DATE
    DECLARE @CONTRACTNO VARCHAR(50), @CONTRACTDATE DATE
    DECLARE @SHIPPEDPER VARCHAR(50), @SHIPPEDFROM VARCHAR(50), @SHIPPEDTO VARCHAR(50)
    DECLARE @PURCHASEORDERNO VARCHAR(50), @PURCHASEORDERDATED DATE
    DECLARE @BINNO VARCHAR(50), @TIN VARCHAR(50), @UNITNAME NVARCHAR(200)
    DECLARE @INVOICETO VARCHAR(50), @CUSTOMERADDRESS NVARCHAR(MAX)
    DECLARE @GROSSWEIGHT DECIMAL(18,2), @NETWEIGHT DECIMAL(18,2)
    DECLARE @PRODUCT_QUANTITY NVARCHAR(500), @DESCRIPTION_SPECIFICATION NVARCHAR(1000)
    DECLARE @MARKS NVARCHAR(MAX) = '', @TRUSSES NVARCHAR(MAX) = ''
    DECLARE @CARTONS NVARCHAR(MAX) = '', @BUNDLES NVARCHAR(MAX) = ''
    DECLARE @SALESCONTRACTHEADERID INT

    SELECT 
        @INVOICENUMBER = ISNULL(H.INVOICENUMBER, ''),
        @INVOICEDATE = TRY_CONVERT(DATE, H.INVOICEDATE),
        @INVOICETO = ISNULL(H.INVOICETO, ''),
        @SHIPPEDPER = ISNULL(H.SHIPPEDPER, ''),
        @SHIPPEDFROM = ISNULL(H.SHIPPEDFROM, ''),
        @SHIPPEDTO = ISNULL(H.SHIPPEDTO, ''),
        @CONTRACTNO = ISNULL(H.CONTRACTNO, ''),
        @CONTRACTDATE = H.CONTRACTDATE,
        @PURCHASEORDERNO = ISNULL(H.PURCHASEORDERNO, ''),
        @PURCHASEORDERDATED = H.PURCHASEORDERDATED,
        @SALESCONTRACTHEADERID = H.SALESCONTRACTHEADERID,
        @BINNO = ISNULL(U.strBINNo, ''),
        @TIN = ISNULL(U.strTIN, '')
    FROM TBLPACKINGREQUESTHEADER H
    INNER JOIN ERP_HR.dbo.tblUnit U ON U.intUnitID = H.UNITID
    WHERE H.ID = @HEADERID AND H.ISACTIVE = 1

    IF @SALESCONTRACTHEADERID IS NULL
        SELECT @SALESCONTRACTHEADERID = SALESQUOTATIONHEADERID FROM TBLPISCHEADER 
        WHERE ID = (SELECT PISCNUMBER FROM TBLPACKINGREQUESTHEADER WHERE ID = @HEADERID)

    SELECT @UNITNAME = ISNULL(U.strDescription, '')
    FROM TBLSALESQUOTATIONHEADER SQ
    INNER JOIN ERP_HR.dbo.tblUnit U ON U.intUnitID = SQ.UNITID
    WHERE SQ.ID = @SALESCONTRACTHEADERID

    SELECT @CUSTOMERADDRESS = ISNULL(C.strAddress, '')
    FROM TBLPISCHEADER PIS
    INNER JOIN ERP_SAD.dbo.tblCustomer C ON C.intCusID = PIS.CUSTOMERID
    WHERE PIS.ID = (SELECT PISCNUMBER FROM TBLPACKINGREQUESTHEADER WHERE ID = @HEADERID)

    SELECT @GROSSWEIGHT = ISNULL(SUM(GROSSWEIGHT), 0), @NETWEIGHT = ISNULL(SUM(ADDITIONALWEIGHT), 0)
    FROM TBLPACKINGREQUESTLINE WHERE PACKINGREQUESTHEADERID = @HEADERID AND ISACTIVE = 1

    SELECT @PRODUCT_QUANTITY = ISNULL(PRODUCT_QUANTITY, ''), @DESCRIPTION_SPECIFICATION = ISNULL(DESCRIPTION_SPECIFICATION, '')
    FROM TBLSALESQUOTATIONHEADER WHERE ID = @SALESCONTRACTHEADERID AND ISACTIVE = 1

    -- Build MARKS
    SELECT @MARKS = @MARKS 
        + CASE WHEN @MARKS != '' THEN ', ' ELSE '' END
        + ISNULL(ITEMNAME, '')
        + CASE WHEN SIZE IS NOT NULL AND SIZE != '' THEN ' ' + SIZE ELSE '' END
        + CASE WHEN QUALITIES != '' THEN ', ' + QUALITIES ELSE '' END
    FROM (
        SELECT ITEMNAME, MAX(SIZE) AS SIZE, STRING_AGG(QUALITY, ', ') AS QUALITIES
        FROM (
            SELECT DISTINCT I.strProductName AS ITEMNAME, L.SIZE, L.QUALITY
            FROM TBLSALESQUOTATIONLINE L
            INNER JOIN ERP_SAD.dbo.tblItem I ON L.ITEMID = I.intID
            WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID
                AND L.ISACTIVE = 1 AND L.QUALITY IS NOT NULL AND L.QUALITY != ''
        ) AS D
        GROUP BY ITEMNAME
    ) AS G

    -- Build TRUSSES
    DECLARE @PD NVARCHAR(MAX), @POS INT, @NS INT, @NSTR VARCHAR(20), @SN INT
    DECLARE tc CURSOR LOCAL FAST_FORWARD FOR
        SELECT PACKINGDETAILS, SERIALNO FROM TBLSALESQUOTATIONLINE
        WHERE SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID AND ISACTIVE = 1 AND PACKINGDETAILS LIKE '%TRUS%'
        ORDER BY SERIALNO
    OPEN tc
    FETCH NEXT FROM tc INTO @PD, @SN
    WHILE @@FETCH_STATUS = 0
    BEGIN
        SET @POS = PATINDEX('%TRUS%', @PD)
        SET @NSTR = ''
        SET @NS = @POS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) = ' ' SET @NS = @NS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) LIKE '[0-9]'
        BEGIN
            SET @NSTR = SUBSTRING(@PD, @NS, 1) + @NSTR
            SET @NS = @NS - 1
        END
        IF @NSTR != ''
        BEGIN
            IF @TRUSSES != '' SET @TRUSSES = @TRUSSES + ' '
            SET @TRUSSES = @TRUSSES + '1-' + @NSTR
        END
        FETCH NEXT FROM tc INTO @PD, @SN
    END
    CLOSE tc
    DEALLOCATE tc

    -- Build CARTONS
    DECLARE cc CURSOR LOCAL FAST_FORWARD FOR
        SELECT PACKINGDETAILS, SERIALNO FROM TBLSALESQUOTATIONLINE
        WHERE SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID AND ISACTIVE = 1 AND PACKINGDETAILS LIKE '%CARTON%'
        ORDER BY SERIALNO
    OPEN cc
    FETCH NEXT FROM cc INTO @PD, @SN
    WHILE @@FETCH_STATUS = 0
    BEGIN
        SET @POS = PATINDEX('%CARTON%', @PD)
        SET @NSTR = ''
        SET @NS = @POS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) = ' ' SET @NS = @NS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) LIKE '[0-9]'
        BEGIN
            SET @NSTR = SUBSTRING(@PD, @NS, 1) + @NSTR
            SET @NS = @NS - 1
        END
        IF @NSTR != ''
        BEGIN
            IF @CARTONS != '' SET @CARTONS = @CARTONS + ' '
            SET @CARTONS = @CARTONS + '1-' + @NSTR
        END
        FETCH NEXT FROM cc INTO @PD, @SN
    END
    CLOSE cc
    DEALLOCATE cc

    -- Build BUNDLES
    DECLARE bc CURSOR LOCAL FAST_FORWARD FOR
        SELECT PACKINGDETAILS, SERIALNO FROM TBLSALESQUOTATIONLINE
        WHERE SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID AND ISACTIVE = 1 AND PACKINGDETAILS LIKE '%BUNDLE%'
        ORDER BY SERIALNO
    OPEN bc
    FETCH NEXT FROM bc INTO @PD, @SN
    WHILE @@FETCH_STATUS = 0
    BEGIN
        SET @POS = PATINDEX('%BUNDLE%', @PD)
        SET @NSTR = ''
        SET @NS = @POS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) = ' ' SET @NS = @NS - 1
        WHILE @NS > 0 AND SUBSTRING(@PD, @NS, 1) LIKE '[0-9]'
        BEGIN
            SET @NSTR = SUBSTRING(@PD, @NS, 1) + @NSTR
            SET @NS = @NS - 1
        END
        IF @NSTR != ''
        BEGIN
            IF @BUNDLES != '' SET @BUNDLES = @BUNDLES + ' '
            SET @BUNDLES = @BUNDLES + '1-' + @NSTR
        END
        FETCH NEXT FROM bc INTO @PD, @SN
    END
    CLOSE bc
    DEALLOCATE bc

    -- Return one row per item group
    ;WITH ItemGroups AS (
        SELECT
            DENSE_RANK() OVER (ORDER BY L.ITEMTITLE) AS GROUPNO,
            L.ITEMTITLE,
            ROW_NUMBER() OVER (PARTITION BY L.ITEMTITLE ORDER BY L.SERIALNO) AS SUBNO,
            CHAR(64 + ROW_NUMBER() OVER (PARTITION BY L.ITEMTITLE ORDER BY L.SERIALNO)) + ') '
                + FORMAT(L.QUANTITY, '0.##') + ISNULL(U.strUOM, '')
                + CASE WHEN I.strProductName != '' THEN ', ' + I.strProductName ELSE '' END
                + CASE WHEN L.QUALITY IS NOT NULL THEN ', ' + L.QUALITY ELSE '' END
                + CASE WHEN L.PACKINGDETAILS IS NOT NULL THEN ', ' + L.PACKINGDETAILS ELSE '' END
                AS SUBPOINT
        FROM TBLSALESQUOTATIONLINE L
        INNER JOIN ERP_SAD.dbo.tblItem I ON L.ITEMID = I.intID
        LEFT JOIN ERP_SAD.dbo.tblUOM U ON L.UOMID = U.intID
        WHERE L.SALESQUOTATIONHEADERID = @SALESCONTRACTHEADERID AND L.ISACTIVE = 1
    )
    SELECT 
        GROUPNO,
        CAST(GROUPNO AS VARCHAR) + '/. ' + ITEMTITLE + CHAR(13) + CHAR(10) 
            + STRING_AGG(SUBPOINT, CHAR(13) + CHAR(10)) WITHIN GROUP (ORDER BY SUBNO) AS DESCRIPTION_BLOCK,
        @INVOICENUMBER AS INVOICENUMBER,
        FORMAT(@INVOICEDATE, 'dd-MM-yyyy') AS INVOICEDATE,
        @CONTRACTNO AS CONTRACTNO,
        FORMAT(@CONTRACTDATE, 'dd-MM-yyyy') AS CONTRACTDATE,
        @SHIPPEDPER AS SHIPPEDPER,
        @SHIPPEDFROM AS SHIPPEDFROM,
        @SHIPPEDTO AS SHIPPEDTO,
        @PURCHASEORDERNO AS PURCHASEORDERNO,
        FORMAT(@PURCHASEORDERDATED, 'dd-MM-yyyy') AS PURCHASEORDERDATED,
        @BINNO AS BINNO, @TIN AS TIN, @UNITNAME AS UNITNAME,
        @INVOICETO AS INVOICETO, @CUSTOMERADDRESS AS CUSTOMERADDRESS,
        @GROSSWEIGHT AS GROSSWEIGHT, @NETWEIGHT AS NETWEIGHT,
        @PRODUCT_QUANTITY AS PRODUCT_QUANTITY,
        @DESCRIPTION_SPECIFICATION AS DESCRIPTION_SPECIFICATION,
        UPPER(@MARKS) AS MARKS,
        CASE WHEN @TRUSSES != '' THEN 'TRUSS NO. ' + @TRUSSES ELSE '' END AS TRUSSNO,
        CASE WHEN @CARTONS != '' THEN 'CARTON NO. ' + @CARTONS ELSE '' END AS CARTONNO,
        CASE WHEN @BUNDLES != '' THEN 'BUNDLE NO. ' + @BUNDLES ELSE '' END AS BUNDLENO
    FROM ItemGroups
    GROUP BY GROUPNO, ITEMTITLE
    ORDER BY GROUPNO
END