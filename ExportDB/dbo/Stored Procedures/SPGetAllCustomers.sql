
CREATE PROCEDURE [dbo].[SPGetAllCustomers]
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKADDRESSLINEONE,
        CUSTOMERBANKADDRESSLINETWO,
        CUSTOMERBANKADDRESSLINETHREE,
        CUSTOMERBANKBINNO,
        ISACTIVE,
        CREATEDBY,
        UPDATEDBY,
        CREATEDDATE,
        UPDATEDDATE
    FROM TBLCUSTOMERBANK -- Make sure to include the schema if needed, e.g., dbo.TBLCUSTOMERBANK
    ORDER BY CUSTOMERNAME; -- optional sorting
END