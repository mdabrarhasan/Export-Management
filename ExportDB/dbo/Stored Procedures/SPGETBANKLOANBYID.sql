
CREATE PROCEDURE SPGETBANKLOANBYID
(
@ID			INT
)
AS
BEGIN
	SELECT BL.ID,BL.LENDERBANKID,BI.BANKNAME AS LENDERBANK,BL.BORROWERUNITID AS BORROWERUNITID,TU.NAME AS BORROWERUNIT,
	BL.LOANTYPEID,LT.LOANTYPE,BL.LOANAMOUNT,
	BL.CONRATE,
	CURR.ID AS CURRENCYID,CURR.NAME AS CURRENCY,
	CAST(CAST(BL.ISSUEDATE AS DATE) AS VARCHAR(100)) AS ISSUEDATE,
	CAST(CAST(BL.MATURITYDATE AS DATE) AS VARCHAR(100)) AS MATURITYDATE,
	BL.INTERESTRATE,BL.LOANNUMBER,BL.NARRATION
	FROM TBLBANKLOAN BL				INNER JOIN	TBLBANKFORTREASURY BI
	ON BL.LENDERBANKID=BI.BANKID	INNER JOIN	TBLUNITFORTREASURY TU
	ON BL.BORROWERUNITID=TU.ID		INNER JOIN  TBLLOANTYPE		   LT
	ON BL.LOANTYPEID=LT.ID			INNER JOIN  TBLCURRENCY		   CURR
	ON BL.CURRENCYID=CURR.ID
	WHERE BL.ID=@ID
END;