
CREATE PROCEDURE [dbo].[SPSAVEPICKPACKCONFIRM]
(
@ID			INT
)
AS
BEGIN
DECLARE @VPACKREQHEADERID INT,@VGLOBALID INT,@VPACKREQNUMBER VARCHAR(50),@VPACKREQDATE VARCHAR(50),@VCUSTOMERID INT,@VTERMSCONDITION VARCHAR(500),@VDESCRIPTIONS VARCHAR(500),
@DOCUMENTCREATEDDATE VARCHAR(50),@VDOCUMENTCREATEDBY INT,@VDOCUMENTSTATUSID INT,@VISACTIVE BIT,@VUNITID INT,@VPISCNUMBER INT,@VFLAG INT, @VSHIPMENTPERIOD VARCHAR(50),
@VDOCSTATUSID INT,@VAUTOID INT,@VPICKPACKNUMBER VARCHAR(50),@piid int,@formattedDate VARCHAR(8)
SELECT @piid=isnull(MAX(ID),0) FROM TBLPICKINGPACKINGHEADER;
	    set @piid=@piid+1;

	    SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	  	SET @VPICKPACKNUMBER='PP' + '-' + @formattedDate + '-' + cast(@piid as varchar(10));

SELECT @VPACKREQHEADERID=ID,@VGLOBALID=GLOBALID,@VPACKREQNUMBER=PACKREQNUMBER,@VPACKREQDATE=PACKREQDATE,@VCUSTOMERID=CUSTOMERID,@VTERMSCONDITION=TERMSCONDITION,
@VDESCRIPTIONS=DESCRIPTIONS,@DOCUMENTCREATEDDATE=DOCUMENTCREATEDDATE,@VDOCUMENTCREATEDBY=DOCUMENTCREATEDBY,
@VDOCUMENTSTATUSID=DOCUMENTSTATUSID,@VISACTIVE=ISACTIVE,@VUNITID=UNITID,@VPISCNUMBER=PISCNUMBER,@VFLAG=CASE WHEN FLAG=NULL THEN NULL ELSE FLAG END,@VSHIPMENTPERIOD=SHIPMENTPERIOD FROM TBLPACKINGREQUESTHEADER WHERE ID=@ID

SET @VDOCSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='PEND')

INSERT INTO TBLPICKINGPACKINGHEADER
(
PICKPACKNUMBER,
GLOBALID,
PACKINGREQUESTHEADERID,
--PICKPACKNUMBER,
PICKPACKDATE,
CUSTOMERID,
TERMSCONDITION,
DESCRIPTIONS,
DOCUMENTCREATEDDATE,
DOCUMENTCREATEDBY,
DOCUMENTSTATUSID,
ISACTIVE,
UNITID,
FLAG
)
VALUES
(
@VPICKPACKNUMBER,
@VGLOBALID,
@VPACKREQHEADERID,
GETDATE(),
@VCUSTOMERID,
@VTERMSCONDITION,
@VDESCRIPTIONS,
@DOCUMENTCREATEDDATE,
@VDOCUMENTCREATEDBY,
@VDOCSTATUSID,
1,
@VUNITID,
0
--@VFLAG
)

SET @VAUTOID=SCOPE_IDENTITY()
--SET @VPICKPACKNUMBER='PP'+CAST(@VAUTOID AS VARCHAR(50))

--UPDATE TBLPICKINGPACKINGHEADER
--SET PICKPACKNUMBER=@VPICKPACKNUMBER WHERE ID=@VAUTOID


DECLARE @LINEID INT,@LINEPACKINGREQUESTHEADERID INT,@LINEBATCHID VARCHAR(50),@LINESERIALNO INT,@PISCLINEID INT,@LINEITEMID INT,@LINEQUANTITY DECIMAL(18,2),@LINEPACKINGREQQUANTITY DECIMAL(18,2),
@LINETOLERANCEID INT,@LINEEXPPRODUCTIONORDERDATE VARCHAR(50),@LINEISACTIVE BIT,@LINEREMARKS VARCHAR(500),@LINEDESCRIPTIONS VARCHAR(500)

DECLARE SQLCURSOR CURSOR FOR  
SELECT ID,PACKINGREQUESTHEADERID,BATCHID,SERIALNO,PISCLINEID,ITEMID,QUANTITY,PACKINGREQQUANTITY,TOLERANCEID,EXPPRODUCTIONORDERDATE,ISACTIVE,REMARKS,DESCRIPTIONS FROM TBLPACKINGREQUESTLINE WHERE PACKINGREQUESTHEADERID=@ID

OPEN SQLCURSOR
FETCH NEXT FROM SQLCURSOR INTO @LINEID,@LINEPACKINGREQUESTHEADERID,@LINEBATCHID,@LINESERIALNO,@PISCLINEID,@LINEITEMID,@LINEQUANTITY,@LINEPACKINGREQQUANTITY,@LINETOLERANCEID,@LINEEXPPRODUCTIONORDERDATE,@LINEISACTIVE,@LINEREMARKS,@LINEDESCRIPTIONS;  


  WHILE @@FETCH_STATUS = 0  
  BEGIN
  INSERT INTO TBLPICKINGPACKINGLINE
  (
  PISCLINEID,
  PICKINGPACKINGHEADERID,
  BATCHID,
  SERIALNO,
  ITEMID,
  QUANTITY,
  PACKINGREQQUANTITY,
  PICKINGPACKINGQUANTITY,
  TOLERANCEID,
  ISACTIVE,
  REMARKS,
  DESCRIPTIONS
  )
  VALUES
  (
  @PISCLINEID,
  @VAUTOID,
  @LINEBATCHID,
  @LINESERIALNO,
  @LINEITEMID,
  @LINEQUANTITY,
  @LINEPACKINGREQQUANTITY,
  0,
  @LINETOLERANCEID,
  1,
  @LINEREMARKS,
  @LINEDESCRIPTIONS
  )
  FETCH NEXT FROM sqlcursor INTO @LINEID,@LINEPACKINGREQUESTHEADERID,@LINEBATCHID,@LINESERIALNO,@PISCLINEID,@LINEITEMID,@LINEQUANTITY,@LINEPACKINGREQQUANTITY,@LINETOLERANCEID,@LINEEXPPRODUCTIONORDERDATE,@LINEISACTIVE,@LINEREMARKS,@LINEDESCRIPTIONS; 
  END;

END;