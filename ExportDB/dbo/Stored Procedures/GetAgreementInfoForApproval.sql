CREATE Procedure [dbo].[GetAgreementInfoForApproval]
(
@Enroll		INT,
@UnitID		INT,
@Code		varchar(100),
@ID			varchar(100),
@AGGCODE			varchar(100)
)
AS
BEGIN
declare @docstatusid int,@checkstatusid int,@AGGTYPEID INT,@CHECKINIT INT
set @docstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
set @checkstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
SET @AGGTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@AGGCODE)
SET @CHECKINIT=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT')
SELECT PH.ID AS AGREEMENTID,SQH.TEXTFROMSHIPMENT,'' AS TEXTPAYMENT,SQH.DESTINATIONPORT,SQH.TOSHIPMENT,PH.UNITID,'' AS AGREEMENTTYPEID,'' AS AGREEMENTTYPE,PH.BUYERREGNO,PH.CURRENCYID,APVMH.DESCRIPTIONS,PH.TERMSCONDITION,PH.DELIVERYTERMID,PH.HSCODE,PH.SALESQUOTATIONHEADERID,PH.SHIPMENTMODEID,
PH.NUMBER AS PINUMBER,cast(PH.DATE AS VARCHAR) AS PIDATE,CAST(PH.EXPIREDATE AS VARCHAR) AS PIEXPIREDATE,
CAST(PH.SHIPMENTDATE AS VARCHAR) AS SHIPMENTDATE,CAST(PH.DOCUMENTCREATEDDATE AS VARCHAR) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,SQH.SQNUMBER,
ISNULL(SM.ID,0) AS SHIPMENTID,SM.NAME AS SHIPMENT,ISNULL(PT.ID,0) AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,
ISNULL(TSC.ID,0) AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,ISNULL(FSC.ID,0) AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,
ISNULL(LP.ID,0) AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,ISNULL(DP.ID,0) AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,
PH.TARRIFCODE,ISNULL(INCO.ID,0) AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,DS.ID AS DOCSTATUSID,DS.NAME AS DOSSTATUS,'' AS CURRENCY,'' AS DELIVERYTERM,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
APVMH.ID AS HISTRYID,
PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
PH.NOTIFYPARTY,PH.OTHERSPAYTERM,PH.ISPROCESSEDWITHAPPROVAL
from TBLPISCHEADER PH				 INNER JOIN ERP_SAD.DBO.tblCustomer			   CUS
ON ph.CUSTOMERID=cus.intCusID		 LEFT JOIN TBLSALESQUOTATIONHEADER			   SQH		
ON PH.SALESQUOTATIONHEADERID=SQH.ID  LEFT JOIN TBLSHIPMENTMODE					   SM
ON PH.SHIPMENTMODEID=SM.ID			 LEFT JOIN TBLPAYMENTTERMS					   PT
ON PH.PAYMENTTERMID=PT.ID			 LEFT JOIN TBLCOUNTRY						   TSC
ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 LEFT JOIN TBLCOUNTRY						   FSC
ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 LEFT JOIN TBLFROMLOADINGPORT				   LP
ON PH.FROMSHIPMENTPORTID=LP.ID		 LEFT JOIN TBLFROMLOADINGPORT				   DP
ON PH.TODISCHARGEPORT=DP.ID			 LEFT JOIN TBLINCOTERM						   INCO
ON PH.INCOTERM=INCO.ID				 INNER JOIN TBLAPPROVERMATRIXHISTORY           APVMH
ON PH.ID=APVMH.PROCESSID			 INNER JOIN TBLDOCUMENTSTATUS				   DS
on APVMH.DOCUMENTSTATUSID=ds.ID
WHERE APVMH.ACTIONTAKERID=@Enroll AND 
PH.AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@AGGCODE) AND
(APVMH.DOCUMENTSTATUSID=@checkstatusid and APVMH.DOCUMENTSTATUSID != @CHECKINIT) AND
PH.AGREEMENTTYPEID=@AGGTYPEID AND
PH.ISACTIVE=1 and
SUBMENUID=(select ID from TBLSUBMENU where CODE=trim(@Code))
order by PH.ID desc
END;