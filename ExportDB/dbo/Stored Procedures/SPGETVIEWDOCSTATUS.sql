
CREATE PROCEDURE [dbo].[SPGETVIEWDOCSTATUS]  
(
@PROCESSID			INT,
@MODULECODE			VARCHAR(50),
@UNITID				INT
)
AS
BEGIN
SELECT 
APH.ID,
PROCESSCODE,
EMPINIT.strEmployeeName+' ('+CAST(APH.INITIATORID AS VARCHAR(50))+')' AS VINITIATOR,
EMPAPPR.strEmployeeName+' ('+CAST(APH.ACTIONTAKERID AS VARCHAR(50))+')' AS APPROVAR,
CAST(APH.DOCUMENTCREATEDDATE AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
DS.NAME AS DOCSTATUS,
APH.DESCRIPTIONS
FROM TBLAPPROVERMATRIXHISTORY APH
INNER JOIN				ERP_HR.DBO.tblEmployee   EMPINIT
ON						APH.INITIATORID=EMPINIT.intEmployeeID
INNER JOIN				ERP_HR.DBO.tblEmployee   EMPAPPR
ON						APH.ACTIONTAKERID=EMPAPPR.intEmployeeID		
INNER JOIN				TBLDOCUMENTSTATUS		 DS
ON						DS.ID=APH.DOCUMENTSTATUSID
WHERE PROCESSID=@PROCESSID AND SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=@MODULECODE) AND APH.UNITID=@UNITID
END;