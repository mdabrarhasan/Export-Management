CREATE PROCEDURE [dbo].[EditbyID]
(
    @ID INT,
    @HEADERID INT
)
AS
BEGIN
    SET NOCOUNT ON;

    IF @ID = 0
    BEGIN
        SELECT 
            SQH.SQTYPEID,
            SQTYPE.strTypeName AS SQTYPENAME,

            CAST(CAST(SQH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,
            0 AS HISTRYID,

            SQH.ID,
            SQH.GLOBALID,
            SQH.SQNUMBER AS SQNumber,

            SQH.UNITID AS UnitID,
            UNIT.STRDESCRIPTION AS UnitName,
            UNIT.STRDESCRIPTION AS UnitDescription,
            UNIT.STRACCEMAILADDRESS AS SellerEmail,
            UNIT.STRPHONE AS SellerPhone,
            UNIT.STRTIN AS SellerTin,

            SQH.CUSTOMERID AS CusID,
            CUS.STRNAME AS CustomerName,
            CUS.STRPHONE AS CusPhone,
            CUS.STREMAILADDRESS AS CusEmail,
            CUS.STRADDRESS AS CusAddress,

            SQH.DESCRIPTIONS,
            SQH.DESCRIPTION_SPECIFICATION AS DESCRIPTIONSPECIFICATION,
            SQH.PRODUCT_QUANTITY AS QUANTITYSUMMARY,
            SQH.TERMSCONDITION,

            CAST(SQH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
            SQH.DOCUMENTCREATEDBY,
            SQH.DOCUMENTSTATUSID,

            DS.NAME AS DocStatus,
            DS.CODE,

            SQH.SHIPMENTMODE,
            ISNULL(SQH.FROMSHIPMENT, 0) AS FROMSHIPMENT,
            SQH.TOSHIPMENT,
            SQH.TEXTFROMSHIPMENT,
            SQH.DESTINATIONPORT,

            SQH.CURRENCY,
            SQH.LOADINGPORT,
            SQH.LOADINGPLACE,
            SQH.INCOTERM,
            SQH.TRANSPORTATIONMODE,

            SQH.PAYMENTTERMS_ID AS PAYMENTTERMSID,
            SQH.PAYMENTTERMS_OTHERS AS PAYMENTTERMSOTHERS,
			SQH.PAYMENTTERMS,
            SQH.SHIPPINGPERIOD,

            ISNULL(SQH.FLAG, 0) AS FLAG,
            SQH.ISPROCESSEDWITHAPPROVAL

        FROM TBLSALESQUOTATIONHEADER SQH
        INNER JOIN ERP_HR.DBO.TBLUNIT UNIT
            ON SQH.UNITID = UNIT.INTUNITID
        INNER JOIN ERP_SAD.DBO.TBLCUSTOMER CUS
            ON SQH.CUSTOMERID = CUS.INTCUSID
        INNER JOIN TBLDOCUMENTSTATUS DS
            ON SQH.DOCUMENTSTATUSID = DS.ID
        INNER JOIN ERP_SAD.DBO.TBLCUSTOMERTYPE SQTYPE
            ON SQH.SQTYPEID = SQTYPE.intTypeID

        WHERE SQH.ID = @HEADERID;
    END;

	ELSE IF @ID = 1  
	BEGIN  
		SELECT 
			ID,
			SALESQUOTATIONHEADERID,
			B.STRPRODUCTNAME + 
			CASE 
				WHEN ITEMTYPEID = 1 THEN ' ' + ISNULL(QUALITY,'')
				WHEN ITEMTYPEID = 2 THEN ISNULL(SIZE, '') + ' ' + ISNULL(CONSTRUCTION,'') + ' ' + ISNULL(WEIGHT,'')
				WHEN ITEMTYPEID = 3 THEN ISNULL(SIZE, '') + ' ' + ISNULL(WEIGHT, '') + ' ' + ISNULL(SLIT, '') + ' ' + ISNULL(SCRIM, '')
			END AS ITEMNAME,
			A.ITEMTYPEID,
			A.ITEMTITLE,
			PACKINGDETAILS,
			SIZE AS SIZE,
			SLIT AS SLIT,
			SCRIM AS SCRIM,
			CONSTRUCTION AS CONSTRUCTION,
			QUALITY AS QUALITY,
			WEIGHT AS WEIGHT,
			UOMID,
			UOM.strUOM AS UOM,
			BATCHID,
			SERIALNO,
			ITEMID,
			QUANTITY,
			PRICE,
			DISCOUNTID,
			DISCOUNT,
			TOTALAMOUNT,
			DESCRIPTIONS,
			REMARKS,
			CASE 
				WHEN A.DISCOUNTID = 0 THEN '' 
				ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID = A.DISCOUNTID) 
			END AS DISNAME
		FROM 
			TBLSALESQUOTATIONLINE A
			JOIN ERP_SAD.DBO.TBLITEM B ON A.ITEMID = B.INTID
			JOIN ERP_SAD.DBO.tblUOM UOM ON A.UOMID = UOM.intID
		WHERE 
			A.ISACTIVE = 1
			AND SALESQUOTATIONHEADERID = @HEADERID
		ORDER BY 
			A.ITEMID DESC
	END;  

	ELSE IF @ID = 2  
	BEGIN  
		SELECT 
			ID,
			SALESQUOTATIONHEADERID,
			B.STRPRODUCTNAME + 
			CASE 
				WHEN ITEMTYPEID = 1 THEN ' ' + ISNULL(QUALITY,'')
				WHEN ITEMTYPEID = 2 THEN ISNULL(SIZE, '') + ' ' + ISNULL(CONSTRUCTION,'') + ' ' + ISNULL(WEIGHT,'')
				WHEN ITEMTYPEID = 3 THEN ISNULL(SIZE, '') + ' ' + ISNULL(WEIGHT, '') + ' ' + ISNULL(SLIT, '') + ' ' + ISNULL(SCRIM, '')
			END AS ITEMNAME,
			A.ITEMTYPEID,
			A.ITEMTITLE,
			PACKINGDETAILS,
			'' AS SIZE,
			'' AS SLIT,
			'' AS SCRIM,
			'' AS CONSTRUCTION,
			'' AS QUALITY,
			'' AS WEIGHT,
			UOMID,
			UOM.strUOM AS UOM,
			BATCHID,
			SERIALNO,
			ITEMID,
			QUANTITY,
			PRICE,
			DISCOUNTID,
			DISCOUNT,
			TOTALAMOUNT,
			DESCRIPTIONS,
			REMARKS,
			CASE 
				WHEN A.DISCOUNTID = 0 THEN '' 
				ELSE (SELECT NAME FROM TBLDISCOUNT WHERE ID = A.DISCOUNTID) 
			END AS DISNAME
		FROM 
			TBLSALESQUOTATIONLINE A
			JOIN ERP_SAD.DBO.TBLITEM B ON A.ITEMID = B.INTID
			JOIN ERP_SAD.DBO.tblUOM UOM ON A.UOMID = UOM.intID
		WHERE 
			A.ISACTIVE = 1
			AND SALESQUOTATIONHEADERID = @HEADERID
		ORDER BY 
			A.ITEMID DESC
	END;

	ELSE IF @ID=3
	BEGIN
		SELECT 
			SQH.ID,
			FROMSHIPMENT.NAME AS FROMSHIPMENTNAME,
			CURR.NAME AS CURRENCYNAME,
			FLP.NAME AS FROMLOADINGPART,
			SQH.DESTINATIONPORT,
			PMT.NAME AS PAYMENTTERMSNAME,
			INCO.NAME AS INCOTERMNAME,
			FLP.NAME AS FROMLOADINGPARTNAME,
			TPM.NAME AS TRANSPORTATIONMODENAME,

            SQH.SQTYPEID,
            SQTYPE.strTypeName AS SQTYPENAME,

            CAST(CAST(SQH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,
            0 AS HISTRYID,

            SQH.GLOBALID,
            SQH.SQNUMBER AS SQNumber,

            SQH.UNITID AS UnitID,
            UNIT.STRDESCRIPTION AS UnitName,
            UNIT.STRDESCRIPTION AS UnitDescription,
            UNIT.STRACCEMAILADDRESS AS SellerEmail,
            UNIT.STRPHONE AS SellerPhone,
            UNIT.STRTIN AS SellerTin,

            SQH.CUSTOMERID AS CusID,
            CUS.STRNAME AS CustomerName,
            CUS.STRPHONE AS CusPhone,
            CUS.STREMAILADDRESS AS CusEmail,
            CUS.STRADDRESS AS CusAddress,

            SQH.DESCRIPTIONS,
            SQH.DESCRIPTION_SPECIFICATION AS DESCRIPTIONSPECIFICATION,
            SQH.PRODUCT_QUANTITY AS QUANTITYSUMMARY,
            SQH.TERMSCONDITION,

            CAST(SQH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
            SQH.DOCUMENTCREATEDBY,
            SQH.DOCUMENTSTATUSID,

            DS.NAME AS DocStatus,
            DS.CODE,

            SQH.SHIPMENTMODE,
			TOSHIP.NAME AS TOSHIPMENT,
            ISNULL(SQH.FROMSHIPMENT, 0) AS FROMSHIPMENT,
            --SQH.TOSHIPMENT,
            SQH.TEXTFROMSHIPMENT,


            SQH.CURRENCY,
            SQH.LOADINGPORT,
            SQH.LOADINGPLACE,
            SQH.INCOTERM,
            SQH.TRANSPORTATIONMODE,

            SQH.PAYMENTTERMS_ID AS PAYMENTTERMSID,
            SQH.PAYMENTTERMS_OTHERS AS PAYMENTTERMSOTHERS,
			PMT.ID AS PAYMENTTERMS,
            SQH.SHIPPINGPERIOD,

            ISNULL(SQH.FLAG, 0) AS FLAG,
            SQH.ISPROCESSEDWITHAPPROVAL

        FROM TBLSALESQUOTATIONHEADER SQH
        INNER JOIN ERP_HR.DBO.TBLUNIT UNIT
            ON SQH.UNITID = UNIT.INTUNITID
        INNER JOIN ERP_SAD.DBO.TBLCUSTOMER CUS
            ON SQH.CUSTOMERID = CUS.INTCUSID
        INNER JOIN TBLDOCUMENTSTATUS DS
            ON SQH.DOCUMENTSTATUSID = DS.ID
        INNER JOIN ERP_SAD.DBO.TBLCUSTOMERTYPE SQTYPE
            ON SQH.SQTYPEID = SQTYPE.intTypeID
		LEFT JOIN TBLCOUNTRY FROMSHIPMENT
		    ON SQH.FROMSHIPMENT=FROMSHIPMENT.ID
		LEFT JOIN TBLCURRENCY CURR
			ON CURR.ID=SQH.CURRENCY
		LEFT JOIN TBLFROMLOADINGPORT FLP
		    ON SQH.LOADINGPORT=FLP.ID
		LEFT JOIN TBLINCOTERM INCO
		    ON SQH.INCOTERM=INCO.ID
		LEFT JOIN TBLPAYMENTTERMS PMT
		    ON SQH.PAYMENTTERMS_ID=PMT.ID
		LEFT JOIN TBLTRANSPORTATIONMODE TPM
			ON SQH.TRANSPORTATIONMODE=TPM.ID
		LEFT JOIN TBLTOSHIPMENTCOUNTRY TOSHIP
			ON SQH.TOSHIPMENT = TOSHIP.ID
        WHERE SQH.ID = @HEADERID;

	

	END;

END