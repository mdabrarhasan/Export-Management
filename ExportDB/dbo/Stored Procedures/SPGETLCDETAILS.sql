CREATE PROCEDURE [dbo].[SPGETLCDETAILS]
AS
BEGIN
SELECT LVB.ID,LCNUMBER,
CAST(CAST(LCISSUEDATE AS DATE) AS VARCHAR(100)) AS LCISSUEDATE,
CAST(CAST(LCEXPIREDATE AS DATE) AS VARCHAR(100)) AS LCEXPIREDATE,
CUS.strName AS CUSNAME,BILL.strCode AS CODE,BILL.strHeader AS INVOICENO,BILL.monTotal AS TOTAL,'' AS PARTNUMBER,
QH.QUOTATIONNUMBER,CAST(CAST(QH.DATE AS DATE) AS VARCHAR(100)) QUOTATIONDATE
FROM TBLLCDETAILS LCD				INNER JOIN ERP_SAD.DBO.tblCustomer			CUS
ON LCD.CUSTOMERID=CUS.intCusID		INNER JOIN TBLLCVSBILL						LVB 
ON LCD.ID=LVB.LCSCID				INNER JOIN TBLQUOTATIONHEADER				QH
ON LCD.PISCHEADERID=QH.ID			INNER JOIN ERP_DURBIN.DBO.tblCusBilling		BILL				
ON LVB.BILLID=BILL.intBillID		
AND LVB.BILLID=BILL.intBillID		AND LVB.ISACTIVE=1
END;