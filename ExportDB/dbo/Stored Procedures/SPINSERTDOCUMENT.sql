CREATE PROCEDURE [dbo].[SPINSERTDOCUMENT]
(
@DOCUMENTSETUPHEADERID				INT,
@PICKINGPACKINGHEADERID				INT,
@DESCRIPTIONS						VARCHAR(500),
@TERMSCONDITION						VARCHAR(500),

@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN 

	DECLARE @GLOBAL VARCHAR(50),@DOCNUMBER VARCHAR(50),@CUSTOMERID INT,@ID INT,@DOCSTATUSID INT,@VDOCUMENTSETUPHEADERID INT,@VMODULECODE VARCHAR(100),@VPROCESSNAME VARCHAR(100),
	@VID INT,@VDOCHEADERID INT,@DOCUMENTSETUPLINEID INT,@DOCUMENTSTATUSID INT,@VTERMSCONDITION VARCHAR(500),@VDESCRIPTION VARCHAR(500),@VPROCESS VARCHAR(100),@CHECKPICKPACK INT,
	@VDOCUMENTSETUPHEADERCODE	VARCHAR(50),@PROCESSCODE VARCHAR(50),@CHECKFILEEXIST INT

	 SET @CHECKFILEEXIST=(SELECT COUNT(ID) from TBLDOCUMENTSETUPLINE WHERE DOCUMENTSETUPHEADERID=@DOCUMENTSETUPHEADERID AND ISMANDATORY=1 AND ID NOT IN(select PROCESSLINEID from TBLFILEDETAILS WHERE PICKINGPACKINGHEADERID=@PICKINGPACKINGHEADERID))
	 
	 IF @CHECKFILEEXIST=0
	 BEGIN
	 SET @CUSTOMERID=(SELECT CUSTOMERID FROM TBLPICKINGPACKINGHEADER WHERE ID=@PICKINGPACKINGHEADERID)
	 SET @DOCSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@DOCSTATUS)
	 SET @CHECKPICKPACK=(SELECT COUNT(ID) FROM TBLDOCHEADER WHERE PICKINGPACKINGHEADERID=@PICKINGPACKINGHEADERID AND UNITID=@UNITID)
	 
	 IF @CHECKPICKPACK<=0
	 BEGIN
	 DECLARE SQL_CURSOR CURSOR FOR  
	 SELECT ID FROM TBLDOCUMENTSETUPLINE WHERE DOCUMENTSETUPHEADERID=(SELECT ID from TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID)
	 
	 OPEN SQL_CURSOR
	 FETCH NEXT FROM SQL_CURSOR INTO @DOCUMENTSETUPLINEID;  

	 SET @DOCNUMBER=(SELECT CODE FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID)
	 SET @MODULECODE=(SELECT CODE FROM TBLSUBMENU WHERE ID=(SELECT SUBMENUID FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID))
	 SET @VMODULECODE=(SELECT CODE FROM TBLSUBMENU WHERE ID=(SELECT SUBMENUID FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID))


		INSERT INTO TBLDOCHEADER
		(
		PICKINGPACKINGHEADERID,
		DOCUMENTSETUPHEADERID,
		--DOCNUMBER,
		DOCDATE,
		CUSTOMERID,
		TERMSCONDITION,
		DESCRIPTIONS,
		DOCUMENTCREATEDDATE,
		DOCUMENTCREATEDBY,
		DOCUMENTSTATUSID,
		ISACTIVE,
		UNITID
		)
		VALUES
		(
		@PICKINGPACKINGHEADERID,
		@DOCUMENTSETUPHEADERID,
		GETDATE(),
		@CUSTOMERID,
		@TERMSCONDITION,
		@DESCRIPTIONS,
		GETDATE(),
		@ENROLL,
		@DOCSTATUSID,
		1,
		@UNITID
		)

	SET @ID=SCOPE_IDENTITY()

	  IF @VMODULECODE='PRE00001'
	  BEGIN
	  SET @PROCESSNAME='PRE'
	  SET @MsgStatus='PRESAVE'
	  SET @DOCNUMBER='PRE'+CAST(@ID AS VARCHAR(50))
	  END;
	  ELSE IF @VMODULECODE='POST00001'
	  BEGIN
	  SET @PROCESSNAME='POST'
	  SET @MsgStatus='POSTSAVE'
	  SET @DOCNUMBER='POST'+CAST(@ID AS VARCHAR(50))
	  END;

	UPDATE TBLDOCHEADER
	SET GLOBALID='GLOB'+CAST(@ID AS VARCHAR(100)),DOCNUMBER=@DOCNUMBER WHERE ID=@ID

	WHILE @@FETCH_STATUS = 0  
	BEGIN
	INSERT INTO TBLDOCLINE
	(
	DOCHEADERID,
	DOCUMENTSETUPLINEID,
	DOCUMENTSTATUSID,
	TERMSCONDITION,
	DESCRIPTIONS,
	DOCUMENTCREATEDDATE,
	DOCUMENTCREATEDBY
	)
	VALUES
	(
	@ID,
	@DOCUMENTSETUPLINEID,
	@DOCSTATUSID,
	@VTERMSCONDITION,
	@VDESCRIPTION,
	GETDATE(),
	@ENROLL
	)

	  FETCH NEXT FROM sql_cursor INTO @DOCUMENTSETUPLINEID;
	  END;

	  SET @PROCESSCODE=@PROCESSNAME+CAST(@ID AS VARCHAR(100))
	--set @MSG=@ID
	SET @LOG='INSERT INTO TBLDOCHEADER (ID'+CAST(@ID AS VARCHAR(100))+ 'PICKINGPACKINGHEADERID'+CAST(@PICKINGPACKINGHEADERID AS VARCHAR(50))+'DOCUMENTSETUPHEADERID='+CAST(@DOCUMENTSETUPHEADERID AS VARCHAR(50))+'DOCNUMBER='+CAST(@DOCNUMBER AS VARCHAR(50))+'CUSTOMERID='+CAST(@CUSTOMERID AS VARCHAR(50))
	+'DOCUMENTCREATEDBY='+CAST(@ENROLL AS VARCHAR(50))+'UNITID='+CAST(@UNITID AS VARCHAR(50))
	set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)+' DOC NO:'+CAST(@ID AS VARCHAR(100))
	  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
	  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@ProcessName,@Notification
	  EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSNAME,@UNITID,@ENROLL
	END 

	ELSE
	BEGIN
	SET @Msg='PICKING PACKING NUMBER ALREADY TAKEN.THANKS'
	END

	 END;
	 ELSE
	 BEGIN
	 SET @Msg='FIRST UPLOAD MANDATORY FILE AND THEN TRY AGAIN.'
	 END;
END;