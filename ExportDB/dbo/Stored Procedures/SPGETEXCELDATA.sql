CREATE PROCEDURE [dbo].[SPGETEXCELDATA]
AS
BEGIN
SELECT LINE.ID AS ID,0 AS HEADERID,LINE.intProductID AS ITEMID,LINE.strProductCode AS PRODUCTCODE,LINE.strProductName AS ITEMNAME,'' AS BUYERNAME,0 AS BUYERID,
CAST(LINE.intOrderQty AS decimal(18,2)) AS QUANTITY,0.0 PRICE,0 AS DISCOUNTID,'' AS DISCOUNT,0.0 AS TOTALAMOUNT,LINE.intUOM AS UOMID,UOM.strUOM AS UOM,
LINE.decThickness AS THIKNESS,LINE.decWidth AS WIDTH,LINE.decLength AS LENGTH,
LINE.strTreatmentLavel AS TREATMENTLEVEL,
ISNULL(LINE.intTreatmentDirectionID,0) AS TREATMENTDIRECTIONID,DIR.strTreatmentDirection AS TREATMENTDIRECTION,
ISNULL(LINE.intCoreID,0) AS COREID,COREID.strBiaxFlimCoreID AS CORENAME,
CAST(CAST(LINE.dteDesiredDateofDelivery AS DATE) AS VARCHAR(50)) AS DISEREDDATEOFDELIVERY,
CAST(CAST(LINE.dteTentativeDateofDelivery AS DATE) AS VARCHAR(50)) AS TENTATIVEDATEOFDELIVERY,'' AS REMARKS,
'' AS DESCRIPTIONS,LINE.strRealOD REALOD,0 AS TOLERANCEID,'' AS TOLERANCE
FROM TBLEXCELUPLOAD LINE										INNER JOIN ERP_SAD.DBO.tblItem					LIST
ON LINE.intProductID=LIST.intID									INNER JOIN ERP_SAD.DBO.tblUOM					UOM
ON LINE.intUOM=UOM.intID										LEFT JOIN ERP_SAD.DBO.tblTreatmentDirection		DIR			
ON LINE.intTreatmentDirectionID=DIR.intTreatmentDirection		LEFT JOIN ERP_SAD.DBO.tblBiaxFlimCoreID			COREID
ON LINE.intCoreID=COREID.intBiaxFlimCoreID						
			
END;