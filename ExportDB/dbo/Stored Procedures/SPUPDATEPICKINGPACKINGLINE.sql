

CREATE PROCEDURE [dbo].[SPUPDATEPICKINGPACKINGLINE]
(
@ID									INT,
@PACKINGREQQUANTITY					int,
@REMARKS       						VARCHAR(500),
@DESCRIPTIONS						VARCHAR(500),

@TRUCKNO							VARCHAR(100),
@GROSSMEASURE						int,
@CONTAINERSIZE						int,
@CONTAINERNO						VARCHAR(100),

@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN

DECLARE @ProcessCode VARCHAR(50)
UPDATE TBLPICKINGPACKINGLINE
SET PICKINGPACKINGQUANTITY=@PACKINGREQQUANTITY,REMARKS=@REMARKS,DESCRIPTIONS=@DESCRIPTIONS,
TRUCKNO=@TRUCKNO,GROSSMEASURE=@GROSSMEASURE, CONTAINERSIZE=@CONTAINERSIZE,CONTAINERNO=@CONTAINERNO WHERE ID=@ID
--IF EXISTS (
--    SELECT 1
--    FROM TBLPICKINGPACKINGLINE
--    WHERE PACKINGREQQUANTITY < QUANTITY and ID=@ID
--)
begin
update TBLPICKINGPACKINGLINE set QTYCHECK=1  where ID=@ID
end
  SET @LOG='UPDATE TBLPICKINGPACKINGLINE SET PICKINGPACKINGQUANTITY='+CAST(@PACKINGREQQUANTITY AS VARCHAR(50))+'REMARKS='+@REMARKS+'DESCRIPTIONS='+@DESCRIPTIONS+'WHERE ID='+CAST(@ID AS VARCHAR(50))
  SET @ProcessCode=@PROCESSNAME+CAST(@id AS VARCHAR(50))
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  --EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@submenuid,@Notification
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll

END