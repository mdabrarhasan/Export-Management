

CREATE PROCEDURE [dbo].[SPINTERESTCALCULATIONDELETE]
(
@ID									INT,
@MODULECODE							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@DOCSTATUS							VARCHAR(100),
@MESSAGENAME						VARCHAR(100),
@NOTIFICATION						VARCHAR(100),
@UNITID								INT,
@DOCUMENTCREATEDBY					INT,
@MSG								VARCHAR(100)		OUT,
@STATUSMSG							VARCHAR(100)		OUT
)
AS
BEGIN
	UPDATE TBLINTERESTCALCULATION
	SET ISACTIVE=0 WHERE ID=@ID

	SET @MSG='DATA DELETED SUCCESSFULLY.'
	SET @STATUSMSG='error';
END;