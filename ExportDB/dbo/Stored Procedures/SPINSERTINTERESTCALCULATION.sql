
CREATE PROCEDURE [dbo].[SPINSERTINTERESTCALCULATION]
(
@LENDERUNITID						INT,
@BORROWERUNITID						INT,
@AMOUNT								DECIMAL(18,2),
@STARTDATE							DATE,
@ENDDATE							DATE,
@NOOFDAYS							INT,
@INTERESTRATE						DECIMAL(18,2),
@INTERESTAMT						DECIMAL(18,2),
@DETAILS							VARCHAR(MAX),

@MODULECODE							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@DOCSTATUS							VARCHAR(100),
@MESSAGENAME						VARCHAR(100),
@NOTIFICATION						VARCHAR(100),			
@DOCUMENTCREATEDBY					INT,
@UNITID								INT,
@MSG								VARCHAR(100)		OUT,
@STATUSMSG							VARCHAR(100)		OUT
)
AS
BEGIN
	DECLARE @DOCSTATUSID	INT,@ID INT,@PROCESSCODE VARCHAR(100)
	SET @DOCSTATUSID=(SELECT ID FROM ABGAPIS.DBO.TBLDOCUMENTSTATUS WHERE CODE=@DOCSTATUS)

	INSERT INTO TBLINTERESTCALCULATION
	(
	LENDERUNITID,
	BORROWERUNITID,
	AMOUNT,
	STARTDATE,
	ENDDATE,
	NOOFDAYS,
	INTERESTRATE,
	INTERESTAMT,
	DETAILS,
	CREATEDBY,
	UPDATEDBY,
	CREATEDDATE,
	UPDATEDDATE,
	ISACTIVE,
	DOCSTATUSID
	)
	VALUES
	(
	@LENDERUNITID,
	@BORROWERUNITID,
	@AMOUNT,
	@STARTDATE,
	@ENDDATE,
	@NOOFDAYS,
	@INTERESTRATE,
	@INTERESTAMT,
	@DETAILS,
	@DOCUMENTCREATEDBY,
	@DOCUMENTCREATEDBY,
	GETDATE(),
	GETDATE(),
	1,
	@DOCSTATUSID
	)
	SET @ID=SCOPE_IDENTITY()
	SET @PROCESSCODE=CAST(@ID AS VARCHAR(100))+@PROCESSNAME;
	EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@DOCUMENTCREATEDBY,@UNITID
	SET @MSG='DATA SAVED SUCCESSFULLY.'
	SET @STATUSMSG='success';
END;