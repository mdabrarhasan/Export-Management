CREATE PROCEDURE [dbo].[SPLASTTENITEM]
(
@ID			INT
)
AS
BEGIN
DECLARE @CUSTOMER INT
SET @CUSTOMER=(SELECT CUSTOMERID FROM TBLQUOTATIONHEADER WHERE ID=(SELECT PROFORMAINVOICEHEADERID FROM TBLPRICECONFIRMHEADER WHERE ID=@ID AND SELLERID=91))

SELECT 
QTL.ID,QTL.PRICE,(SELECT strProductName FROM ERP_SAD.DBO.tblItem WHERE intID=QTL.ITEMID) AS NAME

FROM TBLQUOTATIONLINE QTL  WHERE QTL.ITEMID IN 


(SELECT ITEMID FROM TBLQUOTATIONLINE WHERE QUOTATIONHEADERID IN 
(SELECT TOP 10 ID FROM TBLQUOTATIONHEADER WHERE CUSTOMERID=@CUSTOMER)
)

END;