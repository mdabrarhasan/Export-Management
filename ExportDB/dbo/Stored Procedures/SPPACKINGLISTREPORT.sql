
CREATE PROCEDURE [dbo].[SPPACKINGLISTREPORT]
@HEADERID INT
AS
BEGIN
SET NOCOUNT ON;

-- Resolve the SalesQuotationHeaderID for this packing request
DECLARE @SALESQUOTATIONHEADERID INT;
SELECT @SALESQUOTATIONHEADERID = PISC.SALESQUOTATIONHEADERID
FROM TBLPACKINGREQUESTHEADER PRH
INNER JOIN TBLPISCHEADER PISC
ON PISC.ID = PRH.PISCNUMBER
WHERE PRH.ID = @HEADERID;

-- Get contract number from PISC header
    DECLARE @CONTRACTNUMBER NVARCHAR(50)
    SELECT TOP 1
        @CONTRACTNUMBER = ISNULL([NUMBER], '')
    FROM TBLPISCHEADER
    WHERE SALESQUOTATIONHEADERID = @SALESQUOTATIONHEADERID
        AND ISACTIVE = 1

-- Build ALLMILLIDS: distinct mill IDs formatted as "1.3.4 & 5"
DECLARE @ALLMILLIDS NVARCHAR(MAX) = ''
DECLARE @MILLCOUNT INT

;WITH DistinctMills AS (
    SELECT DISTINCT MILLID
    FROM TBLPACKINGREQUESTLINE
    WHERE PACKINGREQUESTHEADERID = @HEADERID
        AND ISACTIVE = 1
        AND MILLID IS NOT NULL
        AND MILLID > 0
),
NumberedMills AS (
    SELECT 
        MILLID,
        ROW_NUMBER() OVER (ORDER BY MILLID) AS RN,
        COUNT(*) OVER () AS TOTAL
    FROM DistinctMills
)
SELECT @ALLMILLIDS = @ALLMILLIDS 
    + CAST(MILLID AS VARCHAR(10))
    + CASE 
        WHEN RN = TOTAL THEN ''                  -- last item, no separator after
        WHEN RN = TOTAL - 1 THEN ' & '           -- second-to-last, use &
        ELSE '.'                                  -- everything else, use .
      END
FROM NumberedMills
ORDER BY RN

-- Return one row per packing request line, grouped by ITEMTITLE
SELECT
ROW_NUMBER() OVER (
ORDER BY SQL.ITEMTITLE, PRL.ID
) AS ROWNO,
DENSE_RANK() OVER (
ORDER BY SQL.ITEMTITLE
) AS GROUPNO,
ISNULL(I.strProductName, '')
+ CASE WHEN SQL.QUALITY IS NOT NULL AND SQL.QUALITY != ''
THEN ' (' + SQL.QUALITY + ')'
ELSE ''
END AS QUALITY,
ISNULL(PRL.TRUSSNO, 0) AS NOOFTRUSS,
ISNULL(PRL.TOTALCARTOON, 0) AS NOOFCARTONS,
ISNULL(PRL.ADDITIONALWEIGHT, 0) AS NETWEIGHT,
ISNULL(PRL.GROSSWEIGHT, 0) AS GROSSWEIGHT,
ISNULL(PRL.TOTALSPOOL, 0) AS SPOOL,
ISNULL(PRL.MEASUREMENT, '') AS MEASUREMENT,
ISNULL(PRL.SINO, '') AS SINO,
ISNULL(PRL.MILLID, 0) AS MILLID,
ISNULL(PRL.MARKINK, '') AS MARKINK,
@CONTRACTNUMBER                   AS CONTRACTNUMBER,
@ALLMILLIDS							AS ALLMILLIDS
FROM TBLPACKINGREQUESTLINE PRL				INNER JOIN TBLPACKINGREQUESTHEADER  PRH
ON PRH.ID = PRL.PACKINGREQUESTHEADERID	    INNER JOIN TBLPISCLINE				SQL
--ON SQL.PISCHEADER = @SALESQUOTATIONHEADERID
ON SQL.ITEMID = PRL.ITEMID AND SQL.ID=PRL.PISCLINEID
INNER JOIN ERP_SAD.dbo.tblItem I
ON I.intID = PRL.ITEMID
WHERE PRL.PACKINGREQUESTHEADERID = @HEADERID
ORDER BY SQL.ITEMTITLE, PRL.ID;
END