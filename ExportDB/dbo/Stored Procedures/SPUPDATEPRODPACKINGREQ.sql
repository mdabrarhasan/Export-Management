
CREATE PROCEDURE [dbo].[SPUPDATEPRODPACKINGREQ]
(
@ID							INT,
@PACKREQNUMBER              VARCHAR(50),
@PACKREQDATE				date,
@SHIPMENTPERIOD				date,
@CUSTOMERID                 INT,

@TERMSCONDITION				VARCHAR(500),
@DESCRIPTIONS				VARCHAR(500),
@DOCUMENTCREATEDDATE         VARCHAR(500), 

@DOCUMENTCREATEDBY INT,
@UNITID INT,
@PISCNUMBER VARCHAR(500), 
@PACKINGMODE VARCHAR(500),
@CUSTOMERCATEGORY INT,
@SHIPPOINT INT,
@BIAXPROTYPE VARCHAR(500),

@INVOICENUMBER VARCHAR(500),
@INVOICEDATE VARCHAR(500),
@INVOICETO VARCHAR(500),
@CONTRACTNO VARCHAR(500),
@SHIPPEDPER VARCHAR(500),

@SHIPPEDFROM  VARCHAR(500),
@SHIPPEDTO  VARCHAR(500),
@PURCHASEORDERNO VARCHAR(500),
@PURCHASEORDERDATED date,

@ModuleCode					VARCHAR(50),
@Enroll						INT,
@DocStatus					VARCHAR(50),
@ProcessName				VARCHAR(500),
@MsgStatus					VARCHAR(500),
@NOTIFICATION				VARCHAR(100),
@LOG						VARCHAR(MAX),
@Msg						VARCHAR(100) OUTPUT
)
AS
BEGIN
DECLARE @PROCESSCODE VARCHAR(50)
UPDATE TBLPACKINGREQUESTHEADER
SET 
PACKREQNUMBER = @PACKREQNUMBER ,
PACKREQDATE = @PACKREQDATE	,
SHIPMENTPERIOD =@SHIPMENTPERIOD	,

TERMSCONDITION = @TERMSCONDITION	,
DESCRIPTIONS = @DESCRIPTIONS,


PACKINGMODE = @PACKINGMODE ,

SHIPPOINT = @SHIPPOINT,


INVOICENUMBER = @INVOICENUMBER,
INVOICEDATE = @INVOICEDATE ,
INVOICETO = @INVOICETO,
CONTRACTNO = @CONTRACTNO ,
SHIPPEDPER = @SHIPPEDPER,

SHIPPEDFROM = @SHIPPEDFROM,
SHIPPEDTO = @SHIPPEDTO ,
PURCHASEORDERNO = @PURCHASEORDERNO ,
PURCHASEORDERDATED =@PURCHASEORDERDATED 

WHERE ID=@ID

  SET @LOG='UPDATE TBLPACKINGREQUESTHEADER SET PACKREQDATE='
  +CAST(@PACKREQDATE AS VARCHAR(50))
  +'SHIPMENTPERIOD='+CAST(@SHIPMENTPERIOD AS VARCHAR(50))
  +'DESCRIPTIONS='+CAST(@DESCRIPTIONS AS VARCHAR(50))
  +'TERMSCONDITION='+CAST(@TERMSCONDITION AS VARCHAR(50))
  +' WHERE ID='+CAST(@ID AS VARCHAR(50))
  SET @PROCESSCODE=@PROCESSNAME+CAST(@ID AS VARCHAR(50))
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  --EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@HEADER,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @HEADER,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@PROCESSCODE,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll

END;