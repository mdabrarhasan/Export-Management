
CREATE PROCEDURE [dbo].[SPCUSTOMERINFOSAVE]
    @ID INT,
    @CUSTOMERNAME VARCHAR(100),
    @CUSTOMERBANKNAME VARCHAR(500),
    @CUSTOMERBANKBRANCHNAME VARCHAR(500),
    @ADDRESS1 VARCHAR(500),
    @ADDRESS2 VARCHAR(500),
    @ADDRESS3 VARCHAR(500),
    @BINNO VARCHAR(500),
    @ISACTIVE INT,
    @CREATEDBY INT,
    @Msg CHAR(100) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    IF @ID = 0
    BEGIN
        -- Insert new record
        INSERT INTO TBLCUSTOMERBANK (
            CUSTOMERNAME, CUSTOMERBANKNAME, CUSTOMERBANKBRANCHNAME,
            CUSTOMERBANKADDRESSLINEONE, CUSTOMERBANKADDRESSLINETWO,
            CUSTOMERBANKADDRESSLINETHREE, CUSTOMERBANKBINNO, ISACTIVE, CREATEDBY, CREATEDDATE
        )
        VALUES (
            @CUSTOMERNAME, @CUSTOMERBANKNAME, @CUSTOMERBANKBRANCHNAME,
            @ADDRESS1, @ADDRESS2, @ADDRESS3, @BINNO, @ISACTIVE, @CREATEDBY, GETDATE()
        );

        SET @Msg = 'Customer added successfully';
    END
    ELSE
    BEGIN
        -- Update existing record
        UPDATE TBLCUSTOMERBANK
        SET
            CUSTOMERNAME = @CUSTOMERNAME,
            CUSTOMERBANKNAME = @CUSTOMERBANKNAME,
            CUSTOMERBANKBRANCHNAME = @CUSTOMERBANKBRANCHNAME,
            CUSTOMERBANKADDRESSLINEONE = @ADDRESS1,
            CUSTOMERBANKADDRESSLINETWO = @ADDRESS2,
            CUSTOMERBANKADDRESSLINETHREE = @ADDRESS3,
            CUSTOMERBANKBINNO = @BINNO,
            ISACTIVE = @ISACTIVE,
            UPDATEDBY = @CREATEDBY,
            UPDATEDDATE = GETDATE()
        WHERE ID = @ID;

        SET @Msg = 'Customer updated successfully';
    END
END