CREATE PROCEDURE [dbo].[SPINSERTBANKLOAN]
(
@LENDERBANKID						INT,
@BORROWERUNITID						INT,
@LOANTYPEID							INT,
@LOANAMOUNT							DECIMAL(18,2),
@CURRENCYID							INT,
@CONRATE							DECIMAL(18,2),
@ISSUEDATE							VARCHAR(100),
@MATURITYDATE						VARCHAR(100),					
@INTERESTRATE						DECIMAL(18,2), 
@LOANNUMBER							VARCHAR(500),
@NARRATION							VARCHAR(MAX),

@MODULECODE							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@DOCSTATUS							VARCHAR(100),
@MESSAGENAME						VARCHAR(100),
@NOTIFICATION						VARCHAR(100),			
@DOCUMENTCREATEDBY					INT,
@UNITID								INT,
@MSG								VARCHAR(100)		OUT,
@STATUSMSG							VARCHAR(100)		OUT
)
AS
BEGIN

	DECLARE @DOCSTATUSID	INT,@ID INT,@PROCESSCODE VARCHAR(100),
	@TOTAL DECIMAL(30,2)=0.0,@BLNO VARCHAR(500),@LOANSTATUSID INT

	SET @DOCSTATUSID=(SELECT ID FROM ABGAPIS.DBO.TBLDOCUMENTSTATUS WHERE CODE=@DOCSTATUS)
	--SET @LOANSTATUSID=(SELECT ID FROM TBLPAYMENTRESCHEDULE WHERE CODE='BL00001')

	SET @BLNO='BL-'+(SELECT strUnit FROM ERP_HR.DBO.tblUnit WHERE intUnitID=@BORROWERUNITID)+'-'+
	(SELECT REPLACE(CONVERT(VARCHAR, GETDATE(), 3),'/',''))+'-'+
	CAST((SELECT convert(numeric(6,0),rand() * 899999) + 100000) AS VARCHAR(200))

	INSERT INTO TBLBANKLOAN
	(
	LENDERBANKID,
	BORROWERUNITID,
	LOANTYPEID,
	LOANAMOUNT,
	CURRENCYID,
	CONRATE,
	ISSUEDATE,
	MATURITYDATE,
	INTERESTRATE,
	LOANNUMBER,
	NARRATION,
	CREATEDBY,
	UPDATEDBY,
	CREATEDDATE,
	UPDATEDDATE,
	STATUSID,
	ISACTIVE
	--RESCHEDULEDID
	)
	VALUES
	(
	@LENDERBANKID,
	@BORROWERUNITID,
	@LOANTYPEID,
	@LOANAMOUNT,
	@CURRENCYID,
	@CONRATE,
	@ISSUEDATE,
	@MATURITYDATE,
	@INTERESTRATE,
	@LOANNUMBER,
	@NARRATION,
	@DOCUMENTCREATEDBY,
	@DOCUMENTCREATEDBY,
	GETDATE(),
	GETDATE(),
	@DOCSTATUSID,
	1
	--@LOANSTATUSID
	)
	
	SET @MSG='DATA SAVED SUCCESSFULLY.SANCTION NO :'+@BLNO
	SET @STATUSMSG='success';
END;