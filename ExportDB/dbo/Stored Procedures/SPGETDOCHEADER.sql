CREATE PROCEDURE [dbo].[SPGETDOCHEADER]
(
@TYPE						INT,
@DOCSETUPHEADER				INT
)
AS
BEGIN
IF @TYPE=1
BEGIN
SELECT HEADER.ID,HEADER.DOCNUMBER,HEADER.PICKINGPACKINGHEADERID,PICKPACKHEADER.PICKPACKNUMBER,CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
HEADER.CUSTOMERID,CUS.strName AS CUSNAME,CAST(CAST(HEADER.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DS.NAME AS DOCSTATUSNAME,DS.CODE AS CODE,SETUPH.ID AS DOCSETUPHEADERID,
HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS,0 AS DOCHEADERID
FROM TBLDOCHEADER		HEADER,TBLPICKINGPACKINGHEADER PICKPACKHEADER,ERP_SAD.DBO.tblCustomer CUS,TBLDOCUMENTSTATUS DS,TBLDOCUMENTSETUPHEADER SETUPH
WHERE  HEADER.PICKINGPACKINGHEADERID=PICKPACKHEADER.ID AND CUS.intCusID=HEADER.CUSTOMERID
AND HEADER.DOCUMENTSTATUSID=DS.ID AND SETUPH.ID=HEADER.DOCUMENTSETUPHEADERID AND HEADER.DOCUMENTSETUPHEADERID=@DOCSETUPHEADER AND HEADER.ISACTIVE=1
END
ELSE IF @TYPE=2
BEGIN
SELECT HEADER.ID,HEADER.DOCNUMBER,HEADER.PICKINGPACKINGHEADERID,PICKPACKHEADER.PICKPACKNUMBER,CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
HEADER.CUSTOMERID,CUS.strName AS CUSNAME,CAST(CAST(HEADER.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DS.NAME AS DOCSTATUSNAME,DS.CODE AS CODE,SETUPH.ID AS DOCSETUPHEADERID,
HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS,0 AS DOCHEADERID
FROM TBLDOCHEADER		HEADER,TBLPICKINGPACKINGHEADER PICKPACKHEADER,ERP_SAD.DBO.tblCustomer CUS,TBLDOCUMENTSTATUS DS,TBLDOCUMENTSETUPHEADER SETUPH
WHERE  HEADER.PICKINGPACKINGHEADERID=PICKPACKHEADER.ID AND CUS.intCusID=HEADER.CUSTOMERID
AND HEADER.DOCUMENTSTATUSID=DS.ID AND SETUPH.ID=HEADER.DOCUMENTSETUPHEADERID AND HEADER.ID=@DOCSETUPHEADER AND SETUPH.ISACTIVE=1
END;
END;