CREATE PROCEDURE [dbo].[SPGETLOANFACILITY]
(
@UNITID				INT,
@MODULECODE			VARCHAR(100),
@DOCSTATUS			VARCHAR(100),
@CREATEDBY			INT
)
AS
BEGIN
IF @UNITID=0 
	BEGIN
	SELECT LF.ID,UNITID,SANCTIONNO,SANCTIONREF,SODLIMIT,CAST(CAST(EXPIREDATE AS DATE) AS VARCHAR(100)) AS EXPIREDATE,
	CASE WHEN (INNERUNITID=0 OR INNERUNITID IS NULL) THEN (SELECT NAME FROM TBLUNITFORTREASURY WHERE ID=LF.UNITID) ELSE UNIT.NAME+'[inner '+(SELECT CODE FROM TBLUNITFORTREASURY WHERE ID=LF.INNERUNITID)+']' END AS UNIT,
	ISNULL(INNERUNITID,0) AS INNERUNITID,
	'' AS INNERUNIT,BANKID,(SELECT strBankName FROM ERP_Accounts.DBO.tblBankInfo WHERE intBankID=LF.BANKID) AS BANKNAME,ISNULL(RAWMATERIALLIMIT,0.0) AS RAWMATERIALLIMIT,ISNULL(LOANLIMIT,0.0) AS LOANLIMIT,
	ISNULL(MACHINERYLIMIT,0.0) AS MACHINERYLIMIT,ISNULL(SHORTTERMLOAN,0.0) AS SHORTTERMLOAN,
	ISNULL(OVERDRAFTFACILITY,0.0) AS OVERDRAFTFACILITY,ISNULL(BANKGUARANTEELIMIT,0.0) AS BANKGUARANTEELIMIT,
	ISNULL(TIMELOANLIMIT,0.0) AS TIMELOANLIMIT,ISNULL(TERMLOANLIMIT,0.0) AS TERMLOANLIMIT,ISNULL(LCSPARESMACHINERYLIMIT,0.0) AS LCSPARESMACHINERYLIMIT,ISNULL(TOTAL,0.0) AS TOTAL
	FROM TBLLIMITFACILITY LF INNER JOIN TBLUNITFORTREASURY UNIT
	ON LF.UNITID=UNIT.ID AND LF.ISACTIVE=1
	END;
ELSE
	BEGIN
	SELECT LF.ID,UNITID,SANCTIONNO,SANCTIONREF,SODLIMIT,CAST(CAST(EXPIREDATE AS DATE) AS VARCHAR(100)) AS EXPIREDATE,
	CASE WHEN (INNERUNITID=0 OR INNERUNITID IS NULL) THEN (SELECT NAME FROM TBLUNITFORTREASURY WHERE ID=LF.UNITID) ELSE UNIT.NAME+'[inner '+(SELECT CODE FROM TBLUNITFORTREASURY WHERE ID=LF.INNERUNITID)+']' END AS UNIT,
	ISNULL(INNERUNITID,0) AS INNERUNITID,
	'' AS INNERUNIT,BANKID,(SELECT strBankName FROM ERP_Accounts.DBO.tblBankInfo WHERE intBankID=LF.BANKID) AS BANKNAME,ISNULL(RAWMATERIALLIMIT,0.0) AS RAWMATERIALLIMIT,ISNULL(LOANLIMIT,0.0) AS LOANLIMIT,
	ISNULL(MACHINERYLIMIT,0.0) AS MACHINERYLIMIT,ISNULL(SHORTTERMLOAN,0.0) AS SHORTTERMLOAN,
	ISNULL(OVERDRAFTFACILITY,0.0) AS OVERDRAFTFACILITY,ISNULL(BANKGUARANTEELIMIT,0.0) AS BANKGUARANTEELIMIT,
	ISNULL(TIMELOANLIMIT,0.0) AS TIMELOANLIMIT,ISNULL(TERMLOANLIMIT,0.0) AS TERMLOANLIMIT,ISNULL(LCSPARESMACHINERYLIMIT,0.0) AS LCSPARESMACHINERYLIMIT,ISNULL(TOTAL,0.0) AS TOTAL
	FROM TBLLIMITFACILITY LF INNER JOIN TBLUNITFORTREASURY UNIT
	ON LF.UNITID=UNIT.ID
	WHERE LF.UNITID=@UNITID AND LF.ISACTIVE=1
	END;
END;