CREATE PROCEDURE SPGETPICKPACKNUMBER
(
@TYPE			INT,
@PREFIX			VARCHAR(50)
)
AS
BEGIN
SELECT ID,PICKPACKNUMBER+' ['+CUS.strName+']' AS NAME FROM TBLPICKINGPACKINGHEADER PICKPACKH,ERP_SAD.DBO.tblCustomer CUS
WHERE PICKPACKH.CUSTOMERID=CUS.intCusID AND PICKPACKH.DOCUMENTSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP') AND (PICKPACKNUMBER like '%'+@PREFIX+'%');
END;