CREATE PROCEDURE [dbo].[SPGETDOCLIST]
(
@TYPE						INT,
@DOCSETUPHEADER				INT,
@PICKPACKID					INT
)
AS
BEGIN
--TYPE 2 AND 4 ADDED ROOTURL AND ENDURL BY MAHAMUD
--DECLARE @VDOCSETUPHEADER INT
IF @TYPE=1
BEGIN
--SET @VDOCSETUPHEADER=(SELECT ID FROM TBLDOCUMENTSETUPHEADER WHERE CODE=@DOCSETUPHEADER)
	SELECT DOCLINE.ID,DOCH.ID AS DOCHEADERID,DOCH.PICKINGPACKINGHEADERID,DOCH.DOCUMENTSETUPHEADERID,DOCSETUPH.NAME AS ROOTDOCNAME,DOCSETUPLINE.NAME AS CHILDDOCNAME,DOCSETUPLINE.TYPE,
	DOCH.DOCNUMBER,CAST(CAST(DOCH.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DOCH.CUSTOMERID,CUS.strName AS CUSTOMERNAME,DOCH.TERMSCONDITION,DOCH.DESCRIPTIONS,
	DOCSETUPLINE.ISMANDATORY,CASE WHEN DOCSETUPLINE.ISMANDATORY=0 THEN 'Optional' ELSE 'Mandatory' END AS MANDATORYLABEL,
	DOCLINE.DOCUMENTSETUPLINEID
	FROM 

	TBLDOCHEADER									 DOCH,
	TBLDOCLINE										 DOCLINE,
	TBLDOCUMENTSETUPHEADER							 DOCSETUPH,
	TBLDOCUMENTSETUPLINE							 DOCSETUPLINE,
	ERP_SAD.DBO.tblCustomer							 CUS

	WHERE DOCH.ID=DOCLINE.DOCHEADERID				 AND 
	DOCH.DOCUMENTSETUPHEADERID=DOCSETUPH.ID			 AND 
	DOCSETUPH.ID=DOCSETUPLINE.DOCUMENTSETUPHEADERID  AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCH.CUSTOMERID=CUS.intCusID					 AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCH.DOCUMENTSETUPHEADERID=@DOCSETUPHEADER ORDER BY DOCH.DOCUMENTCREATEDDATE DESC
END;

IF @TYPE=2
BEGIN
	/*SELECT  DOCSETUPLINE.ID AS ID,DOCSETUPH.ID AS DOCHEADER,DOCSETUPH.NAME AS ROOTDOCNAME,DOCSETUPH.CODE AS ROOTDOCCODE,DOCSETUPLINE.NAME AS CHILDDOCNAME,DOCSETUPLINE.TYPE,
	CASE WHEN DOCSETUPLINE.ISMANDATORY=0 THEN 'Optional' ELSE 'Mandatory' END AS MANDATORYLABEL,'' AS TERMSCONDITION,'' AS DESCRIPTIONS
	FROM 
	TBLDOCUMENTSETUPHEADER							 DOCSETUPH,
	TBLDOCUMENTSETUPLINE							 DOCSETUPLINE
	WHERE 
	DOCSETUPH.ID=DOCSETUPLINE.DOCUMENTSETUPHEADERID  AND DOCSETUPH.ID=@DOCSETUPHEADER ORDER BY TYPE*/
	SELECT DOCSETUPLINE.ID AS ID,0 AS DOCHEADERID,
	DOCSETUPH.ID AS DOCHEADER,
	DOCSETUPH.NAME AS ROOTDOCNAME,
	DOCSETUPH.CODE AS ROOTDOCCODE,DOCSETUPLINE.REPORTROOTURL AS rooturl,DOCSETUPLINE.REPORTENDURL AS endurl,
	DOCSETUPLINE.NAME AS CHILDDOCNAME,
	DOCSETUPLINE.TYPE,
	CASE WHEN DOCSETUPLINE.ISMANDATORY=0 THEN 'Optional' ELSE 'Mandatory' END AS MANDATORYLABEL,
	'' AS TERMSCONDITION,
	'' AS DESCRIPTIONS,
	case when DOCSETUPLINE.id in (select PROCESSLINEID from TBLFILEDETAILS where PICKINGPACKINGHEADERID=@PICKPACKID) then 'Y' else 'N' end as DOCSTATUS,
	'' AS FILENAME
	FROM
	TBLDOCUMENTSETUPHEADER DOCSETUPH
	INNER JOIN TBLDOCUMENTSETUPLINE DOCSETUPLINE ON DOCSETUPH.ID=DOCSETUPLINE.DOCUMENTSETUPHEADERID
	WHERE DOCSETUPH.ID=@DOCSETUPHEADER order by TYPE
END;


IF @TYPE=3
BEGIN
	 SELECT DOCH.ID AS DOCHEADERID,DOCH.PICKINGPACKINGHEADERID,DOCH.DOCUMENTSETUPHEADERID,DOCH.DOCNUMBER,
	CAST(CAST(DOCH.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DOCH.CUSTOMERID,CUS.strName AS CUSTOMERNAME,DOCH.TERMSCONDITION,DOCH.DESCRIPTIONS,
	PICKPACK.PICKPACKNUMBER
	FROM 

	TBLDOCHEADER									 DOCH,
	ERP_SAD.DBO.tblCustomer							 CUS,
	TBLPICKINGPACKINGHEADER							 PICKPACK

	WHERE 
	DOCH.CUSTOMERID=CUS.intCusID					 AND
	DOCH.PICKINGPACKINGHEADERID=PICKPACK.ID			 AND
	DOCH.ID=@DOCSETUPHEADER ORDER BY DOCH.DOCUMENTCREATEDDATE DESC

END;

IF @TYPE=4
BEGIN

SELECT DOCSETUPLINE.ID AS ID,DOCH.ID AS DOCHEADERID,DOCH.PICKINGPACKINGHEADERID,DOCSETUPH.ID AS DOCHEADER,
DOCSETUPH.CODE AS ROOTDOCCODE,DOCH.DOCUMENTSETUPHEADERID,
DOCSETUPH.NAME+'/'+DOCSETUPLINE.NAME+'/'+ISNULL((SELECT FD.FILENAME FROM TBLFILEDETAILS FD WHERE 
FD.PROCESSLINEID=DOCSETUPLINE.ID AND FD.PICKINGPACKINGHEADERID=DOCH.PICKINGPACKINGHEADERID),'') AS ROOTDOCNAME,
DOCSETUPLINE.NAME AS CHILDDOCNAME,DOCSETUPLINE.REPORTROOTURL AS rooturl,DOCSETUPLINE.REPORTENDURL AS endurl,
DOCSETUPLINE.TYPE,
	DOCH.DOCNUMBER,CAST(CAST(DOCH.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DOCH.CUSTOMERID,CUS.strName AS CUSTOMERNAME,DOCH.TERMSCONDITION,DOCH.DESCRIPTIONS,
	DOCSETUPLINE.ISMANDATORY,CASE WHEN DOCSETUPLINE.ISMANDATORY=0 THEN 'Optional' ELSE 'Mandatory' END AS MANDATORYLABEL,
	DOCLINE.DOCUMENTSETUPLINEID,case when DOCSETUPLINE.ID not in (select PROCESSLINEID from TBLFILEDETAILS where PICKINGPACKINGHEADERID=@PICKPACKID) then 'Y' else 'N' end as DOCSTATUS,
	ISNULL((SELECT FD.FILENAME FROM TBLFILEDETAILS FD WHERE FD.PROCESSLINEID=DOCSETUPLINE.ID AND FD.PICKINGPACKINGHEADERID=DOCH.PICKINGPACKINGHEADERID),'') AS FILENAME
	FROM 

	TBLDOCHEADER									 DOCH,
	TBLDOCLINE										 DOCLINE,
	TBLDOCUMENTSETUPHEADER							 DOCSETUPH,
	TBLDOCUMENTSETUPLINE							 DOCSETUPLINE,
	ERP_SAD.DBO.tblCustomer							 CUS

	WHERE DOCH.ID=DOCLINE.DOCHEADERID				 AND 
	DOCH.DOCUMENTSETUPHEADERID=DOCSETUPH.ID			 AND 
	DOCSETUPH.ID=DOCSETUPLINE.DOCUMENTSETUPHEADERID  AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCH.CUSTOMERID=CUS.intCusID					 AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCLINE.DOCHEADERID=@DOCSETUPHEADER ORDER BY TYPE
END;

END;