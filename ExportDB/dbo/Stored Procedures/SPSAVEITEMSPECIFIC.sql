

CREATE PROCEDURE [dbo].[SPSAVEITEMSPECIFIC]
(
@ITEMID						INT,
@LENGTH						VARCHAR(100),
@WIDTH						VARCHAR(100),
@HEIGHT						VARCHAR(100),
@THICKNESS					VARCHAR(100),
@WEIGHT 					VARCHAR(100),
@COLOR						VARCHAR(100),
@SIZE						VARCHAR(100),
@DESIGN						VARCHAR(100),
@PACKAGING					VARCHAR(100),
@MATERIAL					VARCHAR(100),
@CONSTRUCTION				VARCHAR(100),
@PLY						VARCHAR(100),
@CORE						VARCHAR(100),
@TREATMENTDIRECTION			VARCHAR(100),
@OTHERS						VARCHAR(100),
@REMARK						VARCHAR(100),
@SESSIONID					VARCHAR(100),
@DOCUMENTCREATEDBY			INT,
@MSG						VARCHAR(100)   OUTPUT
)
AS
BEGIN
DECLARE @CHECKITEM INT
SET @CHECKITEM=(SELECT COUNT(ITEMID) FROM TBLITEMORDERSPECSTAGING WHERE ITEMID=@ITEMID)
    IF @CHECKITEM=0 
	BEGIN
	INSERT INTO TBLITEMORDERSPECSTAGING
	(
	ITEMID,LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,SESSIONID,DOCUMENTCREATEDBY,DOCUMENTCREATEDDATE
	)
	VALUES
	(
	@ITEMID,@LENGTH,@WIDTH,@HEIGHT,@THICKNESS,@WEIGHT,@COLOR,@SIZE,@DESIGN,@PACKAGING,@MATERIAL,@CONSTRUCTION,@PLY,@CORE,@TREATMENTDIRECTION,@OTHERS,@REMARK,@SESSIONID,@DOCUMENTCREATEDBY,GETDATE()
	)
	SET @MSG='Item Specification added for this Item.'
	END;
	ELSE
	BEGIN
	DELETE FROM TBLITEMORDERSPECSTAGING WHERE ITEMID=@ITEMID
	INSERT INTO TBLITEMORDERSPECSTAGING
	(
	ITEMID,LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,SESSIONID,DOCUMENTCREATEDBY,DOCUMENTCREATEDDATE
	)
	VALUES
	(
	@ITEMID,@LENGTH,@WIDTH,@HEIGHT,@THICKNESS,@WEIGHT,@COLOR,@SIZE,@DESIGN,@PACKAGING,@MATERIAL,@CONSTRUCTION,@PLY,@CORE,@TREATMENTDIRECTION,@OTHERS,@REMARK,@SESSIONID,@DOCUMENTCREATEDBY,GETDATE()
	)
	SET @MSG='Item Specification added for this Item.'
	END;
END;