		ON PRL.ITEMID=ITEM.intID
		WHERE PICKINGPACKINGHEADERID=@ID AND ISACTIVE=1 --GROUP BY SERIALNO,ITEMID,ITEM.strItemName,ITEM.strUoM,REMARKS,DESCRIPTIONS
		--HAVING MAX(PACKINGREQQUANTITY)-SUM(PICKINGPACKINGQUANTITY)>0 ORDER BY EXPPRODUCTIONORDERDATE*/

		
