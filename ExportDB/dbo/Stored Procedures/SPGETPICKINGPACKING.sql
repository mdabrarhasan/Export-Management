
	CREATE PROCEDURE [dbo].[SPGETPICKINGPACKING]
		(
		@Type			INT,
		@ENROLL			INT,
		@ID				INT,
		@UnitID			INT
		)
		AS
		BEGIN
		IF @Type=0
		BEGIN
		SELECT PICKPACK.ID,PICKPACK.PICKPACKNUMBER,PICKPACK.PACKINGREQUESTHEADERID,CAST(CAST(PICKPACK.PICKPACKDATE AS DATE) AS VARCHAR(50)) PICKPACKDATE,
		PACKH.PACKREQNUMBER,
		CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,
		CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TOSHIPM.NAME AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PICKPACK.FLAG
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY					TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLFROMLOADINGPORT			TOSHIPM		
		ON		 PISCH.TODISCHARGEPORT=TOSHIPM.ID					LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					INNER JOIN TBLPICKINGPACKINGHEADER		PICKPACK
		ON       PACKH.ID=PICKPACK.PACKINGREQUESTHEADERID			INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PICKPACK.DOCUMENTSTATUSID
		WHERE    PICKPACK.DOCUMENTCREATEDBY=@ENROLL  AND PICKPACK.ISACTIVE=1
		order by  PICKPACK.ID desc
		END;

		IF @Type=1
		BEGIN
		SELECT 
		--Mill Declaration No.
		PACKH.PACKREQNUMBER AS MILLDECLARATIONNO,
        --Mill Declaration Date
		PACKH.PACKREQDATE as MILLDECLARATIONDATE,
       -- Invoice No. 
	   PACKH.INVOICENUMBER as INVOICENO,
        --Invoice Date
		PACKH.INVOICEDATE as INVOICEDATE,
       -- Invoice To. 
	   PACKH.INVOICETO as INVOICETO,
        --Shipped from 
		PACKH.SHIPPEDFROM as SHIPPEDFROM,
        --Shipped To. 
		PACKH.SHIPPEDTO as SHIPPEDTO,

		PICKPACK.VEHICALNO,
		PICKPACK.DRIVERNAME,
		PICKPACK.DRIVERPHONE,
		PICKPACK.CUSTOMERDETAILS,
		PICKPACK.GATENO,
		PICKPACK.GATEPERSON,

		PICKPACK.ID,PICKPACK.PICKPACKNUMBER,PICKPACK.PACKINGREQUESTHEADERID,CAST(CAST(PICKPACK.PICKPACKDATE AS DATE) AS VARCHAR(50)) PICKPACKDATE,
		PACKH.PACKREQNUMBER,
		CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,
		CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TOSHIPM.NAME AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PICKPACK.FLAG
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    LEFT JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY   				TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLFROMLOADINGPORT				TOSHIPM		
		ON		 PISCH.TODISCHARGEPORT=TOSHIPM.ID					LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					INNER JOIN TBLPICKINGPACKINGHEADER		PICKPACK
		ON       PACKH.ID=PICKPACK.PACKINGREQUESTHEADERID
		WHERE    PICKPACK.ID=@ID  AND PACKH.ISACTIVE=1
		END;

		ELSE IF @Type=2
		BEGIN
		
	SELECT PRL.ID AS ID,
		0 AS SERIALNO,
		PISCL.ITEMID,
		LIST.strProductName+CASE WHEN ITEMTYPEID=1 THEN ' '+QUALITY WHEN ITEMTYPEID=2 THEN SIZE+' '+CONSTRUCTION+' '+WEIGHT ELSE SLIT+' '+SCRIM+' '+CONSTRUCTION END AS ITEMNAME,
		UOM.strUOM AS UOM,
		PRL.QUANTITY AS QUANTITY,
		PRL.PACKINGREQQUANTITY AS PACKINGREQQUANTITY,
		0 AS TOLERANCEID,
		'' AS EXPPRODUCTIONORDERDATE,
		0 AS PICKINGPACKINGHEADERID,
		PRL.QUANTITY-PRL.PACKINGREQQUANTITY AS REMAININGQTY,
		PRL.TRUCKNO,
		ISNULL(PRL.COUNT,0.0) AS COUNT,
		ISNULL(PRL.GROSSMEASURE,0.0) AS GROSSMEASURE,
		ISNULL(PRL.CONTAINERSIZE,0) AS CONTAINERSIZE,
		PRL.REMARKS as REMARKS,
		PRL.DESCRIPTIONS as DESCRIPTIONS,
		PRL.CONTAINERNO,
		(SELECT CODE FROM TBLDOCUMENTSTATUS WHERE  ID=(SELECT DOCUMENTSTATUSID FROM TBLPICKINGPACKINGHEADER WHERE ID=PRL.PICKINGPACKINGHEADERID)) AS CODE

		FROM TBLPRICECONFIRMLINE LINE			INNER JOIN ERP_SAD.dbo.tblItem LIST
		ON LINE.ITEMID=LIST.intID 				INNER JOIN TBLPRICECONFIRMHEADER PCH
		ON PCH.ID=LINE.PRICECONFIRMHEADERID		INNER JOIN TBLPISCHEADER   PISCH
		ON PISCH.ID=PCH.PROFORMAINVOICEHEADERID INNER JOIN TBLPISCLINE     PISCL
		ON PISCH.ID=PISCL.PISCHEADER			AND PISCL.ITEMID=LIST.intID AND PISCL.ID=LINE.QUOTATIONLINEID INNER JOIN ERP_SAD.dbo.tblUOM UOM
		ON PISCL.UOMID=UOM.intID				INNER JOIN TBLPACKINGREQUESTHEADER PRH
		ON PRH.PISCNUMBER=PISCH.ID				INNER JOIN TBLPICKINGPACKINGHEADER  PPH
		ON PRH.ID=PPH.PACKINGREQUESTHEADERID    INNER JOIN TBLPICKINGPACKINGLINE    PRL
		ON PPH.ID=PRL.PICKINGPACKINGHEADERID    AND PISCL.ITEMID=PRL.ITEMID AND PRL.PISCLINEID=PISCL.ID
		WHERE PICKINGPACKINGHEADERID=@ID AND PRL.ISACTIVE=1

		END;
		ELSE IF @Type=3   
		BEGIN
		DECLARE @STATUS INT
		SET @STATUS=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='PEND')
		SELECT APPHISTORY.ID AS ID,PACKH.PACKREQNUMBER,CAST(PACKH.PACKREQDATE AS VARCHAR(100)) AS PACKREQDATE,PACKH.TERMSCONDITION,PACKH.DESCRIPTIONS,CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,CUR.NAME AS CURRENCY,PISCH.NUMBER AS PISCNUMBER,DS.CODE,DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TOSHIPM.NAME AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD
		FROM     TBLPACKINGREQUESTHEADER PACKH						INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							INNER JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						INNER JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						INNER JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							INNER JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							INNER JOIN TBLSHIPMENTMODE				TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				INNER JOIN TBLSHIPMENTMODE				TOSHIPM		
		ON		 PISCH.TODISCHARGEPORT=TOSHIPM.ID					INNER JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						INNER JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					INNER JOIN TBLAPPROVERMATRIXHISTORY		APPHISTORY
		ON		 PACKH.ID=APPHISTORY.PROCESSID
		WHERE    APPHISTORY.ACTIONTAKERID=@ENROLL AND PACKH.ISACTIVE=1
		END;
		ELSE IF @Type=4
		BEGIN

		SELECT PRL.ID AS ID,0 AS SERIALNO,ITEMID,ITEM.strProductName AS ITEMNAME,case when ITEM.intUnitID=91 then 'KG' when ITEM.intUnitID=178 then 'pecs' when ITEM.intUnitID=182 then 'Pecs' end AS UOM,PACKINGREQQUANTITY AS QUANTITY,PICKINGPACKINGQUANTITY AS PACKINGREQQUANTITY,0 AS TOLERANCEID,
		'' AS EXPPRODUCTIONORDERDATE,REMARKS,DESCRIPTIONS,'' as CODE,
		0 AS PICKINGPACKINGHEADERID,PACKINGREQQUANTITY-PICKINGPACKINGQUANTITY AS REMAININGQTY,
		PRL.TRUCKNO,ISNULL(PRL.COUNT,0) AS COUNT,ISNULL(PRL.GROSSMEASURE,0) AS GROSSMEASURE,PRL.CONTAINERNAME,PRL.CONTAINERNO
		from TBLPICKINGPACKINGLINE PRL			INNER JOIN	ERP_SAD.dbo.tblItem ITEM
		ON PRL.ITEMID=ITEM.intID
		WHERE PICKINGPACKINGHEADERID IN (SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID) AND ISACTIVE=1 --GROUP BY SERIALNO,ITEMID,ITEM.strItemName,ITEM.strUoM,REMARKS,DESCRIPTIONS

		/*SELECT MAX(ID) AS ID,0 AS SERIALNO,ITEMID,ITEM.strItemName AS ITEMNAME,ITEM.strUoM AS UOM,MAX(PACKINGREQQUANTITY) AS QUANTITY,SUM(PICKINGPACKINGQUANTITY) AS PACKINGREQQUANTITY,0 AS TOLERANCEID,
		'' AS EXPPRODUCTIONORDERDATE,REMARKS,DESCRIPTIONS,
		0 AS PICKINGPACKINGHEADERID,MAX(PACKINGREQQUANTITY)-SUM(PICKINGPACKINGQUANTITY) AS REMAININGQTY
		from TBLPICKINGPACKINGLINE PRL			INNER JOIN	ERP_Inventory.dbo.tblItemList ITEM
		ON PRL.ITEMID=ITEM.intItemID
		WHERE PICKINGPACKINGHEADERID IN (SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID) AND ISACTIVE=1 GROUP BY SERIALNO,ITEMID,ITEM.strItemName,ITEM.strUoM,REMARKS,DESCRIPTIONS

			SELECT MAX(PRL.ID) AS ID,ITEMID,ITEM.strItemName AS ITEMNAME,ITEM.strUoM AS UOM, MAX(QUANTITY) AS QUANTITY,SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,MAX(QUANTITY)-SUM(PACKINGREQQUANTITY) AS REMAININGQTY,
		PRL.PICKINGPACKINGHEADERID
		from TBLPICKINGPACKINGLINE PRL			INNER JOIN	ERP_Inventory.dbo.tblItemList ITEM
		ON PRL.ITEMID=ITEM.intItemID
		WHERE PRL.ID=(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ID) AND ISACTIVE=1 GROUP BY ITEMID,ITEM.strItemName,PRL.PICKINGPACKINGHEADERID,ITEM.strUoM;*/
		END;

		ELSE IF @Type=5
		BEGIN
		SELECT PICKPACK.ID,

			--Mill Declaration No.
		PACKH.PACKREQNUMBER AS MILLDECLARATIONNO,
        --Mill Declaration Date
		PACKH.PACKREQDATE as MILLDECLARATIONDATE,
       -- Invoice No. 
	   PACKH.INVOICENUMBER as INVOICENO,
        --Invoice Date
		PACKH.INVOICEDATE as INVOICEDATE,
       -- Invoice To. 
	   PACKH.INVOICETO as INVOICETO,
        --Shipped from 
		PACKH.SHIPPEDFROM as SHIPPEDFROM,
        --Shipped To. 
		PACKH.SHIPPEDTO as SHIPPEDTO,

		PICKPACK.VEHICALNO,
		PICKPACK.DRIVERNAME,
		PICKPACK.DRIVERPHONE,
		PICKPACK.CUSTOMERDETAILS,
		PICKPACK.GATENO,
		PICKPACK.GATEPERSON,

		PICKPACK.PICKPACKNUMBER,
		PICKPACK.PACKINGREQUESTHEADERID,
		CAST(CAST(PICKPACK.PICKPACKDATE AS DATE) AS VARCHAR(50)) PICKPACKDATE,
		PACKH.PACKREQNUMBER,
		CAST(CAST(PACKH.PACKREQDATE AS DATE) AS VARCHAR(100)) AS PACKREQDATE,
		PACKH.TERMSCONDITION,
		PACKH.DESCRIPTIONS,
		CAST(PACKH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
		CUS.strName AS CUSTOMERNAME,
		CUR.NAME AS CURRENCY,
		PISCH.NUMBER AS PISCNUMBER,
		DS.CODE,
		DS.NAME DOCSTATUS,
		PACKH.CUSTOMERID AS AGREEMENTTYPEID,
		AGR.NAME AS AGREEMENTTYPE,PISCH.SHIPMENTMODEID,SM.NAME AS SHIPMENTMODE,PISCH.PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PISCH.TOSHIPMENTCOUNTRYID,TOSHIP.NAME AS TOSHIPMENTCOUNTRY,
		PISCH.TODISCHARGEPORT,TOSHIPM.NAME AS DISCHARGEPORT,PISCH.TRANSHIPMENT,TRANSHIP.NAME AS TRANSHIPMENTNAME,PISCH.PARTIALSHIPMENT,PARTIAL.NAME AS PARTIALSHIPMENTNAME,
		PISCH.NOTIFYPARTY,CAST(PACKH.SHIPMENTPERIOD AS VARCHAR(100)) AS SHIPMENTPERIOD,PICKPACK.FLAG
		FROM TBLPACKINGREQUESTHEADER PACKH							INNER JOIN TBLPISCHEADER				PISCH
		ON		 PACKH.PISCNUMBER=PISCH.ID							LEFT JOIN TBLCURRENCY					CUR
		ON		 PISCH.CURRENCYID=CUR.ID							INNER JOIN ERP_SAD.dbo.tblCustomer		CUS
		ON		 PACKH.CUSTOMERID=CUS.intCusID					    INNER JOIN TBLDOCUMENTSTATUS			DS
		ON		 DS.ID=PACKH.DOCUMENTSTATUSID						LEFT JOIN TBLAGREEMENTTYPE				AGR
		ON		 PISCH.AGREEMENTTYPEID=AGR.ID						LEFT JOIN TBLSHIPMENTMODE				SM
		ON		 PISCH.SHIPMENTMODEID=SM.ID							LEFT JOIN TBLPAYMENTTERMS				PT
		ON		 PISCH.PAYMENTTERMID=PT.ID							LEFT JOIN TBLCOUNTRY				    TOSHIP
		ON		 PISCH.TOSHIPMENTCOUNTRYID=TOSHIP.ID				LEFT JOIN TBLFROMLOADINGPORT			TOSHIPM		
		ON		 PISCH.TODISCHARGEPORT=TOSHIPM.ID					LEFT JOIN TBLCONFIRM					TRANSHIP
		ON		 PISCH.TRANSHIPMENT=TRANSHIP.ID						LEFT JOIN TBLCONFIRM					PARTIAL
		ON		 PISCH.PARTIALSHIPMENT=PARTIAL.ID					INNER JOIN TBLPICKINGPACKINGHEADER		PICKPACK
		ON       PACKH.ID=PICKPACK.PACKINGREQUESTHEADERID
		WHERE    PICKPACK.DOCUMENTCREATEDBY=@ENROLL AND PICKPACK.ID=@ID  AND PICKPACK.ISACTIVE=1
		END;

		ELSE IF @Type=6
		BEGIN
		/*SELECT MAX(PRL.ID) AS ID,ITEMID,ITEM.strItemName AS ITEMNAME,ITEM.strUoM AS UOM, MAX(QUANTITY) AS QUANTITY,SUM(PACKINGREQQUANTITY) AS PACKINGREQQUANTITY,MAX(QUANTITY)-SUM(PACKINGREQQUANTITY) AS REMAININGQTY,
		PRL.PICKINGPACKINGHEADERID
