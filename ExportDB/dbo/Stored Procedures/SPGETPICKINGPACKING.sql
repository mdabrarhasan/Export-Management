		ON PPH.ID=PRL.PICKINGPACKINGHEADERID    AND PISCL.ITEMID=PRL.ITEMID AND PISCL.ID=PRL.PISCLINEID AND LINE.QUOTATIONLINEID=PISCL.ID
		WHERE PICKINGPACKINGHEADERID=@ID AND PRL.ISACTIVE=1

