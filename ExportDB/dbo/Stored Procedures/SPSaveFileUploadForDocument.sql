

CREATE procedure [dbo].[SPSaveFileUploadForDocument]
(
@typefileupload			TypeFileUploadForDocument readonly,
@UnitID int,
@ModuleCode varchar(100),
@Enroll	int,
@ProcessName	varchar(50),
@MessageName	varchar(50),
@Msg			varchar(100) out
)
as
begin try
		declare @vPROCESSCODE varchar(100),@PROCESS varchar(100),@FILENAME varchar(100),@FILESIZE varchar(100),@submenuid int,
		@FILETYPE varchar(100),@FILEURL varchar(100),@DOCUMENTCREATEDBY int,@CODE VARCHAR(100),@PROCESSID INT,
		@PROCESSHEADERID INT,@PROCESSLINEID INT, @PROCESSCODE VARCHAR(100),@PICKPACKID INT,@PROCESSLINECODE VARCHAR(100),
		@VPROCESSNAME VARCHAR(100),
		@FILEID VARCHAR(100)


	   DECLARE sql_cursor CURSOR FOR  
	   select  ProcessLineID,ProcessHeaderID,PickPackID,[FILENAME],[FILESIZE],[FILETYPE],[FILEURL],[DOCUMENTCREATEDBY] from @typefileupload
	   OPEN sql_cursor;  
	   FETCH NEXT FROM sql_cursor INTO @PROCESSLINEID,@PROCESSHEADERID,@PICKPACKID,@FILENAME,@FILESIZE,@FILETYPE,@FILEURL,@DOCUMENTCREATEDBY; 
	   set @FILEID=(select 'FILE' +''+cast(isnull(max(ID),0)+1 as varchar(100))  from TBLFILEDETAILS)

	   set @submenuid=(select SUBMENUID from TBLDOCUMENTSETUPHEADER where ID=@PROCESSHEADERID)
	   --SELECT @ProcessID=ID,@vProcessCode=SQNUMBER FROM TBLSALESQUOTATIONHEADER WHERE ID=@PROCESSCODE and UNITID=@UnitID

	   WHILE @@FETCH_STATUS = 0  
	   begin

	   SET @VPROCESSNAME=(SELECT CODE FROM TBLDOCUMENTSETUPHEADER WHERE ID=@PROCESSHEADERID)   
	   SET @PROCESSCODE=@VPROCESSNAME+CAST(@PROCESSHEADERID AS VARCHAR(100));
	   SET @PROCESSLINECODE=(SELECT CODE FROM TBLDOCUMENTSETUPLINE WHERE ID=@PROCESSLINEID)

	   insert into TBLFILEDETAILS
	   (
	    [CODE],
		[SUBMENUID],
		[PROCESSID],
		[PROCESSCODE],
		[PROCESSNAME],
		[PROCESSLINEID],
		[PROCESSLINECODE],
		[FILENAME],
		[FILESIZE],
		[FILETYPE],
		[FILEURL],
		[UNITID],
		[DOCUMENTCREATEDDATE],
		[DOCUMENTCREATEDBY],
		[DOCUMENTUPDATEDBY],
		[PICKINGPACKINGHEADERID],
		[ISACTIVE]
	   )
	   values
	    (
	    @FILEID,
		@submenuid,
		@PROCESSHEADERID,
		@PROCESSCODE,
		@VPROCESSNAME,
		@PROCESSLINEID,
		@PROCESSLINECODE,
		@FILENAME,
		@FILESIZE,
		@FILETYPE,
		@FILEURL,
		@UnitID,
		GETDATE(),
		@DOCUMENTCREATEDBY,
		@DOCUMENTCREATEDBY,
		@PICKPACKID,
		1
		)
		FETCH NEXT FROM sql_cursor INTO  @PROCESSLINEID,@PROCESSHEADERID,@PICKPACKID,@FILENAME,@FILESIZE,@FILETYPE,@FILEURL,@DOCUMENTCREATEDBY; 
	end;
	set @Msg=(select trim(name) from TBLMESSAGE where SUBMENUID=@submenuid and CODE=@MessageName);
END try
begin catch
set @Msg=ERROR_MESSAGE()
end catch