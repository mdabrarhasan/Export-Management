--EXEC SPGETOCFPILISTVIEW 1,1165
CREATE PROCEDURE [dbo].[SPGETOCFPILISTVIEW]
(
@TYPEID		INT,
@ID			INT
)
AS
BEGIN
IF @TYPEID=1 
BEGIN
SELECT LINE.ID AS ID,QH.ID AS HEADERID,LIST.intID AS ITEMID,LIST.strProductCode AS PRODUCTCODE,LIST.strProductName AS ITEMNAME,
LINE.QUANTITY,

--LINE.PRICE,
(CASE WHEN (select COUNT(PH.ID) from TBLPRICECONFIRMHEADER PH
INNER JOIN TBLPRICECONFIRMLINE PL ON PH.ID=PL.PRICECONFIRMHEADERID WHERE PROFORMAINVOICEHEADERID=QH.ID)>0 THEN 
(select PL.CONFIRMPRICE from TBLPRICECONFIRMHEADER PH
INNER JOIN TBLPRICECONFIRMLINE PL ON PH.ID=PL.PRICECONFIRMHEADERID WHERE PROFORMAINVOICEHEADERID=QH.ID AND ITEMID=LINE.ITEMID)
ELSE LINE.PRICE END ) AS PRICE
,

LINE.DISCOUNTID,DIS.NAME AS DISCOUNT,LINE.TOTALAMOUNT,LINE.UOMID,UOM.strUOM AS UOM,
LINE.THIKNESS,LINE.WIDTH,LINE.LENGTH,LINE.TREATMENTLEVEL,LINE.TREATMENTDIRECTIONID,DIR.strTreatmentDirection AS TREATMENTDIRECTION,
LINE.COREID,COREID.strBiaxFlimCoreID AS CORENAME,
CAST(CAST(LINE.DISEREDDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS DISEREDDATEOFDELIVERY,
CAST(CAST(LINE.TENTATIVEDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS TENTATIVEDATEOFDELIVERY,LINE.REMARKS,
LINE.DESCRIPTIONS,LINE.REALOD,ISNULL(TOL.ID,0) AS TOLERANCEID,TOL.NAME AS TOLERANCE,0 AS BUYERID,''  AS BUYERNAME
FROM 
TBLQUOTATIONHEADER QH										INNER JOIN TBLQUOTATIONLINE						LINE
ON QH.ID=LINE.QUOTATIONHEADERID								INNER JOIN ERP_SAD.DBO.tblItem					LIST
ON LINE.ITEMID=LIST.intID									LEFT JOIN TBLDISCOUNT							DIS
ON LINE.DISCOUNTID=DIS.ID									INNER JOIN ERP_SAD.DBO.tblUOM					UOM
ON LINE.UOMID=UOM.intID										LEFT JOIN ERP_SAD.DBO.tblTreatmentDirection		DIR			
ON LINE.TREATMENTDIRECTIONID=DIR.intTreatmentDirection		LEFT JOIN ERP_SAD.DBO.tblBiaxFlimCoreID			COREID
ON LINE.COREID=COREID.intBiaxFlimCoreID						LEFT JOIN TBLTOLERANCE							TOL
ON LINE.TOLERANCEID=TOL.ID
WHERE QH.ID=@ID AND LINE.ISACTIVE=1
END;
END;


select COUNT(PH.ID) from TBLPRICECONFIRMHEADER PH
INNER JOIN TBLPRICECONFIRMLINE PL ON PH.ID=PL.PRICECONFIRMHEADERID WHERE PROFORMAINVOICEHEADERID=1165


(select PL.CONFIRMPRICE from TBLPRICECONFIRMHEADER PH
INNER JOIN TBLPRICECONFIRMLINE PL ON PH.ID=PL.PRICECONFIRMHEADERID WHERE PROFORMAINVOICEHEADERID=1165


AND ITEMID=10)

select * from TBLPRICECONFIRMLINE
select * from TBLPRICECONFIRMHEADER