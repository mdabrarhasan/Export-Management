CREATE PROCEDURE [dbo].[SPINSERTSALESQUATATION]
(
    @TYPEINSERTSALESQUATATIONHEADER INSERTSALESQUATATIONHEADER READONLY,
    @TYPEINSERTSALESQUATATIONLINE INSERTSALESQUATATIONLINE READONLY,

    @SHIPMENTMODE INT,
    @SQTYPE INT,
    @FROMSHIPMENT INT,
    @TOSHIPMENT INT,
    @TEXTFROMSHIPMENT VARCHAR(500),
    @DESTINATIONPORT VARCHAR(50),
    @CURRENCY INT,
    @LOADINGPORT INT,
    @LOADINGPLACE VARCHAR(500),
    @INCOTERM INT,

    @PAYMENTTERMS VARCHAR(500),
    @PAYMENTTERMS_OTHERS VARCHAR(500),
    @PAYMENTTERMSID INT,

    @SHIPPINGPERIOD VARCHAR(500),
    @TRANSPORTATIONMODE INT,
    @UNITID INT,

    @QUANTITYSUMMARY VARCHAR(500),
    @DESCRIPTIONSPECIFICATION VARCHAR(1000),

    @MODULECODE VARCHAR(50),
    @ENROLL INT,
    @DOCSTATUS VARCHAR(100),
    @PROCESSNAME VARCHAR(100),
    @MSGSTATUS VARCHAR(100),
    @NOTIFICATION VARCHAR(100),
    @LOG NVARCHAR(MAX),

    @MSG VARCHAR(100) OUT
)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRAN;

        DECLARE @HEADERID INT;
        DECLARE @SQNO VARCHAR(50);
        DECLARE @DOCSTATUSID INT;

        -- Validation
        IF EXISTS (SELECT 1 FROM @TYPEINSERTSALESQUATATIONLINE WHERE ITEMID = 0)
        BEGIN
            SET @MSG = 'Invalid ItemID found';
            ROLLBACK;
            RETURN;
        END

        -- Generate SQ No
        SET @SQNO = 'SQ-' + FORMAT(GETDATE(), 'ddMMyy') + '-' +
                    CAST((SELECT ISNULL(MAX(ID),0)+1 FROM TBLSALESQUOTATIONHEADER) AS VARCHAR);

        SELECT @DOCSTATUSID = ID FROM TBLDOCUMENTSTATUS WHERE CODE = @DOCSTATUS;

        -- Insert Header
        INSERT INTO TBLSALESQUOTATIONHEADER
        (
            SQTYPEID, EXPIREDATE, GLOBALID, SQNUMBER, CUSTOMERID, UNITID,
            DESCRIPTIONS, DOCUMENTCREATEDDATE, DOCUMENTCREATEDBY,
            DOCUMENTSTATUSID, ISACTIVE, TERMSCONDITION,
            ISPROCESSEDWITHAPPROVAL, SHIPMENTMODE, FROMSHIPMENT, TOSHIPMENT,
            CURRENCY, LOADINGPORT, LOADINGPLACE, INCOTERM,
            PAYMENTTERMS, PAYMENTTERMS_OTHERS, SHIPPINGPERIOD,
            TRANSPORTATIONMODE, TEXTFROMSHIPMENT, DESTINATIONPORT,
            PRODUCT_QUANTITY, DESCRIPTION_SPECIFICATION, PAYMENTTERMS_ID
        )
        SELECT 
            SQTYPEID, EXPIREDATE, '',
            @SQNO, CUSTOMERID, UNITID,
            DESCRIPTIONS, GETDATE(), DOCUMENTCREATEDBY,
            @DOCSTATUSID, 1, TERMSCONDITION,
            1, @SHIPMENTMODE, @FROMSHIPMENT, @TOSHIPMENT,
            @CURRENCY, @LOADINGPORT, @LOADINGPLACE, @INCOTERM,
            @PAYMENTTERMS, @PAYMENTTERMS_OTHERS, @SHIPPINGPERIOD,
            @TRANSPORTATIONMODE, @TEXTFROMSHIPMENT, @DESTINATIONPORT,
            @QUANTITYSUMMARY, @DESCRIPTIONSPECIFICATION, @PAYMENTTERMSID
        FROM @TYPEINSERTSALESQUATATIONHEADER;

        SET @HEADERID = SCOPE_IDENTITY();

        -- Insert Details (FAST)
        INSERT INTO TBLSALESQUOTATIONLINE
        (
            SALESQUOTATIONHEADERID, BATCHID, SERIALNO,
            ITEMTYPEID, ITEMID, UOMID,
            SIZE, CONSTRUCTION, WEIGHT, SLIT, SCRIM,
            QUALITY, ITEMTITLE, PACKINGDETAILS,
            QUANTITY, PRICE, DISCOUNTID, DISCOUNT,
            TOTALAMOUNT, DESCRIPTIONS, REMARKS, ISACTIVE
        )
        SELECT
            @HEADERID,
            'BSQ' + CAST(@HEADERID AS VARCHAR),
            ROW_NUMBER() OVER (ORDER BY (SELECT 1)),
            ITEMTYPEID, ITEMID, UOMID,
            SIZE, CONSTRUCTION, WEIGHT, SLIT, SCRIM,
            QUALITY, ITEMTITLE, PACKINGDETAILS,
            QUANTITY, PRICE, DISCOUNTID, DISCOUNT,
            TOTALAMOUNT, DESCRIPTIONS, REMARKS, 1
        FROM @TYPEINSERTSALESQUATATIONLINE;

        SET @MSG = 'Saved Successfully. Quotation No: ' + @SQNO;

		  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@HEADERID,@MODULECODE,@MODULECODE,@PROCESSNAME,@ENROLL,@UNITID
        COMMIT;
    END TRY
    BEGIN CATCH
        ROLLBACK;
        SET @MSG = ERROR_MESSAGE();
    END CATCH
END