CREATE PROCEDURE [dbo].[SPINSERTLIMITFACILITY]
(
@INNERUNITID						INT,
@BANKID								INT,
@RAWMATERIALLIMIT					DECIMAL(30,2),
@LOANLIMIT							DECIMAL(30,2),
@MACHINERYLIMIT						DECIMAL(30,2),
@SHORTTERMLOAN						DECIMAL(30,2),
@OVERDRAFTFACILITY					DECIMAL(30,2),
@BANKGUARANTEELIMIT					DECIMAL(30,2),
@TIMELOANLIMIT						DECIMAL(30,2),
@TERMLOANLIMIT						DECIMAL(30,2),
@LCSPARESMACHINERYLIMIT				DECIMAL(30,2),

@SODLIMIT							DECIMAL(30,2),
@SANCTIONREF						VARCHAR(500),
@EXPIREDATE							VARCHAR(50),

@MODULECODE							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@DOCSTATUS							VARCHAR(100),
@MESSAGENAME						VARCHAR(100),
@NOTIFICATION						VARCHAR(100),			
@DOCUMENTCREATEDBY					INT,
@UNITID								INT,
@MSG								VARCHAR(100)		OUT,
@STATUSMSG							VARCHAR(100)		OUT
)
AS
BEGIN
	DECLARE @DOCSTATUSID	INT,@ID INT,@PROCESSCODE VARCHAR(100),@TOTAL DECIMAL(30,2)=0.0,@SANCNO VARCHAR(500)
	SET @DOCSTATUSID=(SELECT ID FROM ABGAPIS.DBO.TBLDOCUMENTSTATUS WHERE CODE=@DOCSTATUS)

	SET @SANCNO='SANC-'+(SELECT strUnit FROM ERP_HR.DBO.tblUnit WHERE intUnitID=@UNITID)+'-'+
	(SELECT REPLACE(CONVERT(VARCHAR, GETDATE(), 3),'/',''))+'-'+
	CAST((SELECT convert(numeric(6,0),rand() * 899999) + 100000) AS VARCHAR(200))

	IF @RAWMATERIALLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@RAWMATERIALLIMIT
	END
	IF @LOANLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@LOANLIMIT
	END
	IF @MACHINERYLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@MACHINERYLIMIT
	END
	IF @SHORTTERMLOAN>0
	BEGIN
	SET @TOTAL=@TOTAL+@SHORTTERMLOAN
	END
	IF @OVERDRAFTFACILITY>0
	BEGIN
	SET @TOTAL=@TOTAL+@OVERDRAFTFACILITY
	END
	IF @BANKGUARANTEELIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@BANKGUARANTEELIMIT
	END
	IF @TIMELOANLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@TIMELOANLIMIT
	END
	IF @TERMLOANLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@TERMLOANLIMIT
	END
	IF @SODLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@SODLIMIT
	END
	IF @LCSPARESMACHINERYLIMIT>0
	BEGIN
	SET @TOTAL=@TOTAL+@LCSPARESMACHINERYLIMIT
	END
	IF @TOTAL=0
	BEGIN
	SET @TOTAL=0
	END

	INSERT INTO TBLLIMITFACILITY
	(
	SANCTIONNO,
	UNITID,
	INNERUNITID,
	BANKID,
	RAWMATERIALLIMIT,
	LOANLIMIT,
	MACHINERYLIMIT,
	SHORTTERMLOAN,
	OVERDRAFTFACILITY,
	BANKGUARANTEELIMIT,
	TIMELOANLIMIT,
	TERMLOANLIMIT,
	LCSPARESMACHINERYLIMIT,
	SANCTIONREF,
	SODLIMIT,
	EXPIREDATE,
	TOTAL,
	CREATEDBY,
	UPDATEDBY,
	CREATEDDATE,
	UPDATEDDATE,
	ISACTIVE
	)
	VALUES
	(
	@SANCNO,
	@UNITID,
	@INNERUNITID,
	@BANKID,
	@RAWMATERIALLIMIT,
	@LOANLIMIT,
	@MACHINERYLIMIT,
	@SHORTTERMLOAN,
	@OVERDRAFTFACILITY,
	@BANKGUARANTEELIMIT,
	@TIMELOANLIMIT,
	@TERMLOANLIMIT,
	@LCSPARESMACHINERYLIMIT,
	@SANCTIONREF,
	@SODLIMIT,
	@EXPIREDATE,
	@TOTAL,
	@DOCUMENTCREATEDBY,
	@DOCUMENTCREATEDBY,
	GETDATE(),
	GETDATE(),
	1
	)
	
	SET @MSG='DATA SAVED SUCCESSFULLY.SANCTION NO :'+@SANCNO
	SET @STATUSMSG='success';
END;