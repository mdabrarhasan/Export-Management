CREATE PROCEDURE [dbo].[SPLCUPDATE]
(
@ID												INT,
@DOCUMENTREQUIRE                                VARCHAR(500), 
@BUYERBANKID                                    int,
@BILLNOID                                       int,
@INVOICENO                                      VARCHAR(500), 
@TYPE                                            int,
@LCNUMBER										VARCHAR(100),
@LCISSUEDATE 									VARCHAR(100),
@LCEXPIREDATE 									VARCHAR(100),
@LCCREATEDPLACE 								VARCHAR(200),
@TOELRANCECRAMTPERCENTAGE						DECIMAL(18,2),
@PRESENTATIONINDATE 							VARCHAR(100),						
@PARTIALSHIPMENT								INT,
@BUYERDOCUMENTREQUIRED							VARCHAR(500),
@BUYERADDITIONALCONDITION						VARCHAR(500),
@TRANSSHIPMENT									INT,
@NOTIFIEDPARTYDETAILS							VARCHAR(100),
@PISCHEADERID									INT,
@BUYERBANK										VARCHAR(100),

@SHIPMENTLATESTDATE								VARCHAR(100),
@LCTENORPERIOD									VARCHAR(100),
@LCEXPIREDPLACE									VARCHAR(100),

@MODULECODE										VARCHAR(100),
@UNITID											INT,
@ENROLL											INT,
@DOCSTATUS										VARCHAR(100),
@PROCESSNAME									VARCHAR(100),
@MsgStatus										VARCHAR(100),
@NOTIFICATION									VARCHAR(100),
@LOG											VARCHAR(MAX),
@MSG											VARCHAR(100) OUTPUT								
)
AS
BEGIN
DECLARE @SALESQUOTATIONHEADERID	INT,@VPISCHEADERID INT,@CUSTOMERID INT,@PROCESSCODE VARCHAR(100),@GLOBALID VARCHAR(100)
SELECT @SALESQUOTATIONHEADERID=SALESQUOTATIONHEADERID,@CUSTOMERID=CUSTOMERID FROM TBLPISCHEADER WHERE ID=@PISCHEADERID

UPDATE TBLLCDETAILS
SET LCNUMBER=@LCNUMBER,
LCISSUEDATE=@LCISSUEDATE,
LCEXPIREDATE=@LCEXPIREDATE,
--LCCREATEDPLACE=@LCCREATEDPLACE,
LCEXPIREDPLACE=@LCEXPIREDPLACE,
LCTENORPERIOD=@LCTENORPERIOD,
SHIPMENTLATESTDATE=@SHIPMENTLATESTDATE,
TOELRANCECRAMTPERCENTAGE=@TOELRANCECRAMTPERCENTAGE,
PRESENTATIONINDATE=@PRESENTATIONINDATE,
PARTIALSHIPMENT=@PARTIALSHIPMENT,
BUYERDOCUMENTREQUIRED=@BUYERDOCUMENTREQUIRED,
BUYERADDITIONALCONDITION=@BUYERADDITIONALCONDITION,
TRANSSHIPMENT=@TRANSSHIPMENT,
NOTIFIEDPARTYDETAILS=@NOTIFIEDPARTYDETAILS,
DOCUMENTCREATEDDATE=GETDATE(),
BUYERBANK=@BUYERBANK ,
BUYERBANKID=@BUYERBANKID,
   BILLNOID= @BILLNOID,
   INVOICENO=@INVOICENO,
   TYPE= @TYPE,
   DOCUMENTREQUIRE=@DOCUMENTREQUIRE

WHERE ID=@ID
						

set @LOG='UPDATE TBLLCDETAILS SET LCNUMBER='+CAST(@LCNUMBER as varchar(100))+ 'LCISSUEDATE='+@LCISSUEDATE+'EXPIREDATE='+CAST(@LCEXPIREDATE as varchar(100))+'TOELRANCECRAMTPERCENTAGE='+CAST(@TOELRANCECRAMTPERCENTAGE as varchar(100))+
'PRESENTATIONINDATE='+CAST(@PRESENTATIONINDATE as varchar(100))+'PARTIALSHIPMENT='+CAST(@PARTIALSHIPMENT as varchar(100))+'WHERE ID='+CAST(@ID AS VARCHAR(50))

set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)+' LC NO:'+CAST(@ID AS VARCHAR(50))

  SET @PROCESSCODE=@PROCESSNAME+CAST(@ID AS VARCHAR(100))
  --EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@ProcessName,@Notification
  EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSNAME,@UNITID,@ENROLL

END;