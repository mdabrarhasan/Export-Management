CREATE PROCEDURE [dbo].[SPSQGET]
    @PREFIX NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        SQH.ID,
        SQH.SQNUMBER AS NAME
    FROM TBLSALESQUOTATIONHEADER SQH
    WHERE SQH.SQNUMBER LIKE '%' + @PREFIX + '%'
      AND SQH.ISACTIVE = 1
      AND EXISTS (
          SELECT 1
          FROM TBLPISCHEADER PISCH
          INNER JOIN TBLPACKINGREQUESTHEADER PRH 
              ON PRH.PISCNUMBER = PISCH.ID
          INNER JOIN TBLPACKINGREQUESTLINE PRL 
              ON PRH.ID = PRL.PACKINGREQUESTHEADERID
          WHERE PISCH.SALESQUOTATIONHEADERID = SQH.ID
            AND PRL.ISACTIVE = 1
          GROUP BY PRL.ITEMID
          HAVING MAX(PRL.QUANTITY) - SUM(PRL.PACKINGREQQUANTITY) > 0
      )
    ORDER BY SQH.ID DESC;
END