CREATE PROCEDURE sp_Master_GetById
(
    @Type VARCHAR(50),
    @ID INT
)
AS
BEGIN

    IF(@Type='SIZE')
        SELECT ID, SIZE AS Value, ISACTIVE FROM TBLSIZE WHERE ID=@ID

    ELSE IF(@Type='WEIGHT')
        SELECT ID, WEIGHT AS Value, ISACTIVE FROM TBLWEIGHT WHERE ID=@ID

    ELSE IF(@Type='CONSTRUCTION')
        SELECT ID, CONSTRUCTION AS Value, ISACTIVE FROM TBLCONSTRUCTION WHERE ID=@ID

    ELSE IF(@Type='SLIT')
        SELECT ID, SLIT AS Value, ISACTIVE FROM TBLSLIT WHERE ID=@ID

    ELSE IF(@Type='SCRIM')
        SELECT ID, SCRIM AS Value, ISACTIVE FROM TBLSCRIM WHERE ID=@ID

    ELSE IF(@Type='QUALITY')
        SELECT ID, QUALITY AS Value, ISACTIVE FROM TBLQUALITY WHERE ID=@ID
END