CREATE PROCEDURE [dbo].[sp_GetAllCustomersIS]
AS
BEGIN
    SET NOCOUNT ON;

    SELECT 
        ID,
        CUSTOMERNAME,
        CUSTOMERBANKNAME,
        CUSTOMERBANKBRANCHNAME,
        CUSTOMERBANKADDRESSLINEONE,
        ISACTIVE,
        CREATEDBY,
        UPDATEDBY,
        CREATEDDATE,
        UPDATEDDATE
    FROM CustomerInfoX
    ORDER BY CUSTOMERNAME; -- optional sorting
END