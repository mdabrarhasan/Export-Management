create PROCEDURE [dbo].[SPQUOTATIONSAVESQ]
(
@TYPEQUOTATIONINSERTLINE			TYPEQUOTATIONINSERTLINE readonly,
@QUOTATIONTYPEID					INT,
@OCFID								INT,
@OCFNO								VARCHAR(500),
@SQTYPEID							INT,
@CUSTOMERID							INT,
@ISEXCEL							INT,
@EXPIREDATE							VARCHAR(100),
@DESCRIPTIONS						VARCHAR(MAX),
@TERMSCONDITION						VARCHAR(MAX),
@SALESTYPEID						INT,
@CREDITTYPEID						INT,
@CREDITDAYS							INT,
@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN
DECLARE @NUMBER VARCHAR(100),@id INT,@AGREEMENTTYPE INT,@piid int,@formattedDate VARCHAR(8),
@ITEMID INT,@QUANTITY DECIMAL(18,2),@PRICE DECIMAL(18,2),@DISCOUNTID INT,@DISCOUNT DECIMAL(18,2),@VATID INT,@VATAMOUNT DECIMAL(18,2),
@COMMISSION DECIMAL(18,2),@TOTALAMOUNT DECIMAL(18,2),@REMARKS VARCHAR(MAX),@HSCODELINE VARCHAR(100),
@TOLARANCEID DECIMAL(18,2),@FROMSHIPMENTSCHEDULEDATE VARCHAR(50),@TOSHIPMENTSCHEDULEDATE VARCHAR(50),@BATCHID VARCHAR(100),@SERIALNO INT,
@hid int,@lineid int,@nextactiontacker int,@checkapproid int,
@submenuid int,@scopdeid int,@BATCHIDAPPHISTORY VARCHAR(50),@ProcessID int,@ProcessCode varchar(100),@DocStatusID int,@sqllog nvarchar(max),@initiateid int,
@approvecheck int,@checkcom int,@PITOSCID INT,@CHECKPITOSCCHECK INT,@ITEMSPEBATCH VARCHAR(1000),@Toleranceid int,
@UOMID INT,@THIKNESS DECIMAL(18,2),@WIDTH DECIMAL(18,2),@LENGTH DECIMAL(18,2),@TREATMENTLEVEL VARCHAR(500),@TREATMENTDIRECTIONID INT,@COREID INT,@REALOD VARCHAR(500),
@DISEREDDATEOFDELIVERY VARCHAR(500),@TENTATIVEDATEOFDELIVERY VARCHAR(500),@DESCRIPTIONLINE VARCHAR(MAX),@OCFIDCHECK INT
	SELECT @piid=isnull(MAX(ID),0) FROM TBLQUOTATIONHEADER;
	set @piid=@piid+1;
	
	 SET @OCFIDCHECK=(SELECT COUNT(*) FROM TBLQUOTATIONHEADER WHERE OCFID=@OCFID AND OCFID>@OCFID) 
	 SET @formattedDate = REPLACE(CONVERT(varchar, GETDATE(), 3), '/', '');
	 --SET @NUMBER=(CASE WHEN @QUOTATIONTYPEID=1 THEN 'PI' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @QUOTATIONTYPEID=2 THEN 'SQ' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @QUOTATIONTYPEID=3 THEN 'SP' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) WHEN @QUOTATIONTYPEID=4 THEN 'CA' + '-' + @formattedDate + '-' + cast(@piid as varchar(10)) END)
	 
	 SET @NUMBER=(SELECT 'QT-'+Right(Year(getDate()),2)+UPPER(LEFT(Datename(month, GetDate()),3))+
	 CASE WHEN @piid BETWEEN 0 AND 9 THEN '0' + CAST(@piid AS VARCHAR(2)) WHEN @piid BETWEEN 10 AND 99 THEN '0' + CAST(@piid AS VARCHAR(2)) 
	 ELSE CAST(@piid AS VARCHAR(10)) END)
	  --##
	    -- DECLARE @piid INT;
			DECLARE @prefix VARCHAR(20);
			DECLARE @newIncrement INT;
			DECLARE @newQTNumber VARCHAR(30);
			SET @prefix = 'QT-' + RIGHT(YEAR(GETDATE()), 2) + UPPER(LEFT(DATENAME(month, GETDATE()), 3));

			SELECT @newIncrement = 
				ISNULL(MAX(CAST(RIGHT(QUOTATIONNUMBER, 3) AS INT)), 0) + 1
			FROM TBLQUOTATIONHEADER
			WHERE 
				LEFT(QUOTATIONNUMBER, LEN(@prefix)) = @prefix;

			SET @newQTNumber = @prefix + RIGHT('000' + CAST(@newIncrement AS VARCHAR(3)), 3);

			SET @NUMBER=@newQTNumber



	 --##

	 DECLARE SQL_CURSOR CURSOR FOR  
	 SELECT ITEMID,QUANTITY,PRICE,DISCOUNTID,DISCOUNT,VATID,VATAMOUNT,TOLERANCEID,TOTALAMOUNT,REMARKS,DESCRIPTIONS,FROMSHIPMENTSCHEDULEDATE,TOSHIPMENTSCHEDULEDATE,HSCODE,
	 UOMID,THIKNESS,WIDTH,LENGTH,TREATMENTLEVEL,TREATMENTDIRECTIONID,COREID,REALOD,DISEREDDATEOFDELIVERY,TENTATIVEDATEOFDELIVERY
	 FROM @TYPEQUOTATIONINSERTLINE
	 OPEN SQL_CURSOR
	 FETCH NEXT FROM SQL_CURSOR INTO @ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONLINE,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
	 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
	 
	BEGIN
	IF @OCFIDCHECK=0
		BEGIN
		INSERT INTO TBLQUOTATIONHEADER
		(
		QUOTATIONTYPEID,
		OCFID,
		OCFNO,
		SQTYPEID,
		QUOTATIONNUMBER,
		CUSTOMERID,
		EXPIREDATE,
		DESCRIPTIONS,
		TERMSCONDITION,
		DOCUMENTCREATEDDATE,
		DOCUMENTCREATEDBY,
		DOCUMENTSTATUSID,
		ISACTIVE,
		UNITID,
		ORIGINOFCOUNTRY,
		ISPROCESSEDWITHAPPROVAL,
		SALESTYPEID,
		CREDITTYPEID,
		CREDITDAYS
		)
		VALUES
		(
		@QUOTATIONTYPEID,
		@OCFID,
		@OCFNO,
		@SQTYPEID,
		@NUMBER,
		@CUSTOMERID,
		@EXPIREDATE,
		@DESCRIPTIONS,
		@TERMSCONDITION,
		GETDATE(),
		@ENROLL,
		1,
		1,
		@UNITID,			
		'Bangladesh',
		1,
		@SALESTYPEID,
		@CREDITTYPEID,
		@CREDITDAYS
		);

		SET @id=SCOPE_IDENTITY()
		SET @BATCHID=(SELECT 'BATCH'+CAST(@id AS VARCHAR(100)))

		UPDATE TBLQUOTATIONHEADER
		SET GLOBALID='GLOB'+@NUMBER WHERE ID=@id;

		WHILE @@FETCH_STATUS = 0  
		  BEGIN
		  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLQUOTATIONLINE where QUOTATIONHEADERID=@id)
		  INSERT INTO TBLQUOTATIONLINE
		  (
		  QUOTATIONHEADERID,
		  OCFITEMID,
		  BATCHID,
		  SERIALNO,
		  ITEMID,
		  QUANTITY,
		  PRICE,
		  DISCOUNTID,
		  DISCOUNT,
		  VATID,
		  VATAMOUNT,
		  TOTALAMOUNT,

		  UOMID,
		  THIKNESS,
		  WIDTH,
		  LENGTH,
		  TREATMENTLEVEL,
		  TREATMENTDIRECTIONID,
		  COREID,
		  REALOD,
		  DISEREDDATEOFDELIVERY,
		  TENTATIVEDATEOFDELIVERY,

		  TOLERANCEID,
		  REMARKS,
		  DESCRIPTIONS,
		  ISACTIVE
		  )
		  VALUES
		  (
		  @id,
		  @VATID,
		  @BATCHID,
		  @SERIALNO,
		  @ITEMID,
		  @QUANTITY,
		  @PRICE,
		  @DISCOUNTID,
		  @DISCOUNT,
		  @VATID,
		  @VATAMOUNT,
		  @TOTALAMOUNT,

		  @UOMID,
		  @THIKNESS,
		  @WIDTH,
		  @LENGTH,
		  @TREATMENTLEVEL,
		  @TREATMENTDIRECTIONID,
		  @COREID,
		  @REALOD,
		  @DISEREDDATEOFDELIVERY,
		  @TENTATIVEDATEOFDELIVERY,

		  @Toleranceid,
		  @REMARKS,
		  @DESCRIPTIONLINE,
		  1
		  )
		  FETCH NEXT FROM sql_cursor INTO @ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONLINE,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
			 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
		  END
		  SET @ProcessCode=@NUMBER
		END;
	ELSE
	BEGIN
		SELECT @ID=ID FROM TBLQUOTATIONHEADER WHERE OCFID=@OCFID
		SET @BATCHID=(SELECT 'BATCH'+CAST(@ID AS VARCHAR(100)))

		WHILE @@FETCH_STATUS = 0  
		  BEGIN
		  set @SERIALNO=(select ISNULL(max(SERIALNO),0)+1 from TBLQUOTATIONLINE where QUOTATIONHEADERID=@id)
		  INSERT INTO TBLQUOTATIONLINE
		  (
		  QUOTATIONHEADERID,
		  OCFITEMID,
		  BATCHID,
		  SERIALNO,
		  ITEMID,
		  QUANTITY,
		  PRICE,
		  DISCOUNTID,
		  DISCOUNT,
		  VATID,
		  VATAMOUNT,
		  TOTALAMOUNT,

		  UOMID,
		  THIKNESS,
		  WIDTH,
		  LENGTH,
		  TREATMENTLEVEL,
		  TREATMENTDIRECTIONID,
		  COREID,
		  REALOD,
		  DISEREDDATEOFDELIVERY,
		  TENTATIVEDATEOFDELIVERY,

		  TOLERANCEID,
		  REMARKS,
		  DESCRIPTIONS,
		  ISACTIVE
		  )
		  VALUES
		  (
		  @id,
		  @VATID,
		  @BATCHID,
		  @SERIALNO,
		  @ITEMID,
		  @QUANTITY,
		  @PRICE,
		  @DISCOUNTID,
		  @DISCOUNT,
		  @VATID,
		  @VATAMOUNT,
		  @TOTALAMOUNT,

		  @UOMID,
		  @THIKNESS,
		  @WIDTH,
		  @LENGTH,
		  @TREATMENTLEVEL,
		  @TREATMENTDIRECTIONID,
		  @COREID,
		  @REALOD,
		  @DISEREDDATEOFDELIVERY,
		  @TENTATIVEDATEOFDELIVERY,

		  @Toleranceid,
		  @REMARKS,
		  @DESCRIPTIONLINE,
		  1
		  )
		  FETCH NEXT FROM sql_cursor INTO @ITEMID,@QUANTITY,@PRICE,@DISCOUNTID,@DISCOUNT,@VATID,@VATAMOUNT,@Toleranceid,@TOTALAMOUNT,@REMARKS,@DESCRIPTIONLINE,@FROMSHIPMENTSCHEDULEDATE,@TOSHIPMENTSCHEDULEDATE,@HSCODELINE,
			 @UOMID,@THIKNESS,@WIDTH,@LENGTH,@TREATMENTLEVEL,@TREATMENTDIRECTIONID,@COREID,@REALOD,@DISEREDDATEOFDELIVERY,@TENTATIVEDATEOFDELIVERY
		  END;
	  --set @Msg=@id
		  SET @ProcessCode=@NUMBER
	END
	END;
	

  

  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@MODULECODE) and CODE=@MsgStatus) +@ProcessCode
  EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@submenuid,@Notification
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
  
END