
CREATE PROCEDURE SPGETDOCSTATUS  
(
@PROCESSID			INT
)
AS
BEGIN
SELECT PROCESSCODE,EMPINIT.strEmployeeName+' ('+CAST(APH.INITIATORID AS VARCHAR(50))+')' AS INITIATOR,
EMPAPPR.strEmployeeName+' ('+CAST(APH.ACTIONTAKERID AS VARCHAR(50))+')' AS APPROVAR,CAST(APH.DOCUMENTCREATEDDATE AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
DS.NAME AS DOCSTATUS,APH.DESCRIPTIONS
FROM TBLAPPROVERMATRIXHISTORY APH
INNER JOIN				ERP_HR.DBO.tblEmployee   EMPINIT
ON						APH.INITIATORID=EMPINIT.intEmployeeID
INNER JOIN				ERP_HR.DBO.tblEmployee   EMPAPPR
ON						APH.ACTIONTAKERID=EMPAPPR.intEmployeeID		
INNER JOIN				TBLDOCUMENTSTATUS		 DS
ON						DS.ID=APH.DOCUMENTSTATUSID
WHERE PROCESSID=@PROCESSID
END;