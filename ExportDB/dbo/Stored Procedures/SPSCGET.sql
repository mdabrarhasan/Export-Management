CREATE PROCEDURE [dbo].[SPSCGET]
    @PREFIX NVARCHAR(100),
    @SQIDS NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;

    -- Parse comma-separated SQ IDs into a temp table
    DECLARE @SQIDTable TABLE (ID INT);
    INSERT INTO @SQIDTable (ID)
    SELECT CAST(value AS INT)
    FROM STRING_SPLIT(@SQIDS, ',')
    WHERE LTRIM(RTRIM(value)) <> '';

    SELECT 
        PISCH.ID AS ID,
        PISCH.NUMBER AS NAME
    FROM TBLPISCHEADER PISCH
    INNER JOIN TBLPACKINGREQUESTHEADER PRH 
        ON PRH.PISCNUMBER = PISCH.ID
    INNER JOIN TBLPACKINGREQUESTLINE PRL 
        ON PRL.PACKINGREQUESTHEADERID = PRH.ID
    WHERE PISCH.NUMBER LIKE '%' + @PREFIX + '%'
      AND PISCH.ISACTIVE = 1
      AND PRL.ISACTIVE = 1
      AND PISCH.SALESQUOTATIONHEADERID IN (SELECT ID FROM @SQIDTable)
    GROUP BY PISCH.ID, PISCH.NUMBER, PRL.ITEMID
    HAVING MAX(PRL.QUANTITY) - SUM(PRL.PACKINGREQQUANTITY) > 0;
END