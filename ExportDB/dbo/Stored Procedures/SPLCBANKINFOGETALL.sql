CREATE PROCEDURE [dbo].[SPLCBANKINFOGETALL]
AS
BEGIN
    SELECT 
        LBI.ID,
        LBI.LCID,
        LCD.LCNUMBER,
        CAST(CAST(LBI.DOCNEGOTIATEDATE AS DATE) AS VARCHAR(100)) AS DOCNEGOTIATEDATE,
        LBI.BENEFICIARYBANKCOST,
        LBI.CROSSBANKCHARGE,
        CAST(CAST(LBI.PAYMENTRECEIVEDATE AS DATE) AS VARCHAR(100)) AS PAYMENTRECEIVEDATE,
        LBI.IDPBIDBCNO
    FROM TBLLCBANKINFO LBI
    INNER JOIN TBLLCDETAILS LCD ON LBI.LCID = LCD.ID
    WHERE LBI.ISACTIVE = 1
END