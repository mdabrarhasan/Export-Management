
CREATE PROCEDURE [dbo].[SPGETITEMSPECIFIC]
	(
	@ITEMID				INT,
	@NUMBER				VARCHAR(100)
	)
	AS
	BEGIN
	DECLARE @PROCESS VARCHAR(100)
	SET @PROCESS=(SELECT REPLACE(TRANSLATE(@NUMBER,'0123456789','          '),' ',''))
	IF @PROCESS='SQ'
	BEGIN
	
	SELECT ID,PROCESSID,PROCESSNAME,PROCESSCODE,PROCESSLINEID,PROCESSLINECODE,ITEMORDERSPECSTAGINGID,ITEMID,
	LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,
	DOCUMENTCREATEDBY,CAST(DOCUMENTCREATEDDATE AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,SESSIONID
	FROM TBLITEMORDERSPEC WHERE ITEMID=@ITEMID AND PROCESSCODE=@NUMBER
	END;
	ELSE
	BEGIN
	SELECT ID,PROCESSID,PROCESSNAME,PROCESSCODE,PROCESSLINEID,PROCESSLINECODE,ITEMORDERSPECSTAGINGID,ITEMID,
	LENGTH,WIDTH,HEIGHT,THICKNESS,WEIGHT,COLOR,SIZE,DESIGN,PACKAGING,MATERIAL,CONSTRUCTION,PLY,CORE,TREATMENTDIRECTION,OTHERS,REMARK,
	DOCUMENTCREATEDBY,CAST(DOCUMENTCREATEDDATE AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,SESSIONID
	FROM TBLITEMORDERSPEC WHERE ITEMID=@ITEMID AND BATCHID=(SELECT DISTINCT BATCHID FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@NUMBER)
	--CASE WHEN (SELECT COUNT(*) FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@NUMBER AND ITEMID=@ITEMID)=0 THEN (SELECT SQNUMBER FROM TBLSALESQUOTATIONHEADER WHERE ID=(SELECT SALESQUOTATIONHEADERID FROM TBLPISCHEADER WHERE NUMBER=@NUMBER))
	--ELSE @NUMBER END
	END;
	END;