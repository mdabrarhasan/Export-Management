CREATE Procedure [dbo].[GETPRICECONFIRMFORAPPROVALBIAX]
(
@Enroll		INT,
@UnitID		INT,
@Code		varchar(100),
@ID			varchar(100),
@TYPE   	INT
)
AS
BEGIN
declare @docstatusid int,@checkstatusid int,@AGGTYPEID INT,@CHECKINIT INT
set @docstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
set @checkstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@ID)
SET @CHECKINIT=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT')
IF @TYPE=0
	BEGIN
		SELECT  APVMH.ID AS HISTRYID,PCH.ID,SQH.CUSTOMERID,SQH.UNITID,0 AS SALESQUOTATIONHEADERID,PCH.PCNUMBER,
		SQH.QUOTATIONNUMBER AS SQNUMBER,PCH.PROFORMAINVOICEHEADERID,SQH.OCFNO AS NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,PCH.DESCRIPTIONS,CAST(CAST(SQH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		ISNULL(CUS.strName,'') AS CUSNAME,UNIT.strUnit AS SELLERNAME,ISNULL(CUR.NAME,'') AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLQUOTATIONHEADER  			SQH
		ON	PCH.PROFORMAINVOICEHEADERID=SQH.ID		INNER JOIN  TBLQUOTATIONTYPE				AGT
		ON  SQH.QUOTATIONTYPEID=AGT.ID				LEFT JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  SQH.CUSTOMERID=CUS.intCusID				LEFT JOIN  TBLCURRENCY						CUR
		ON  SQH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON	PCH.SELLERID=UNIT.intUnitID				INNER JOIN  TBLAPPROVERMATRIXHISTORY		APVMH
		ON  PCH.ID=APVMH.PROCESSID					INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  DS.ID=APVMH.DOCUMENTSTATUSID
		WHERE APVMH.ACTIONTAKERID=@Enroll AND 
		(APVMH.DOCUMENTSTATUSID=@checkstatusid and APVMH.DOCUMENTSTATUSID != @CHECKINIT)
		AND
		PCH.ISACTIVE=1 and
		SUBMENUID=(select ID from TBLSUBMENU where CODE=trim(@Code))	
		order by PCH.id desc;
	END;
ELSE IF @TYPE=1
	BEGIN
	SELECT  0 AS HISTRYID,PCH.ID,SQH.CUSTOMERID,SQH.UNITID,0 AS SALESQUOTATIONHEADERID,PCH.PCNUMBER,
		SQH.QUOTATIONNUMBER AS SQNUMBER,PCH.PROFORMAINVOICEHEADERID,SQH.OCFNO AS NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,PCH.DESCRIPTIONS,CAST(CAST(PCH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		CUS.strName AS CUSNAME,UNIT.strUnit AS SELLERNAME,CUR.NAME AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLQUOTATIONHEADER  			SQH
		ON	PCH.PROFORMAINVOICEHEADERID=SQH.ID		INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  PCH.DOCUMENTSTATUSID=DS.ID				INNER JOIN  TBLQUOTATIONTYPE				AGT
		ON  SQH.QUOTATIONTYPEID=AGT.ID				LEFT JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  SQH.CUSTOMERID=CUS.intCusID				LEFT JOIN  TBLCURRENCY						CUR
		ON  SQH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON	PCH.SELLERID=UNIT.intUnitID		
		WHERE  PCH.ISACTIVE=1 AND PCH.ID=@UnitID    --AS ID
		order by PCH.id desc;
	END;
	ELSE IF @TYPE=2
	BEGIN
	SELECT PCLINE.ID AS ID,QH.ID AS HEADERID,LIST.intID AS ITEMID,LIST.strProductCode AS PRODUCTCODE,LIST.strProductName AS ITEMNAME,
	CAST(PCLINE.QUANTITY AS DECIMAL(18,2)) AS QUANTITY,PCLINE.PRICE,ISNULL(LINE.DISCOUNTID,0) AS DISCOUNTID,CAST(LINE.DISCOUNT AS VARCHAR(50)) AS DISCOUNT, 
	
	(CASE WHEN PCLINE.OFFERPRICE=PCLINE.CONFIRMPRICE THEN 
	((PCLINE.OFFERPRICE*PCLINE.QUANTITY)-ISNULL(LINE.DISCOUNT,0))  
	ELSE   ((PCLINE.CONFIRMPRICE*PCLINE.QUANTITY)-ISNULL(LINE.DISCOUNT,0))  END)
	AS TOTALAMOUNT
	
	,


	LINE.UOMID,UOM.strUOM AS UOM,
	PCLINE.THIKNESS,PCLINE.WIDTH,PCLINE.LENGTH,ISNULL(LINE.TREATMENTLEVEL,0) AS TREATMENTLEVEL,
	ISNULL(LINE.TREATMENTDIRECTIONID,0) AS TREATMENTDIRECTIONID,DIR.strTreatmentDirection AS TREATMENTDIRECTION,
	ISNULL(LINE.COREID,0) AS COREID,COREID.strBiaxFlimCoreID AS CORENAME,
	CAST(CAST(LINE.DISEREDDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS DISEREDDATEOFDELIVERY,
	CAST(CAST(LINE.TENTATIVEDATEOFDELIVERY AS DATE) AS VARCHAR(50)) AS TENTATIVEDATEOFDELIVERY,LINE.REMARKS,
	LINE.DESCRIPTIONS,LINE.REALOD,PCLINE.OFFERPRICE,PCLINE.CONFIRMPRICE
	FROM 
	TBLQUOTATIONHEADER QH										INNER JOIN TBLQUOTATIONLINE						LINE
	ON QH.ID=LINE.QUOTATIONHEADERID								LEFT JOIN TBLDISCOUNT							DIS
	ON LINE.DISCOUNTID=DIS.ID									INNER JOIN ERP_SAD.DBO.tblUOM					UOM
	ON LINE.UOMID=UOM.intID										LEFT JOIN ERP_SAD.DBO.tblTreatmentDirection		DIR			
	ON LINE.TREATMENTDIRECTIONID=DIR.intTreatmentDirection		LEFT JOIN ERP_SAD.DBO.tblBiaxFlimCoreID			COREID
	ON LINE.COREID=COREID.intBiaxFlimCoreID						INNER JOIN TBLPRICECONFIRMHEADER				PCHEADER
	ON PCHEADER.PROFORMAINVOICEHEADERID=QH.ID					INNER JOIN TBLPRICECONFIRMLINE					PCLINE
	ON PCHEADER.ID=PCLINE.PRICECONFIRMHEADERID					AND LINE.ID=PCLINE.QUOTATIONLINEID	
	INNER JOIN ERP_SAD.DBO.tblItem					LIST
	ON PCLINE.ITEMID=LIST.intID
	WHERE PCHEADER.ID=@ID AND LINE.ISACTIVE=1
	order by  PCHEADER.ID desc;
	END;
	ELSE IF @TYPE=3
	BEGIN
		SELECT  0 AS HISTRYID,PCH.ID,ISNULL(SQH.CUSTOMERID,0) AS CUSTOMERID,SQH.UNITID,0 AS SALESQUOTATIONHEADERID,PCH.PCNUMBER,
		SQH.QUOTATIONNUMBER AS SQNUMBER,PCH.PROFORMAINVOICEHEADERID,SQH.OCFNO AS NUMBER,AGT.NAME AS AGREEMENTTYPE,
		PCH.TERMSCONDITION,PCH.DESCRIPTIONS,CAST(CAST(SQH.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,DS.NAME AS DOCSTATUS,DS.CODE,
		ISNULL(CUS.strName,'') AS CUSNAME,UNIT.strUnit AS SELLERNAME,CUR.NAME AS CURRENCY,CASE WHEN ISNULL(PCH.FLAG,0)=0 THEN 0 ELSE PCH.FLAG END AS FLAG
		FROM TBLPRICECONFIRMHEADER PCH				INNER JOIN  TBLQUOTATIONHEADER  			SQH
		ON	PCH.PROFORMAINVOICEHEADERID=SQH.ID		INNER JOIN  TBLDOCUMENTSTATUS				DS
		ON  PCH.DOCUMENTSTATUSID=DS.ID				INNER JOIN  TBLQUOTATIONTYPE				AGT
		ON  SQH.QUOTATIONTYPEID=AGT.ID				LEFT JOIN  ERP_SAD.dbo.TBLCUSTOMER			CUS
		ON  SQH.CUSTOMERID=CUS.intCusID				LEFT JOIN  TBLCURRENCY						CUR
		ON  SQH.CURRENCYID=CUR.ID					INNER JOIN  ERP_HR.dbo.tblUnit				UNIT
		ON	PCH.SELLERID=UNIT.intUnitID		
		WHERE  PCH.ISACTIVE=1
		order by PCH.ID desc;
	END;
	ELSE IF @TYPE=4
	BEGIN
	SELECT [ID] AS ID,[PRICECONFIRMHEADERID],[ITEMID],LIST.strProductName AS ITEMNAME,case when LIST.intUnitID=91 then 'KG' when LIST.intUnitID=178 then 'pecs' when LIST.intUnitID=182 then 'Pecs' end AS  strUoM, [QUANTITY],[PRICE],[OFFERPRICE],[CONFIRMPRICE] 
	FROM TBLPRICECONFIRMLINE LINE INNER JOIN ERP_SAD.dbo.tblItem LIST
	ON LINE.ITEMID=LIST.intID WHERE PRICECONFIRMHEADERID=@ID AND LINE.ISACTIVE=1
	END;
END;