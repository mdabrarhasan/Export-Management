CREATE PROCEDURE SPCUSTOMERBANKINFSAVE
    @CUSTOMERNAME NVARCHAR(MAX),
    @CUSTOMERBANKBRANCHNAME NVARCHAR(MAX),
    @CUSTOMERBANKNAME NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINEONE NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINETWO NVARCHAR(MAX),
    @CUSTOMERBANKADDRESSLINETHREE NVARCHAR(MAX),
    @CUSTOMERBANKBINNO NVARCHAR(MAX),
    @CREATEDBY INT,
    @Msg CHAR(100) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        INSERT INTO [ABGAPIS].[dbo].[TBLCUSTOMERBANK]
        (CUSTOMERNAME, CUSTOMERBANKBRANCHNAME, CUSTOMERBANKNAME, 
         CUSTOMERBANKADDRESSLINEONE, CUSTOMERBANKADDRESSLINETWO, 
         CUSTOMERBANKADDRESSLINETHREE, CUSTOMERBANKBINNO, ISACTIVE, 
         CREATEDBY, CREATEDDATE, UPDATEDBY, UPDATEDDATE)
        VALUES
        (@CUSTOMERNAME, @CUSTOMERBANKBRANCHNAME, @CUSTOMERBANKNAME,
         @CUSTOMERBANKADDRESSLINEONE, @CUSTOMERBANKADDRESSLINETWO,
         @CUSTOMERBANKADDRESSLINETHREE, @CUSTOMERBANKBINNO, 1,
         @CREATEDBY, GETDATE(), @CREATEDBY, GETDATE())
        
        SET @Msg = 'Record saved successfully'
    END TRY
    BEGIN CATCH
        SET @Msg = ERROR_MESSAGE()
    END CATCH
END