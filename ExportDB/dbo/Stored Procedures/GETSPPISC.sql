-- GETSPPISC 7,'MD'
CREATE PROCEDURE [dbo].[GETSPPISC]
@Type			INT,
@Prefix			VARCHAR(100)
AS
BEGIN
DECLARE @CHECKCOM INT;
SET @CHECKCOM=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP')
IF @Type=0
	BEGIN
	SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';--ID NOT IN(SELECT DISTINCT ISNULL(PROFORMAINVOICEHEADERID,0) FROM TBLPRICECONFIRMHEADER) AND DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	END;
ELSE IF @Type=1
	BEGIN
	SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE ID NOT IN(SELECT DISTINCT ISNULL(PISCHEADERID,0) FROM TBLLCDETAILS) AND DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	END;
	ELSE IF @Type=2
	BEGIN
	--SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE ID NOT IN(SELECT DISTINCT PISCNUMBER FROM TBLPACKINGREQUESTHEADER) AND DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	END;
	ELSE IF @Type=3
	BEGIN
	/*SELECT ID,QUOTATIONNUMBER AS Name FROM TBLQUOTATIONHEADER WHERE DOCUMENTSTATUSID=@CHECKCOM AND ID 
	NOT IN(SELECT DISTINCT PROFORMAINVOICEHEADERID FROM TBLPRICECONFIRMHEADER) AND
	QUOTATIONNUMBER like '%'+@Prefix+'%';*/
	SELECT ID,QUOTATIONNUMBER AS Name FROM TBLQUOTATIONHEADER WHERE DOCUMENTSTATUSID=@CHECKCOM AND
	QUOTATIONNUMBER like '%'+@Prefix+'%';
	END;
	ELSE IF @Type=4
	BEGIN
	--SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE ID NOT IN(SELECT DISTINCT PISCNUMBER FROM TBLPACKINGREQUESTHEADER) AND DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	SELECT intOCFID AS ID,strOCFNo AS NAME FROM ERP_SAD.DBO.tblOCF
	WHERE strOCFNo like '%'+@Prefix+'%' ORDER BY intOCFID DESC;
	END;
	ELSE IF @Type=91
	BEGIN
	--SELECT ID,NUMBER AS Name FROM TBLPISCHEADER WHERE ID NOT IN(SELECT DISTINCT PISCNUMBER FROM TBLPACKINGREQUESTHEADER) AND DOCUMENTSTATUSID=@CHECKCOM AND NUMBER like '%'+@Prefix+'%';
	SELECT ID,QUOTATIONNUMBER AS Name FROM TBLQUOTATIONHEADER WHERE DOCUMENTSTATUSID=@CHECKCOM AND ID NOT IN(SELECT DISTINCT PISCHEADERID FROM TBLLCDETAILS) 
	AND QUOTATIONTYPEID=1 AND QUOTATIONNUMBER like '%'+@Prefix+'%';
	END;
	ELSE IF @TYPE=7 --CR7 is GOAT (By Fahim)
	BEGIN
	SELECT ID AS ID ,PACKREQNUMBER AS Name FROM TBLPACKINGREQUESTHEADER WHERE  PACKREQNUMBER like '%'+@Prefix+'%';
	END;
END;