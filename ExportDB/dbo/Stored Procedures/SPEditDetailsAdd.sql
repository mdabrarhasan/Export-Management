
CREATE PROCEDURE [DBO].[SPEditDetailsAdd]
(
@SALESQUOTATIONHEADERID					INT,
@ITEMTYPEID								INT,
@ITEMID									INT,
@UOMID									INT,
@SIZE									VARCHAR(MAX),
@CONSTRUCTION							VARCHAR(MAX),
@WEIGHT									VARCHAR(MAX),
@SLIT									VARCHAR(MAX),
@SCRIM									VARCHAR(MAX),
@QUANTITY								DECIMAL(18,2),
@ITEMTITLE								VARCHAR(MAX),
@QUALITY								VARCHAR(MAX),
@PRICE									DECIMAL(18,2),
@DISCOUNTID								INT,
@DISCOUNT								VARCHAR(MAX),
@TOTALAMOUNT							DECIMAL(18,2),
@REMARKS								VARCHAR(MAX),
@DESCRIPTIONS							VARCHAR(MAX),
@UNITID									INT,
@MODULECODE								VARCHAR(100),
@ENROLL									INT,
@PROCESSNAME							VARCHAR(100),
@MESSAGENAME							VARCHAR(100), 
@MSG									VARCHAR(100)  OUTPUT
)
AS
BEGIN TRY
DECLARE @BATCHID VARCHAR(100),@SERIALNO INT,@LOG NVARCHAR(MAX),@ID INT,@PROCESSCODE VARCHAR(100),@ITEMSPEBATCH VARCHAR(500)
SET @SERIALNO=(SELECT ISNULL(MAX(SERIALNO),0)+1 FROM TBLSALESQUOTATIONLINE WHERE SALESQUOTATIONHEADERID=@SALESQUOTATIONHEADERID)
SET @BATCHID='BSQ' +CAST(@SALESQUOTATIONHEADERID AS VARCHAR(100))

		INSERT INTO TBLSALESQUOTATIONLINE
        (
            SALESQUOTATIONHEADERID, BATCHID, SERIALNO,ITEMTYPEID,ITEMID,UOMID,SIZE,CONSTRUCTION,WEIGHT,SLIT,SCRIM,QUALITY,ITEMTITLE,QUANTITY, PRICE, DISCOUNTID,
            DISCOUNT, TOTALAMOUNT, DESCRIPTIONS, REMARKS, ISACTIVE
        )
        VALUES
        (
            @SALESQUOTATIONHEADERID, @BATCHID, @SERIALNO,@ITEMTYPEID, @ITEMID,@UOMID,@SIZE,@CONSTRUCTION,@WEIGHT,@SLIT,@SCRIM,@QUALITY,@ITEMTITLE,@QUANTITY, @PRICE, @DISCOUNTID,
            @DISCOUNT, @TOTALAMOUNT, @DESCRIPTIONS, @REMARKS, 1
        );	

SET @ID=SCOPE_IDENTITY()
SET @PROCESSCODE=@PROCESSNAME+CAST(@SALESQUOTATIONHEADERID AS VARCHAR(50))
		   
		   SET @ITEMSPEBATCH=(SELECT CASE WHEN (SELECT DISTINCT COUNT(BATCHID) FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@PROCESSCODE)=0 THEN
			'BATCH'+CAST((SELECT CONVERT(NUMERIC(12,0),RAND() * 899999999999) + 100000000000) AS VARCHAR(500))
			ELSE (SELECT DISTINCT BATCHID FROM TBLITEMORDERSPEC WHERE PROCESSCODE=@PROCESSCODE) END AS BATCHID)
	

	SET @MSG=(SELECT NAME FROM TBLMESSAGE WHERE SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=@MODULECODE) AND CODE=@MESSAGENAME)
	SET @LOG='INSERT INTO TBLSALESQUOTATIONLINE(ID,SALESQUOTATIONHEADERID,BATCHID,ITEMID,QUANTITY,PRICE,DISCOUNT,TOTALAMOUNT,DISCOUNTID) VALUES('+
	''+CAST(@ID AS VARCHAR(50))+','+CAST(@SALESQUOTATIONHEADERID AS VARCHAR(50))+','+CAST(@BATCHID AS VARCHAR(50))+','+CAST(@ITEMID AS VARCHAR(50))+','+
	CAST(@QUANTITY AS VARCHAR(50))+','+CAST(@PRICE AS VARCHAR(50))+','+CAST(@DISCOUNTID AS VARCHAR(50))+','+CAST(@DISCOUNT AS VARCHAR(50))
	+','+CAST(@TOTALAMOUNT AS VARCHAR(50))+')'
	EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSNAME,@UNITID,@ENROLL
END TRY
BEGIN CATCH
SET @MSG=ERROR_MESSAGE()
END CATCH