CREATE PROCEDURE [dbo].[SPGETPIINFOLINE]
(
@TYPEID				INT,
@ID					INT
)
AS
BEGIN
SELECT LINE.ID,ITEM.strProductCode AS PRODUCTCODE,ITEM.strProductName AS PRODUCTNAME,QH.SQTYPEID,
LINE.THIKNESS,LINE.WIDTH,LINE.QUANTITY,LINE.PRICE AS BASCPRICE,(CASE WHEN QH.SQTYPEID=136 THEN (0.15*LINE.PRICE) ELSE 0 END) AS VAT,
(CASE WHEN QH.SQTYPEID=136 THEN LINE.PRICE+(0.15*LINE.PRICE) ELSE LINE.PRICE END) AS UNITPRICE,
(CASE WHEN QH.SQTYPEID=136 THEN LINE.QUANTITY*(LINE.PRICE+(0.15*LINE.PRICE)) ELSE LINE.QUANTITY*LINE.PRICE END) AS TOTALAMOUNT
FROM TBLQUOTATIONLINE LINE		INNER JOIN	ERP_SAD.DBO.tblItem  ITEM
ON ITEM.INTID=LINE.ITEMID		INNER JOIN  TBLQUOTATIONHEADER   QH
ON QH.ID=LINE.QUOTATIONHEADERID
WHERE LINE.QUOTATIONHEADERID=@ID  AND LINE.ISACTIVE=1
END;