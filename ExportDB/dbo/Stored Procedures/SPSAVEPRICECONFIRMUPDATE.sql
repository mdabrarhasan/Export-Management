
CREATE PROCEDURE [dbo].[SPSAVEPRICECONFIRMUPDATE]
(
@TYPEPCINSERTLINEAPPROVE			TYPEPCINSERTLINEAPPROVE readonly,
@ID									INT,
@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(100),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN
DECLARE @NUMBER VARCHAR(100),@SALESQUOTATIONHEADERID INT,@PROFORMAINVID INT,@GLOBALID VARCHAR(50),
@ITEMID INT,@QUANTITY DECIMAL(18,2),@PRICE DECIMAL(18,2),@OFFERPRICE DECIMAL(18,2),@CONFIRMPRICE DECIMAL(18,2),@VATID INT,@VATAMOUNT DECIMAL(18,2),
@REMARKS VARCHAR(MAX),@BATCHID VARCHAR(100),@SERIALNO INT,@MAXID VARCHAR(100),
@hid int,@lineid int,@nextactiontacker int,
@submenuid int,@scopdeid int,@BATCHIDAPPHISTORY VARCHAR(50),@ProcessID int,@ProcessCode varchar(100),@DocStatusID int,@sqllog nvarchar(max),@initiateid int,
@approvecheck int,@checkcom int

DECLARE SQL_CURSOR CURSOR FOR  
 SELECT ID,ITEMID,QUANTITY,PRICE,OFFERPRICE,CONFIRMPRICE FROM @TYPEPCINSERTLINEAPPROVE
 OPEN SQL_CURSOR
 FETCH NEXT FROM SQL_CURSOR INTO @ID,@ITEMID,@QUANTITY,@PRICE,@OFFERPRICE,@CONFIRMPRICE;  

  WHILE @@FETCH_STATUS = 0  
  BEGIN
  
  UPDATE TBLPRICECONFIRMLINE
  SET CONFIRMPRICE=@CONFIRMPRICE,QUANTITY=@QUANTITY,PRICE=@PRICE,OFFERPRICE=@OFFERPRICE WHERE ID=@ID
  
  FETCH NEXT FROM sql_cursor INTO @ID,@ITEMID,@QUANTITY,@PRICE,@OFFERPRICE,@CONFIRMPRICE;

  END;
  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)
  SET @ProcessCode=@PROCESSNAME+CAST(@ID AS VARCHAR(50))
END