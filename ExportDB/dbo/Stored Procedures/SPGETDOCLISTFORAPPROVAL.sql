
CREATE PROCEDURE [dbo].[SPGETDOCLISTFORAPPROVAL]
(
@TYPE						INT,
@STATUSID					VARCHAR(100),
@ROOTDOCLISTID				INT,
@UNITID						INT,
@ENROLL						INT
)
AS
BEGIN
declare @docstatusid int,@checkstatusid int,@AGGTYPEID INT,@CHECKINIT INT
set @docstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@STATUSID)
set @checkstatusid=(select ID from TBLDOCUMENTSTATUS where CODE=@STATUSID)
SET @CHECKINIT=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='INIT')

	IF @TYPE=1
	BEGIN
	SELECT APPHISTORY.ID,HEADER.DOCNUMBER,HEADER.PICKINGPACKINGHEADERID,PICKPACKHEADER.PICKPACKNUMBER,HEADER.ID AS DOCHEADERID,
	CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	HEADER.CUSTOMERID,CUS.strName AS CUSNAME,CAST(CAST(HEADER.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,
	DS.NAME AS DOCSTATUSNAME,DS.CODE AS CODE,SETUPH.ID AS DOCSETUPHEADERID,
	HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS

	FROM TBLDOCHEADER		HEADER,
	TBLPICKINGPACKINGHEADER PICKPACKHEADER,
	ERP_SAD.DBO.tblCustomer CUS,
	TBLDOCUMENTSTATUS DS,
	TBLDOCUMENTSETUPHEADER SETUPH,
	TBLAPPROVERMATRIXHISTORY APPHISTORY

	WHERE  HEADER.PICKINGPACKINGHEADERID=PICKPACKHEADER.ID		AND 
	CUS.intCusID=HEADER.CUSTOMERID								AND 
	APPHISTORY.DOCUMENTSTATUSID=DS.ID								AND 
	SETUPH.ID=HEADER.DOCUMENTSETUPHEADERID						AND 
	APPHISTORY.PROCESSID=HEADER.ID								AND
	HEADER.DOCUMENTSETUPHEADERID=@ROOTDOCLISTID					AND 
	(APPHISTORY.DOCUMENTSTATUSID=@checkstatusid and APPHISTORY.DOCUMENTSTATUSID != @CHECKINIT)
	AND APPHISTORY.ACTIONTAKERID=@ENROLL AND
	HEADER.ISACTIVE=1
	END

	ELSE IF @TYPE=2
	BEGIN
	SELECT APPHISTORY.ID,HEADER.DOCNUMBER,HEADER.PICKINGPACKINGHEADERID,PICKPACKHEADER.PICKPACKNUMBER,HEADER.ID AS DOCHEADERID,
	CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	HEADER.CUSTOMERID,CUS.strName AS CUSNAME,CAST(CAST(HEADER.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,
	DS.NAME AS DOCSTATUSNAME,DS.CODE AS CODE,SETUPH.ID AS DOCSETUPHEADERID,
	HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS

	FROM TBLDOCHEADER		HEADER,
	TBLPICKINGPACKINGHEADER PICKPACKHEADER,
	ERP_SAD.DBO.tblCustomer CUS,
	TBLDOCUMENTSTATUS DS,
	TBLDOCUMENTSETUPHEADER SETUPH,
	TBLAPPROVERMATRIXHISTORY APPHISTORY

	WHERE  HEADER.PICKINGPACKINGHEADERID=PICKPACKHEADER.ID		AND 
	CUS.intCusID=HEADER.CUSTOMERID								AND 
	HEADER.DOCUMENTSTATUSID=DS.ID								AND 
	SETUPH.ID=HEADER.DOCUMENTSETUPHEADERID						AND 
	APPHISTORY.PROCESSID=HEADER.ID								AND
	APPHISTORY.ID=@ROOTDOCLISTID					AND 
	--(APPHISTORY.DOCUMENTSTATUSID=@checkstatusid and APPHISTORY.DOCUMENTSTATUSID != @CHECKINIT) AND
	HEADER.ISACTIVE=1
	END;
	IF @TYPE=3
	BEGIN
	SELECT APPHISTORY.ID,HEADER.DOCNUMBER,HEADER.PICKINGPACKINGHEADERID,PICKPACKHEADER.PICKPACKNUMBER,
	CAST(CAST(HEADER.DOCUMENTCREATEDDATE AS DATE) AS VARCHAR(50)) AS DOCUMENTCREATEDDATE,
	HEADER.CUSTOMERID,CUS.strName AS CUSNAME,CAST(CAST(HEADER.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,
	DS.NAME AS DOCSTATUSNAME,DS.CODE AS CODE,SETUPH.ID AS DOCSETUPHEADERID,
	HEADER.TERMSCONDITION,HEADER.DESCRIPTIONS

	FROM TBLDOCHEADER		HEADER,
	TBLPICKINGPACKINGHEADER PICKPACKHEADER,
	ERP_SAD.DBO.tblCustomer CUS,
	TBLDOCUMENTSTATUS DS,
	TBLDOCUMENTSETUPHEADER SETUPH,
	TBLAPPROVERMATRIXHISTORY APPHISTORY

	WHERE  HEADER.PICKINGPACKINGHEADERID=PICKPACKHEADER.ID		AND 
	CUS.intCusID=HEADER.CUSTOMERID								AND 
	APPHISTORY.DOCUMENTSTATUSID=DS.ID								AND 
	SETUPH.ID=HEADER.DOCUMENTSETUPHEADERID						AND 
	APPHISTORY.PROCESSID=HEADER.ID								AND
	HEADER.DOCUMENTSETUPHEADERID=@ROOTDOCLISTID					AND 
	(APPHISTORY.DOCUMENTSTATUSID=@checkstatusid and APPHISTORY.DOCUMENTSTATUSID != @CHECKINIT) AND
	--AND APPHISTORY.ACTIONTAKERID=@ENROLL AND
	HEADER.ISACTIVE=1
	END

	IF @TYPE=4
BEGIN
	DECLARE @DOCHEADER INT
	SET @DOCHEADER=(SELECT PROCESSID FROM TBLAPPROVERMATRIXHISTORY WHERE ID=@ROOTDOCLISTID)
	SELECT DOCLINE.ID,DOCH.ID AS DOCHEADERID,DOCH.PICKINGPACKINGHEADERID,DOCH.DOCUMENTSETUPHEADERID,DOCSETUPH.NAME AS ROOTDOCNAME,DOCSETUPLINE.NAME AS CHILDDOCNAME,DOCSETUPLINE.TYPE,
	DOCH.DOCNUMBER,CAST(CAST(DOCH.DOCDATE AS DATE) AS VARCHAR(50)) AS DOCDATE,DOCH.CUSTOMERID,CUS.strName AS CUSTOMERNAME,DOCH.TERMSCONDITION,DOCH.DESCRIPTIONS,
	DOCSETUPLINE.ISMANDATORY,CASE WHEN DOCSETUPLINE.ISMANDATORY=0 THEN 'Optional' ELSE 'Mandatory' END AS MANDATORYLABEL,
	DOCLINE.DOCUMENTSETUPLINEID
	FROM 

	TBLDOCHEADER									 DOCH,
	TBLDOCLINE										 DOCLINE,
	TBLDOCUMENTSETUPHEADER							 DOCSETUPH,
	TBLDOCUMENTSETUPLINE							 DOCSETUPLINE,
	ERP_SAD.DBO.tblCustomer							 CUS

	WHERE DOCH.ID=DOCLINE.DOCHEADERID				 AND 
	DOCH.DOCUMENTSETUPHEADERID=DOCSETUPH.ID			 AND 
	DOCSETUPH.ID=DOCSETUPLINE.DOCUMENTSETUPHEADERID  AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCH.CUSTOMERID=CUS.intCusID					 AND
	DOCLINE.DOCUMENTSETUPLINEID=DOCSETUPLINE.ID		 AND
	DOCLINE.DOCHEADERID=@DOCHEADER ORDER BY TYPE
END;
END;