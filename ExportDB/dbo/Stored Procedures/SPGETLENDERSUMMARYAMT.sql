CREATE PROCEDURE [dbo].[SPGETLENDERSUMMARYAMT]
(
@LENDERUNITID			INT,
@STARTDATE				VARCHAR(100),
@ENDDATE				VARCHAR(100)
)
AS
BEGIN
SELECT MAX(IC.ID) AS ID,IC.LENDERUNITID AS LENDERUNITID,(SELECT strDescription FROM ERP_HR.DBO.tblUnit WHERE intUnitID=IC.LENDERUNITID) AS LENDERUNIT,
BORROWERUNITID AS BORROWERUNITID,(SELECT strDescription FROM ERP_HR.DBO.tblUnit WHERE intUnitID=IC.BORROWERUNITID) AS BORROWERUNIT,
ISNULL(SUM(AMOUNT),0)-ISNULL((SELECT SUM(AMOUNT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID AND DOCSTATUSID=7),0) AS AMOUNT,
FORMAT(ISNULL(SUM(AMOUNT),0)-ISNULL((SELECT SUM(AMOUNT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID),0),'N2') AS VAMOUNT,
SUM(INTERESTAMT)-ISNULL((SELECT SUM(INTERESTAMT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID),0) AS INTERESTAMT,
FORMAT(SUM(INTERESTAMT)-ISNULL((SELECT SUM(INTERESTAMT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID),0),'N2') AS VINTERESTAMT,
0.0 AS GRANDTOTAL,
0.0 AS GRANDINTERESTAMT,
@STARTDATE AS STARTDATE,@ENDDATE AS ENDDATE
FROM TBLINTERESTCALCULATION IC,ERP_HR.DBO.tblUnit UNIT
WHERE IC.LENDERUNITID=UNIT.intUnitID AND 
CAST(IC.STARTDATE AS DATE) BETWEEN @STARTDATE AND @ENDDATE
AND IC.LENDERUNITID=@LENDERUNITID AND IC.ISACTIVE=1 AND IC.DOCSTATUSID=7
GROUP BY LENDERUNITID,BORROWERUNITID
HAVING ISNULL(SUM(AMOUNT),0)-ISNULL((SELECT SUM(AMOUNT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID),0)>0
OR SUM(INTERESTAMT)-ISNULL((SELECT SUM(INTERESTAMT) FROM TBLINTERESTCALCULATION WHERE LENDERUNITID=IC.BORROWERUNITID AND BORROWERUNITID=@LENDERUNITID),0)>0
END;