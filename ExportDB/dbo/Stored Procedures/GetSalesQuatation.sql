 
CREATE PROCEDURE [dbo].[GetSalesQuatation]
@ENROLL			INT
AS
BEGIN
SET NOCOUNT ON;

SET NOCOUNT ON;

    -- Get the Document Status ID for 'PEND'
    DECLARE @DOCSTATUS INT;
    SELECT @DOCSTATUS = ID
    FROM TBLDOCUMENTSTATUS
    WHERE CODE = 'PEND';

    -- Debugging: check if @DOCSTATUS exists
    IF @DOCSTATUS IS NULL
    BEGIN
        RAISERROR('No document status found with CODE = ''PEND''.', 16, 1);
        RETURN;
    END

    -- Main Query
    SELECT 
        SQH.SQTYPEID,
        SQTYPE.STRTYPENAME AS SQTYPENAME,
        CAST(CAST(SQH.EXPIREDATE AS DATE) AS VARCHAR(50)) AS EXPIREDATE,
        0 AS HISTRYID,
        SQH.UNITID,
        UNIT.STRUNIT AS UNITNAME,
        UNIT.STRDESCRIPTION AS UNITDESCRIPTION,
        UNIT.STRACCEMAILADDRESS AS SELLEREMAIL,
        UNIT.STRPHONE AS SELLERPHONE,
        UNIT.STRTIN AS SELLERTIN,
        SQH.CUSTOMERID AS CUSID,
        CUS.STRNAME AS CUSTOMERNAME,
        CUS.STRPHONE AS CUSPHONE,
        CUS.STREMAILADDRESS AS CUSEMAIL,
        CUS.STRADDRESS AS CUSADDRESS,
        CAST(SQH.DOCUMENTCREATEDDATE AS VARCHAR(100)) AS DOCUMENTCREATEDDATE,
        DS.NAME AS DOCSTATUS,
        SQH.ID,
        SQH.SQNUMBER,
		CURRENCY,
		SQH.DESCRIPTIONS,
            SQH.DESCRIPTION_SPECIFICATION AS DESCRIPTIONSPECIFICATION,
            SQH.PRODUCT_QUANTITY AS QUANTITYSUMMARY,
            SQH.TERMSCONDITION,
            SQH.DOCUMENTCREATEDBY,
            SQH.DOCUMENTSTATUSID,
            DS.CODE,
			SQH.PAYMENTTERMS_ID AS PAYMENTTERMSID,
            SQH.SHIPMENTMODE,
            ISNULL(SQH.FROMSHIPMENT, 0) AS FROMSHIPMENT,
            SQH.TOSHIPMENT,
            SQH.TEXTFROMSHIPMENT,
            SQH.DESTINATIONPORT,
            SQH.LOADINGPORT,
            SQH.LOADINGPLACE,
            SQH.INCOTERM,
            SQH.TRANSPORTATIONMODE,

            SQH.PAYMENTTERMS,
            SQH.PAYMENTTERMS_OTHERS AS PAYMENTTERMSOTHERS,
            SQH.SHIPPINGPERIOD,
			SQH.GLOBALID,
            ISNULL(SQH.FLAG, 0) AS FLAG,
            SQH.ISPROCESSEDWITHAPPROVAL

    FROM TBLSALESQUOTATIONHEADER AS SQH
    INNER JOIN ERP_HR.DBO.TBLUNIT AS UNIT
        ON SQH.UNITID = UNIT.INTUNITID
    INNER JOIN ERP_SAD.DBO.TBLCUSTOMER AS CUS
        ON SQH.CUSTOMERID = CUS.INTCUSID
    INNER JOIN TBLDOCUMENTSTATUS AS DS
        ON SQH.DOCUMENTSTATUSID = DS.ID
    INNER JOIN ERP_SAD.DBO.TBLCUSTOMERTYPE AS SQTYPE
        ON SQH.SQTYPEID = SQTYPE.INTTYPEID
    WHERE SQH.ISACTIVE = 1
      AND SQH.DOCUMENTCREATEDBY = @ENROLL
      -- Uncomment to filter only pending documents
      -- AND SQH.DOCUMENTSTATUSID = @DOCSTATUS
    ORDER BY SQH.ID DESC;

END