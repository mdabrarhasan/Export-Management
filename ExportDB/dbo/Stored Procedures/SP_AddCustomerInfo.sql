CREATE PROCEDURE SP_AddCustomerInfo
    @CUSTOMERNAME NVARCHAR(200),
    @CUSTOMERBANKBRANCHNAME NVARCHAR(200),
    @CUSTOMERBANKNAME NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINEONE NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINETWO NVARCHAR(200),
    @CUSTOMERBANKADDRESSLINETHREE NVARCHAR(200),
    @CUSTOMERBANKBINNO NVARCHAR(50),
    @ISACTIVE BIT,
    @CREATEDBY NVARCHAR(50)
AS
BEGIN
    INSERT INTO CustomerInfoX (CUSTOMERNAME, CUSTOMERBANKBRANCHNAME, CUSTOMERBANKNAME, CUSTOMERBANKADDRESSLINEONE, CUSTOMERBANKADDRESSLINETWO, CUSTOMERBANKADDRESSLINETHREE, CUSTOMERBANKBINNO, ISACTIVE, CREATEDBY, CREATEDDATE)
    VALUES (@CUSTOMERNAME, @CUSTOMERBANKBRANCHNAME, @CUSTOMERBANKNAME, @CUSTOMERBANKADDRESSLINEONE, @CUSTOMERBANKADDRESSLINETWO, @CUSTOMERBANKADDRESSLINETHREE, @CUSTOMERBANKBINNO, @ISACTIVE, @CREATEDBY, GETDATE())
END