
CREATE PROCEDURE [dbo].[SPQUOTATIONUPDATEPI]
(
@ID									INT,
@PITYPEID                           INT,
@QUOTATIONTYPEID					INT,
@CUSTOMERID							INT,
@ISEXCEL							INT,
@DATE								VARCHAR(100),
@EXPIREDATE							VARCHAR(100),
@SHIPMENTDATE						VARCHAR(100),
@SHIPMENTMODEID						INT,
@PAYMENTTERMID						INT,
@DELIVERYTERMID						INT,
@TERMSCONDITION						VARCHAR(MAX),
@LOADINGPLACE                       Varchar(100),
@DELIVERYBY                         INT,
@TOSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTCOUNTRYID				INT,
@FROMSHIPMENTPORTID					INT,
@TODISCHARGEPORT					INT,
@TARRIFCODE							VARCHAR(100),
@HSCODE								VARCHAR(100),
@BUYERREGNO							VARCHAR(100),
@INCOTERM							INT,
@CURRENCYID							INT,
@DESCRIPTIONS						VARCHAR(MAX),

@BUYERBANKDETAILS					VARCHAR(500),
@SELLERBANKID						INT,
@BUYERBANKID                        INT,
@BUYERCOUNTRYHSCODE					VARCHAR(100),
@TRANSHIPMENT						INT,
@PARTIALSHIPMENT					INT,
@ORIGINOFCOUNTRY					VARCHAR(50),
@BUYERORDERCONFIRMDATE				VARCHAR(50),
@NOTIFYPARTY						VARCHAR(500),
@OTHERSPAYTERM						VARCHAR(500),

@SALESTYPEID						INT,
@CREDITTYPEID						INT,
@CREDITDAYS							VARCHAR(100),

@FREEINCOTERM                       VARCHAR(50),
@FREEPAYMENTTERM                    VARCHAR(50),
@TOLARENCEID                        INT,
@DELPOINTID                         INT,


@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN
	DECLARE @ProcessCode VARCHAR(100)
	UPDATE TBLQUOTATIONHEADER
	SET	LOADINGPLACE=@LOADINGPLACE,DATE=@DATE,EXPIREDATE=@EXPIREDATE,SHIPMENTDATE=@SHIPMENTDATE,SHIPMENTMODEID=@SHIPMENTMODEID,PAYMENTTERMID=@PAYMENTTERMID,
	DELIVERYTERMID=@DELIVERYTERMID,TERMSCONDITION=@TERMSCONDITION,TOSHIPMENTCOUNTRYID=@TOSHIPMENTCOUNTRYID,FROMSHIPMENTCOUNTRYID=@FROMSHIPMENTCOUNTRYID,
	FROMSHIPMENTPORTID=@FROMSHIPMENTPORTID,TODISCHARGEPORT=@TODISCHARGEPORT,TARRIFCODE=@TARRIFCODE,HSCODE=@HSCODE,BUYERREGNO=@BUYERREGNO,INCOTERM=@INCOTERM,CURRENCYID=@CURRENCYID,DESCRIPTIONS=@DESCRIPTIONS,
	BUYERBANKID = @BUYERBANKID,
	BUYERBANKDETAILS=@BUYERBANKDETAILS,SELLERBANKID=@SELLERBANKID,BUYERCOUNTRYHSCODE=@BUYERCOUNTRYHSCODE,TRANSHIPMENT=@TRANSHIPMENT,
	PARTIALSHIPMENT=@PARTIALSHIPMENT,ORIGINOFCOUNTRY=@ORIGINOFCOUNTRY,BUYERORDERCONFIRMDATE=@BUYERORDERCONFIRMDATE,
	NOTIFYPARTY=@NOTIFYPARTY,OTHERSPAYTERM=@OTHERSPAYTERM,
	SALESTYPEID=@SALESTYPEID,CREDITTYPEID=@CREDITTYPEID,CREDITDAYS=@CREDITDAYS,LOADINGBYID=@DELIVERYBY,SQTYPEID=@PITYPEID,DELPOINTID=@DELPOINTID,

	FREEINCOTERM=@FREEINCOTERM, FREEPAYMENTTERM=@FREEPAYMENTTERM,TOLARENCEID=@TOLARENCEID

	WHERE ID=@ID
	
  SET @ProcessCode=(SELECT QUOTATIONNUMBER FROM TBLQUOTATIONHEADER WHERE ID=@ID)

  set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@MODULECODE) and CODE=@MsgStatus) + ' '+@PROCESSNAME+ ' No :'+@ProcessCode
  --EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@ProcessCode,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@submenuid,@Notification
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@PROCESSNAME,@Notification
  EXEC SPActivityLog @Log,'',@ProcessCode,@ModuleCode,@PROCESSNAME,@UNITID,@Enroll
  
END