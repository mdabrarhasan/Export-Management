CREATE Procedure [dbo].[GetAgreementInfoPITOSC]
(
@Enroll		INT,
@Code		varchar(100),
@UnitID		INT
)
AS
BEGIN
SELECT 0 AS HISTRYID,PH.ID AS AGREEMENTID,PH.UNITID,PH.NUMBER AS PINUMBER,PH.SALESQUOTATIONHEADERID,AGT.CODE AGREEMENTTYPEID,AGT.NAME AS AGREEMENTTYPE,cast(PH.DATE AS VARCHAR) AS PIDATE,CAST(PH.EXPIREDATE AS VARCHAR) AS PIEXPIREDATE,
CAST(PH.SHIPMENTDATE AS VARCHAR) AS SHIPMENTDATE,PH.SHIPMENTMODEID,CAST(PH.DOCUMENTCREATEDDATE AS VARCHAR) AS DOCUMENTCREATEDDATE,CUS.strName AS CUSTOMERNAME,'' AS SQNUMBER,
SM.ID AS SHIPMENTID,SM.NAME AS SHIPMENT,PT.ID AS PAYMENTTERMID,PT.NAME AS PAYMENTTERM,PH.HSCODE,PH.BUYERREGNO,PH.CURRENCYID,PH.DELIVERYTERMID,PH.DESCRIPTIONS,PH.TERMSCONDITION,
TSC.ID AS TOSHIPMENTCOUNTRYID,TSC.NAME AS TOSHIPMENTCOUNTRY,FSC.ID AS FROMSHIPMENTCOUNTRYID,FSC.NAME AS FROMSHIPMENTCOUNTRY,PH.ISPROCESSEDWITHAPPROVAL,
LP.ID AS FROMSHIPMENTPORTID,LP.NAME AS FROMSHIPMENTPORT,DP.ID AS TOSHIPMENTPORTID,DP.NAME AS TOSHIPMENTPORT,'' AS CURRENCY,'' AS DELIVERYTERM,
PH.TARRIFCODE,INCO.ID AS INCOID,INCO.NAME AS INTOTERM,DS.CODE,DS.ID AS DOCSTATUSID,DS.NAME AS DOSSTATUS,CASE WHEN ISNULL(PH.FLAG,0)=0 THEN 0 ELSE PH.FLAG END AS FLAG,
PH.BUYERBANKDETAILS AS BUYERBANKDETAILS,PH.SELLERBANKID,PH.BUYERCOUNTRYHSCODE,PH.TRANSHIPMENT,PH.PARTIALSHIPMENT,PH.ORIGINOFCOUNTRY,CAST(CAST(PH.BUYERORDERCONFIRMDATE AS DATE) AS VARCHAR(50))  AS BUYERORDERCONFIRMDATE,
PH.NOTIFYPARTY,PH.OTHERSPAYTERM
from TBLPISCHEADER PH				 INNER JOIN ERP_SAD.DBO.tblCustomer			   CUS
ON ph.CUSTOMERID=cus.intCusID	     INNER JOIN TBLSHIPMENTMODE					   SM
ON PH.SHIPMENTMODEID=SM.ID			 INNER JOIN TBLPAYMENTTERMS					   PT
ON PH.PAYMENTTERMID=PT.ID			 INNER JOIN TBLCOUNTRY						   TSC
ON PH.TOSHIPMENTCOUNTRYID=TSC.ID	 INNER JOIN TBLCOUNTRY						   FSC
ON PH.FROMSHIPMENTCOUNTRYID=FSC.ID	 INNER JOIN TBLFROMLOADINGPORT				   LP
ON PH.FROMSHIPMENTPORTID=LP.ID		 INNER JOIN TBLFROMLOADINGPORT				   DP
ON PH.TODISCHARGEPORT=DP.ID			 INNER JOIN TBLINCOTERM						   INCO
ON PH.INCOTERM=INCO.ID				 INNER JOIN TBLDOCUMENTSTATUS				   DS
ON PH.DOCUMENTSTATUSID=DS.ID		 INNER JOIN TBLAGREEMENTTYPE				   AGT
ON PH.AGREEMENTTYPEID=AGT.ID		 	 
WHERE PH.DOCUMENTCREATEDBY=@Enroll AND PH.AGREEMENTTYPEID=(SELECT ID FROM TBLAGREEMENTTYPE WHERE CODE=@Code)
END;