CREATE PROCEDURE [dbo].[SPGETPAYMENTRESCHEDULEDBYID]
(
@ID			INT
)
AS
BEGIN
SELECT PS.ID,UT.ID AS LENDERBANKID,BT.BANKNAME AS LENDERBANK,
UT.ID AS BORROWERUNITID,UT.NAME AS BORROWERUNIT,
PS.AMOUNT,PS.PAYMENT,PS.PRNO,
CAST(CAST(PS.PAYMENTDATE AS DATE) AS VARCHAR(100)) AS PAYMENTDATE,
CAST(CAST(PS.RESCHEDULEDPAYMENTDATE AS DATE) AS VARCHAR(100)) AS RESCHEDULEDPAYMENTDATE,
PS.TYPEID,TYPE.NAME AS TYPE,PS.REFLOANNUMBER,
BL.CURRENCYID,CURR.NAME AS CURRENCY,
ISNULL(PS.CRATE,0.0) AS CRATE,ISNULL(PS.REFID,0) AS REFID,PS.NARRATION,LOANTYPE.LOANTYPE
FROM TBLPAYMENTRESCHEDULE PS,TBLBANKFORTREASURY BT,TBLUNITFORTREASURY UT,TBLPAYMENTRESCHEDULETYPE TYPE,
TBLBANKLOAN BL,TBLCURRENCY CURR,TBLLOANTYPE LOANTYPE
WHERE PS.BANKID=BT.BANKID AND
PS.BORROWERUNITID=UT.ID   AND
PS.TYPEID=TYPE.ID		  AND
PS.REFID=BL.ID			  AND
LOANTYPE.ID=BL.LOANTYPEID AND
CURR.ID=BL.CURRENCYID	  AND
PS.ISACTIVE=1		      AND	 
PS.ID=@ID		 
END;