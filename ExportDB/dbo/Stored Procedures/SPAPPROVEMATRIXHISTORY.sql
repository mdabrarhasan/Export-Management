CREATE PROCEDURE [dbo].[SPAPPROVEMATRIXHISTORY]
(
@DOCSTATUS							VARCHAR(100),
@ID									INT,
@MODULECODE							VARCHAR(100),
@PROCESSCODE						VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@ENROLL							    INT,
@UNITID								INT
)
AS
BEGIN
DECLARE @CHECKCOM INT,@DOCSTATUSID INT,@INITIATEID INT,@APPROVECHECK INT,@HID INT,@LINEID INT,@SUBMENUID INT,
@NEXTACTIONTACKER INT,@BATCHIDAPPHISTORY VARCHAR(100),@CHECKAPPROVEALLOWED INT,@CHECKAPPR INT

SET @CHECKCOM=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='COMP')
SET @CHECKAPPR=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE='APPR')
SET @DOCSTATUSID=(SELECT ID FROM TBLDOCUMENTSTATUS WHERE CODE=@DOCSTATUS)
SET @INITIATEID=(SELECT ID from TBLDOCUMENTSTATUS WHERE CODE='INIT')
--SET @APPROVECHECK=(SELECT COUNT(*) FROM TBLAPPROVERMATRIXHEADER WHERE EXISTS (SELECT ISAPPROVALALLOWED FROM TBLAPPROVERMATRIXHEADER WHERE SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=@MODULECODE) AND UNITID=@UNITID))
--SET @HID=(SELECT ID from TBLAPPROVERMATRIXHEADER WHERE SUBMENUID=(SELECT ID from TBLSUBMENU WHERE CODE=@MODULECODE) AND UNITID=@UNITID)
SET @APPROVECHECK=(SELECT COUNT(*) FROM TBLAPPROVERMATRIXHEADER WHERE EXISTS (SELECT ISAPPROVALALLOWED FROM TBLAPPROVERMATRIXHEADER WHERE SUBMENUID=(SELECT ID FROM TBLSUBMENU WHERE CODE=@MODULECODE) ))
SET @HID=(SELECT  ID from TBLAPPROVERMATRIXHEADER WHERE SUBMENUID=(SELECT ID from TBLSUBMENU WHERE CODE=@MODULECODE) )
SET @CHECKAPPROVEALLOWED=(select ISAPPROVALALLOWED from TBLAPPROVERMATRIXHEADER where ID=@hid)

IF @CHECKAPPROVEALLOWED=0 OR @APPROVECHECK=0
	BEGIN
		 IF (@PROCESSNAME='SQ')
		 BEGIN
		 UPDATE TBLSALESQUOTATIONHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END
		 IF (@PROCESSNAME='QUO')
		 BEGIN
		 UPDATE TBLQUOTATIONHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END
		 ELSE IF (@PROCESSNAME='PI' OR @PROCESSNAME='SC')
		 BEGIN
		 UPDATE TBLPISCHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END

		 ELSE IF @PROCESSNAME='LC'
		 BEGIN
		 UPDATE TBLLCDETAILS 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END
		 ELSE IF @PROCESSNAME='PC'
		 BEGIN
		 UPDATE TBLPRICECONFIRMHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END

		 ELSE IF @PROCESSNAME='PR'
		 BEGIN
		 UPDATE TBLPACKINGREQUESTHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 if @UNITID !=91
		 begin
		 EXEC SPSAVEPICKPACKCONFIRM @ID
		 end
		 END
		 ELSE IF @PROCESSNAME='PRC'
		 BEGIN
		 UPDATE TBLPICKINGPACKINGHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END
		 ELSE 
		 BEGIN
		 UPDATE TBLDOCHEADER 
		 SET DOCUMENTSTATUSID=@CHECKCOM,FLAG=1 WHERE ID=@ID
		 END
	END;
ELSE 
	BEGIN
	
		 SET @HID=(SELECT ID from TBLAPPROVERMATRIXHEADER WHERE SUBMENUID=(SELECT ID from TBLSUBMENU WHERE CODE=@MODULECODE))
		 SET @LINEID=(SELECT ID from TBLAPPROVERMATRIXLINE WHERE APPROVERMATRIXHEADERID=@HID AND SEQUENCE=(SELECT MIN(SEQUENCE) from TBLAPPROVERMATRIXLINE WHERE APPROVERMATRIXHEADERID=@HID))
		 SET @SUBMENUID=(SELECT ID from TBLSUBMENU WHERE CODE=@MODULECODE)
		 SET @NEXTACTIONTACKER=(SELECT value from TBLAPPROVERMATRIXLINE WHERE SEQUENCE=(SELECT MIN(SEQUENCE) from TBLAPPROVERMATRIXLINE WHERE APPROVERMATRIXHEADERID=@HID) AND 	APPROVERMATRIXHEADERID=@HID);
		 SET @BATCHIDAPPHISTORY='BATCH'+CAST(@HID as varchar(100))
		-- select @NEXTACTIONTACKER
		 INSERT INTO TBLAPPROVERMATRIXHISTORY
		 (
				[APPROVERMATRIXHEADERID],
				[APPROVERMATRIXLINEID],
				[SUBMENUID],
				[BATCHID],
				[PROCESSID],
				[PROCESSCODE],
				PROCESSNAME,
				[INITIATORID],
				[ACTIONTAKERID],
				[DOCUMENTSTATUSID],
				[UNITID],
				DOCUMENTCREATEDDATE,
				DOCUMENTCREATEDBY
				)
				VALUES
				(
				@HID,
				@LINEID,
				@SUBMENUID,
				@BATCHIDAPPHISTORY,
				@ID,
				@PROCESSCode,
				@ProcessName,
				@ENROLL,
				@ENROLL,
				@INITIATEID,
				@UNITID,
				GETDATE(),
				@ENROLL
			)

		 INSERT INTO TBLAPPROVERMATRIXHISTORY
			(
				[APPROVERMATRIXHEADERID],
				[APPROVERMATRIXLINEID],
				[SUBMENUID],
				[BATCHID],
				[PROCESSID],
				[PROCESSCODE],
				PROCESSNAME,
				[INITIATORID],
				[ACTIONTAKERID],
				[DOCUMENTSTATUSID],
				[UNITID],
				--DESCRIPTIONS,
				DOCUMENTCREATEDDATE,
				DOCUMENTCREATEDBY
				)
				values
				(
				@HID,
				@LINEID,
				@SUBMENUID,
				@BATCHIDAPPHISTORY,
				@ID,
				@PROCESSCode,
				@ProcessName,
				@ENROLL,
				@NEXTACTIONTACKER,
				@DOCSTATUSID,
				@UNITID,
				GETDATE(),
				@ENROLL
			)

	END;
END;