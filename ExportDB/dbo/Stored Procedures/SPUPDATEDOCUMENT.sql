
CREATE PROCEDURE [dbo].[SPUPDATEDOCUMENT]
(
@ID									INT,
@DOCUMENTSETUPHEADERID				INT,
@PICKINGPACKINGHEADERID				INT,
@DESCRIPTIONS						VARCHAR(500),
@TERMSCONDITION						VARCHAR(500),

@MODULECODE							VARCHAR(100),
@UNITID								INT,
@ENROLL								INT,
@DOCSTATUS							VARCHAR(100),
@PROCESSNAME						VARCHAR(100),
@MsgStatus							VARCHAR(50),
@NOTIFICATION						VARCHAR(100),
@LOG								VARCHAR(MAX),
@Msg								VARCHAR(100) OUTPUT
)
AS
BEGIN 
	DECLARE @GLOBAL VARCHAR(50),@DOCNUMBER VARCHAR(50),@CUSTOMERID INT,@DOCSTATUSID INT,@VDOCUMENTSETUPHEADERID INT,@VMODULECODE VARCHAR(100),@VPROCESSNAME VARCHAR(100),
	@VID INT,@VDOCHEADERID INT,@DOCUMENTSETUPLINEID INT,@DOCUMENTSTATUSID INT,@VTERMSCONDITION VARCHAR(500),@VDESCRIPTION VARCHAR(500),@VPROCESS VARCHAR(100),@CHECKPICKPACK INT,
	@VDOCUMENTSETUPHEADERCODE	VARCHAR(50),@PROCESSCODE VARCHAR(50)

BEGIN
	

 --SET @DOCNUMBER=(SELECT CODE FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID)
 SET @MODULECODE=(SELECT CODE FROM TBLSUBMENU WHERE ID=(SELECT SUBMENUID FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID))
 SET @VMODULECODE=(SELECT CODE FROM TBLSUBMENU WHERE ID=(SELECT SUBMENUID FROM TBLDOCUMENTSETUPHEADER WHERE ID=@DOCUMENTSETUPHEADERID))

	UPDATE TBLDOCHEADER
	SET TERMSCONDITION=@TERMSCONDITION,DESCRIPTIONS=@DESCRIPTIONS WHERE ID=@ID;

  IF @VMODULECODE='PRE00001'
  BEGIN
  SET @PROCESSNAME='PRE'
  SET @MsgStatus='PREEDIT'
  SET @DOCNUMBER='PRE'+CAST(@ID AS VARCHAR(50))
  END;
  ELSE IF @VMODULECODE='POST00001'
  BEGIN
  SET @PROCESSNAME='POST'
  SET @MsgStatus='POSTEDIT'
  SET @DOCNUMBER='POST'+CAST(@ID AS VARCHAR(50))
  END;

  SET @PROCESSCODE=@PROCESSNAME+CAST(@ID AS VARCHAR(100))
--set @MSG=@ID
SET @LOG='UPDATE TBLDOCHEADER SET TERMSCONDITION='+@TERMSCONDITION+'DESCRIPTIONS='+@DESCRIPTIONS+'WHERE ID='+CAST(@ID AS VARCHAR(100))
set @Msg=(select NAME from TBLMESSAGE where SUBMENUID=(select ID from TBLSUBMENU where CODE=@ModuleCode) and CODE=@MsgStatus)+' DOC NO:'+CAST(@ID AS VARCHAR(100))
  --EXEC SPAPPROVEMATRIXHISTORY @DOCSTATUS,@ID,@MODULECODE,@PROCESSCODE,@PROCESSNAME,@ENROLL,@UNITID
  --EXEC SPEmailSend @id,@MODULECODE,@ProcessCode,@ProcessName,@Notification
  EXEC SPACTIVITYLOG @LOG,'',@PROCESSCODE,@MODULECODE,@PROCESSNAME,@UNITID,@ENROLL
END 

END;





